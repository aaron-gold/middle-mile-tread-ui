def sidecar_path(image_path):
    """
    Resolve the JSON sidecar for an image, or None.
    Middle Mile writes  frame_0000.tif + frame_0000.tif.json ; some tools write
    frame_0000.json. Both are accepted - ONE resolver so every consumer agrees.
    """
    cands = [image_path + ".json", os.path.splitext(image_path)[0] + ".json"]
    for c in cands:
        if lp_isfile(c):
            return c
    return None


# ============================================================
# FILE ORDERING  (frame index first, then timestamp, then natural, then mtime)
# ============================================================
_FRAME_RE = re.compile(r"frame[_\-]?(\d+)", re.IGNORECASE)
_TS_RE = re.compile(r"(\d{4})[-_]?(\d{2})[-_]?(\d{2})[T_\-]?(\d{2})[-_:]?(\d{2})[-_:]?(\d{2})")
_NUM_RE = re.compile(r"(\d+)")


def order_key(path):
    """Sort key that works for frame_NNNN.tif, ISO-timestamped names, or anything else."""
    name = os.path.basename(path)
    m = _FRAME_RE.search(name)
    if m:
        return (0, int(m.group(1)), name.lower())
    m = _TS_RE.search(name)
    if m:
        return (1, "".join(m.groups()), name.lower())
    # natural sort on the first number, else by name, else mtime
    m = _NUM_RE.search(name)
    if m:
        return (2, int(m.group(1)), name.lower())
    try:
        return (3, os.path.getmtime(path), name.lower())
    except Exception:
        return (4, 0, name.lower())


# One frame, several encodings: from 2026-09-23 the wall folders write
# frame_NNNN.jpg AND frame_NNNN.tif for the SAME frame (same sidecar content,
# pixel-identical after decode - checked on 2026-09-16T12-09-18). Listing both made
# the slider alternate jpg / tif / jpg / tif, i.e. every frame twice. One file per
# frame stem is shown, the first of this order; the others stay on disk untouched.
IMAGE_EXT_PREFERENCE = (".tif", ".tiff", ".png", ".bmp", ".jpg", ".jpeg")


def _ext_rank(name):
    ext = os.path.splitext(name)[1].lower()
    return IMAGE_EXT_PREFERENCE.index(ext) if ext in IMAGE_EXT_PREFERENCE else 99


def list_images(folder, dedupe=True):
    try:
        names = [f for f in lp_listdir(folder) if f.lower().endswith(IMAGE_EXTS)]
    except Exception:
        return []
    if dedupe:
        best = {}
        for f in names:
            stem = os.path.splitext(f)[0].lower()
            cur = best.get(stem)
            if cur is None or _ext_rank(f) < _ext_rank(cur):
                best[stem] = f
        names = list(best.values())
    files = [os.path.join(folder, f) for f in names]
    files.sort(key=order_key)
    return files
