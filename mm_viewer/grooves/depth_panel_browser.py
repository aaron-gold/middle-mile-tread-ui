class _DepthPanelBrowserMixin:
    """GrooveDepthPanel methods, lines 5601-6123 of the v1.8 monolith.
    Mixed into GrooveDepthPanel (see its class line); not used on its own."""

    # ---------------- frame browser (DISPLAY ONLY) ----------------
    # One LMI unit, one frame at a time - the same interaction as the tread and OCR
    # frame viewers. It reads the profiles the overview already cached plus that
    # frame's own *_grooves.csv. It writes nothing and computes no depth.

    def _build_mode_widgets(self):
        self.mode_seg = SegmentedControl(list(VIEW_MODES))
        self.mode_seg.set_current(VIEW_OVERVIEW)
        self.mode_seg.setToolTip(
            "Overview = every frame of all four units on one 2x2 grid.\n"
            "Frame browser = one unit, one frame, with that frame's own grooves "
            "marked on it.")
        self.mode_seg.changed.connect(self._on_mode_changed)
        return [field_label("View"), self.mode_seg]

    def _build_browser_bar(self):
        """Unit selector + frame nav. Hidden until the browser is the active view."""
        self.br_unit = ArrowComboBox()
        self.br_unit.addItems(list(POS_ORDER))
        self.br_unit.setMinimumWidth(170)
        self.br_unit.setToolTip(
            "Which wheel's LMI laser unit the PLOT steps through, one frame at a time.\n"
            "It does not filter the summary or the per-profile table - that is the\n"
            "'Summary / table' selector in the toolbar row above.")
        self.br_unit.currentIndexChanged.connect(self._on_br_unit)

        self.br_prev = nav_button("◀", "Previous frame  (Ctrl+Alt+Left)")
        self.br_next = nav_button("▶", "Next frame  (Ctrl+Alt+Right)")
        self.br_prev.clicked.connect(lambda: self._br_step(-1))
        self.br_next.clicked.connect(lambda: self._br_step(+1))

        self.br_slider = QSlider(Qt.Orientation.Horizontal)
        self.br_slider.setObjectName("frameSlider")
        self.br_slider.setMinimumWidth(140)
        self.br_slider.setToolTip("Scrub through this unit's frames.")
        self.br_slider.valueChanged.connect(self._on_br_slider)

        self.br_label = QLabel("Frame 0 / 0")
        self.br_label.setObjectName("frameLabel")

        # The frame's filename is already the first thing in the plot title, and in
        # this row it was the widget that yielded its width and vanished. It stays as
        # a hidden label so the nav code has one place to put the name, and so the
        # tooltip on the bar can still show it.
        self.br_file = QLabel("")
        self.br_file.setObjectName("hintText")
        self.br_file.setVisible(False)

        self.br_data_btn = self._toggle_btn(
            "With data only", BR_DATA_ONLY,
            "Skip the frames whose profile file holds no plottable sample.\n"
            "A unit can have 54 profile files and 8 frames with data, and stepping\n"
            "through 46 empty ones tells you nothing. Off = every file, in order.")
        self.br_ghost_btn = self._toggle_btn(
            "Ghost others", BR_GHOST,
            "Draw the unit's other frames behind this one in grey, for context.")
        self.br_accum_btn = self._toggle_btn(
            "Accumulate", BR_ACCUM,
            "Build the profile up in sequence: the slider stops replacing the frame "
            "and starts\nADDING it. At position N every frame from the first to N is "
            "drawn, in rising order,\nshaded light (first) to dark (current), so the "
            "tyre's full profile assembles as you step.\n"
            "Nothing is merged or averaged - the frames are simply overlaid as the "
            "sensor wrote them.\n"
            "The groove markers stay on the current frame only; N frames of markers "
            "is not readable.")
        self.br_data_btn.toggled.connect(self._on_br_filter_changed)
        self.br_ghost_btn.toggled.connect(lambda *_: self._redraw_browser())
        self.br_accum_btn.toggled.connect(self._on_br_accum_changed)

        # a real QHBoxLayout, not the wrapping flow row: the slider is the control
        # this view is steered with, so it takes every pixel the row does not need
        row = QHBoxLayout()
        row.setContentsMargins(0, 0, 0, 0)
        row.setSpacing(8)
        row.addWidget(field_label(BROWSE_UNIT_LABEL))
        row.addWidget(self.br_unit)
        row.addWidget(self.br_prev)
        row.addWidget(self.br_slider, 1)
        row.addWidget(self.br_next)
        row.addWidget(self.br_label)
        row.addWidget(self.br_data_btn)
        row.addWidget(self.br_accum_btn)
        row.addWidget(self.br_ghost_btn)
        row.addStretch(0)

        w = QWidget()
        w.setLayout(row)
        w.setVisible(False)
        self.browser_bar = w
        return w

    def _build_browser_card(self):
        """Per-frame diagnostics: what the file holds, and what the system found."""
        c, v = card("Frame diagnostics  ·  this frame only")

        # side by side, not stacked: stacked, the stats block ate the card and the
        # 10-slot table showed three rows. The stats are narrow text and the table is
        # wide, so beside each other the table gets the card's full height.
        row = QHBoxLayout(); row.setSpacing(12)

        self.br_stats = QLabel("—")
        self.br_stats.setObjectName("depthSummary")
        self.br_stats.setWordWrap(True)
        self.br_stats.setAlignment(Qt.AlignmentFlag.AlignTop | Qt.AlignmentFlag.AlignLeft)
        # NOT allow_shrink(): its Ignored size policy lets a stretch-0 child collapse
        # to nothing beside a stretch-1 table. A capped maximum does the same job -
        # the block can never force the window wider than BR_STATS_W.
        self.br_stats.setMinimumWidth(260)
        self.br_stats.setMaximumWidth(BR_STATS_W)
        self.br_stats.setSizePolicy(QSizePolicy.Policy.Preferred,
                                    QSizePolicy.Policy.Preferred)
        row.addWidget(self.br_stats)

        heads = ["Slot", "Depth (mm)", "Width (mm)", "X (mm)", "Z (mm)",
                 "grooves_full depth (mm)"]
        self.br_table = QTableWidget(0, len(heads))
        self.br_table.setObjectName("depthTable")
        self.br_table.setHorizontalHeaderLabels(heads)
        self.br_table.verticalHeader().setVisible(False)
        self.br_table.setAlternatingRowColors(True)
        self.br_table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        self.br_table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        hh = self.br_table.horizontalHeader()
        hh.setSectionResizeMode(QHeaderView.ResizeMode.Stretch)
        self.br_table.setMinimumHeight(120)
        self.br_table.setToolTip(
            "Left of the divider: this frame's own *_grooves.csv, row for row, as "
            "written.\n"
            "Right: the depth the system reported for the same frame in "
            "*_grooves_full.csv.\n"
            "The two are different files and are shown side by side deliberately - "
            "nothing is\nreconciled, averaged or filled in here. A blank cell is a "
            "sentinel in the source.")
        self.br_table.verticalHeader().setDefaultSectionSize(24)
        row.addWidget(self.br_table, 1)
        v.addLayout(row, 1)
        return c

    # ---------------- browser state ----------------
    def _browser_mode(self):
        s = getattr(self, "mode_seg", None)
        return s is not None and s.current() == VIEW_BROWSER

    def _br_data_only(self):
        b = getattr(self, "br_data_btn", None)
        return bool(b.isChecked()) if b is not None else BR_DATA_ONLY

    def _ghost_on(self):
        b = getattr(self, "br_ghost_btn", None)
        # accumulating already draws every earlier frame; grey ghosts of the LATER
        # ones on top of that is just noise
        if self._accum_on():
            return False
        return bool(b.isChecked()) if b is not None else BR_GHOST

    def _accum_on(self):
        b = getattr(self, "br_accum_btn", None)
        return bool(b.isChecked()) if b is not None else BR_ACCUM

    def _on_br_accum_changed(self, on):
        b = getattr(self, "br_ghost_btn", None)
        if b is not None:
            b.setEnabled(not on)
        self._redraw_browser()

    def _current_src(self):
        """The cache the active filter mode plots from."""
        return ((self._filt_cache if self._filtered() else self._raw_cache) or {})

    def _profile_paths(self, pos):
        """{basename: full path} for one unit - the sibling grooves file needs it."""
        if self._path_cache is None:
            try:
                files = profile_files_by_pos(self.folder, self._axle_keep())
            except Exception:
                files = {p: [] for p in POS_ORDER}
            self._path_cache = {p: {os.path.basename(f): f for f in files.get(p, [])}
                                for p in POS_ORDER}
        return self._path_cache.get(pos, {})

    def _browser_names(self, src, pos):
        """The frame list the slider walks, in file order."""
        raw = (self._raw_cache or {}).get(pos, [])
        have = {n for n, x, _z in src.get(pos, []) if x.size}
        names = [n for n, _x, _z in raw]
        if self._br_data_only():
            names = [n for n in names if n in have]
        return names, have

    def _on_mode_changed(self, key):
        on = (key == VIEW_BROWSER)
        if on:
            # maximise is an overview idea; the browser is already one axes
            self._max_pos = None
        bar = getattr(self, "browser_bar", None)
        if bar is not None:
            bar.setVisible(on)
        btn = getattr(self, "diag_btn", None)
        if btn is not None:
            btn.setEnabled(on)
            if not on and btn.isChecked():
                btn.setChecked(False)       # its card is meaningless in the overview
        self._resize_split()
        self._update_view_hint()
        self.render()

    def _on_br_unit(self, *_):
        self._br_pos = self.br_unit.currentText()
        self._br_idx = 0
        self._redraw_browser()

    def _on_br_filter_changed(self, *_):
        self._br_idx = 0
        self._redraw_browser()

    def _on_br_slider(self, v):
        if v == self._br_idx:
            return
        self._br_idx = int(v)
        self._redraw_browser()

    def _br_step(self, delta):
        s = getattr(self, "br_slider", None)
        if s is None or not self._browser_mode() or self.embedded:
            return                      # embedded: the combined timeline steps it
        s.setValue(min(max(s.value() + int(delta), s.minimum()), s.maximum()))

    def _redraw_browser(self):
        """Re-draw the frame only - the depth rows and the table are already right."""
        if not self._browser_mode():
            return
        if self._raw_cache is None or self.fig is None:
            self.render()
            return
        if self.embedded and self._want_empty is not None:
            self._draw_empty(*self._want_empty)     # a toggle must not resurrect a frame
            return
        self._draw_browser(self._current_src())

    def _sync_browser_nav(self, names):
        n = len(names)
        s = getattr(self, "br_slider", None)
        if s is None:
            return
        s.blockSignals(True)
        s.setMinimum(0)
        s.setMaximum(max(0, n - 1))
        s.setValue(min(max(self._br_idx, 0), max(0, n - 1)))
        s.setEnabled(n > 1)
        s.blockSignals(False)
        self._br_idx = s.value() if n else 0
        self.br_label.setText("Frame %d / %d" % (self._br_idx + 1 if n else 0, n))
        self.br_prev.setEnabled(n > 1 and self._br_idx > 0)
        self.br_next.setEnabled(n > 1 and self._br_idx < n - 1)

    # ---------------- browser drawing ----------------
    def _draw_browser(self, src):
        """One frame, full canvas: its profile, its grooves, its own diagnostics."""
        pos = self._br_pos if self._br_pos in POS_ORDER else POS_ORDER[0]
        self._br_pos = pos
        cb = getattr(self, "br_unit", None)
        if cb is not None and cb.currentText() != pos:
            cb.blockSignals(True); cb.setCurrentText(pos); cb.blockSignals(False)

        names, have_names = self._browser_names(src, pos)
        self._sync_browser_nav(names)

        insp = getattr(self, "inspector", None)
        self.fig.clear()
        if insp is not None:
            insp.reset()
        ax = self.fig.subplots(1, 1)
        ax.set_xlabel("x (mm)"); ax.set_ylabel("z (mm)")
        ax.grid(True, linestyle="--", alpha=0.6)

        n_all = len((self._raw_cache or {}).get(pos, []))
        if not names:
            ax.set_title("%s — no frame to show" % pos, fontsize=11, fontweight="bold")
            msg = ("this unit has no profile file" if not n_all else
                   "no frame in this unit has plottable data\n"
                   "(turn 'With data only' off to step through the empty files)")
            ax.text(0.5, 0.5, msg, ha="center", va="center",
                    transform=ax.transAxes, color="gray")
            self.br_file.setText("")
            ax.set_title("%s   ·   no frame to show" % pos,
                         fontsize=11, fontweight="bold")
            self._apply_fig_rect_browser(1)
            self.canvas.draw()
            self._fill_frame_panel(pos, None, [])
            return

        name = names[self._br_idx]
        self.br_file.setText(name)
        curves = {n: (x, z) for n, x, z in src.get(pos, []) if x.size}
        style = self._draw_style()
        gaps = self._break_gaps_on()

        # ghosts first so the frame under inspection draws on top of them
        if self._ghost_on():
            for gn, gx, gz in src.get(pos, []):
                if gn == name or not gx.size:
                    continue
                bx, bz = break_profile_gaps(gx, gz) if gaps else (gx, gz)
                ax.plot(bx, bz, color=BR_GHOST_COL, alpha=0.5, zorder=1, **style)

        accum = self._accum_on()
        seq = ([n for n in names[:self._br_idx + 1] if n in curves] if accum
               else ([name] if name in curves else []))

        if accum:
            # rising order, oldest first, each one shaded further along the ramp and
            # drawn on top of the last, so the profile assembles as the slider moves
            for k, nm in enumerate(seq):
                x, z = curves[nm]
                bx, bz = break_profile_gaps(x, z) if gaps else (x, z)
                frac = 1.0 if len(seq) < 2 else k / (len(seq) - 1.0)
                ax.plot(bx, bz, color=ramp_color(frac), alpha=0.9, zorder=3 + k,
                        label=nm, **style)
            if insp is not None and seq:
                # every accumulated frame is registered, so the crosshair names
                # whichever one it snapped to and auto-Z fits what is on screen
                insp.register(ax, pos, [(nm, curves[nm][0], curves[nm][1])
                                        for nm in seq])
        elif seq:
            x, z = curves[name]
            bx, bz = break_profile_gaps(x, z) if gaps else (x, z)
            ax.plot(bx, bz, color=BR_CURVE_COL, alpha=0.95, zorder=3,
                    label=name, **style)
            if insp is not None:
                # only this frame is registered, so the crosshair and the z auto-fit
                # answer for the frame on screen and not for the whole unit
                insp.register(ax, pos, [(name, x, z)])

        if not seq:
            why = ("this frame's profile file holds no plottable sample"
                   if name not in have_names and not self._filtered() else
                   "this frame was rejected by the profile filter")
            ax.text(0.5, 0.5, why, ha="center", va="center",
                    transform=ax.transAxes, color="gray")

        # the limits come from the PROFILE, before any groove marker is drawn: a
        # groove row can carry a z hundreds of mm off the tread and would otherwise
        # flatten the very thing the browser exists to show
        x0, x1 = ax.get_xlim()
        y0, y1 = ax.get_ylim()

        path = self._profile_paths(pos).get(name)
        grooves = []
        if path:
            sib = (path[:-len("_profile.csv")] + "_grooves.csv"
                   if path.lower().endswith("_profile.csv") else None)
            if sib:
                grooves = self._grooves_for(sib)

        seen, n_marked, n_off = set(), 0, 0
        gx_seen = []
        for g in grooves:
            gx, gz = g["x"], g["z"]
            if not math.isfinite(gx):
                continue
            key = tuple(round(v, 4) if math.isfinite(v) else None
                        for v in (gx, gz, g["depth"], g["width"]))
            if key in seen:
                continue                       # the same row written twice
            seen.add(key)
            n_marked += 1
            gx_seen.append(gx)
            ax.plot([gx, gx], [y0, y1], color=BR_GROOVE_COL, linewidth=0.9,
                    alpha=0.8, linestyle="--", zorder=2)
            if math.isfinite(gz):
                if y0 <= gz <= y1:
                    ax.plot([gx], [gz], marker="v", markersize=7, linestyle="none",
                            color=BR_GROOVE_COL, markeredgecolor="#ffffff",
                            markeredgewidth=0.8, zorder=4)
                else:
                    n_off += 1
            lbl = "G%d" % g["slot"]
            if math.isfinite(g["depth"]):
                lbl += "  D=%.2f" % g["depth"]
            if math.isfinite(g["width"]):
                lbl += "  W=%.2f" % g["width"]
            ax.annotate(lbl, xy=(gx, y1), xytext=(3, -3), textcoords="offset points",
                        rotation=90, fontsize=7, va="top", ha="left",
                        color=BR_GROOVE_COL, zorder=5)

        # widen x to take in any groove marker that sits outside the profile, then put
        # z back exactly where the profile left it
        if gx_seen:
            lo, hi = min(list(gx_seen) + [x0]), max(list(gx_seen) + [x1])
            pad = (hi - lo) * 0.02 or 1.0
            ax.set_xlim(lo - pad, hi + pad)
        ax.set_ylim(y0, y1)

        if accum:
            head = ("%s   ·   frames 1-%d of %d accumulated   ·   %d drawn   ·   %s"
                    % (pos, self._br_idx + 1, len(names), len(seq),
                       "Filtered" if self._filtered() else "Unfiltered"))
        else:
            head = ("%s   ·   %s   ·   frame %d of %d listed   ·   %s"
                    % (pos, name, self._br_idx + 1, len(names),
                       "Filtered" if self._filtered() else "Unfiltered"))
        if seq and self._legend_on():
            # in accumulate this is the shade-to-frame key, which is the one place a
            # legend on this plot is worth more than the tread it covers
            h, l = ax.get_legend_handles_labels()
            if len(h) > LEGEND_MAX:
                h = h[:LEGEND_MAX] + [Line2D([], [], color="none")]
                l = l[:LEGEND_MAX] + [f"+{len(seq) - LEGEND_MAX} more"]
            # capped here, but it goes through the same helper: an accumulated
            # browser legend must not resize this axes either
            _fit_legend(ax, h, l, loc="upper right")
        if self.embedded and self._frame_note:
            head = head + "\n" + self._frame_note
        ax.set_title(head, fontsize=11, fontweight="bold")
        self._apply_fig_rect_browser(head.count("\n") + 1)
        self.canvas.draw()
        try:
            self.toolbar.update()
        except Exception:
            pass
        self._fill_frame_panel(pos, name, grooves, marked=n_marked, off_view=n_off,
                               path=path, accum=len(seq) if accum else 0)

    def _grooves_for(self, sib):
        """
        v1.2: one frame's *_grooves.csv, read once per folder load. Stepping back and
        forth (and every Tread + Laser step that lands on the same laser frame) used
        to re-open the file each time. The rows are the file's rows, unchanged;
        Reload / a folder change clears this with the other caches.
        """
        c = getattr(self, "_grooves_cache", None)
        if c is None:
            c = self._grooves_cache = {}
        if sib not in c:
            c[sib] = read_frame_grooves(sib) if lp_isfile(sib) else []
        return c[sib]

    def _fill_frame_panel(self, pos, name, grooves, marked=0, off_view=0, path=None,
                          accum=0):
        """The stats line and the per-slot table under the frame plot.

        These stay THIS FRAME's numbers even while accumulating - the panel is headed
        "this frame only", and a statistic pooled over a growing pile of frames would
        be a different measurement wearing the same label.
        """
        tbl = getattr(self, "br_table", None)
        lab = getattr(self, "br_stats", None)
        if tbl is None or lab is None:
            return
        # v1.2: the card is closed by default, and filling it re-reads the profile
        # CSV through pandas on every step. While it is closed only the arguments are
        # kept; opening it (_toggle_diagnostics) fills it for the frame on screen.
        btn = getattr(self, "diag_btn", None)
        if btn is not None and not btn.isChecked():
            self._diag_owed = (pos, name, grooves, marked, off_view, path, accum)
            return
        self._diag_owed = None
        if name is None:
            lab.setText("—")
            tbl.setRowCount(0)
            return

        st = profile_frame_stats(path) if path else None
        parts = [f"<b>{name}</b>"]
        if accum:
            parts.append("accumulating %d frame(s) - the numbers below are this "
                         "frame's own" % accum)
        if st:
            parts.append("%d rows in file · <b>%d plotted</b> · %d dropped (%.1f%%) "
                         "as sentinel / non-finite"
                         % (st["rows"], st["kept"], st["dropped"], st["drop_pct"])
                         if st["rows"] else "file unreadable")
            if st["kept"]:
                parts.append("x %.1f … %.1f mm (span %.1f) · z %.1f … %.1f mm "
                             "(span %.1f)"
                             % (st["x_min"], st["x_max"], st["x_max"] - st["x_min"],
                                st["z_min"], st["z_max"], st["z_max"] - st["z_min"]))
            if math.isfinite(st["median_dx"]):
                parts.append("median sample spacing %.3f mm · largest x gap %.1f mm"
                             % (st["median_dx"], st["max_gap"]))
        g_line = "grooves file: %d rows · %d position(s) marked" % (
            len(grooves), marked)
        if off_view:
            g_line += (" · <span style='color:#d64545'>%d marker(s) with a z outside "
                       "the profile's own range</span>" % off_view)
        if not grooves:
            g_line = "grooves file: none found for this frame"
        parts.append(g_line)
        lab.setText("<br>".join(parts))

        sysd = [math.nan] * N_GROOVES
        for r in self.rows_by_pos.get(pos, []):
            if r.get("file") == name:
                d = r.get("depths") or []
                sysd = list(d) + [math.nan] * (N_GROOVES - len(d))
                break

        n = max(len(grooves), N_GROOVES)
        tbl.setRowCount(n)

        def cell(row, col, val, *, dim=False, flag=False):
            txt = "" if (val is None or (isinstance(val, float)
                                         and not math.isfinite(val))) else (
                "%.3f" % val if isinstance(val, float) else str(val))
            it = QTableWidgetItem(txt)
            it.setTextAlignment(Qt.AlignmentFlag.AlignCenter)
            if dim:
                it.setForeground(QColor("#93a0b4"))
            elif flag and isinstance(val, float) and math.isfinite(val) and not (
                    PLAUSIBLE_MIN <= val <= PLAUSIBLE_MAX):
                it.setForeground(QColor(C_RED))
            tbl.setItem(row, col, it)

        for i in range(n):
            g = grooves[i] if i < len(grooves) else {}
            cell(i, 0, "G%d" % i, dim=True)
            cell(i, 1, g.get("depth", math.nan), flag=True)
            cell(i, 2, g.get("width", math.nan))
            cell(i, 3, g.get("x", math.nan))
            cell(i, 4, g.get("z", math.nan))
            cell(i, 5, sysd[i] if i < len(sysd) else math.nan, flag=True)
