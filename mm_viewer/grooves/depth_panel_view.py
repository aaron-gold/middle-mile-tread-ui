class _DepthPanelViewMixin:
    """GrooveDepthPanel methods, lines 6124-6546 of the v1.8 monolith.
    Mixed into GrooveDepthPanel (see its class line); not used on its own."""

    # ---------------- plot view controls (DISPLAY ONLY) ----------------
    # Nothing in this block changes a measurement. It decides what is drawn and how
    # the mouse behaves; the caches, the depth rows and the summary are untouched.

    @staticmethod
    def _toggle_btn(text, checked, tip):
        b = QPushButton(text)
        b.setObjectName("toggleBtn")
        b.setCheckable(True)
        b.setChecked(bool(checked))
        b.setToolTip(tip)
        return b

    def _build_view_controls(self):
        """The display row under the matplotlib toolbar."""
        self.draw_seg = SegmentedControl(list(DRAW_MODES))
        self.draw_seg.set_current(DRAW_MODE_DEFAULT)
        self.draw_seg.setToolTip(
            "How each profile is drawn.\n"
            "Points = markers only, no connecting segments - the honest view of what "
            "the laser actually returned.")

        # Frame selector button - replaces the old simple Legend toggle
        # Shows all visible frames in the legend (no cap), with add/remove capability
        self.frame_select_btn = QPushButton("Frame selector…")
        self.frame_select_btn.setMinimumWidth(130)
        self.frame_select_btn.setToolTip(
            "Select which frames to display on the plot and in the legend.\n"
            "Choose accumulation order: Rising order (frame_0→N) or Custom.\n"
            "The legend shows ALL selected frames with no truncation.")
        self.frame_select_btn.clicked.connect(self._on_frame_selector_clicked)
        self.draw_seg.changed.connect(self._on_view_changed)

        self.view_hint = QLabel("")
        self.view_hint.setObjectName("hintText")
        # allow_shrink stops a long hint from setting the window's minimum width, but
        # NOT allow_shrink(): an Ignored size policy makes the label clip instead of
        # asking for its width, and the FlowLayout then never learns it does not fit,
        # so the hint was sliced off mid-word at the right edge. With a real sizeHint
        # and a cap the row simply wraps it onto its own line. The modifier keys live
        # in the tooltip.
        self.view_hint.setMaximumWidth(620)
        self.view_hint.setToolTip(
            "wheel = zoom at the cursor  ·  Shift+wheel = x only  ·  "
            "Ctrl+wheel = z only\n"
            "left-drag = pan  ·  double-click a subplot = maximise / restore  ·  "
            "Esc = restore\n"
            "r = reset the view (same as the toolbar's home button)")
        self._update_view_hint()

        return flow_row(self._build_mode_widgets()
                        + [field_label("Draw"), self.draw_seg, self.frame_select_btn,
                           self.view_hint])

    def _build_readout(self):
        """The live x / z / frame line under the canvas."""
        self.readout = QLabel("")
        self.readout.setObjectName("plotReadout")
        self.readout.setTextInteractionFlags(
            Qt.TextInteractionFlag.TextSelectableByMouse)
        allow_shrink(self.readout, 220)
        self.readout.setToolTip(
            "Live cursor readout. x and z are the values of the nearest plotted "
            "sample -\nread straight off the profile, with nothing derived from it.")
        return self.readout

    def _draw_style(self):
        """ax.plot() kwargs for the selected draw mode."""
        mode = self.draw_seg.current() if getattr(self, "draw_seg", None) else DRAW_LINES
        if mode == DRAW_POINTS:
            return {"linestyle": "none", "marker": ".", "markersize": 2.5,
                    "markeredgewidth": 0}
        if mode == DRAW_BOTH:
            return {"linewidth": 1, "marker": ".", "markersize": 2.5,
                    "markeredgewidth": 0}
        return {"linewidth": 1}

    # Not switchable from the UI any more - the constant is the whole story.
    def _break_gaps_on(self):
        return GAP_BREAK_ON

    def _legend_on(self):
        # In frame browser mode, always show legend (with accumulation shading)
        # In overview mode, legend is always shown with the frame selector
        return True

    def _set_readout(self, text):
        r = getattr(self, "readout", None)
        if r is not None:
            r.setText(text or "")

    def _update_view_hint(self):
        h = getattr(self, "view_hint", None)
        if h is None:
            return
        if getattr(self, "embedded", False):
            h.setText("frames follow the Tread + Laser timeline  ·  wheel = zoom  ·  "
                      "drag = pan  ·  r = reset")
        elif self._browser_mode():
            h.setText("◀ ▶ or Ctrl+Alt+←/→ = step frames  ·  wheel = zoom  ·  "
                      "drag = pan  ·  r = reset")
        elif self._max_pos:
            h.setText(f"{self._max_pos} maximised  ·  double-click or Esc to restore")
        else:
            h.setText("wheel = zoom  ·  drag = pan  ·  double-click = maximise  ·  "
                      "r = reset")

    def _on_view_changed(self, *_):
        """A display switch moved - redraw from the cache, no disk, no re-filtering."""
        self.render()

    def _toggle_maximize(self, pos):
        """Double-click / Esc: one subplot full canvas, or back to the 2x2 grid."""
        if not MATPLOTLIB_AVAILABLE or self.fig is None:
            return
        if self._browser_mode():
            return                          # the browser is already a single axes
        new = None if (pos is None or pos == self._max_pos) else pos
        if new == self._max_pos:
            return
        self._max_pos = new
        self._update_view_hint()
        self.render()

    # ---------------- frame selector (overview mode) ----------------
    def _get_available_frames(self):
        """Extract all frame names from the current cache (all positions)."""
        all_frames = []
        cache = self._filt_cache if self._filtered() else self._raw_cache
        if cache:
            for pos in POS_ORDER:
                for name, x, z in cache.get(pos, []):
                    if name not in all_frames:
                        all_frames.append(name)
        return sorted(all_frames)

    def _on_frame_selector_clicked(self):
        """Open frame selector dialog to choose which frames to display."""
        available = self._get_available_frames()
        if not available:
            QMessageBox.information(self, "Frame selector",
                                   "No frames available. Load a groove folder first.")
            return

        dialog = FrameSelectorDialog(available, self._selected_frames or available,
                                     parent=self)
        if dialog.exec() == QDialog.DialogCode.Accepted:
            self._selected_frames = dialog.get_selected_frames()
            self._accum_mode = dialog.get_accumulation_mode()
            if not self._selected_frames:
                self._selected_frames = None  # None = show all
            self.render()

    # ---------------- depth table ----------------
    def _visible_units(self):
        sel = self.unit_combo.currentText()
        return list(POS_ORDER) if sel not in POS_ORDER else [sel]

    def _meas_visible(self):
        """True while the per-profile measurement section is open."""
        b = getattr(self, "show_table_btn", None)
        # the button's checked state, NOT table_card.isVisible(): a panel sitting in a
        # non-current tab is not visible, and the table would then never fill
        return b is not None and b.isChecked()

    def _on_unit_changed(self, *_):
        """Unit drives the summary as well as the rows."""
        self._fill_summary()
        self._fill_table()

    # splitter children, in order, with the height each one opens to
    _SPLIT_OPEN_H = (0, BR_OPEN_H, SUM_OPEN_H, MEAS_OPEN_H)

    def _resize_split(self):
        """Give every open card its slice and hand the whole remainder to the plot."""
        sp = getattr(self, "split", None)
        if sp is None or sp.count() < len(self._SPLIT_OPEN_H):
            return
        total = sum(sp.sizes()) or sp.height()
        want = list(self._SPLIT_OPEN_H)
        for i in range(1, len(want)):
            if not sp.widget(i).isVisible():
                want[i] = 0
        want[0] = max(PLOT_MIN_H, total - sum(want[1:]))
        sp.setSizes(want)

    def _toggle_measurements(self, on):
        self.show_table_btn.setText(MEAS_BTN_HIDE if on else MEAS_BTN_SHOW)
        self._update_meas_btn_count()
        if self.table_card is not None:
            self.table_card.setVisible(on)
        self._resize_split()
        if on:
            self._fill_table()

    def _toggle_summary(self, on):
        self.summary_btn.setText(SUM_BTN_HIDE if on else SUM_BTN_SHOW)
        card_ = getattr(self, "summary_card", None)
        if card_ is not None:
            card_.setVisible(on)
        self._resize_split()
        if on:
            self._fill_summary()

    def _toggle_diagnostics(self, on):
        self.diag_btn.setText(DIAG_BTN_HIDE if on else DIAG_BTN_SHOW)
        card_ = getattr(self, "browser_card", None)
        if card_ is not None:
            card_.setVisible(on)
        self._resize_split()
        owed = getattr(self, "_diag_owed", None)
        if on and owed is not None:
            self._fill_frame_panel(*owed)

    def _update_meas_btn_count(self):
        b = getattr(self, "show_table_btn", None)
        if b is None:
            return
        total = sum(len(self.rows_by_pos.get(p, [])) for p in self._visible_units())
        base = MEAS_BTN_HIDE if b.isChecked() else MEAS_BTN_SHOW
        b.setText(f"{base}  ·  {total} rows" if total else base)

    def _empty_frames(self, pos):
        """
        (empty, total) profile files at one wheel position.

        EMPTY means the file parsed to zero usable samples: every row is the laser's
        no-data sentinel (-1.797e308), or the file has no x/z columns at all. It is
        NOT the same as "dropped by the filter" - the filter rejects a profile it
        could read and judged implausible, and that is already reported separately.
        An empty frame is the laser having produced nothing for that trigger, which
        is a finding about the SENSOR, and on a test day it is the one worth seeing.

        Read off the raw cache, so it costs nothing and always describes exactly the
        frames on screen (the axle filter included).
        """
        entries = (self._raw_cache or {}).get(pos) or []
        empty = sum(1 for _n, x, _z in entries if getattr(x, "size", 0) == 0)
        return empty, len(entries)

    def _fill_summary(self):
        """The headline block - always rendered, whatever the table is doing."""
        units = self._visible_units()

        lines = []
        for pos in units:
            s = self.stats_by_pos.get(pos)
            n_empty, n_seen = self._empty_frames(pos)
            empty_txt = ""
            if n_empty:
                empty_txt = (f"  <span style='color:{C_RED};font-weight:700'>⚠ "
                             f"{n_empty} of {n_seen} frame(s) carry no laser sample "
                             f"at all</span>")
            if not s:
                if n_seen:
                    lines.append(f"<b>{pos}</b> — {n_seen} profile file(s), no "
                                 f"grooves_full depths{empty_txt}")
                continue
            if s["frames"] == 0:
                lines.append(f"<b>{pos}</b> — no profile files")
                continue
            rng = ("—" if math.isnan(s["min"]) else
                   f"min {s['min']:.2f} / median {s['median']:.2f} / "
                   f"mean {s['mean']:.2f} / max {s['max']:.2f} mm")
            warn = ""
            if s["n_outliers"]:
                warn += (f"  <span style='color:{C_RED};font-weight:700'>⚠ {s['n_outliers']} "
                         f"outside {PLAUSIBLE_MIN:g}–{PLAUSIBLE_MAX:g} mm</span>")
            if s["unmatched"]:
                warn += (f"  <span style='color:{C_RED};font-weight:700'>⚠ {s['unmatched']} "
                         f"profile(s) with no grooves_full row</span>")
            if s.get("full_fallback"):
                warn += (f"  <span style='color:{C_ORANGE_LO};font-weight:700'>⚠ "
                         f"grooves_full.csv empty — {s.get('from_frame', 0)} profile(s) "
                         f"read from their own frame_N_grooves.csv</span>")
            if s.get("dropped"):
                warn += (f"  <span style='color:{C_ORANGE_LO};font-weight:700'>⚠ "
                         f"{s['dropped']} profile(s) dropped by filter — excluded from "
                         f"these statistics, still listed below</span>")
            lines.append(
                f"<b>{pos}</b> — {s['frames']} frames · {s['frames_with_depth']} with depth · "
                f"{s['n_depths']} depths · {rng} · "
                f"<span style='color:{C_TEXT_DIM}'>{s['full_files']} grooves_full file(s), "
                f"{s['full_rows']} rows</span>{warn}{empty_txt}")
        self.summary_label.setText("<br>".join(lines) if lines else "—")
        self._update_meas_btn_count()

    def _fill_table(self, *_):
        """Rows are only built while the measurement section is open."""
        if self.table is None:
            return
        if not self._meas_visible():
            self._table_dirty = True            # refill when it is next opened
            return
        self._table_dirty = False
        units = self._visible_units()
        hide_nan = self.hide_nan_cb.isChecked()

        rows = []
        for pos in units:
            for r in self.rows_by_pos.get(pos, []):
                if hide_nan and r["n_valid"] == 0:
                    continue
                rows.append((pos, r))

        # ResizeToContents re-measures the whole column on EVERY setItem, which turns
        # the fill into O(rows x cols) layout passes - 13.5 s for a filtered refill with
        # live styling. Populate with the sizing frozen, then size once at the end.
        hh = self.table.horizontalHeader()
        self.table.setUpdatesEnabled(False)
        hh.setSectionResizeMode(QHeaderView.ResizeMode.Fixed)
        self.table.setSortingEnabled(False)
        self.table.setRowCount(len(rows))
        mono = QFont("Consolas"); mono.setPixelSize(FS_SMALL)
        for i, (pos, r) in enumerate(rows):
            def put(col, text, key=None, *, dim=False, bold=False, num=False,
                    red=False, flag=False):
                it = SortCell(text, key if key is not None else text, i)
                if num:
                    it.setTextAlignment(Qt.AlignmentFlag.AlignRight |
                                        Qt.AlignmentFlag.AlignVCenter)
                    it.setFont(mono)
                if dim:
                    it.setForeground(QColor("#9aa8bd"))
                if red:
                    it.setForeground(QColor(C_RED))
                if flag:
                    it.setForeground(QColor("#ffffff"))
                    it.setBackground(QColor(C_RED))
                if bold:
                    f = it.font(); f.setBold(True); it.setFont(f)
                self.table.setItem(i, col, it)

            # sorting column 0 by the position index keeps the natural order
            put(0, pos, POS_ORDER.index(pos), bold=True)
            if r.get("dropped"):
                put(1, f"{r['file']}   ·  dropped by filter: {r['drop_reason']}",
                    r["file"], dim=True)
                it = self.table.item(i, 1)
                if it is not None:
                    it.setToolTip("Not plotted in Filtered mode and excluded from the "
                                  "summary statistics. The depths below are unchanged, "
                                  "exactly as the system reported them.")
            else:
                # v1.7: red = no depth at all; a per-frame row is a real depth
                nodepth = r.get("source", DEPTH_SRC_NONE) == DEPTH_SRC_NONE
                put(1, r["file"] + ("   ·  per-frame CSV"
                                    if r.get("source") == DEPTH_SRC_FRAME else ""),
                    r["file"], dim=nodepth, red=nodepth)
                if r.get("source") == DEPTH_SRC_FRAME:
                    it = self.table.item(i, 1)
                    if it is not None:
                        it.setToolTip("This unit's grooves_full.csv is empty, so the "
                                      "depths are this frame's own *_grooves.csv "
                                      "Depth column (row k = G(k+1)).")
            put(2, r["ts"] or "—", int(r["ts"]) if r["ts"].isdigit() else None,
                num=True, dim=True)
            for g in range(N_GROOVES):
                d = r["depths"][g]
                if math.isnan(d):
                    put(3 + g, "NaN", math.nan, dim=True, num=True)
                else:
                    put(3 + g, f"{d:.3f}", d, num=True, bold=True,
                        flag=(d < PLAUSIBLE_MIN or d > PLAUSIBLE_MAX))
            put(3 + N_GROOVES, str(r["n_valid"]), r["n_valid"], num=True,
                dim=(r["n_valid"] == 0))
        hh.setSectionResizeMode(QHeaderView.ResizeMode.ResizeToContents)
        hh.setSectionResizeMode(1, QHeaderView.ResizeMode.Stretch)
        self.table.setUpdatesEnabled(True)
        self.table.setSortingEnabled(True)
        self.table.sortItems(0, Qt.SortOrder.AscendingOrder)
        self.table.scrollToTop()

        total = sum(len(self.rows_by_pos.get(p, [])) for p in units)
        self.count_label.setText(f"{len(rows)} of {total} frames shown")

    def _export_depths(self):
        path, _f = QFileDialog.getSaveFileName(self, "Export groove depths",
                                               "groove_depths.csv", "CSV (*.csv)")
        if not path:
            return
        if not path.lower().endswith(".csv"):
            path += ".csv"
        try:
            with open(path, "w", newline="", encoding="utf-8") as fh:
                w = csv.writer(fh)
                w.writerow(["Unit", "Profile file", "sensor_timestamp_msec", "timestamp_msec"]
                           + [f"G{i + 1}" for i in range(N_GROOVES)]
                           + ["n_valid", "matched", "filter_mode", "filter_status",
                              "depth_source"])
                mode = FILTER_MODE_FILT if self._filtered() else FILTER_MODE_RAW
                for pos in POS_ORDER:
                    for r in self.rows_by_pos.get(pos, []):
                        status = (f"dropped: {r['drop_reason']}" if r.get("dropped")
                                  else "kept")
                        w.writerow([pos, r["file"], r["sensor_ts"], r["ts"]]
                                   + ["NaN" if math.isnan(d) else f"{d:.3f}"
                                      for d in r["depths"]]
                                   + [r["n_valid"], "yes" if r["matched"] else "no",
                                      mode, status,
                                      {DEPTH_SRC_FULL: "grooves_full",
                                       DEPTH_SRC_FRAME: "frame_grooves"}.get(
                                          r.get("source"), "none")])
            QMessageBox.information(self, "Export", f"Saved:\n{path}")
        except Exception as e:
            QMessageBox.warning(self, "Export failed", str(e))

    def _save(self):
        if not MATPLOTLIB_AVAILABLE or self.fig is None:
            QMessageBox.warning(self, "matplotlib missing", "pip install matplotlib")
            return
        path, _f = QFileDialog.getSaveFileName(self, "Save groove plot", "groove_profiles.png",
                                               "PNG (*.png)")
        if not path:
            return
        if not path.lower().endswith(".png"):
            path += ".png"
        try:
            self.fig.savefig(path, dpi=150, bbox_inches="tight")
            QMessageBox.information(self, "Save", f"Saved:\n{path}")
        except Exception as e:
            QMessageBox.warning(self, "Save failed", str(e))
