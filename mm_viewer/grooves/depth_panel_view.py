    BR_OPEN_H, DIAG_BTN_HIDE, DIAG_BTN_SHOW, DRAW_BOTH, DRAW_LINES, DRAW_MODE_DEFAULT,
    DRAW_MODES, DRAW_POINTS, FILTER_MODE_FILT, FILTER_MODE_RAW, GAP_BREAK_ON,
