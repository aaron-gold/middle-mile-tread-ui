"""Depth panel figure.

Part of the mm_viewer package - moved verbatim from MiddleMile_GUI v1.8,
lines 5357-5600. Imports generated by the split (2026-10-18)."""


from mm_viewer.common import SCIPY_AVAILABLE
from mm_viewer.config import (
    _fit_legend, CAP_LEGEND, FILT_MAX_PTP, FILT_MAX_STD, FILT_MIN_POINTS, FILT_THRESHOLD,
    FILT_WINDOW
)
from mm_viewer.grooves.loader import annotate_drops, POS_ORDER
from mm_viewer.grooves.profile_inspect import break_profile_gaps


class _DepthPanelFigureMixin:
    """GrooveDepthPanel methods, lines 5357-5600 of the v1.8 monolith.
    Mixed into GrooveDepthPanel (see its class line); not used on its own."""

    # ---------------- drawing ----------------
    def _new_axes(self):
        self.fig.clear()
        insp = getattr(self, "inspector", None)
        if insp is not None:
            # every axes and cursor artist it held died with the figure
            insp.reset()
        mx = getattr(self, "_max_pos", None)
        if mx in POS_ORDER:
            # one subplot, full canvas. The other three positions are reported as
            # absent so the draw loop skips them - no profile and no depth row is
            # dropped, only the axes it would have been drawn on.
            return {mx: self.fig.subplots(1, 1)}
        axes = self.fig.subplots(2, 2)
        return {"FRONT LEFT": axes[0, 0], "FRONT RIGHT": axes[0, 1],
                "REAR LEFT": axes[1, 0], "REAR RIGHT": axes[1, 1]}

    # title block geometry, in PIXELS from the top of the figure
    _T_TITLE_PX, _T_SUB_PX, _T_RECT_PX = 16.0, 38.0, 58.0

    def _title_positions(self):
        """Title/subtitle/rect as figure fractions for the CURRENT canvas height.

        These were fixed fractions (0.985 / 0.94 / 0.925). A fraction keeps a constant
        proportion, so the two heading lines converge and finally overlap as the pane
        gets shorter - which is exactly what opening the measurement table does. Held
        at a constant pixel offset they stay legible at any height.
        """
        h_px = max(self.fig.get_size_inches()[1] * self.fig.dpi, 140.0)
        return (1.0 - self._T_TITLE_PX / h_px,
                1.0 - self._T_SUB_PX / h_px,
                1.0 - self._T_RECT_PX / h_px)

    def _apply_fig_rect_full(self):
        """No reserved heading band - the axes title carries the whole caption.

        The overview keeps its figure suptitle; the browser cannot afford one. The
        band is reserved in PIXELS, so on a short canvas the suptitle, the subtitle
        and the axes title land on top of each other and on the data.
        """
        self._title_txt = self._sub_txt = None
        try:
            self.fig.set_layout_engine("tight", rect=(0, 0, 1, 1))
        except Exception:
            self.fig.tight_layout(rect=(0, 0, 1, 1))

    # v1.2: the frame browser's margins, in PIXELS. tight_layout measured every tick
    # label and title on every frame step - ~60 ms of a ~100 ms step. A single axes
    # with a known title needs no measuring: fixed pixel margins give the same
    # picture, and they are re-applied on resize (see _reflow_titles).
    _BR_M_LEFT, _BR_M_RIGHT, _BR_M_BOTTOM = 70.0, 16.0, 48.0
    _BR_M_TOP_PAD, _BR_M_LINE = 12.0, 18.0

    def _apply_fig_rect_browser(self, title_lines=1):
        self._title_txt = self._sub_txt = None
        self._br_title_lines = max(1, int(title_lines))
        w_in, h_in = self.fig.get_size_inches()
        w_px = max(w_in * self.fig.dpi, 200.0)
        h_px = max(h_in * self.fig.dpi, 160.0)
        top_px = self._BR_M_TOP_PAD + self._BR_M_LINE * self._br_title_lines
        try:
            self.fig.set_layout_engine("none")
        except Exception:
            pass
        self.fig.subplots_adjust(
            left=min(self._BR_M_LEFT / w_px, 0.4),
            right=max(1.0 - self._BR_M_RIGHT / w_px, 0.6),
            bottom=min(self._BR_M_BOTTOM / h_px, 0.4),
            top=max(1.0 - top_px / h_px, 0.55))

    def _apply_fig_rect(self, top):
        # Re-run the layout on EVERY draw, not once at the initial figsize: Qt resizes
        # the canvas to the pane afterwards and subplotpars are FRACTIONS, so a layout
        # computed for a 700 px figure crushes the subplots in a shorter pane.
        try:
            self.fig.set_layout_engine("tight", rect=(0, 0, 1, top))
        except Exception:                   # matplotlib < 3.6 has no layout engine API
            self.fig.tight_layout(rect=(0, 0, 1, top))

    def _finish_fig(self, sub_t):
        t_y, s_y, top = self._title_positions()
        self._title_txt = self.fig.suptitle(
            "Tire Laser Profiles (Groove Depth · LMI)",
            fontsize=14, fontweight="bold", y=t_y, va="top")
        self._sub_txt = self.fig.text(0.5, s_y, sub_t, ha="center", va="top",
                                      fontsize=10, color="#333333")
        self._apply_fig_rect(top)

    def _reflow_titles(self):
        """Re-seat the heading for the current canvas height (cheap - no replot)."""
        if self.fig is None:
            return
        if (getattr(self, "_title_txt", None) is None
                and getattr(self, "_br_title_lines", None) and self._browser_mode()):
            # browser: pixel margins are fractions of the canvas, so re-seat them
            self._apply_fig_rect_browser(self._br_title_lines)
            self.canvas.draw_idle()
            return
        if getattr(self, "_title_txt", None) is None:
            return
        t_y, s_y, top = self._title_positions()
        try:
            self._title_txt.set_y(t_y)
            self._sub_txt.set_y(s_y)
        except RuntimeError:                # texts belong to a cleared figure
            return
        self._apply_fig_rect(top)
        self.canvas.draw_idle()

    def _draw_placeholder(self, msg):
        for pos, ax in self._new_axes().items():
            ax.set_title(f"{pos} Profile", fontsize=11, fontweight="bold")
            ax.set_xlabel("x (mm)"); ax.set_ylabel("z (mm)")
            ax.grid(True, linestyle="--", alpha=0.6)
            ax.text(0.5, 0.5, msg, ha="center", va="center",
                    transform=ax.transAxes, color="gray")
        self._finish_fig("Filtered · despike + smooth" if self._filtered()
                         else "Unfiltered · raw laser profiles")
        self.canvas.draw()

    def _draw_from_cache(self):
        """Plot straight from the cached arrays - no disk, no pandas, no re-filtering."""
        filtered = self._filtered()
        src = (self._filt_cache if filtered else self._raw_cache) or {}
        dropped = (self._drop_cache if filtered else None) or {p: [] for p in POS_ORDER}
        self.dropped_by_pos = dropped

        if self._browser_mode():
            # depth rows FIRST: the frame panel shows the system depth for the frame
            # on screen, so the rows have to exist before the frame is drawn
            self._finish_cache_draw(filtered, dropped)
            pend = self._pending_frame
            if self.embedded and self._want_empty is not None:
                # the timeline moved to a step with NO laser partner while the load
                # ran: the pane must say so, not draw whatever frame the index held
                self._draw_empty(*self._want_empty)
                return
            if pend is not None:
                # a frame the combined timeline asked for before the load finished
                self._pending_frame = None
                names, _h = self._browser_names(src, pend[0])
                self._br_pos = pend[0]
                if pend[1] not in names:
                    # never a neighbour in its place (see show_frame)
                    self._draw_empty(pend[0], "%s is not in the laser folder"
                                     % pend[1])
                    return
                self._br_idx = names.index(pend[1])
            self._draw_browser(src)
            return

        self._placeholder_owed = False
        if not self.isVisible():
            # v1.2: the 2x2 overview of every profile is the most expensive draw in
            # the app (~0.5-1 s on a 16-09 scan). In a tab nobody is looking at it
            # is postponed to showEvent; the depth rows, summary and table - the
            # DATA - are still brought up to date right now.
            self._draw_owed = True
            self._finish_cache_draw(filtered, dropped)
            return
        self._draw_owed = False

        pos_axes = self._new_axes()
        insp = getattr(self, "inspector", None)
        style = self._draw_style()              # display kwargs only
        gaps = self._break_gaps_on()
        for pos in POS_ORDER:
            ax = pos_axes.get(pos)
            if ax is None:
                continue                        # maximised: only one axes exists
            n_files = len((self._raw_cache or {}).get(pos, []))
            curves = [c for c in src.get(pos, []) if c[1].size]
            # Filter by selected frames if frame selector was used
            if self._selected_frames is not None:
                curves = [c for c in curves if c[0] in self._selected_frames]
            plotted = len(curves)
            for name, x, z in curves:
                # the NaN separators are inserted for DRAWING only; the arrays held
                # in the cache and handed to the inspector are the untouched ones
                px, pz = break_profile_gaps(x, z) if gaps else (x, z)
                ax.plot(px, pz, label=name, alpha=0.85, **style)
            if insp is not None:
                insp.register(ax, pos, curves)
            title = f"{pos} Profile"
            if CAP_LEGEND and plotted:
                title += f"   ({plotted} of {n_files} files with data)"
            n_drop = len(dropped.get(pos, []))
            if filtered and n_drop:
                title += f"   [{n_drop} dropped]"
            ax.set_title(title, fontsize=11, fontweight="bold")
            ax.set_xlabel("x (mm)"); ax.set_ylabel("z (mm)")
            ax.grid(True, linestyle="--", alpha=0.6)
            # Show legend with ALL selected frames (no LEGEND_MAX cap)
            # since the frame selector gives the user explicit control
            if plotted:
                h, l = ax.get_legend_handles_labels()
                # With frame selector, show all frames without truncation. _fit_legend
                # keeps it out of the layout (so the subplots keep their height) and
                # wraps it into columns; no entry is dropped.
                _fit_legend(ax, h, l, loc="upper right")
            if not plotted:
                ax.text(0.5, 0.5, "no profile data", ha="center", va="center",
                        transform=ax.transAxes, color="gray")

        if filtered:
            n_drop = sum(len(v) for v in dropped.values())
            sub_t = (f"Filtered · MAD despike (w={FILT_WINDOW}, thr={FILT_THRESHOLD:g}) "
                     f"+ Savitzky-Golay · {n_drop} profile(s) dropped "
                     f"(std>{FILT_MAX_STD:g} mm, range>{FILT_MAX_PTP:g} mm, "
                     f"<{FILT_MIN_POINTS} pts)")
            if not SCIPY_AVAILABLE:
                sub_t += "  —  scipy missing: smoothing step skipped"
        else:
            sub_t = "Unfiltered · raw laser profiles"
        # An axle with nothing on it says so ONCE, under the title, instead of leaving
        # the reader to infer it from four grids that each say "no profile data". The
        # difference matters: empty grids read as a broken tab, and this is a finding
        # about the scan.
        note = self._empty_axle_note(src)
        if note:
            sub_t = note + "   ·   " + sub_t
        self._finish_fig(sub_t)
        self.canvas.draw()
        # the axes objects were replaced, so Home/Back/Forward still point at the
        # dead ones; update() re-seats the view stack on the axes now on screen
        try:
            self.toolbar.update()
        except Exception:
            pass

        self._finish_cache_draw(filtered, dropped)

    def _finish_cache_draw(self, filtered, dropped):
        """The depth bookkeeping both views share - unchanged, just no longer inline."""
        # system-reported depths for the same frames; in Filtered mode the profiles the
        # filter rejected are flagged in the table and left out of the summary stats
        if self._depth_cache is not None:
            rows, counts = self._depth_cache
            self.rows_by_pos, self.stats_by_pos = annotate_drops(
                rows, counts, dropped if filtered else None)
        self._fill_summary()
        self._fill_table()
        self._set_busy(False)
