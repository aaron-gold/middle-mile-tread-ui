import sys
from PyQt6.QtCore import Qt
from PyQt6.QtWidgets import (
    QAbstractItemView, QCheckBox, QFileDialog, QHBoxLayout, QHeaderView, QLabel,
    QMessageBox, QPushButton, QSizePolicy, QTableWidget, QWidget
)


from mm_viewer.common import axle_mod, MATPLOTLIB_AVAILABLE, PANDAS_AVAILABLE
from mm_viewer.config import (
    DIAG_BTN_SHOW, FILTER_MODE_FILT, MEAS_BTN_SHOW, N_GROOVES, PLAUSIBLE_MAX,
    PLAUSIBLE_MIN, SUM_BTN_SHOW, UNIT_ALL_LABEL, UNIT_FILTER_LABEL
)
from mm_viewer.widgets.controls import ArrowComboBox
from mm_viewer.widgets.layout import allow_shrink, card, field_label, flow_row
from mm_viewer.grooves.loader import POS_ORDER, wheel_pos
from mm_viewer.grooves.worker import (
    _GROOVE_INFLIGHT, _groove_share, _GROOVE_SHARED, _GROOVE_WORKERS, GrooveProfileWorker
)


class _DepthPanelBuildMixin:
    """GrooveDepthPanel methods, lines 5053-5356 of the v1.8 monolith.
    Mixed into GrooveDepthPanel (see its class line); not used on its own."""

    # ---------------- groove-depth card ----------------
    @staticmethod
    def _collapse_btn(text, tip):
        b = QPushButton(text)
        b.setObjectName("collapseBtn")
        b.setCheckable(True)
        b.setChecked(False)
        b.setCursor(Qt.CursorShape.PointingHandCursor)
        b.setToolTip(tip)
        return b

    def _build_toolbar_row(self):
        """The matplotlib toolbar plus everything that used to sit under the plot.

        The nav toolbar is a handful of icons on the left of a full-width bar, so the
        collapse toggles, the Unit filter and the export ride in the empty half of it
        instead of costing the panel a row of its own. Every panel they open starts
        collapsed. The Unit filter and the CSV export stay OUT of the cards - a
        collapsed section must never put the numbers out of reach.
        """
        self.diag_btn = self._collapse_btn(
            DIAG_BTN_SHOW,
            "This frame's own diagnostics - how much of the profile file survived to "
            "the plot,\nand the 10 groove slots it reports beside the "
            "grooves_full depth for the same frame.\n"
            "Frame browser only.")
        self.diag_btn.setEnabled(False)                 # browser view only
        self.diag_btn.toggled.connect(self._toggle_diagnostics)

        self.summary_btn = self._collapse_btn(
            SUM_BTN_SHOW,
            "Frame counts and min / median / mean / max per wheel position, as "
            "reported in\n*_grooves_full.csv. Collapsed by default so the profiles "
            "get the panel.")
        self.summary_btn.toggled.connect(self._toggle_summary)

        self.show_table_btn = self._collapse_btn(
            MEAS_BTN_SHOW,
            "The per-profile groove depths - one row per profile file.\n"
            "Collapsed by default so the profile plot gets the full panel height.")
        self.show_table_btn.toggled.connect(self._toggle_measurements)

        self.unit_combo = ArrowComboBox()
        self.unit_combo.addItems([UNIT_ALL_LABEL] + POS_ORDER)
        self.unit_combo.setMinimumWidth(150)
        # Unit filters the SUMMARY as well as the table, so it belongs out here and
        # not inside the collapsed measurement section.
        # v1.2: labelled for what it does - it was "Unit", beside the plot's own
        # "LMI unit", and the two read as one control shown twice.
        self.unit_combo.setToolTip(
            "Which wheel(s) the two TEXT sections list:\n"
            "  ▸ Groove depth summary   and   ▸ Per-profile measurements.\n"
            "It does NOT change the plot (the plot follows 'Browse wheel' / the "
            "timeline)\nand it does NOT change Export depths CSV (always all four).")
        self.unit_combo.currentIndexChanged.connect(self._on_unit_changed)

        self.export_btn = QPushButton("Export depths CSV")
        self.export_btn.setToolTip("Exports every row for ALL four wheel positions.\n"
                                   "It ignores the 'Summary / table' wheel filter and "
                                   "the table's own row filter, and works whether or "
                                   "not\nthe table is on screen.")
        self.export_btn.clicked.connect(self._export_depths)

        # the toolbar's own coordinate read-out is dropped: it repeats what the
        # readout under the canvas says, and it claims the whole empty half of the bar
        # hide the ACTION, not the label: the toolbar holds it in a QWidgetAction,
        # which shows its widget again on the next re-parent or re-layout
        try:
            loc = self.toolbar.locLabel
            for act in self.toolbar.actions():
                if getattr(act, "defaultWidget", None) and act.defaultWidget() is loc:
                    act.setVisible(False)
                    break
            else:
                loc.setVisible(False)
        except Exception:
            pass
        self.toolbar.setSizePolicy(QSizePolicy.Policy.Maximum,
                                   QSizePolicy.Policy.Preferred)

        w = QWidget()
        w.setLayout(flow_row([self.toolbar,
                              self.diag_btn, self.summary_btn, self.show_table_btn,
                              field_label(UNIT_FILTER_LABEL), self.unit_combo,
                              self.export_btn]))
        self.toolbar_row = w
        return w

    def _build_summary_card(self):
        """The headline numbers. Collapsed on open; the strip toggle reopens it."""
        c, v = card("Groove depth summary  ·  grooves_full.csv  (system-reported)")
        self.summary_label = QLabel("—")
        self.summary_label.setObjectName("depthSummary")
        self.summary_label.setWordWrap(True)
        # word wrap alone does not stop a long summary line from setting the panel's
        # minimum WIDTH; it wraps only once it is allowed to be narrow
        allow_shrink(self.summary_label, 220)
        v.addWidget(self.summary_label)
        return c

    def _build_table_card(self):
        """The per-profile measurements - built once, shown only on demand."""
        c, v = card("Per-profile measurements  ·  grooves_full.csv  (system-reported)")

        ctl = QHBoxLayout(); ctl.setSpacing(8)
        self.hide_nan_cb = QCheckBox("Hide frames with no depth")
        self.hide_nan_cb.stateChanged.connect(self._fill_table)
        ctl.addWidget(self.hide_nan_cb)
        ctl.addStretch(1)
        self.count_label = QLabel("")
        self.count_label.setObjectName("hintText")
        ctl.addWidget(self.count_label)
        v.addLayout(ctl)

        heads = (["Unit", "Profile file", "timestamp_msec"]
                 + [f"G{i + 1}" for i in range(N_GROOVES)] + ["# valid"])
        self.table = QTableWidget(0, len(heads))
        self.table.setObjectName("depthTable")
        self.table.setHorizontalHeaderLabels(heads)
        self.table.verticalHeader().setVisible(False)
        self.table.setAlternatingRowColors(True)
        self.table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        self.table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        hh = self.table.horizontalHeader()
        hh.setSectionResizeMode(QHeaderView.ResizeMode.ResizeToContents)
        hh.setSectionResizeMode(1, QHeaderView.ResizeMode.Stretch)
        # only consult the first 40 rows when auto-sizing: the default consults up to
        # 1000, which on an 800-frame scan costs seconds every time the table refills
        hh.setResizeContentsPrecision(40)
        self.table.setMinimumHeight(120)
        self.table.setToolTip(
            "Depths as reported by the system in *_grooves_full.csv.\n"
            "NaN = the laser reported no depth for that groove slot.\n"
            f"Red = outside {PLAUSIBLE_MIN:g}-{PLAUSIBLE_MAX:g} mm (display flag only, "
            "not an acceptance criterion). No value is filtered or edited.")
        v.addWidget(self.table, 1)
        return c

    def _browse(self):
        d = QFileDialog.getExistingDirectory(self, "Select tire_laser_groove_data folder",
                                             self.folder or "")
        if d:
            self.folder = d
            self.path_label.setText(d)
            self._invalidate_cache()
            self.render()

    @staticmethod
    def _wheel_pos(fn):
        # delegates to the module-level function so the two never drift apart
        return wheel_pos(fn)

    def _filtered(self):
        """True when the Filtered profile view is selected."""
        cb = getattr(self, "filter_combo", None)
        return bool(cb) and cb.currentText() == FILTER_MODE_FILT

    def _empty_axle_note(self, src):
        """
        The subtitle line for a selected axle that carries no laser profile, or "".

        Only for an AXLE selection: "All axles" with nothing in it is a scan with no
        laser data, which the four per-position captions already state, and saying it
        twice in different words reads as two different problems.
        """
        bucket = self._axle_bucket
        if not bucket or bucket == getattr(axle_mod, "TRASH", "Trash"):
            return ""
        if any(c[1].size for curves in (src or {}).values() for c in curves):
            return ""
        return ("%s carries no laser profile in this scan — the split resolved "
                "the axle, the laser produced nothing for it" % bucket)

    def render(self, *_):
        """
        Show the current mode. A cached folder redraws immediately; otherwise the
        parse/filter runs in GrooveProfileWorker behind the busy spinner and the
        drawing happens in _draw_from_cache() when the worker reports back.
        """
        if not (MATPLOTLIB_AVAILABLE and PANDAS_AVAILABLE and self.fig is not None):
            return
        if self._worker is not None or self._closing:      # a pass is already running
            return
        if self.embedded and not self.folder:
            return                      # embedded: nothing to read until a wheel opens
        if self._cache_folder != self._cache_key():
            self._invalidate_cache()

        filtered = self._filtered()
        # v1.2: the Laser Grooves tab and the Tread + Laser tab read the SAME folder
        # with the same axle split - each used to parse all ~1000 profile files on its
        # own. A finished read is shared; a read still running is joined.
        self._adopt_shared()
        if not self._needs_work(filtered):
            self._draw_from_cache()
            return
        other = _GROOVE_INFLIGHT.get(self._shared_key())
        if other is not None and (other.filtered or not filtered):
            try:
                running = other.isRunning()
            except RuntimeError:
                running = False
            if running:
                self._attach_worker(other)
                return

        # First pass only: put empty axes up so the tab never looks broken. On a mode
        # switch the previous plot stays on screen under the spinner - redrawing it as
        # a placeholder costs ~1 s on a big scan and shows the user nothing.
        if self._raw_cache is None:
            # v1.2: a hidden tab (every tab while a scan is being built) draws its
            # placeholder when it is first shown - ~0.4 s of 2x2 layout nobody sees
            if self.isVisible():
                self._draw_placeholder("loading…")
            else:
                self._placeholder_owed = True
        self._set_busy(True, "Reading laser profiles…")
        w = GrooveProfileWorker(self.folder or "", filtered,
                                self._raw_cache, self._depth_cache,
                                keep=self._axle_keep())
        self._worker = w
        self._worker_shared = False
        _GROOVE_WORKERS.add(w)
        key = self._shared_key()
        _GROOVE_INFLIGHT[key] = w
        w.phase.connect(self._on_phase)
        w.done.connect(self._on_worker_done)
        w.failed.connect(self._on_worker_failed)
        w.finished.connect(self._on_worker_finished)
        # plain lambdas, not bound methods: these must still run if the panel is
        # gone, otherwise the finished thread would sit in _GROOVE_WORKERS forever
        w.finished.connect(lambda t=w: _GROOVE_WORKERS.discard(t))
        w.done.connect(lambda r, f, d, dp, k=key: _groove_share(k, r, f, d, dp))
        w.finished.connect(lambda t=w, k=key: _GROOVE_INFLIGHT.pop(k, None)
                           if _GROOVE_INFLIGHT.get(k) is t else None)
        w.start()

    # ---------------- v1.2: one read per folder, shared between panels ----------------
    def _shared_key(self):
        return (self.folder, self._axle_bucket, id(self.axle_index))

    def _adopt_shared(self):
        """Take whatever a finished read of the same folder + split already holds."""
        sh = _GROOVE_SHARED.get(self._shared_key())
        if not sh:
            return
        self._cache_folder = self._cache_key()
        if self._raw_cache is None and sh.get("raw") is not None:
            self._raw_cache = sh["raw"]
        if self._depth_cache is None and sh.get("depth") is not None:
            self._depth_cache = sh["depth"]
        if self._filt_cache is None and sh.get("filt") is not None:
            self._filt_cache, self._drop_cache = sh["filt"], sh["drop"]

    def _attach_worker(self, w):
        """Wait on another panel's read of the same data instead of starting a copy."""
        self._worker = w
        self._worker_shared = True           # not ours: never interrupted by us
        w.phase.connect(self._on_phase)
        w.done.connect(self._on_worker_done)
        w.failed.connect(self._on_worker_failed)
        w.finished.connect(self._on_worker_finished)
        if self._raw_cache is None and self.isVisible():
            self._draw_placeholder("loading…")
        elif self._raw_cache is None:
            self._placeholder_owed = True
        self._set_busy(True, "Reading laser profiles…")

    def _needs_work(self, filtered):
        return (self._raw_cache is None or self._depth_cache is None
                or (filtered and self._filt_cache is None))

    def _on_phase(self, text):
        b = getattr(self, "busy", None)
        if b is not None and not b.isHidden():
            b.set_phase(text, force=False)

    def _on_worker_done(self, raw, filt, dropped, depth):
        self._cache_folder = self._cache_key()
        self._raw_cache = raw
        self._depth_cache = depth
        if filt is not None:
            self._filt_cache, self._drop_cache = filt, dropped
        if self._needs_work(self._filtered()):
            # the mode was switched while this pass ran: drawing it now would show the
            # stale mode and flick the spinner off and on. _on_worker_finished starts
            # the pass for the mode that is actually selected.
            return
        self._draw_from_cache()

    def _on_worker_failed(self, tb):
        self._set_busy(False)
        sys.stderr.write(tb + "\n")
        self._draw_placeholder("could not read the profiles — see the console")
        QMessageBox.warning(self, "Groove profiles",
                            "The laser profiles could not be read.\n\n"
                            + tb.strip().splitlines()[-1])

    def _on_worker_finished(self):
        self._worker = None
        # the mode may have been switched while the pass was running
        if not self._closing and self._needs_work(self._filtered()):
            self._retry_timer.start(0)
