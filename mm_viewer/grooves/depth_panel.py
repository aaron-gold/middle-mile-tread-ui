    # ---------------- embedded (Tread + Laser tab) ----------------
    def _setup_embedded(self):
        """Browser view, whole scan, no own navigation. See __init__."""
        for w in (self.axle_combo, self.browse_btn,
                  getattr(self, "frame_select_btn", None)):
            if w is not None:
                w.setVisible(False)
        seg = getattr(self, "mode_seg", None)
        if seg is None:
            return                                   # matplotlib missing
        # Height is the scarce thing when this shares a page with the tread frame:
        # the source card folds into the toolbar row (same controls, one row less),
        # the key hint moves to its tooltip, and the diagnostics card opens shorter.
        row = getattr(self, "toolbar_row", None)
        if row is not None and row.layout() is not None:
            row.layout().addWidget(self.save_btn)
            self.bar_card.setVisible(False)
        # Draw mode and Profile filter join the frame bar (Frame n/N, Accumulate,
        # Ghost) - the same controls, two rows fewer above the profile
        bar_lay = self.browser_bar.layout()
        draw_lbl = next((l for l in self.findChildren(QLabel, "fieldLabel")
                         if l.text() == "Draw"), None)
        at = max(bar_lay.count() - 1, 0)          # before the trailing stretch
        for w in [x for x in (draw_lbl, self.draw_seg) if x is not None] + [
                field_label("Profile filter"), self.filter_combo]:
            bar_lay.insertWidget(at, w)
            at += 1
        self.filter_combo.setMinimumWidth(190)
        if getattr(self, "view_hint", None) is not None:
            self.view_hint.setVisible(False)
        self._SPLIT_OPEN_H = (0, 170, SUM_OPEN_H, MEAS_OPEN_H)
        seg.set_current(VIEW_BROWSER)
        seg.setVisible(False)
        # the "View" field label sits right before the segmented control
        for lbl in self.findChildren(QLabel, "fieldLabel"):
            if lbl.text() in ("View", "Axle", BROWSE_UNIT_LABEL):
                lbl.setVisible(False)
        for w in (self.br_unit, self.br_prev, self.br_next, self.br_slider,
                  self.br_data_btn):
            w.setVisible(False)
        # every file of the unit is a frame on the timeline, empty ones included -
        # "the nearest laser frame holds no sample" is a finding, not a skip
        self.br_data_btn.blockSignals(True)     # no draw yet: there is no folder
        self.br_data_btn.setChecked(False)
        self.br_data_btn.blockSignals(False)
        self.browser_bar.setVisible(True)
        if getattr(self, "diag_btn", None) is not None:
            # enabled, but CLOSED: the groove numbers are already on the plot
            # (G# D= W= at each marker) and the card costs the plot its height
            self.diag_btn.setEnabled(True)
        self.reload_btn.setVisible(False)            # whole-scan read, once
        if self.canvas is not None:
            self.canvas.setMinimumHeight(200)        # the profile never collapses
        self._update_view_hint()

    def set_frame_note(self, text):
        """A caption line the embedding tab puts on the plot title (the Δt)."""
        self._frame_note = text or ""

    def show_frame(self, pos, name):
        """
        Put one unit's frame on screen, by its profile file name.

        Returns True when it is (or will be, once the first load finishes) shown.
        An unknown name leaves the panel where it was and returns False - the caller
        says so; nothing here guesses a neighbour.
        """
        if pos not in POS_ORDER:
            return False
        self._want_empty = None
        self._br_pos = pos
        if (self._raw_cache is None or self._worker is not None
                or self._cache_folder != self._cache_key()):
            # not loaded - or loaded for another folder: ask, and draw on arrival
            self._pending_frame = (pos, name)
            self.render()                             # starts the load if needed
            return True
        names, _have = self._browser_names(self._current_src(), pos)
        if name not in names:
            return False
        self._br_idx = names.index(name)
        self._pending_frame = None
        self._redraw_browser()
        return True

    def show_empty(self, pos, why):
        """The combined tab has no laser frame to show for this step."""
        self._pending_frame = None
        # remembered: a whole-scan load still running must not later draw a frame
        # over this statement (see _draw_from_cache)
        self._want_empty = (pos, why)
        self._draw_empty(pos, why)

    def _draw_empty(self, pos, why):
        if self.fig is None:
            return
        insp = getattr(self, "inspector", None)
        self.fig.clear()
        if insp is not None:
            insp.reset()
        ax = self.fig.subplots(1, 1)
        ax.set_xlabel("x (mm)"); ax.set_ylabel("z (mm)")
        ax.grid(True, linestyle="--", alpha=0.6)
        ax.set_title("%s   ·   no laser frame" % (pos or "laser"),
                     fontsize=11, fontweight="bold")
        ax.text(0.5, 0.5, why, ha="center", va="center", transform=ax.transAxes,
                color="gray", wrap=True)
        self._apply_fig_rect_browser(1)
        self.canvas.draw()
        self._fill_frame_panel(pos, None, [])
        if getattr(self, "br_label", None) is not None:
            self.br_label.setText("—")

    def laser_names(self, pos):
        """Every profile file of one unit, in the browser's order (whole scan)."""
        if self._raw_cache is None:
            return []
        return [n for n, _x, _z in self._raw_cache.get(pos, [])]

    # ---------------- busy overlay / thread lifecycle ----------------
    def resizeEvent(self, ev):
        super().resizeEvent(ev)
        b = getattr(self, "busy", None)
        # isHidden(), not isVisible(): the panel is still an unshown tab child while
        # the first load runs, so isVisible() is False and the overlay would keep a
        # stale geometry until the user resized the window
        if b is not None and not b.isHidden():
            b.setGeometry(self.rect())

    def showEvent(self, ev):
        super().showEvent(ev)
        # v1.2: draws postponed while this panel sat in a hidden tab
        if self._worker is None and getattr(self, "_draw_owed", False) \
                and self._raw_cache is not None:
            self._draw_owed = False
            self._draw_from_cache()
        elif getattr(self, "_placeholder_owed", False) and self._raw_cache is None:
            self._placeholder_owed = False
            self._draw_placeholder("loading…")

    def closeEvent(self, ev):
        self.shutdown()
        super().closeEvent(ev)

    def shutdown(self):
        """
        Tear this panel down safely BEFORE its C++ object is destroyed.

        The worker is deliberately kept alive past the panel (see _GROOVE_WORKERS -
        destroying a running QThread is an instant abort), but its done/failed/
        finished signals still point at THIS panel's bound methods. If the panel is
        destroyed first - which is what MainWindow.rebuild() does to the previous
        scan's tabs - the next emit lands on a deleted wrapper, PyQt raises inside a
        Qt slot, and an unhandled exception in a slot is qFatal(): the process dies
        with exit 0xC0000409 and no traceback.

        Disconnecting first, then stopping, closes that window completely.
        """
        self._closing = True
        self._disconnect_worker()
        self._stop_worker()

    def _disconnect_worker(self):
        """Drop every signal this panel owns on the running worker."""
        w = self._worker
        if w is None:
            return
        for sig, slot in ((w.phase, self._on_phase),
                          (w.done, self._on_worker_done),
                          (w.failed, self._on_worker_failed),
                          (w.finished, self._on_worker_finished)):
            try:
                sig.disconnect(slot)
            except (TypeError, RuntimeError):
                pass          # already disconnected, or the C++ side is gone

    def _stop_worker(self):
        """Never destroy a running QThread (same rule as the scan loader)."""
        w, self._worker = self._worker, None
        if w is None:
            return
        if getattr(self, "_worker_shared", False):
            # another panel's read: it keeps running for its owner
            self._worker_shared = False
            return
        try:
            w.requestInterruption()
            if w.isRunning():
                w.wait(5000)
        except RuntimeError:
            pass

    def _set_busy(self, on, phase=""):
        """Disable the controls and raise the spinner, exactly like a scan load."""
        for wdg in (self.filter_combo, self.reload_btn, self.browse_btn, self.save_btn,
                    getattr(self, "unit_combo", None), getattr(self, "export_btn", None),
                    getattr(self, "hide_nan_cb", None),
                    getattr(self, "show_table_btn", None)):
            if wdg is not None:
                wdg.setEnabled(not on)
        b = getattr(self, "busy", None)
        if b is None:
            return
        if on:
            b.setGeometry(self.rect())
            b.start(phase)
        else:
            b.stop()

    # ---------------- axle filter ----------------
    def _populate_axles(self):
        """
        Fill the axle selector. With no classification there is exactly one entry
        ("All axles") and the control is disabled, so the panel behaves and reads
        exactly as it did before the axle split existed.

        EVERY axle the classification resolved is listed, 2026-09-08 - including one
        with no laser profile on it. It used to be skipped, and on the 3-axle scan of
        2026-09-07 that made Axle 3 disappear from this tab entirely: the split says
        three axles, the vehicle map draws three axles, and the laser dropdown offered
        two. An axle with no laser data is a FINDING (the third gate3 window produced
        no groove file), and a finding that is not on screen is a finding nobody has.
        It is listed with what it holds, selectable, and it plots an explicit reason
        rather than an empty grid.
        """
        self.axle_combo.blockSignals(True)
        self.axle_combo.clear()
        self._axle_buckets = [None]
        self.axle_combo.addItem("All axles")

        idx = self.axle_index
        n_trash = 0
        axle_counts = []
        if idx is not None:
            # Counts are PROFILE files, because profiles are what this panel plots.
            axle_counts = [(label, self._n_profiles(idx, label))
                           for label in idx.axle_labels()]
            n_trash = self._n_profiles(idx, axle_mod.TRASH)

        # Whether ANY laser profile was attributed at all. When none was, the split
        # has nothing to say about this tab (his classifier places a file by a
        # timestamp column *_profile.csv does not carry on a millisecond scan), so
        # the control stays off exactly as it did before rather than offering a list
        # of axles that would every one of them plot nothing.
        anything = bool(n_trash) or any(n for _l, n in axle_counts)
        if anything:
            for label, n in axle_counts:
                self.axle_combo.addItem(
                    f"{label}  ·  {n} profiles" if n
                    else f"{label}  ·  no laser profiles")
                self._axle_buckets.append(label)
            if n_trash:
                self.axle_combo.addItem(f"Unassigned  ·  {n_trash} profiles")
                self._axle_buckets.append(axle_mod.TRASH)

        self.axle_combo.setEnabled(anything)
        if idx is not None and not anything:
            self.axle_combo.setToolTip(
                "Per-axle filtering is not available for laser profiles.\n\n"
                "The axle classification places a file using its timestamp_msec "
                "column, and *_profile.csv has no such column, so no profile is\n"
                "assigned to an axle. The plots below show the whole scan.")
        elif anything:
            empties = [l for l, n in axle_counts if not n]
            self.axle_combo.setToolTip(
                "Filter the four laser positions to one axle.\n\n"
                + ("%s carries no laser profile at all - selected, it says so "
                   "instead of plotting an empty grid." % ", ".join(empties)
                   if empties else
                   "Every axle in this scan carries laser data."))
        self.axle_combo.blockSignals(False)

    @staticmethod
    def _n_profiles(idx, bucket):
        """
        Profile files on one bucket.

        Media is what a classification his script or his manifest produced always
        carries. A split READ off a folder tree can leave it "unknown" (his Trash
        layout writes no media folder), and counting only MEDIA_LASER there would
        report every axle as empty on a tree the user is looking straight at - so a
        file whose own name says it is a profile counts either way.
        """
        n = 0
        for p in idx.paths_in(bucket):          # unsorted: this only counts
            if not p.lower().endswith("_profile.csv"):
                continue
            media = (idx.meta.get(p, {}) or {}).get("media")
            if media in (axle_mod.MEDIA_LASER, None, "unknown"):
                n += 1
        return n

    def _axle_keep(self):
        """
        Absolute paths allowed by the current axle selection, or None for all.

        An EMPTY set is a real answer, not a missing one: it means the selected axle
        carries no laser file, and the plot has to say that rather than fall back to
        the whole scan. Media is matched the same way _n_profiles counts it, so the
        dropdown's number and the plot's content can never disagree.
        """
        if self._axle_bucket is None or self.axle_index is None:
            return None
        idx = self.axle_index
        keep = set()
        for p in idx.paths_in(self._axle_bucket):   # unsorted: this builds a set
            media = (idx.meta.get(p, {}) or {}).get("media")
            if media in (axle_mod.MEDIA_LASER, None, "unknown"):
                keep.add(os.path.abspath(p))
        return keep

    def _on_axle_changed(self, i):
        bucket = self._axle_buckets[i] if 0 <= i < len(self._axle_buckets) else None
        if bucket == self._axle_bucket:
            return
        self._axle_bucket = bucket
        self._invalidate_cache()
        self.render()

    def _cache_key(self):
        """Folder AND axle: two axles are two file sets, so the axle has to be part
        of the cache identity or switching axles would redraw axle 1's profiles."""
        return (self.folder, self._axle_bucket)

    def _invalidate_cache(self):
        self._cache_folder = self._cache_key()
        self._raw_cache = self._filt_cache = self._drop_cache = self._depth_cache = None
        self._path_cache = None
        self._grooves_cache = None
        # Reset frame selection when cache is invalidated (e.g., folder change)
        self._selected_frames = None
        self._accum_mode = "rising_order"

    def _reload(self):
        """Reload re-reads the folder from disk; the dropdown alone never does."""
        _GROOVE_SHARED.pop(self._shared_key(), None)     # really from disk (v1.2)
        self._invalidate_cache()
        self.render()


