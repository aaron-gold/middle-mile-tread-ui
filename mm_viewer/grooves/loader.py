# ============================================================
# GROOVE DEPTH LOADER   (*_grooves_full.csv -> per-profile depths)
# ============================================================
#
# Join notes - verified 2026-08-16 against 6 scan folders, 1291/1294 profiles matched:
#   * a unit can have MANY *_grooves_full.csv files (one per pass/batch), not one -
#     11 in the 11-22-15 scan, 64 in the 09-40-31 scan. All must be aggregated.
#   * the timestamp in a filename is NOT that frame's timestamp_msec
#     (..._1626408_profile.csv -> timestamp_msec 1625915), so filenames cannot join.
#   * the reliable key is (sensor_timestamp_msec, timestamp_msec), read from the
#     profile's sibling *_grooves.csv and looked up in the aggregated full table.
#   * Depth_0..Depth_9 in grooves_full matched the sibling's Depth column exactly on
#     every frame checked (63/63), so the two sources agree and the join is right.

POS_ORDER = ["FRONT LEFT", "FRONT RIGHT", "REAR LEFT", "REAR RIGHT"]


def _pos_from_token(t):
    """Wheel position carried by one already-upper-cased path token, or None."""
    if "FRONT_LEFT" in t or "FRONT LEFT" in t or "_FL_" in t: return "FRONT LEFT"
    if "FRONT_RIGHT" in t or "FRONT RIGHT" in t or "_FR_" in t: return "FRONT RIGHT"
    if "REAR_LEFT" in t or "REAR LEFT" in t or "_RL_" in t: return "REAR LEFT"
    if "REAR_RIGHT" in t or "REAR RIGHT" in t or "_RR_" in t: return "REAR RIGHT"
    return None


def wheel_pos(fn):
    """
    Wheel position for a groove file, across BOTH scan layouts.

      new (per-unit subfolder)
        tire_laser_groove_data/LMI_0_FRONT_LEFT/frame_3_profile.csv
      old (flat, unit in the filename)
        tire_laser_groove_data/output_LMI_0_FRONT_LEFT_1626408_profile.csv

    Under the new layout every filename is just frame_<N>_*, so the PARENT DIRECTORY
    is the only thing that carries the unit - it is checked first. The filename is the
    fallback, which keeps every pre-change scan resolving exactly as it did before.
    Returns None when neither token names a unit, and the caller drops the file.
    """
    p = _pos_from_token(os.path.basename(os.path.dirname(os.path.abspath(fn))).upper())
    if p:
        return p
    return _pos_from_token(os.path.basename(fn).upper())


def groove_files(folder, pattern):
    """
    Every file matching `pattern` in a groove folder, under BOTH layouts: directly in
    the folder (old flat) and one level down in the per-unit subfolders (new). Both
    levels are globbed unconditionally, so a half-migrated folder still yields
    everything it holds instead of silently reporting one layout as empty.
    """
    if not (folder and lp_isdir(folder)):
        return []
    # listdir + fnmatch, not glob: an extended-length path carries a '?', which glob
    # reads as a metacharacter, so a long scan folder would match nothing at all.
    out = lp_listmatch(folder, pattern)
    for name in sorted(lp_listdir(folder) if lp_isdir(folder) else []):
        sub = os.path.join(folder, name)
        if lp_isdir(sub):
            out.extend(lp_listmatch(sub, pattern))
    return out


def _frame_sort_key(fp):
    """
    Frame order for a groove file. The LAST digit run in the basename is the frame
    index (new layout, frame_10_profile.csv -> 10) or the acquisition timestamp (old
    layout, output_LMI_0_FRONT_LEFT_1626408_profile.csv -> 1626408); either way it is
    the number that orders the files. Sorting the strings instead would put frame_10
    before frame_2. The unit folder leads the key so units never interleave.
    """
    b = os.path.basename(fp)
    nums = re.findall(r"\d+", b)
    return (os.path.basename(os.path.dirname(os.path.abspath(fp))),
            int(nums[-1]) if nums else -1, b)


def _depth_num(v):
    """CSV cell -> float, with the laser no-data sentinel folded to NaN."""
    try:
        x = float(v)
    except (TypeError, ValueError):
        return math.nan
    if not math.isfinite(x) or abs(x) > LASER_SENTINEL_ABS:
        return math.nan
    return x


# ------------------------------------------------------------
# THE GROOVE DEPTH JOIN, 2026-09-08
# ------------------------------------------------------------
# A frame's depths live in *_grooves_full.csv and a frame's identity lives in its own
# *_grooves.csv; the two are joined on the timestamp columns they share. Those columns
# CHANGED WITH THE FIRMWARE, and the join was still keyed on the old pair:
#
#   up to 2026-08-31    sensor_timestamp_msec , timestamp_msec
#   from 2026-09-03     Device_Timestamp_usec , Host_Timestamp_usec
#
# On every scan from 03.09 onward both lookups returned "" for every row, so the whole
# per-position index collapsed onto the single key ("", "") and every frame reported
# "0 with depth · 0 depths". MEASURED on 2026-09-03T08-36-36 and on the 3-axle scan of
# 2026-09-07: the Groove depth summary and the per-profile measurement table were
# empty on both, with no error - the numbers simply were not there.
#
# The pair is read off each file's own header instead of assumed, newest first, so
# both schemas work and a scan that mixes them still joins file by file.
GROOVE_KEY_COLS = (("Device_Timestamp_usec", "Host_Timestamp_usec"),
                   ("sensor_timestamp_msec", "timestamp_msec"))


def groove_key_cols(fieldnames):
    """The (sensor, host) timestamp column pair a groove CSV carries, or None."""
    cols = {(c or "").strip() for c in (fieldnames or [])}
    for pair in GROOVE_KEY_COLS:
        if all(c in cols for c in pair):
            return pair
    return None


def groove_row_key(row, pair):
    """The join key for one row, as two trimmed strings."""
    if not pair:
        return None
    return (str(row.get(pair[0], "")).strip(), str(row.get(pair[1], "")).strip())


def _first_data_row(path):
    """
    (first data row, key column pair) - the sibling files are 10 rows that all carry
    the same timestamp, so parsing the rest buys nothing.

    The column pair is returned with the row because it is a property of the FILE,
    not of the scan: a folder can hold both schemas after a firmware change mid-test.
    """
    try:
        with lp_open(path, newline="") as fh:
            rd = csv.DictReader(fh)
            for row in rd:
                # the key columns come from THIS file's header - see GROOVE_KEY_COLS
                return row, groove_key_cols(rd.fieldnames)
    except Exception:
        return None, None
    return None, None


# v1.7: where a depth row's numbers came from.
#   full  - the unit's *_grooves_full.csv, joined on the timestamp pair (as v1.6)
#   frame - the profile's own frame_<N>_grooves.csv, Depth column, row k = slot k.
#           Used ONLY for a unit whose full table has no rows. The two sources are
#           the same numbers: 2288/2288 frames identical, 0 differ, on the 11 scans
#           of 30 Sep (2026-10-06); 63/63 on the 2026-08-16 check above.
#   none  - no depth for this profile
DEPTH_SRC_FULL = "full"
DEPTH_SRC_FRAME = "frame"
DEPTH_SRC_NONE = ""


def frame_groove_depths(path):
    """
    v1.7: [d0..d9] from one frame_<N>_grooves.csv - row k's Depth is slot k, the
    sentinel folded to NaN, missing rows NaN. Only the Depth column is read: Width /
    X / Z are not reliably on the same row (see read_frame_grooves).
    """
    depths = [math.nan] * N_GROOVES
    try:
        with lp_open(path, newline="") as fh:
            for i, r in enumerate(csv.DictReader(fh)):
                if i >= N_GROOVES:
                    break
                depths[i] = _depth_num(r.get("Depth"))
    except Exception:
        return [math.nan] * N_GROOVES
    return depths


def _axle_keeps(keep, path):
    """
    True when `path` survives the axle filter. `keep` is None (no filter - the
    pre-axle behaviour, unchanged) or a set of absolute paths for one axle.
    """
    return keep is None or os.path.abspath(path) in keep


def build_full_index(folder, keep=None):
    """unit -> { (sensor_ts, host_ts) : [d0..d9] }, over every grooves_full file.

    The key columns are whichever pair the file's own header carries - see
    GROOVE_KEY_COLS. A file with neither pair contributes no rows rather than
    contributing all of them under one empty key, which is what used to happen and is
    how a whole scan's depths turned into a single row.

    `keep` is the optional axle filter; the *_grooves_full.csv files are whole-scan
    artefacts and are deliberately NOT filtered - they are the depth lookup table for
    every axle, and dropping them would blank the depths for the selected axle.
    """
    idx = {p: {} for p in POS_ORDER}
    counts = {p: {"files": 0, "rows": 0} for p in POS_ORDER}
    for fp in sorted(groove_files(folder, "*_grooves_full.csv"), key=_frame_sort_key):
        pos = wheel_pos(fp)
        if pos not in idx:
            continue
        counts[pos]["files"] += 1
        try:
            with lp_open(fp, newline="") as fh:
                rd = csv.DictReader(fh)
                pair = groove_key_cols(rd.fieldnames)
                for row in rd:
                    key = groove_row_key(row, pair)
                    if key is None:
                        continue        # no timestamp columns: nothing to join on
                    idx[pos][key] = [_depth_num(row.get(f"Depth_{i}"))
                                     for i in range(N_GROOVES)]
                    counts[pos]["rows"] += 1
        except Exception:
            continue
    return idx, counts


def profile_files_by_pos(folder, keep=None):
    """The profile-file selection the 2x2 plot uses, grouped by wheel position.

    `keep=None` returns everything, exactly as before the axle split existed.
    """
    out = {p: [] for p in POS_ORDER}
    if not (folder and lp_isdir(folder)):
        return out
    all_files = groove_files(folder, "*.csv")
    profs = [f for f in all_files
             if "profile" in os.path.basename(f).lower()
             and "groove" not in os.path.basename(f).lower()
             and _axle_keeps(keep, f)]
    for fp in sorted(profs, key=_frame_sort_key):
        p = wheel_pos(fp)
        if p in out:
            out[p].append(fp)
    return out


def _rolling_median_pair(a):
    """
    Exact numpy twin of `pd.Series(a).rolling(2, center=True, min_periods=1).median()`.

    Verified against pandas: with an EVEN window and center=True the window is the
    BACKWARD pair, i.e. out[i] = mean(a[i-1], a[i]) and out[0] = a[0]. Getting that
    offset wrong silently shifts every despike decision by one sample.
    """
    out = np.empty_like(a)
    out[0] = a[0]
    out[1:] = (a[:-1] + a[1:]) / 2.0
    return out


def filter_profile_xz(x, z, window=FILT_WINDOW, threshold=FILT_THRESHOLD):
    """
    Despike + smooth ONE profile, on plain arrays. This is the implementation; the
    DataFrame helpers below are thin wrappers so the maths exists exactly once.

    1. rolling median / MAD -> modified z-score; samples above `threshold` are
       treated as edge/side noise spikes,
    2. the spikes are replaced by positional linear interpolation so the curve stays
       continuous and the sample count is preserved,
    3. Savitzky-Golay (polyorder 2) smooths small deltas without cutting data.

    Returns (x, z_filtered). If every sample is a spike there is nothing left to
    interpolate from, so two empty arrays come back and the validity gate rejects
    the profile as "Too few points".

    NOTE: at the shipped default (window=2 -> savgol window_length=3, polyorder=2)
    the Savitzky-Golay step is mathematically the IDENTITY - a quadratic through
    three points reproduces the middle point exactly. It only begins to smooth once
    FILT_WINDOW is raised to 4 or more.
    """
    x = np.asarray(x, dtype=float)
    z = np.asarray(z, dtype=float)
    if z.size == 0:
        return x, z

    if window == 2:
        med = _rolling_median_pair(z)
        diff = np.abs(z - med)
        mad = _rolling_median_pair(diff) + 1e-6
    else:
        # a tuned window falls back to pandas, so the maths stays identical to the
        # reference script at every setting and not just at the default
        roll = dict(window=window, center=True, min_periods=1)
        med = pd.Series(z).rolling(**roll).median().to_numpy()
        diff = np.abs(z - med)
        mad = pd.Series(diff).rolling(**roll).median().to_numpy() + 1e-6

    spike = (0.6745 * diff / mad) > threshold
    zf = z.copy()
    if spike.any():
        keep = ~spike
        if not keep.any():
            return x[:0], z[:0]
        idx = np.arange(z.size, dtype=float)
        zf[spike] = np.interp(idx[spike], idx[keep], z[keep])

    savgol_window = window if window % 2 else window + 1      # must be odd
    if SCIPY_AVAILABLE and savgol_window > 2 and zf.size >= savgol_window:
        zf = savgol_filter(zf, window_length=savgol_window, polyorder=2)
    return x, zf


def is_profile_valid_xz(z, max_std=FILT_MAX_STD, max_ptp=FILT_MAX_PTP,
                        min_points=FILT_MIN_POINTS):
    """
    Profile-level plausibility gate for the filtered view, on plain arrays.
    Returns (ok, reason). Rejected profiles are NOT plotted, but they still appear
    in the depth table, greyed and labelled with the reason.
    """
    zz = np.asarray(z, dtype=float)
    zz = zz[np.isfinite(zz)]
    if zz.size < min_points:
        return False, f"Too few points ({zz.size} < {min_points})"
    std_val = float(np.std(zz))
    ptp_val = float(np.ptp(zz))
    if std_val > max_std:
        return False, f"High STD ({std_val:.2f} > {max_std:g})"
    if ptp_val > max_ptp:
        return False, f"High range ({ptp_val:.2f} > {max_ptp:g})"
    return True, "OK"


def read_profile_xz(path):
    """
    One *_profile.csv -> (x, z) float arrays: sentinel-masked, NaN-dropped, x-sorted.
    Returns None if the file has no x/z columns or cannot be parsed.

    This is the ONLY place a profile is read from disk. The panel caches the result
    per folder, so flipping the filter dropdown never touches the disk again.
    """
    try:
        df = pd.read_csv(lp(path))
    except Exception:
        return None
    xcol = "x" if "x" in df.columns else ("X" if "X" in df.columns else None)
    zcol = "z" if "z" in df.columns else ("Z" if "Z" in df.columns else None)
    if xcol is None or zcol is None:
        return None
    x = pd.to_numeric(df[xcol], errors="coerce").to_numpy(dtype=float)
    z = pd.to_numeric(df[zcol], errors="coerce").to_numpy(dtype=float)
    bad = ((~np.isfinite(x)) | (~np.isfinite(z))
           | (np.abs(x) > LASER_SENTINEL_ABS) | (np.abs(z) > LASER_SENTINEL_ABS))
    x, z = x[~bad], z[~bad]
    if x.size:
        order = np.argsort(x, kind="stable")
        x, z = x[order], z[order]
    return x, z


def clean_and_smooth_profile(df, x_col="x", z_col="z",
                             window=FILT_WINDOW, threshold=FILT_THRESHOLD):
    """DataFrame wrapper around filter_profile_xz(). Expects an already x-sorted,
    NaN-free frame; returns a NEW frame, empty if every sample was a spike."""
    d = df.sort_values(by=x_col).copy()
    _x, zf = filter_profile_xz(d[x_col].to_numpy(dtype=float),
                               d[z_col].to_numpy(dtype=float), window, threshold)
    if zf.size != len(d):
        return d.iloc[0:0]
    d[z_col] = zf
    return d


def is_profile_valid(df, z_col="z", max_std=FILT_MAX_STD, max_ptp=FILT_MAX_PTP,
                     min_points=FILT_MIN_POINTS):
    """DataFrame wrapper around is_profile_valid_xz()."""
    return is_profile_valid_xz(df[z_col].to_numpy(dtype=float),
                               max_std, max_ptp, min_points)


def build_depth_rows(folder, keep=None):
    """
    Returns (rows_by_pos, full_counts) - the system-reported depths, WITHOUT any
    filter flags. Nothing here depends on the filter mode, so the panel reads the
    CSVs once per folder and only re-flags them when the dropdown changes.

    rows_by_pos[pos] = [ {file, sensor_ts, ts, depths[10], n_valid, matched}, ... ]

    EVERY profile file produces a row. A profile with no matching grooves_full entry
    still appears, with 10 NaN and matched=False, so a missing depth is always visible
    and never silently dropped.

    v1.7: a unit whose grooves_full table has NO rows (0-byte file, or no file) takes
    each profile's depths from its sibling frame_<N>_grooves.csv instead - see
    DEPTH_SRC_FRAME. row["source"] says where the depths came from; matched stays
    "has a grooves_full row", so it is False on those rows.
    """
    full_idx, full_counts = build_full_index(folder or "", keep)
    profs = profile_files_by_pos(folder, keep)

    rows_by_pos = {}
    for pos in POS_ORDER:
        rows = []
        # v1.7: only a unit with no full table falls back; one WITH a table keeps
        # v1.6's join exactly, unmatched frames included
        fallback = full_counts[pos]["rows"] == 0
        full_counts[pos]["fallback"] = fallback and bool(profs[pos])
        for fp in profs[pos]:
            sib = (fp[:-len("_profile.csv")] + "_grooves.csv"
                   if fp.lower().endswith("_profile.csv") else None)
            key, matched = None, False
            if sib and lp_isfile(sib):
                r0, pair = _first_data_row(sib)
                if r0 is not None:
                    key = groove_row_key(r0, pair)
            depths = [math.nan] * N_GROOVES
            source = DEPTH_SRC_NONE
            if key is not None and key in full_idx[pos]:
                depths = list(full_idx[pos][key])
                matched = True
                source = DEPTH_SRC_FULL
            elif fallback and sib and lp_isfile(sib):
                depths = frame_groove_depths(sib)
                source = DEPTH_SRC_FRAME
            rows.append({
                "file": os.path.basename(fp),
                # v1.4: the full path, so the vehicle map can look the profile up in
                # the axle split (which is keyed by path). Nothing else reads it.
                "path": fp,
                "sensor_ts": key[0] if key else "",
                "ts": key[1] if key else "",
                "depths": depths,
                "n_valid": sum(1 for d in depths if not math.isnan(d)),
                "matched": matched,
                "source": source,                  # v1.7: DEPTH_SRC_*
                # filter bookkeeping - set by annotate_drops(), never here
                "dropped": False,
                "drop_reason": "",
            })
        rows_by_pos[pos] = rows
    return rows_by_pos, full_counts


def annotate_drops(rows_by_pos, full_counts, dropped_by_pos=None):
    """
    Flag the profiles the filter rejected and recompute the per-unit statistics over
    the rest. Pure bookkeeping on rows already in memory - this is what makes a
    filter-mode switch instant once the folder has been read.

    `dropped_by_pos` (filtered view only) = {pos: [(profile_filename, reason), ...]}.
    A flagged row is greyed and labelled in the table but never removed; it is only
    left out of the summary statistics.
    """
    dropped_by_pos = dropped_by_pos or {}
    stats_by_pos = {}
    for pos in POS_ORDER:
        rows = rows_by_pos.get(pos, [])
        drop_map = dict(dropped_by_pos.get(pos) or [])
        for r in rows:
            reason = drop_map.get(r["file"])
            r["dropped"] = reason is not None
            r["drop_reason"] = reason or ""

        kept = [r for r in rows if not r["dropped"]]
        vals = sorted(d for r in kept for d in r["depths"] if not math.isnan(d))
        n = len(vals)
        stats_by_pos[pos] = {
            "frames": len(rows),
            "dropped": len(rows) - len(kept),
            "matched": sum(1 for r in kept if r["matched"]),
            # v1.7: "unmatched" = no depth source at all. A per-frame row is not a
            # missing depth; it is counted on its own. Same numbers as v1.6 on any
            # unit with a full table (no per-frame rows there).
            "unmatched": sum(1 for r in kept
                             if r.get("source", DEPTH_SRC_NONE) == DEPTH_SRC_NONE),
            "from_frame": sum(1 for r in kept if r.get("source") == DEPTH_SRC_FRAME),
            "full_fallback": bool(full_counts[pos].get("fallback")),
            "frames_with_depth": sum(1 for r in kept if r["n_valid"] > 0),
            "n_depths": n,
            "min": vals[0] if n else math.nan,
            # median sits next to the mean because a handful of 200-570 mm readings
            # drag the mean far away from the bulk of the data
            "median": ((vals[n // 2] if n % 2 else (vals[n // 2 - 1] + vals[n // 2]) / 2)
                       if n else math.nan),
            "mean": (sum(vals) / n) if n else math.nan,
            "max": vals[-1] if n else math.nan,
            "n_outliers": sum(1 for d in vals if d < PLAUSIBLE_MIN or d > PLAUSIBLE_MAX),
            "full_files": full_counts[pos]["files"],
            "full_rows": full_counts[pos]["rows"],
        }
    return rows_by_pos, stats_by_pos


def load_groove_depths(folder, dropped_by_pos=None, keep=None):
    """Read a folder and flag it in one call (kept for callers and tests)."""
    rows_by_pos, full_counts = build_depth_rows(folder, keep)
    return annotate_drops(rows_by_pos, full_counts, dropped_by_pos)
