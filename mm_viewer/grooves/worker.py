import numpy as np
import os
import traceback
from PyQt6.QtCore import pyqtSignal, QThread


from mm_viewer.grooves.loader import (
    build_depth_rows, filter_profile_xz, is_profile_valid_xz, POS_ORDER,
    profile_files_by_pos, read_profile_xz
)


# ============================================================
# GROOVE PROFILE WORKER  (all the heavy lifting, off the GUI thread)
# ============================================================
#
# Why this exists - measured on the 09-40-31 scan (815 profiles, ~12k rows each):
#   pd.read_csv of every profile   19.4 s
#   depth join (grooves_full)       1.7 s
#   filtering every profile         9.2 s   (pandas rolling, per profile)
# All of it used to run synchronously inside render(), on the GUI thread, on EVERY
# filter-dropdown change - so the window froze for ~30 s and looked hung. Now the
# parse happens once per folder in this thread, the arrays are cached, the filter is
# vectorised, and the spinner keeps animating throughout.

_GROOVE_WORKERS = set()          # strong refs so a running thread is never GC'd
GROOVE_READ_THREADS = 4          # v1.2: measured 2 -> 1.7x, 4 -> 2.2x, 8 -> 2.3x
# v1.2: one read of a groove folder serves every panel showing it.
#   key = (folder, axle bucket, id(axle index)) - see GrooveDepthPanel._shared_key
# The stored objects are the worker's own results, which no panel modifies in place.
# Cleared whenever the main window tears its tabs down (a new scan, Clear).
_GROOVE_SHARED = {}              # key -> {"raw", "filt", "drop", "depth"}
_GROOVE_INFLIGHT = {}            # key -> the GrooveProfileWorker reading it now


def _groove_share(key, raw, filt, dropped, depth):
    sh = _GROOVE_SHARED.setdefault(key, {})
    if raw is not None:
        sh["raw"] = raw
    if depth is not None:
        sh["depth"] = depth
    if filt is not None:
        sh["filt"], sh["drop"] = filt, dropped


class GrooveProfileWorker(QThread):
    """
    Parses / filters the laser profiles and joins the system-reported depths.
    Touches no Qt widgets and no panel state - everything is handed back by signal
    and applied on the GUI thread.
    """
    phase = pyqtSignal(str)
    # raw_by_pos, filt_by_pos, dropped_by_pos, (rows_by_pos, full_counts)
    done = pyqtSignal(object, object, object, object)
    failed = pyqtSignal(str)

    def __init__(self, folder, filtered, raw_cache=None, depth_cache=None, keep=None):
        super().__init__(None)               # unparented: outlives a closing tab
        self.folder = folder or ""
        self.filtered = bool(filtered)
        self._raw = raw_cache
        self._depth = depth_cache
        self.keep = keep                     # axle filter, or None for the whole scan

    def run(self):
        try:
            raw = self._raw
            if raw is None:
                raw = {}
                files = profile_files_by_pos(self.folder, self.keep)
                total = sum(len(v) for v in files.values()) or 1
                seen = 0
                # v1.2: GROOVE_READ_THREADS files parsed at once - pandas' C parser
                # releases the GIL, so a 16-09 scan (480 x ~0.5 MB) reads ~2.3x
                # faster. Results are collected IN FILE ORDER (map), and each file
                # is parsed by the same read_profile_xz as before - measured
                # bit-identical to the serial read on 240 real frames.
                from concurrent.futures import ThreadPoolExecutor
                pool = ThreadPoolExecutor(max_workers=GROOVE_READ_THREADS,
                                          thread_name_prefix="groove-read")
                try:
                    for pos in POS_ORDER:
                        out = []
                        for fp, xz in zip(files[pos],
                                          pool.map(read_profile_xz, files[pos])):
                            if self.isInterruptionRequested():
                                return
                            seen += 1
                            if seen % 10 == 0 or seen == total:
                                self.phase.emit(
                                    f"Reading laser profiles…  {seen} / {total}")
                            if xz is None:
                                # unreadable / no x,z columns - still counted as a
                                # file, so "N of M files with data" stays honest
                                xz = (np.empty(0), np.empty(0))
                            out.append((os.path.basename(fp), xz[0], xz[1]))
                        raw[pos] = out
                finally:
                    pool.shutdown(wait=False, cancel_futures=True)

            filt = dropped = None
            if self.filtered:
                filt, dropped = {}, {}
                total = sum(len(v) for v in raw.values()) or 1
                seen = 0
                for pos in POS_ORDER:
                    kept, drops = [], []
                    for name, x, z in raw.get(pos, []):
                        if self.isInterruptionRequested():
                            return
                        seen += 1
                        if seen % 25 == 0 or seen == total:
                            self.phase.emit(f"Filtering profiles…  {seen} / {total}")
                        if x.size == 0:
                            continue        # no data at all: not a filter rejection
                        try:
                            xf, zf = filter_profile_xz(x, z)
                        except Exception as e:
                            drops.append((name, f"Filter error ({e})"))
                            continue
                        ok, reason = is_profile_valid_xz(zf)
                        if ok:
                            kept.append((name, xf, zf))
                        else:
                            drops.append((name, reason))
                    filt[pos], dropped[pos] = kept, drops

            depth = self._depth
            if depth is None:
                self.phase.emit("Reading system-reported depths…")
                depth = build_depth_rows(self.folder, self.keep)
            if self.isInterruptionRequested():
                return
            self.done.emit(raw, filt, dropped, depth)
        except Exception:
            self.failed.emit(traceback.format_exc())
