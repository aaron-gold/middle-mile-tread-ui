def break_profile_gaps(x, z, factor=GAP_BREAK_FACTOR, min_mm=GAP_BREAK_MIN_MM):
    """
    DISPLAY ONLY. Returns (x, z) copies with a NaN inserted at every x jump that is
    both > factor x median(dx) and >= min_mm, so matplotlib lifts the pen instead of
    drawing a straight segment across a laser dropout.

    Nothing is removed, edited, re-ordered or smoothed - the returned arrays are the
    input arrays with NaN separators added. Never feed this to a measurement.
    """
    if x is None or z is None or x.size < 3 or x.size != z.size:
        return x, z
    dx = np.diff(x)
    good = dx[np.isfinite(dx) & (dx > 0)]
    if good.size == 0:
        return x, z
    med = float(np.median(good))
    if not np.isfinite(med) or med <= 0:
        return x, z
    cut = max(factor * med, float(min_mm))
    at = np.nonzero(dx > cut)[0] + 1
    if at.size == 0:
        return x, z
    return (np.insert(x.astype(float), at, np.nan),
            np.insert(z.astype(float), at, np.nan))


def read_frame_grooves(path):
    """
    DISPLAY ONLY. One frame_<N>_grooves.csv -> the rows it holds, sentinel-folded.

    Columns are Depth, Width, X, Z (plus the two timestamps), 10 rows - one per
    groove slot. WARNING: the four columns are NOT guaranteed to be filled on the
    same row. A real file (LMI_0_FRONT_LEFT/frame_10_grooves.csv) carries a Depth on
    a row whose X/Z are sentinel, repeats the same X/Z pair on two rows, and carries
    a Width/X/Z with no Depth. So nothing here pairs a depth with a position: every
    row is reported exactly as written, with its own slot index, and the caller
    decides what to draw. Returns [] if the file is missing or unreadable.
    """
    rows = []
    try:
        with lp_open(path, newline="") as fh:
            for i, r in enumerate(csv.DictReader(fh)):
                rows.append({"slot": i,
                             "depth": _depth_num(r.get("Depth")),
                             "width": _depth_num(r.get("Width")),
                             "x": _depth_num(r.get("X")),
                             "z": _depth_num(r.get("Z"))})
    except Exception:
        return []
    return rows


def ramp_color(frac, first=BR_RAMP_FIRST, last=BR_RAMP_LAST):
    """Position along the accumulate ramp, 0 = first frame added, 1 = current."""
    try:
        f = min(max(float(frac), 0.0), 1.0)
    except (TypeError, ValueError):
        f = 1.0
    return tuple(a + (b - a) * f for a, b in zip(first, last))


def profile_frame_stats(path):
    """
    DISPLAY ONLY diagnostics for one *_profile.csv: how much of the file survived to
    the plot, and how sparse what is left really is.

    read_profile_xz() stays the single authority on what a plotted sample is; this
    repeats its mask only to COUNT what it discarded. mm_groove_inspect_test asserts
    that `kept` equals read_profile_xz()'s sample count on every real frame, so the
    two can never drift apart unnoticed.
    """
    out = {"rows": 0, "kept": 0, "dropped": 0, "drop_pct": math.nan,
           "x_min": math.nan, "x_max": math.nan, "z_min": math.nan, "z_max": math.nan,
           "median_dx": math.nan, "max_gap": math.nan}
    try:
        df = pd.read_csv(lp(path))
    except Exception:
        return out
    xcol = "x" if "x" in df.columns else ("X" if "X" in df.columns else None)
    zcol = "z" if "z" in df.columns else ("Z" if "Z" in df.columns else None)
    if xcol is None or zcol is None:
        return out
    x = pd.to_numeric(df[xcol], errors="coerce").to_numpy(dtype=float)
    z = pd.to_numeric(df[zcol], errors="coerce").to_numpy(dtype=float)
    out["rows"] = int(x.size)
    bad = ((~np.isfinite(x)) | (~np.isfinite(z))
           | (np.abs(x) > LASER_SENTINEL_ABS) | (np.abs(z) > LASER_SENTINEL_ABS))
    x, z = x[~bad], z[~bad]
    out["kept"] = int(x.size)
    out["dropped"] = out["rows"] - out["kept"]
    if out["rows"]:
        out["drop_pct"] = 100.0 * out["dropped"] / out["rows"]
    if x.size:
        order = np.argsort(x, kind="stable")
        x = x[order]
        z = z[order]
        out["x_min"], out["x_max"] = float(x.min()), float(x.max())
        out["z_min"], out["z_max"] = float(z.min()), float(z.max())
    if x.size > 1:
        dx = np.diff(x)
        pos = dx[dx > 0]
        if pos.size:
            out["median_dx"] = float(np.median(pos))
        out["max_gap"] = float(dx.max())
    return out


class ProfilePlotInspector:
    """
    Mouse inspection for an embedded matplotlib figure.

      * snapping crosshair - locks onto the nearest REAL sample and reports it
      * wheel zoom at the cursor - Shift = x only, Ctrl = z only
      * left-drag pan whenever no toolbar tool is armed
      * double-click a subplot to maximise it, double-click again (or Esc) to restore
      * auto-Z: after an x zoom, re-fit z to the data inside the x window

    It OWNS no data. The panel hands it the same (name, x, z) tuples it has just
    drawn and the inspector only READS them to answer "which sample is under the
    cursor". Nothing here writes to a cache, a row or a statistic, and the z auto-fit
    changes axis limits only.
    """

    def __init__(self, canvas, fig, toolbar, on_readout=None, on_maximize=None):
        self.canvas = canvas
        self.fig = fig
        self.toolbar = toolbar
        self._on_readout = on_readout
        self._on_maximize = on_maximize

        self._curves = {}        # ax -> [(name, x, z), ...]   ORIGINAL arrays
        self._keys = {}          # ax -> wheel position label
        self._art = {}           # ax -> (vline, hline, marker)
        self._bg = None
        self._crosshair = CROSSHAIR_ON
        self._auto_z = AUTO_Z_ON
        self._suspend_autoz = False
        self._in_autoz = False
        self._pan_ax = None
        self._pan_px = None

        # ClickFocus, not StrongFocus: the canvas must not steal Tab focus from the
        # controls above it, but it does need focus for the "r" / Esc keys.
        try:
            self.canvas.setFocusPolicy(Qt.FocusPolicy.ClickFocus)
        except Exception:
            pass

        self._cids = [
            canvas.mpl_connect("draw_event", self._on_draw),
            canvas.mpl_connect("motion_notify_event", self._on_motion),
            canvas.mpl_connect("axes_leave_event", self._on_leave),
            canvas.mpl_connect("figure_leave_event", self._on_leave),
            canvas.mpl_connect("scroll_event", self._on_scroll),
            canvas.mpl_connect("button_press_event", self._on_press),
            canvas.mpl_connect("button_release_event", self._on_release),
            canvas.mpl_connect("key_press_event", self._on_key),
        ]

    # ---------------- registry ----------------
    def reset(self):
        """The figure was cleared - every axes and artist we held is now dead."""
        self._curves.clear()
        self._keys.clear()
        self._art.clear()
        self._bg = None
        self._pan_ax = None

    def register(self, ax, key, curves):
        """curves: the [(name, x, z), ...] actually plotted, ORIGINAL arrays."""
        self._curves[ax] = [(n, x, z) for (n, x, z) in curves
                            if x is not None and x.size]
        self._keys[ax] = key
        # xlim_changed, not ylim: the z re-fit is a REACTION to an x zoom/pan
        ax.callbacks.connect("xlim_changed", self._on_xlim_changed)

    def set_crosshair(self, on):
        self._crosshair = bool(on)
        if not self._crosshair:
            self._hide_cursor()
            self._emit("")

    def set_auto_z(self, on):
        self._auto_z = bool(on)

    # ---------------- crosshair ----------------
    def _artists(self, ax):
        """Lazily create the three animated cursor artists for one axes.

        ax.plot([], []) - NOT axvline/axhline: an empty line contributes nothing to
        the axes data limits, so adding the cursor can never move the view.
        """
        got = self._art.get(ax)
        if got is not None:
            return got
        v, = ax.plot([], [], color="#1e78e8", linewidth=0.8, alpha=0.9,
                     animated=True, zorder=50)
        h, = ax.plot([], [], color="#1e78e8", linewidth=0.8, alpha=0.9,
                     animated=True, zorder=50)
        m, = ax.plot([], [], marker="o", markersize=5, color="#e8791e",
                     markeredgecolor="#ffffff", markeredgewidth=0.8,
                     linestyle="none", animated=True, zorder=51)
        self._art[ax] = (v, h, m)
        return self._art[ax]

    def _hide_cursor(self):
        if self._bg is None:
            return
        try:
            self.canvas.restore_region(self._bg)
            self.canvas.blit(self.fig.bbox)
        except Exception:
            pass

    def _emit(self, text):
        if self._on_readout is not None:
            try:
                self._on_readout(text)
            except Exception:
                pass

    def _nearest(self, ax, event):
        """Nearest plotted sample to the cursor, in SCREEN pixels.

        x is sorted (read_profile_xz sorts it), so searchsorted finds the candidate
        index in one step per curve and only a few points around it are measured.
        Returns (name, x, z, index, dist_px) or None.
        """
        curves = self._curves.get(ax) or []
        if not curves or event.xdata is None:
            return None
        cand_xy, cand_meta = [], []
        for name, x, z in curves:
            i = int(np.searchsorted(x, event.xdata))
            lo, hi = max(0, i - SNAP_WIN), min(x.size, i + SNAP_WIN + 1)
            for j in range(lo, hi):
                if np.isfinite(x[j]) and np.isfinite(z[j]):
                    cand_xy.append((x[j], z[j]))
                    cand_meta.append((name, j))
        if not cand_xy:
            return None
        pts = ax.transData.transform(np.asarray(cand_xy, dtype=float))
        d = np.hypot(pts[:, 0] - event.x, pts[:, 1] - event.y)
        k = int(np.argmin(d))
        name, j = cand_meta[k]
        return name, cand_xy[k][0], cand_xy[k][1], j, float(d[k])

    def _on_draw(self, _event):
        # the animated cursor artists are excluded from this draw, so the captured
        # region is a clean plate to blit them onto
        try:
            self._bg = self.canvas.copy_from_bbox(self.fig.bbox)
        except Exception:
            self._bg = None

    def _on_leave(self, _event):
        self._hide_cursor()
        self._emit("")

    def _on_motion(self, event):
        if self._pan_ax is not None:
            self._do_pan(event)
            return
        ax = event.inaxes
        if ax is None or ax not in self._curves:
            self._hide_cursor()
            self._emit("")
            return
        pos = self._keys.get(ax, "")
        if not self._crosshair:
            self._emit("%s    x = %8.2f mm    z = %8.2f mm"
                       % (pos, event.xdata, event.ydata))
            return
        if self._bg is None:
            # No clean plate to blit onto yet. Drawing SYNCHRONOUSLY from inside a
            # motion handler would re-run the live tight-layout engine and shift the
            # axes under the cursor mid-hover, so ask for a draw and report the plain
            # coordinates for this one move; the next move blits normally.
            self.canvas.draw_idle()
            self._emit("%s    x = %8.2f mm    z = %8.2f mm"
                       % (pos, event.xdata, event.ydata))
            return

        v, h, m = self._artists(ax)
        hit = self._nearest(ax, event)
        x0, x1 = ax.get_xlim()
        y0, y1 = ax.get_ylim()
        if hit is not None and hit[4] <= SNAP_MAX_PX:
            name, sx, sz, idx, _dist = hit
            cx, cz = sx, sz
            m.set_data([sx], [sz])
            m.set_visible(True)
            txt = ("%s    x = %8.2f mm    z = %8.2f mm    |    %s   [sample %d]"
                   % (pos, sx, sz, name, idx))
        else:
            cx, cz = event.xdata, event.ydata
            m.set_visible(False)
            txt = ("%s    x = %8.2f mm    z = %8.2f mm    |    "
                   "(no sample within %d px)" % (pos, cx, cz, SNAP_MAX_PX))
        v.set_data([cx, cx], [y0, y1])
        h.set_data([x0, x1], [cz, cz])
        v.set_visible(True)
        h.set_visible(True)

        try:
            self.canvas.restore_region(self._bg)
            for a in (v, h, m):
                if a.get_visible():
                    ax.draw_artist(a)
            self.canvas.blit(self.fig.bbox)
        except Exception:
            self.canvas.draw_idle()
        self._emit(txt)

    # ---------------- zoom / pan / maximise ----------------
    @staticmethod
    def _mods():
        try:
            m = QApplication.keyboardModifiers()
            return (bool(m & Qt.KeyboardModifier.ShiftModifier),
                    bool(m & Qt.KeyboardModifier.ControlModifier))
        except Exception:
            return False, False

    @staticmethod
    def _zoom_axis(lo, hi, at, f):
        return at - (at - lo) * f, at + (hi - at) * f

    def _on_scroll(self, event):
        ax = event.inaxes
        if ax is None or ax not in self._curves or event.xdata is None:
            return
        shift, ctrl = self._mods()
        f = (1.0 / ZOOM_STEP) if event.step > 0 else ZOOM_STEP
        do_x = not ctrl
        # with auto-Z armed an x zoom already re-fits z; zooming z here as well would
        # be undone a moment later and the wheel would feel dead in the vertical
        do_y = (not shift) and not (do_x and self._auto_z)
        if do_y:
            self._suspend_autoz = True
            lo, hi = ax.get_ylim()
            ax.set_ylim(*self._zoom_axis(lo, hi, event.ydata, f))
            self._suspend_autoz = False
        if do_x:
            lo, hi = ax.get_xlim()
            ax.set_xlim(*self._zoom_axis(lo, hi, event.xdata, f))
        self.canvas.draw_idle()

    def _on_press(self, event):
        if event.inaxes is None or event.inaxes not in self._curves:
            return
        if event.dblclick:
            if self._on_maximize is not None:
                self._on_maximize(self._keys.get(event.inaxes))
            return
        # only when no toolbar tool is armed, otherwise this would fight zoom-rect
        if event.button == 1 and not str(getattr(self.toolbar, "mode", "") or ""):
            self._pan_ax = event.inaxes
            self._pan_px = (event.x, event.y)
            self._suspend_autoz = True

    def _on_release(self, _event):
        if self._pan_ax is not None:
            self._pan_ax = None
            self._pan_px = None
            self._suspend_autoz = False

    def _do_pan(self, event):
        ax = self._pan_ax
        if ax is None or event.x is None:
            return
        inv = ax.transData.inverted()
        # the press pixel is re-projected through the CURRENT limits every move, so
        # the grabbed point stays under the cursor instead of drifting
        x0, y0 = inv.transform(self._pan_px)
        x1, y1 = inv.transform((event.x, event.y))
        dx, dy = x0 - x1, y0 - y1
        xlo, xhi = ax.get_xlim()
        ylo, yhi = ax.get_ylim()
        ax.set_xlim(xlo + dx, xhi + dx)
        ax.set_ylim(ylo + dy, yhi + dy)
        self.canvas.draw_idle()

    def _on_key(self, event):
        if event.key in ("r", "R"):
            try:
                self.toolbar.home()
            except Exception:
                pass
        elif event.key == "escape" and self._on_maximize is not None:
            self._on_maximize(None)

    # ---------------- auto-Z ----------------
    def _on_xlim_changed(self, ax):
        if not self._auto_z or self._suspend_autoz or self._in_autoz:
            return
        curves = self._curves.get(ax)
        if not curves:
            return
        x0, x1 = sorted(ax.get_xlim())
        lo = hi = None
        for _name, x, z in curves:
            i0 = int(np.searchsorted(x, x0, "left"))
            i1 = int(np.searchsorted(x, x1, "right"))
            if i1 <= i0:
                continue
            seg = z[i0:i1]
            seg = seg[np.isfinite(seg)]
            if seg.size == 0:
                continue
            a, b = float(seg.min()), float(seg.max())
            lo = a if lo is None else min(lo, a)
            hi = b if hi is None else max(hi, b)
        if lo is None:
            return
        if hi - lo < 1e-9:                       # a flat window still needs a window
            lo, hi = lo - 0.5, hi + 0.5
        pad = (hi - lo) * AUTO_Z_PAD
        self._in_autoz = True
        try:
            ax.set_ylim(lo - pad, hi + pad)
        finally:
            self._in_autoz = False
