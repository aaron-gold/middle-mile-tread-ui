# v1.10: the TIF polarity rule lives in uveye_common (one copy for the viewer and the IQ toolkit).
# Middle Mile tread / tire-wall .tif files omit TIFF tag 262; Pillow then falls back to
# WhiteIsZero and returns (dtype max - stored sample). read_true() undoes exactly that, and
# leaves files that DO declare 262, and non-TIFF files, untouched.
