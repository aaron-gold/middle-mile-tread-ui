# ============================================================
# IMAGE LOADING  (byte-faithful, no value manipulation)
# ============================================================
def _load_via_pil(path):
    if not PIL_AVAILABLE:
        return None
    try:
        return read_true(lp(path))          # native dtype, PIL RGB order, polarity restored
    except Exception:
        return None


def _imread_unicode(path):
    """cv2.imread cannot open non-ASCII Windows paths - read the bytes ourselves."""
    try:
        buf = np.fromfile(lp(path), dtype=np.uint8)
        if buf.size == 0:
            return None
        return cv2.imdecode(buf, cv2.IMREAD_UNCHANGED)
    except Exception:
        return None


def load_image_raw(path):
    """
    Load an image exactly as stored. Returns a numpy array in native dtype, or None.
    Colour images are returned in RGB order (channel order only is corrected).
    Grayscale stays 2-D. No normalization / contrast / bit manipulation.

    Middle Mile tread/OCR .tif files carry a non-standard TIFF header that
    OpenCV's libtiff rejects, so .tif/.tiff are decoded with Pillow first
    (cv2 as fallback). Standard formats go through cv2 first.
    """
    ext = os.path.splitext(path)[1].lower()
    if ext in (".tif", ".tiff"):
        a = _load_via_pil(path)
        if a is not None:
            return a

    a = _imread_unicode(path)
    if a is None:
        return _load_via_pil(path)
    if a.ndim == 3:
        if a.shape[2] == 3:
            a = a[:, :, ::-1]                    # BGR -> RGB
        elif a.shape[2] == 4:
            a = a[:, :, [2, 1, 0, 3]]            # BGRA -> RGBA
    return np.ascontiguousarray(a)


class FrameCache:
    """
    Tiny LRU of decoded RAW frames. Frame stepping / slider dragging re-reads the
    same 3-20 MB TIFs constantly; caching keeps stepping responsive without ever
    changing pixel values (the cached array IS the decoded array).
    """
    def __init__(self, max_items=10, max_bytes=768 * 1024 * 1024):
        self.max_items = max_items
        self.max_bytes = max_bytes
        self._d = OrderedDict()
        self._bytes = 0

    def get(self, path):
        try:
            key = (path, os.path.getmtime(path))
        except OSError:
            return None
        a = self._d.get(key)
        if a is not None:
            self._d.move_to_end(key)
        return a

    def put(self, path, arr):
        if arr is None:
            return
        try:
            key = (path, os.path.getmtime(path))
        except OSError:
            return
        if key in self._d:
            return
        self._d[key] = arr
        self._bytes += arr.nbytes
        while self._d and (len(self._d) > self.max_items or self._bytes > self.max_bytes):
            _k, old = self._d.popitem(last=False)
            self._bytes -= old.nbytes

    def clear(self):
        self._d.clear()
        self._bytes = 0


FRAME_CACHE = FrameCache()


def load_frame_cached(path):
    a = FRAME_CACHE.get(path)
    if a is None:
        a = load_image_raw(path)
        FRAME_CACHE.put(path, a)
    return a


def raw_to_gray_f32(raw):
    """Grayscale float32 view of the RAW data (for faithful measurements)."""
    if raw is None:
        return None
    if raw.ndim == 2:
        return raw.astype(np.float32)
    c = raw[:, :, :3].astype(np.float32)   # RGB
    return 0.299 * c[:, :, 0] + 0.587 * c[:, :, 1] + 0.114 * c[:, :, 2]


def _to_uint8_for_display(raw):
    """
    Convert to 8-bit ONLY when the source is not already 8-bit (needed so Qt can show
    it). 8-bit data is passed through untouched. Non-8-bit is scaled by the dtype's
    full range (display necessity, flagged in the UI) - not a contrast stretch.
    Float images in 0..1 are scaled by 255 (otherwise they would render black).
    """
    if raw.dtype == np.uint8:
        return raw, False
    if np.issubdtype(raw.dtype, np.integer):
        info = np.iinfo(raw.dtype)
        lo = 0 if info.min >= 0 else info.min
        span = max(1, int(info.max) - int(lo))
        a8 = ((raw.astype(np.float32) - lo) * (255.0 / span)).clip(0, 255).astype(np.uint8)
        return a8, True
    # floating point
    finite = raw[np.isfinite(raw)] if raw.size else raw
    vmax = float(finite.max()) if finite.size else 1.0
    scale = 255.0 if vmax <= 1.0 + 1e-6 else 1.0
    a8 = np.nan_to_num(raw.astype(np.float32) * scale, nan=0.0,
                       posinf=255.0, neginf=0.0).clip(0, 255).astype(np.uint8)
    return a8, True


def to_display_rgb(raw, gamma=1.0, brightness=0):
    """
    Build the on-screen RGB image. Default (gamma=1, brightness=0, 8-bit source) is a
    faithful copy of the data. Gamma/brightness are view-only.
    Returns (rgb_uint8_contiguous, display_scaled_flag).
    """
    a8, scaled = _to_uint8_for_display(raw)
    if a8.ndim == 2:
        rgb = np.stack([a8, a8, a8], axis=-1)
    elif a8.shape[2] == 4:
        rgb = a8[:, :, :3].copy()
    elif a8.shape[2] == 3:
        rgb = a8.copy()
    else:                                       # 2-channel or exotic -> use first plane
        p = a8[:, :, 0]
        rgb = np.stack([p, p, p], axis=-1)

    if brightness != 0:
        rgb = np.clip(rgb.astype(np.int16) + int(brightness), 0, 255).astype(np.uint8)
    if gamma and gamma > 0 and abs(gamma - 1.0) > 1e-9:
        table = np.array([(i / 255.0) ** gamma * 255 for i in range(256)], dtype=np.uint8)
        rgb = cv2.LUT(rgb, table)
    return np.ascontiguousarray(rgb), scaled


def imwrite_unicode(path, rgb):
    """
    Save an RGB uint8 array as PNG. Uses imencode + tofile so non-ASCII Windows
    paths work, and forces a contiguous BGR buffer (a reversed view has negative
    strides and makes cv2 fail silently).
    """
    try:
        bgr = np.ascontiguousarray(rgb[:, :, ::-1])
        ok, buf = cv2.imencode(".png", bgr)
        if not ok:
            return False
        buf.tofile(path)
        return True
    except Exception:
        return False
