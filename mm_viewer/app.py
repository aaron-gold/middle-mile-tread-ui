from mm_viewer.common import _APP_DIR
from mm_viewer.theme import ICON_PATH, LIGHT_QSS
from mm_viewer.main_window import MainWindow


# ============================================================
# EXE BUILDER
# ============================================================
def build_exe():
    exe_name = "MiddleMile_GUI_v1.15"
    script_path = Path(_APP_DIR) / "MiddleMile_GUI.py"     # the launcher
    assets_dir = script_path.parent / "assets"
    py = sys.executable
    try:
        subprocess.check_call([py, "-m", "PyInstaller", "--version"])
    except Exception:
        print("PyInstaller not found. Install it:  pip install pyinstaller")
        sys.exit(1)
    cmd = [py, "-m", "PyInstaller", "--onefile", "--noconsole", "--name", exe_name]
    if assets_dir.is_dir():
        cmd += ["--add-data", f"{assets_dir}{os.pathsep}assets"]
        ico = assets_dir / "uveye_logo.ico"
        if ico.is_file():
            cmd += ["--icon", str(ico)]
    cmd.append(str(script_path))
    print("Building EXE:", " ".join(cmd))
    subprocess.check_call(cmd)
    print("\nDONE ->", script_path.parent / "dist" / f"{exe_name}.exe")
    sys.exit(0)


# ============================================================
# ENTRY
# ============================================================
def install_exception_guard():
    """
    Keep a Python error from killing the whole app.

    PyQt6 hands an unhandled exception raised inside a slot to sys.excepthook and
    the DEFAULT hook calls qFatal() - the process dies instantly, with no traceback
    and no chance to save work. Replacing the hook keeps the app alive: the error
    is printed and shown in a dialog, and the user can carry on.
    v1.10: the hook itself is uveye_common.qt_guard (same text, binding-agnostic).
    """
    from uveye_common.qt_guard import install_exception_guard as _install_guard
    _install_guard(lambda title, text: QMessageBox.warning(None, title, text))


def main():
    if "--build-exe" in sys.argv:
        build_exe()
    install_exception_guard()
    app = QApplication(sys.argv)
    app.setStyleSheet(LIGHT_QSS)
    if os.path.isfile(ICON_PATH):
        app.setWindowIcon(QIcon(ICON_PATH))
    win = MainWindow()
    # Open maximised, but never larger than the work area. The window's own
    # minimumSizeHint used to be 1827x946, so on a smaller display Qt could not
    # honour the maximise and the right-hand controls sat off the screen edge.
    # The toolbars now wrap, and the restore geometry is clamped to what the screen
    # actually has, so "maximised" really is the work area on every display.
    scr = app.primaryScreen()
    if scr is not None:
        avail = scr.availableGeometry()
        w = min(win.width(), avail.width())
        h = min(win.height(), avail.height())
        win.resize(w, h)
        win.move(avail.left() + (avail.width() - w) // 2,
                 avail.top() + (avail.height() - h) // 2)
    win.showMaximized()
    # optional: a scan folder or a scan .tar on the command line opens straight away
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    if args:
        QTimer.singleShot(0, lambda p=args[0]: win.load_path(os.path.abspath(p)))
    sys.exit(app.exec())


if __name__ == "__main__":
    main()
