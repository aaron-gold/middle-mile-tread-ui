def classify_folder(folder_name):
    """
    Return (collection_id, group_key, camera_id, variant) for a leaf camera folder,
    or (None, None, None, None) if it is not a recognised camera folder.
    variant is 'raw' or 'compressed'. camera_id strips the 'compressed_' prefix so the
    same physical camera pairs its raw and compressed folders.
    """
    raw_name = folder_name
    low = folder_name.lower()

    if low.startswith("compressed_"):
        variant = "compressed"
        core = raw_name[len("compressed_"):]
    else:
        variant = "raw"
        core = raw_name
    core_low = core.lower()

    # Laser-groove ALGO diagnostics - a data folder, not an image camera. Checked
    # before the groove folder: "laser_tread" contains neither GROOVE_HINT nor
    # GROOVE_NAMES, and "diagnostics" matches nothing else, so order is not critical,
    # but keeping it first makes the intent explicit.
    if core_low in DIAG_NAMES or DIAG_HINT in core_low:
        return (COL_DIAG, "Artemis", core, variant)

    # Groove depth (LMI laser) - a data folder, not an image camera
    if core_low in GROOVE_NAMES or GROOVE_HINT in core_low:
        return ("ArtemisGroove", "Artemis", core, variant)

    # Wheel assembler trigger/sensor log - a data folder, not an image camera
    if core_low in WA_NAMES or WA_HINT in core_low:
        return (COL_WA, None, core, variant)

    if core_low.startswith(OCR_PREFIXES) or (
            core_low.startswith(OCR_NEW_PREFIX) and OCR_NEW_HINT in core_low):
        return (COL_OCR, "Artemis", core, variant)
    if core_low.startswith(TREAD_PREFIXES):
        return (COL_TREAD, "Artemis", core, variant)
    if core_low.startswith(ATLAS_PREFIXES):
        return (COL_ATLAS, "Atlas", core, variant)
    if core_low.startswith(HELIOS_PREFIXES):
        return (COL_HELIOS, "Helios", core, variant)

    return (None, None, None, None)
