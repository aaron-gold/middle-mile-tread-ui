def _fit_legend(ax, handles, labels, **kw):
    """
    Draw a legend that cannot resize the axes and does not tower over them.

    Returns the Legend, or None when there is nothing to list. See the LEGEND
    GEOMETRY note above for why both halves are needed; either one alone leaves a
    real defect on screen.
    """
    if not handles:
        return None
    ncol = 1
    try:
        # axes height in pixels for the CURRENT canvas, so the same code is right on
        # a tall window and a short one
        ax_px = ax.get_window_extent().height
        budget = max(ax_px * LEGEND_MAX_AXES_FRAC - LEGEND_CHROME_PX, LEGEND_ROW_PX)
        rows_per_col = max(int(budget // LEGEND_ROW_PX), 1)
        ncol = min(max(-(-len(handles) // rows_per_col), 1), LEGEND_MAX_COLS)
    except Exception:
        pass                                # geometry not available yet: one column
    kw.setdefault("fontsize", LEGEND_FS)
    kw.setdefault("framealpha", 0.85)
    leg = ax.legend(handles, labels, ncol=ncol, **kw)
    # THE fix for the collapsing subplots. Without it tight-layout sizes the axes to
    # fit the legend instead of the other way round.
    try:
        leg.set_in_layout(False)
    except Exception:
        pass
    return leg

