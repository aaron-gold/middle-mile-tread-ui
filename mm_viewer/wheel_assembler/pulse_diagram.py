# ============================================================
# SYSTEM PULSE DIAGRAM VIEWER  (v1.1 - his saved PNG, readable)
# ============================================================
#
# His system_pulse_diagram.png is a 4500 x 5100 px portrait figure with 11-13 rows.
# Drawn through matplotlib and contain-fitted into a wide, short pane it came out
# ~600 px wide - every row label and tick unreadable. It is now shown by Qt directly:
#   * FIT WIDTH (default): the figure fills the pane's width and the pane scrolls
#     vertically - at a 1500 px pane that is 1/3 scale, where his 8.5 pt row labels
#     are ~10 px tall and every row is legible. Scroll down to read the lower rows.
#   * The pixmap is PRE-SCALED with Qt's smooth (area-averaging) filter to the exact
#     on-screen size, instead of letting the view down-sample a 4500 px bitmap on the
#     fly with bilinear filtering, which drops 1-px trace lines and thins text.
#   * Whole figure / 100 % / Ctrl+wheel zoom / drag to pan / double-click = full
#     screen. The image itself is never altered (only the flat margin is trimmed for
#     display, same rule as _wa_trim_border).
PNG_FIT_WIDTH = "width"
PNG_FIT_PAGE = "page"
PNG_ACTUAL = "actual"
PNG_FIT_MODES = ((PNG_FIT_WIDTH, "Fit width"), (PNG_FIT_PAGE, "Whole figure"),
                 (PNG_ACTUAL, "100 %"))


# v1.2: the pulse PNG (4500 x 5100) is decoded and trimmed on the scan-load THREAD
# (ScanPrescanWorker) instead of on the GUI thread while the tabs are built - that
# was ~0.7 s of frozen window. QImage is safe to build off the GUI thread (QPixmap is
# not). Keyed by path + size + mtime so a rewritten file is never served stale; holds
# one scan's diagram at a time.
_DIAGRAM_CACHE = {}


def _diagram_key(path):
    try:
        st = lp_stat(path)
        return (os.path.abspath(path), st.st_size, st.st_mtime_ns)
    except Exception:
        return None


def preload_diagram_qimage(path):
    """Worker-thread side: decode + trim once, park the result for the GUI thread."""
    key = _diagram_key(path) if path else None
    if key is None:
        return
    res = _load_diagram_qimage(path)
    _DIAGRAM_CACHE.clear()
    _DIAGRAM_CACHE[key] = res


def load_diagram_qimage(path):
    """(QImage trimmed of its flat margin, error or None). Never raises."""
    key = _diagram_key(path) if path else None
    if key is not None and key in _DIAGRAM_CACHE:
        img, err = _DIAGRAM_CACHE[key]
        return (QImage(img) if img is not None else None), err
    return _load_diagram_qimage(path)


def _load_diagram_qimage(path):
    if not path or not lp_isfile(path):
        return None, "no saved diagram"
    try:
        with lp_open(path, "rb") as fh:
            data = fh.read()
    except Exception as exc:
        return None, "%s: %s" % (type(exc).__name__, exc)
    img = QImage.fromData(data)
    if img.isNull():
        return None, "not a readable image"
    try:
        box = _diagram_ink_bbox(data)
        if box is not None:
            x0, y0, x1, y1 = box
            if (x1 - x0, y1 - y0) != (img.width(), img.height()):
                img = img.copy(QRect(x0, y0, x1 - x0, y1 - y0))
    except Exception:
        pass                                     # cosmetic crop only
    return img, None


def _diagram_ink_bbox(data, pad=WA_DIAG_TRIM_PAD, tol=5):
    """
    (x0, y0, x1, y1) of everything that is not flat background, padded, or None.

    Same timid rule as _wa_trim_border - background = the corner pixel, anything more
    than `tol` away from it in ANY channel is ink - but done by Pillow in C: the numpy
    version builds float copies of a 4500 x 5100 figure (~275 MB) for a cosmetic crop.
    A transparent margin is composited onto white first, so alpha decides it.
    """
    if not PIL_AVAILABLE:
        return None
    from PIL import ImageChops
    with Image.open(io.BytesIO(data)) as im:
        im.load()
        if im.mode in ("RGBA", "LA", "P"):
            rgba = im.convert("RGBA")
            base = Image.new("RGBA", rgba.size, (255, 255, 255, 255))
            rgb = Image.alpha_composite(base, rgba).convert("RGB")
        else:
            rgb = im.convert("RGB")
    bg = rgb.getpixel((0, 0))
    diff = ImageChops.difference(rgb, Image.new("RGB", rgb.size, bg))
    r, g, b = diff.split()
    mx = ImageChops.lighter(ImageChops.lighter(r, g), b)
    bbox = mx.point(lambda v: 255 if v > tol else 0).getbbox()
    if not bbox:
        return None
    x0, y0, x1, y1 = bbox
    W, H = rgb.size
    x0, y0 = max(0, x0 - pad), max(0, y0 - pad)
    x1, y1 = min(W, x1 + pad), min(H, y1 + pad)
    if (x1 - x0) < 16 or (y1 - y0) < 16:
        return None
    return x0, y0, x1, y1


class PulseDiagramView(QGraphicsView):
    """A read-only, readable view of one large figure PNG."""
    zoomChanged = pyqtSignal(float)          # current on-screen scale, 1.0 = 100 %
    doubleClicked = pyqtSignal()

    MIN_SCALE = 0.05
    MAX_SCALE = 1.5
    MAX_PIXELS = 64e6          # pre-scaled pixmap budget (~256 MB ARGB) - see _apply

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setScene(QGraphicsScene(self))
        self._src = None                     # QImage, full resolution
        self._item = None
        self._mode = PNG_FIT_PAGE           # v1.3 default: the whole figure
        self._scale = 1.0                    # on-screen px per source px
        self._cache_key = None
        self.setRenderHints(QPainter.RenderHint.SmoothPixmapTransform
                            | QPainter.RenderHint.Antialiasing)
        self.setDragMode(QGraphicsView.DragMode.ScrollHandDrag)
        self.setTransformationAnchor(QGraphicsView.ViewportAnchor.NoAnchor)
        self.setAlignment(Qt.AlignmentFlag.AlignHCenter | Qt.AlignmentFlag.AlignTop)
        self.setBackgroundBrush(QBrush(QColor("#ffffff")))
        self.setStyleSheet("QGraphicsView{background:#ffffff;border:1px solid %s;"
                           "border-radius:8px;}" % C_BORDER)
        self.setMinimumHeight(160)
        self._refit_timer = QTimer(self)
        self._refit_timer.setSingleShot(True)
        self._refit_timer.timeout.connect(self._apply)

    # ---- data ----
    def set_image(self, qimage):
        self._src = qimage if (qimage is not None and not qimage.isNull()) else None
        self._cache_key = None
        self._apply()

    def has_image(self):
        return self._src is not None

    def image_size(self):
        return (self._src.width(), self._src.height()) if self._src else (0, 0)

    def scale_factor(self):
        return self._scale

    def mode(self):
        return self._mode

    def set_mode(self, mode):
        if mode not in (PNG_FIT_WIDTH, PNG_FIT_PAGE, PNG_ACTUAL):
            return
        self._mode = mode
        if mode == PNG_ACTUAL:
            self._scale = 1.0
        self._apply()

    # ---- sizing ----
    def _fit_scale(self):
        if self._src is None:
            return 1.0
        vp = self.viewport().size()
        w, h = max(1, self._src.width()), max(1, self._src.height())
        bar = self.verticalScrollBar()
        # the viewport already excludes a VISIBLE bar; only a bar that is about to
        # appear has to be taken off in advance
        sb = 0 if bar.isVisible() else bar.sizeHint().width()
        if self._mode == PNG_FIT_WIDTH:
            # the vertical scrollbar WILL be there (the figure is taller than the
            # pane at width-fit), so its width is taken off up front - otherwise the
            # bar appears, steals the width, and a horizontal bar follows it
            avail = vp.width() - (sb if (vp.width() * h / w) > vp.height() else 0) - 4
            return max(self.MIN_SCALE, min(self.MAX_SCALE, avail / float(w)))
        if self._mode == PNG_FIT_PAGE:
            return max(self.MIN_SCALE, min(self.MAX_SCALE,
                                           min((vp.width() - 2) / float(w),
                                               (vp.height() - 2) / float(h))))
        return self._scale

    def _apply(self):
        """Re-render the pixmap at the exact on-screen size (area-filtered)."""
        sc = self.scene()
        if self._src is None:
            sc.clear()
            self._item = None
            self.zoomChanged.emit(0.0)
            return
        if self._mode in (PNG_FIT_WIDTH, PNG_FIT_PAGE):
            self._scale = self._fit_scale()
        dpr = max(1.0, float(self.devicePixelRatioF()))
        # the whole figure is pre-scaled, so the zoom is capped by a PIXEL budget:
        # 4500 x 5100 at 4x on a 150 % display would be a 3 GB allocation
        area = float(self._src.width() * self._src.height()) or 1.0
        self._scale = min(self._scale, (self.MAX_PIXELS / area) ** 0.5 / dpr)
        s = self._scale
        tw = max(1, int(self._src.width() * s * dpr))
        th = max(1, int(self._src.height() * s * dpr))
        key = (tw, th)
        if key != self._cache_key:
            same = (tw, th) == (self._src.width(), self._src.height())
            pm = QPixmap.fromImage(self._src if same else self._src.scaled(
                tw, th, Qt.AspectRatioMode.IgnoreAspectRatio,
                Qt.TransformationMode.SmoothTransformation))
            pm.setDevicePixelRatio(dpr)
            # keep the reading position (as a fraction) across a re-render
            vb = self.verticalScrollBar()
            frac = (vb.value() / float(vb.maximum())) if vb.maximum() > 0 else 0.0
            sc.clear()
            self._item = sc.addPixmap(pm)
            self._item.setTransformationMode(Qt.TransformationMode.SmoothTransformation)
            sc.setSceneRect(QRectF(0, 0, tw / dpr, th / dpr))
            self.resetTransform()
            self._cache_key = key
            if vb.maximum() > 0:
                vb.setValue(int(round(frac * vb.maximum())))
        self.zoomChanged.emit(s)

    def resizeEvent(self, ev):
        super().resizeEvent(ev)
        if self._mode in (PNG_FIT_WIDTH, PNG_FIT_PAGE):
            self._refit_timer.start(60)       # debounced: a drag-resize is many events

    def wheelEvent(self, ev):
        if ev.modifiers() & Qt.KeyboardModifier.ControlModifier and self._src is not None:
            f = 1.15 if ev.angleDelta().y() > 0 else 1 / 1.15
            new = max(self.MIN_SCALE, min(self.MAX_SCALE, self._scale * f))
            if abs(new - self._scale) < 1e-6:
                return
            # zoom about the cursor: keep the image point under it in place
            pos = ev.position()
            before = self.mapToScene(pos.toPoint())
            ratio = new / self._scale
            self._mode = "custom"
            self._scale = new
            self._apply()
            target = QPointF(before.x() * ratio, before.y() * ratio)
            self.horizontalScrollBar().setValue(int(target.x() - pos.x()))
            self.verticalScrollBar().setValue(int(target.y() - pos.y()))
            ev.accept()
            return
        super().wheelEvent(ev)

    def mouseDoubleClickEvent(self, ev):
        self.doubleClicked.emit()
        ev.accept()


class PulseDiagramPane(QWidget):
    """PulseDiagramView + its sizing strip. Used in the tab and in the full window."""
    doubleClicked = pyqtSignal()

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setObjectName("pngPane")
        self.setAttribute(Qt.WidgetAttribute.WA_StyledBackground, True)
        self.view = PulseDiagramView()
        self.view.doubleClicked.connect(self.doubleClicked)
        self.mode_seg = SegmentedControl(list(PNG_FIT_MODES))
        self.mode_seg.set_current(PNG_FIT_PAGE)
        self.mode_seg.setToolTip(
            "Fit width - the figure fills the pane's width; scroll down "
            "through the rows.\nWhole figure (default) - everything on one screen.\n"
            "100 % - the PNG's own pixels.")
        # every click applies its mode - including a click on the one already lit,
        # which is how a Ctrl+wheel zoom is undone back to Fit width
        for key, (btn, _label) in self.mode_seg._buttons.items():
            btn.clicked.connect(lambda _c=False, k=key: self.view.set_mode(k))
        self.zoom_lbl = QLabel("—")
        self.zoom_lbl.setObjectName("pixelLabel")
        self.zoom_lbl.setMinimumWidth(64)
        self.view.zoomChanged.connect(self._on_zoom)
        hint = QLabel("scroll = move through the rows  ·  Ctrl+wheel = zoom  ·  "
                      "drag = pan  ·  double-click = full screen")
        hint.setObjectName("hintText")
        allow_shrink(hint, 120)
        row = QHBoxLayout()
        row.setContentsMargins(0, 0, 0, 0)
        row.setSpacing(8)
        row.addWidget(field_label("Size"))
        row.addWidget(self.mode_seg)
        row.addWidget(self.zoom_lbl)
        row.addWidget(hint, 1)
        lay = QVBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)
        lay.setSpacing(6)
        lay.addLayout(row)
        lay.addWidget(self.view, 1)

    def _on_zoom(self, s):
        self.zoom_lbl.setText("%d %%" % round(s * 100) if s > 0 else "—")
        m = self.view.mode()
        if m in (PNG_FIT_WIDTH, PNG_FIT_PAGE, PNG_ACTUAL):
            if self.mode_seg.current() != m:
                self.mode_seg.set_current(m)

    def set_image(self, qimage):
        self.view.set_image(qimage)


class PulseDiagramWindow(QDialog):
    """His PNG in its own maximisable window. Parented, not WA_DeleteOnClose."""

    def __init__(self, qimage, title, parent=None):
        super().__init__(parent)
        self.setWindowTitle(title)
        self.setWindowFlag(Qt.WindowType.WindowMaximizeButtonHint, True)
        self.setSizeGripEnabled(True)
        self.pane = PulseDiagramPane(self)
        lay = QVBoxLayout(self)
        lay.setContentsMargins(8, 8, 8, 8)
        lay.addWidget(self.pane)
        self.pane.set_image(qimage)
