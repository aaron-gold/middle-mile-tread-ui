WA_ENGINEER_MIN_PX = 260
# Per ROW, once the grid can be taller than his eleven. 260/11 is what the measured
# floor above works out to; keeping the same per-row height is what stops a 12- or
# 13-row figure from being squeezed into the space eleven rows needed.
WA_ENGINEER_MIN_PX_PER_ROW = 24


def wa_engineer_min_px(n_rows):
    """
    Legibility floor for a generated diagram of `n_rows` rows.

    At his eleven rows this is the MEASURED floor above and nothing else - a 1- or
    2-axle scan is sized exactly as it was before the N-axle figure existed. Only the
    rows beyond his eleven add height, so a 12-row figure is not squeezed into the
    space eleven rows needed and an 11-row one gains nothing it did not have.
    """
    try:
        n = int(n_rows or WA_ENGINEER_ROWS)
    except (TypeError, ValueError):
        n = WA_ENGINEER_ROWS
    if n <= WA_ENGINEER_ROWS:
        return WA_ENGINEER_MIN_PX
    return int(WA_ENGINEER_MIN_PX
               + WA_ENGINEER_MIN_PX_PER_ROW * (n - WA_ENGINEER_ROWS))


def wa_engineer_choice(axle_index):
    """
    (script, function, n_axles) - WHICH plot script draws this scan's diagram.

    Decided from the axle count alone, and from nothing else: at one or two axles his
    own script is the whole vehicle and is run unchanged; at three or more it has no
    row to put the rest in, so the N-axle twin is run instead. The count is reported
    back so the caller can size the canvas and say which script it got.
    """
    n = int(getattr(axle_index, "n_axles", 0) or 0)
    if n >= WA_N_AXLE_MIN:
        return ENGINEER_PLOT_SCRIPT_N, ENGINEER_PLOT_FUNC_N, n
    return ENGINEER_PLOT_SCRIPT, ENGINEER_PLOT_FUNC, n


def wa_engineer_rows(axle_index):
    """How many rows the diagram for this scan has."""
    script, _fn, n = wa_engineer_choice(axle_index)
    if script == ENGINEER_PLOT_SCRIPT_N:
        return WA_NAXLE_FIXED_ROWS + max(n, 1)
    return WA_ENGINEER_ROWS

# Re-fit constants. Every one of them replaces a print-scale value in his script with
# the screen-scale equivalent; they are gathered here so the fit is one edit.
WA_FIT_LABELPAD = 6.0          # his 120 pt gutter -> a right-aligned label at the axis
WA_FIT_LABEL_FS = 7.0          # his 8.5 pt row labels
WA_FIT_TICK_FS = 6.5           # his 9 pt bold '0'/'1' tick labels
WA_FIT_LEGEND_FS = 6.0         # his 8.5 pt axle legends
WA_FIT_XLABEL_FS = 8.5         # his 12 pt x label
WA_FIT_SUPTITLE_FS = 10.0      # his 14 pt suptitle
# hspace was 0.34. Eleven rows in a short pane read as one block when the gap between
# them is smaller than the trace inside them, so the gap is widened - at the cost of
# ~4 px of row height each, which the fitted view and the full-size window both have
# to spare. left/right are also pulled in: his row labels are re-fitted to sit against
# the axis (WA_FIT_LABELPAD), so the old gutter was width the traces were not getting.
WA_FIT_MARGINS = dict(left=0.135, right=0.995, top=0.945, bottom=0.075, hspace=0.46)

# subplots_adjust works in FIGURE FRACTIONS, and the x label and suptitle do not
# shrink with the pane - so a fraction that leaves room at 430 px clips the x label at
# 300 px, which is exactly what a short window gives this tab. These are the pixel
# heights those two need; the fractions above are floors, and whichever is larger
# wins at the size the figure is actually drawn at.
WA_FIT_BOTTOM_PX = 38.0        # x tick labels + "Time (Seconds from Vehicle Entry)"
WA_FIT_TOP_PX = 22.0           # the suptitle
WA_FIT_MAX_MARGIN = 0.30       # never eat more than this much of the figure


def _wa_refit_engineer_axes(fig):
    """
    Re-fit his print-scale typography to the pane, after his function has drawn.

    Reads nothing off his script and re-plots nothing: it walks the axes he created
    and adjusts label padding, alignment and font sizes so eleven rows are legible
    without a scrollbar. Every failure is swallowed per-element - a diagram with one
    un-resized label is still the diagram, and an exception here would take the whole
    view down for a cosmetic reason.
    """
    axes = list(getattr(fig, "axes", []) or [])
    if not axes:
        return
    for ax in axes:
        try:
            lab = ax.get_ylabel()
            if lab:
                # ha='right' with a small pad puts the label AGAINST the axis instead
                # of 120 pt out in a gutter the pane cannot afford. His rotation (0)
                # and colour are read back off the artist, never re-decided here.
                ax.set_ylabel(lab, rotation=0, ha="right", va="center",
                              labelpad=WA_FIT_LABELPAD,
                              fontsize=WA_FIT_LABEL_FS, fontweight="bold",
                              color=ax.yaxis.label.get_color())
            ax.tick_params(axis="both", labelsize=WA_FIT_TICK_FS,
                           pad=1.5, length=2)
            leg = ax.get_legend()
            if leg is not None:

                handles, labels = ax.get_legend_handles_labels()
                if handles:
                    ax.legend(handles, labels, loc=leg._loc if
                              isinstance(getattr(leg, "_loc", None), (int, str))
                              else "upper right",
                              ncol=len(handles), fontsize=WA_FIT_LEGEND_FS,
                              frameon=True, framealpha=0.85, borderpad=0.25,
                              handlelength=1.3, handletextpad=0.4,
                              labelspacing=0.15, columnspacing=0.9,
                              borderaxespad=0.25)
                else:
                    for txt in leg.get_texts():
                        txt.set_fontsize(WA_FIT_LEGEND_FS)
        except Exception:
            continue
    try:
        xlab = axes[-1].get_xlabel()
        if xlab:
            axes[-1].set_xlabel(xlab, fontsize=WA_FIT_XLABEL_FS, fontweight="bold")
    except Exception:
        pass
    try:
        if getattr(fig, "_suptitle", None) is not None:
            fig._suptitle.set_fontsize(WA_FIT_SUPTITLE_FS)
            fig._suptitle.set_y(0.995)
    except Exception:
        pass

    try:
        fig.set_layout_engine("none")
    except Exception:
        pass
    try:
        h_px = max(float(fig.get_figheight()) * float(fig.dpi), 1.0)
        margins = dict(WA_FIT_MARGINS)
        # hspace is a FRACTION OF ROW HEIGHT, so the gap his eleven rows can afford
        # takes a 12- or 13-row figure past what the pane has. It is scaled back by
        # the row count, with a floor that keeps the rows visibly separate.
        n_rows = max(len(axes), 1)
        if n_rows > WA_ENGINEER_ROWS:
            margins["hspace"] = max(0.30, margins["hspace"]
                                    * float(WA_ENGINEER_ROWS) / float(n_rows))
        margins["bottom"] = min(WA_FIT_MAX_MARGIN,
                                max(margins["bottom"], WA_FIT_BOTTOM_PX / h_px))
        margins["top"] = max(1.0 - WA_FIT_MAX_MARGIN,
                             min(margins["top"], 1.0 - WA_FIT_TOP_PX / h_px))
        fig.subplots_adjust(**margins)
    except Exception:
        pass


class _WaPlotHost:
    """
    The `self` a plot fragment reads: a trigger CSV and an output folder.

    `n_axles` and `axle_source` are read by the N-axle script only, and only when they
    are there - his own fragment never looks for them, so handing them over cannot
    change what it draws. They exist so the figure draws a row for every axle the
    SPLIT resolved rather than only for the ones the trigger log happens to support,
    which is what stops the figure and the banner from disagreeing.
    """

    def __init__(self, triggers_file, output_dir, n_axles=0, axle_source=None):
        self.triggers_file = triggers_file
        self.output_dir = output_dir
        self.n_axles = int(n_axles or 0)
        self.axle_source = axle_source


class _WaPyplotShim:
    """
    Stands in for `plt` inside his plot fragment so it draws on the tab's canvas.

    Only the calls his code actually makes are implemented. Anything else returns a
    no-op and RECORDS its name in `unsupported`, which the panel surfaces - a future
    revision of his script that reaches for a pyplot call this shim has not been
    taught will show up as a warning rather than as a silently missing element or a
    dead tab.
    """

    def __init__(self, fig):
        self.__dict__["fig"] = fig
        self.__dict__["unsupported"] = []

    def subplots(self, nrows=1, ncols=1, **kw):
        """His `plt.subplots(11, 1, figsize=..., sharex=True)`, onto the canvas figure.

        figsize is deliberately dropped: the figure belongs to the canvas and its size
        comes from the pane. Everything else - the row count, sharex - is his.
        """
        self.fig.clear()
        kw.pop("figsize", None)
        axes = self.fig.subplots(nrows, ncols, squeeze=False, **kw)
        return self.fig, (axes[:, 0] if ncols == 1 else axes)

    def suptitle(self, *a, **k):
        return self.fig.suptitle(*a, **k)

    def tight_layout(self, *a, **k):
        """
        His tight_layout, forwarded - and its warning swallowed on purpose.

        He authors the figure at 15x17 inches; on a 300 px pane matplotlib cannot fit
        eleven rows plus their decorations and says so - about a layout the viewer
        REPLACES two steps later, when _wa_refit_engineer_axes clears the engine and
        sets its own margins. The message is filtered app-wide next to the matplotlib
        import, because it is raised at DRAW time and cannot be caught at the call
        site; this local filter covers the part that is raised inside his call, and
        keeps the reason next to the code that causes it. Only that message is
        filtered - anything else matplotlib has to say still reaches the console.
        """
        try:
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore", message=".*[Tt]ight layout.*")
                self.fig.tight_layout(*a, **k)
        except Exception:
            pass                      # a tight layout that will not converge is not
                                      # a reason to lose the whole diagram

    def subplots_adjust(self, *a, **k):
        try:
            self.fig.subplots_adjust(*a, **k)
        except Exception:
            pass

    def savefig(self, *a, **k):
        """
        Deliberate no-op. His code saves the PNG into self.output_dir, which is inside
        the scan folder; the viewer writes nothing into a scan just because a tab was
        opened. Save Plot PNG exports the same figure wherever the user chooses.
        """
        return None

    def close(self, *a, **k):
        """No-op: closing the canvas figure would leave the tab blank."""
        return None

    def show(self, *a, **k):
        """No-op: pyplot's own window is not the tab, and it blocks the event loop."""
        return None

    def __getattr__(self, name):
        if name.startswith("__"):
            raise AttributeError(name)
        recorded = self.__dict__.setdefault("unsupported", [])

        def _noop(*a, **k):
            if name not in recorded:
                recorded.append(name)
            return None
        return _noop


def load_engineer_plot(fig, script_name=None, func_name=None):
    """
    (bound callable, shim) for a plot fragment, drawing onto `fig`.

    ONE loader for both scripts - his, and the N-axle twin - so there is a single
    path that injects the globals, the pyplot shim and the host object. A second copy
    of this for the second script is a second thing to keep in step.

    Raises RuntimeError with a readable message; the caller turns that into the
    message the view shows instead of an empty grid.
    """
    script_name = script_name or ENGINEER_PLOT_SCRIPT
    func_name = func_name or ENGINEER_PLOT_FUNC
    if axle_mod is None:
        raise RuntimeError("mm_axle_classifier could not be imported, so the "
                           "engineer's plot script cannot be located.")
    path = axle_mod.find_engineer_script(script_name)
    if not path:
        raise RuntimeError("%s was not found next to the viewer or in "
                           "..\\Wheel Assembler\\Scripts." % script_name)
    try:
        import pandas as _pd
    except Exception as exc:
        raise RuntimeError("his plot script needs pandas (%s: %s)."
                           % (type(exc).__name__, exc))
    with lp_open(path, "r", encoding="utf-8", errors="replace") as fh:
        src = fh.read()
    # the fragment carries no execution block, but it is split the same way his other
    # scripts are - a later revision that grows one must not run it here
    head, _marker = axle_mod.split_definitions(src)
    shim = _WaPyplotShim(fig)
    mod = types.ModuleType("mm_engineer_plot")
    mod.__file__ = path
    mod.__dict__.update({"os": os, "pd": _pd, "plt": shim, "np": np})
    try:
        exec(compile(head, path, "exec"), mod.__dict__)
    except Exception as exc:
        raise RuntimeError("his plot script could not be loaded (%s: %s)."
                           % (type(exc).__name__, exc))
    fn = getattr(mod, func_name, None)
    if not callable(fn):
        raise RuntimeError("%s() was not found in %s." % (func_name, script_name))
    return fn, shim


# What his plot fragment prints on a normal run: the savefig announcement and the
# path under it. Both describe a write the shim did not perform, so both are dropped;
# anything else he prints is surfaced instead, because an unexpected line out of a
# script the viewer does not own is a finding, not noise.
WA_ENGINEER_EXPECTED_PRINTS = ("saved updated diagram", "->")


def _wa_engineer_stdout_warnings(text):
    """Warnings for anything his script printed that was NOT its phantom save."""
    out = []
    for line in (text or "").splitlines():
        line = line.strip()
        if not line:
            continue
        low = line.lower()
        if any(low.startswith(p) for p in WA_ENGINEER_EXPECTED_PRINTS):
            continue
        out.append(line)
    if not out:
        return []
    return ["his plot script printed: " + " | ".join(out[:3])
            + (" (+%d more, see the console)" % (len(out) - 3) if len(out) > 3
               else "")]


def wa_draw_diagram_png(fig, png_path):
    """
    Put his saved system-pulse PNG on `fig`. Returns a warning list.

    Drawn through imshow on a single full-bleed axes rather than figimage, so the
    toolbar's zoom, pan and Home still work and Save Plot PNG still exports what is
    on screen. The aspect is locked to the image's own, so nothing about his figure
    is stretched to fit the pane.

    Every failure is turned into a message ON the figure, for the same reason
    wa_draw_engineer_diagram does it: a traceback out of a Qt slot is a silent
    process abort, not an error dialog.
    """
    fig.clear()
    if not png_path or not lp_isfile(png_path):
        _wa_axis_message(fig, "This scan carries no %s."
                              % axle_mod.ENGINEER_DIAGRAM_NAME)
        return ["no saved diagram"]
    img, err = wa_load_diagram_image(png_path)
    if img is None:
        _wa_axis_message(fig, "%s could not be read.\n\n%s\n\nSwitch the source to "
                              "\u201c%s\u201d to draw it from the trigger log "
                              "instead."
                              % (os.path.basename(png_path), err, WA_DIAG_LIVE))
        return [err or "saved diagram unreadable"]
    ax = fig.add_subplot(111)
    ax.imshow(img, interpolation="antialiased", aspect="equal")
    ax.set_axis_off()
    # No reserved band: his own suptitle is baked into the PNG, and a second one over
    # it would read as a caption the viewer added to his figure.
    try:
        fig.subplots_adjust(left=0, right=1, top=1, bottom=0)
    except Exception:
        pass
    return []


def wa_draw_engineer_diagram(fig, triggers_path, axle_index=None, refit=True):
    """
    Run the system-diagram fragment against `triggers_path`, onto `fig`.
    Returns a warning list.

    WHICH fragment is wa_engineer_choice()'s answer: his own up to two axles, the
    N-axle twin from three. Nothing else about this function changed with it.

    `refit=False` skips the pane re-fit, for the high-resolution export - there the
    figure is drawn at print size and his own typography is the right one.

    Every failure is turned into a message ON the figure: this view runs third-party
    code over a file the viewer does not control, and a traceback out of a Qt slot is
    a silent process abort (qFatal), not an error dialog.
    """
    fig.clear()
    if not triggers_path or not lp_isfile(triggers_path):
        _wa_axis_message(fig, "No %s to draw." % WA_CSV_NAME)
        return ["no trigger log"]
    # A header-only log is not an error for his script - it draws eleven empty rows
    # off a NaN time axis and says nothing. Eleven blank rows read as "the controller
    # fired nothing", which is a different claim from "this file has no edges", so the
    # emptiness is checked here rather than shown as a diagram.
    try:
        with lp_open(triggers_path, "r", encoding="utf-8",
                     errors="replace") as _fh:
            _fh.readline()                     # header
            _has_rows = any(ln.strip() for ln in _fh)
    except Exception as exc:
        _wa_axis_message(fig, "%s could not be read.\n\n%s: %s"
                              % (WA_CSV_NAME, type(exc).__name__, exc))
        return ["%s: %s" % (type(exc).__name__, exc)]
    if not _has_rows:
        _wa_axis_message(fig, "%s holds no trigger edges, so there is nothing to "
                              "draw." % WA_CSV_NAME)
        return ["trigger log has no rows"]
    script, func, n_axles = wa_engineer_choice(axle_index)
    try:
        fn, shim = load_engineer_plot(fig, script, func)
    except RuntimeError as exc:
        _wa_axis_message(fig, "The engineer's system diagram is unavailable.\n\n%s"
                              % exc)
        return [str(exc)]
    host = _WaPlotHost(triggers_path, os.path.dirname(triggers_path),
                       n_axles=n_axles,
                       axle_source=getattr(axle_index, "source", None))

    _out = io.StringIO()
    try:
        with contextlib.redirect_stdout(_out):
            fn(host)
    except Exception as exc:
        _wa_axis_message(
            fig,
            "%s() failed on this trigger log.\n\n%s: %s\n\n"
            "The script is run exactly as written; nothing in it is patched here."
            % (func, type(exc).__name__, exc))
        return ["%s: %s" % (type(exc).__name__, exc)]

    # print-scale typography, re-fitted to the pane. Presentation only - see
    # _wa_refit_engineer_axes. Kept out of the try above so a re-fit failure can never
    # be reported as "the script failed".
    if refit:
        _wa_refit_engineer_axes(fig)

    warns = []
    warns.extend(_wa_engineer_stdout_warnings(_out.getvalue()))
    if shim.unsupported:
        warns.append("his plot called pyplot function(s) this view does not "
                     "implement, and they did nothing: "
                     + ", ".join(sorted(shim.unsupported)))
    axes = list(getattr(fig, "axes", []) or [])
    if script == ENGINEER_PLOT_SCRIPT_N:
        warns.append("this scan has %d axles, which his fixed 11-row grid cannot "
                     "show, so the diagram was drawn by %s - the same rows, with one "
                     "sliced-data row per axle." % (n_axles, ENGINEER_PLOT_SCRIPT_N))
    else:
        if n_axles > 2:
            warns.append("this scan has %d axles; his diagram has a fixed grid and "
                         "draws axles 1 and 2 only, so axles 3-%d are not on this "
                         "figure at all." % (n_axles, n_axles))

        if len(axes) >= 11 and not axes[10].get_ylabel():
            warns.append("the last row of his fixed grid is left blank%s - it is an "
                         "empty row, not a missing signal."
                         % (" (this scan has one axle)" if n_axles == 1 else ""))
    return warns


class WaDiagramWindow(QDialog):
    """
    One plot in its own resizable window, re-drawn at whatever size the window is.

    `draw_fn(figure)` is the SAME function the tab uses, so this window can never
    show a different figure from the one behind it - there is one drawing path, not
    a second copy of it that has to be kept in step.

    NOT WA_DeleteOnClose: an unhandled exception in a Qt slot holding a deleted
    wrapper is a silent process abort (qFatal), and this window is closed and
    reopened from a button. It is parented to the panel instead, so it goes away with
    the tab, and the panel holds the only reference.
    """

    def __init__(self, draw_fn, title, parent=None, rows=None):
        super().__init__(parent)
        self.setWindowTitle(title)
        self.setWindowFlag(Qt.WindowType.WindowMaximizeButtonHint, True)
        self.setSizeGripEnabled(True)
        self._draw_fn = draw_fn
        # `rows` is the diagram's row count when the caller knows it. A 12- or 13-row
        # figure in a window authored for 11 is the same squeeze this window exists to
        # get away from, so the figure grows with the grid.
        _h = 9.0 if not rows else max(9.0, 0.82 * float(rows))
        self.fig = Figure(figsize=(12, _h), dpi=100)
        self.canvas = FigureCanvas(self.fig)
        self.canvas.setMinimumHeight(200)
        self.toolbar = NavigationToolbar(self.canvas, self)
        lay = QVBoxLayout(self)
        lay.setContentsMargins(8, 8, 8, 8)
        lay.setSpacing(6)
        lay.addWidget(self.toolbar)
        lay.addWidget(self.canvas, 1)
        # The generated figure re-fits its typography to the canvas it is drawn on,
        # so it is re-drawn when the window is resized. Debounced through a CHILD
        # timer for the same reason the panel debounces its own: a pending
        # single-shot firing into a torn-down window takes the process with it.
        self._timer = QTimer(self)
        self._timer.setSingleShot(True)
        self._timer.timeout.connect(self._redraw)
        self.canvas.mpl_connect("resize_event", lambda _e: self._timer.start(120))
        self._redraw()

    def _redraw(self):
        try:
            self._draw_fn(self.fig)
        except Exception:
            traceback.print_exc()       # a draw failure is not worth the process
            return
        self.canvas.draw_idle()
