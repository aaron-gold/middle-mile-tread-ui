def _wa_trim_border(img, pad=WA_DIAG_TRIM_PAD):
    """
    Crop the flat background margin off his saved figure. Returns the array unchanged
    on anything it is not certain about.

    The rule is deliberately timid: a row or column is background only when EVERY
    pixel in it matches the image's own corner pixel (and, where there is an alpha
    channel, is fully transparent). The crop therefore stops at the first pixel of
    his figure - frame, title, row label or trace - and `pad` puts a few of the
    trimmed rows back so nothing sits against the canvas edge.

    This is presentation only, and it is the same reasoning as _wa_refit_engineer_axes:
    what the viewer owns is the surface his figure is drawn on, never the figure.
    """
    try:
        if getattr(img, "ndim", 0) < 2 or img.size == 0:
            return img
        a = img
        if a.ndim == 3 and a.shape[2] == 4:
            # transparent margin: alpha alone decides, colour under it is undefined
            solid = a[:, :, 3] > (0.5 if a.dtype.kind == "f" else 127)
            rgb = a[:, :, :3]
        elif a.ndim == 3:
            solid = None
            rgb = a[:, :, :3]
        else:
            solid = None
            rgb = a
        bg = rgb[0, 0]
        tol = 0.02 if rgb.dtype.kind == "f" else 5
        ink = (np.abs(rgb.astype(np.float32) - np.asarray(bg, dtype=np.float32))
               > tol)
        ink = ink.any(axis=2) if ink.ndim == 3 else ink
        if solid is not None:
            ink = ink & solid
        rows = np.flatnonzero(ink.any(axis=1))
        cols = np.flatnonzero(ink.any(axis=0))
        if rows.size == 0 or cols.size == 0:
            return img                      # a blank image is not ours to reshape
        r0 = max(int(rows[0]) - pad, 0)
        r1 = min(int(rows[-1]) + 1 + pad, a.shape[0])
        c0 = max(int(cols[0]) - pad, 0)
        c1 = min(int(cols[-1]) + 1 + pad, a.shape[1])
        if (r1 - r0) < 16 or (c1 - c0) < 16:
            return img                      # nothing sane came out of it
        return a[r0:r1, c0:c1]
    except Exception:
        return img                          # a cosmetic crop never fails a view


def wa_load_diagram_image(path):
    """
    (image array, error string). Never raises - the caller draws the error.

    Cached: see _WA_DIAG_CACHE. Only one image is held, because only one scan is open
    and a 92 MB array per scan the user has ever opened is not a cache, it is a leak.
    """
    if not path or not lp_isfile(path):
        return None, "no saved diagram"
    try:
        st = lp_stat(path)
        key = (os.path.abspath(path), st.st_mtime_ns, st.st_size)
    except OSError as exc:
        return None, "%s: %s" % (type(exc).__name__, exc)
    hit = _WA_DIAG_CACHE.get(key)
    if hit is not None:
        return hit[0], hit[1]
    try:
        img = mpimg.imread(lp(path))
    except Exception as exc:
        _WA_DIAG_CACHE.clear()
        _WA_DIAG_CACHE[key] = (None, "%s: %s" % (type(exc).__name__, exc))
        return _WA_DIAG_CACHE[key]
    if getattr(img, "size", 0) == 0 or getattr(img, "ndim", 0) < 2:
        img, err = None, "saved diagram is empty"
    else:
        # cropped ONCE, here, so the aspect every sizing rule reads is the aspect
        # that is actually drawn - see _wa_trim_border
        img, err = _wa_trim_border(img), None
    _WA_DIAG_CACHE.clear()
    _WA_DIAG_CACHE[key] = (img, err)
    return img, err


def wa_pipeline_line(axle_index):
    """
    One line saying WHERE this scan's axle split came from.

    Three answers, and the difference between them changes how every axle number on
    the screen should be read, so none of them is left to be inferred:
      * one of his two pipelines ran here - named, with the Host unit it read.
      * the split was READ off an existing classified folder tree; nothing ran.
      * there is no classification at all - the line is empty.
    """
    if axle_index is None:
        return ""
    if getattr(axle_index, "source", None) == WA_SOURCE_MANIFEST:
        return ("<span style='color:%s'>Split <b>read from %s</b> as his classifier "
                "wrote it &middot; nothing was re-run here, so no gate windows are "
                "available.</span>"
                % (C_TEXT_DIM, os.path.basename(
                    getattr(axle_index, "manifest_path", "") or "the scan manifest")))
    if getattr(axle_index, "source", None) == WA_SOURCE_TREE:
        return ("<span style='color:%s'>Split <b>read from the classified folder "
                "tree</b> as it stands &middot; the split script was not re-run, so "
                "no gate windows are available.</span>" % C_TEXT_DIM)
    if not getattr(axle_index, "pipeline", None):
        return ""
    unit = getattr(axle_index, "time_unit", None) or "?"
    return ("<span style='color:%s'>Classified by <b>%s</b> (%s) &middot; Host in "
            "<b>%s</b>.</span>"
            % (C_TEXT_DIM, axle_index.pipeline_class or "?",
               os.path.basename(axle_index.pipeline), unit))


