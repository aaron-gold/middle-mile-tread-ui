    def _axle_of(self, e):
        """Axle label for one trigger row, or '—' when it belongs to none."""
        if self.axle_index is None:
            return "—"
        return self.axle_index.axle_for_host(e.get("host")) or "—"

    def _visible_events(self):
        sig, mode = self._signal(), self.edge_combo.currentText()
        out = []
        for e in self.events:
            if sig and e["event"] != sig:
                continue
            if mode == WA_EDGE_RISE and not e["rise"]:
                continue
            if mode == WA_EDGE_FALL and e["rise"]:
                continue
            out.append(e)
        return out

    def _fill_table(self, *_):
        raw = self.raw_cb.isChecked()
        heads = WA_RAW_HEADS if raw else WA_FULL_HEADS
        rows = self._visible_events()

        # deltas and skew are ALWAYS computed against the full file, never against
        # the filtered view - a filtered delta would silently mean something else
        order = {e["i"]: k for k, e in enumerate(self.events)}
        widths = wa_pulse_widths(self.events)
        t0 = self.events[0]["ts"] if self.events else None
        h0 = next((e["host_ms"] for e in self.events
                   if e.get("host_ms") is not None), None)

        self.table.setSortingEnabled(False)
        self.table.setColumnCount(len(heads))
        self.table.setHorizontalHeaderLabels(heads)
        self.table.setRowCount(len(rows))
        # the two views have different columns, so the stretch has to follow the mode
        _hh = self.table.horizontalHeader()
        _hh.setSectionResizeMode(QHeaderView.ResizeMode.ResizeToContents)
        _hh.setSectionResizeMode(heads.index("Event"), QHeaderView.ResizeMode.Stretch)
        mono = QFont("Consolas")
        mono.setPointSize(9)

        for r, e in enumerate(rows):
            k = order[e["i"]]
            prev = self.events[k - 1] if k > 0 else None
            t_rel = (e["ts"] - t0).total_seconds()
            ts_txt = e["ts"].strftime("%Y-%m-%dT%H:%M:%S.%f")
            w = widths.get(e["i"])
            short = (w is not None and w * 1000.0 < WA_SHORT_PULSE_MS)

            if raw:
                cells = [(ts_txt, ts_txt), (e["event"], e["event"]),
                         ("" if e["host"] is None else str(e["host"]), e["host"]),
                         (e["orig"], e["orig"]), (e["edge_raw"], e["edge_raw"])]
                mono_cols, edge_col, width_col = (0, 2), None, None
            else:
                d_dev = "" if prev is None else "%.6f" % (e["ts"] - prev["ts"]).total_seconds()
                d_host = ("" if (prev is None or e.get("host_ms") is None
                                 or prev.get("host_ms") is None)
                          else "%.3f" % (e["host_ms"] - prev["host_ms"]))
                skew = ("" if (h0 is None or e.get("host_ms") is None)
                        else "%+.3f" % (t_rel * 1000.0 - (e["host_ms"] - h0)))
                wtxt = "" if w is None else (("%.1f ms" % (w * 1000.0)) if w < 1
                                             else ("%.3f s" % w))
                if short:
                    wtxt += "  ⚠"
                kind = wa_kind(e["event"])
                axle = self._axle_of(e)
                cells = [("%d" % e["i"], e["i"]), (ts_txt, ts_txt),
                         ("%.6f" % t_rel, t_rel), (e["event"], e["event"]),
                         (axle, axle),
                         (kind, kind),
                         ("RISE ▲" if e["rise"] else "FALL ▼", int(e["rise"])),
                         ("" if e["host"] is None else str(e["host"]), e["host"]),
                         (d_dev, float(d_dev) if d_dev else None),
                         (d_host, float(d_host) if d_host else None),
                         (skew, float(skew) if skew else None),
                         (wtxt, w), (e["orig"], e["orig"])]
                mono_cols, edge_col, width_col = (0, 1, 2, 7, 8, 9, 10), 6, 11

            for col, (txt, key) in enumerate(cells):
                it = SortCell(txt, key, k)
                if col in mono_cols:
                    it.setFont(mono)
                    it.setTextAlignment(Qt.AlignmentFlag.AlignRight
                                        | Qt.AlignmentFlag.AlignVCenter)
                if col == edge_col:
                    it.setForeground(QBrush(QColor(WA_C_RISE if e["rise"] else WA_C_FALL)))
                    f = it.font(); f.setBold(True); it.setFont(f)
                if col == width_col and short:
                    it.setForeground(QBrush(QColor(C_RED)))
                    f = it.font(); f.setBold(True); it.setFont(f)
                if not raw and col == 3 and e["event"] in (WA_ENTRY_EVT, WA_EXIT_EVT):
                    f = it.font(); f.setBold(True); it.setFont(f)
                if not raw and col == 4:
                    # Axle: the attributed rows are the point of the column, so an
                    # unattributed "—" is dimmed rather than competing with them
                    named = txt and txt != "—"
                    it.setForeground(QBrush(QColor(C_ORANGE_LO if named else C_TEXT_DIM)))
                    if named:
                        f = it.font(); f.setBold(True); it.setFont(f)
                    it.setTextAlignment(Qt.AlignmentFlag.AlignCenter)
                if not raw and col == 5:
                    # Type cell carries the lane colour, so scanning the table and
                    # scanning the plot group the signals the same way
                    it.setForeground(QBrush(QColor(WA_KIND_COLOR.get(txt, C_TEXT_DIM))))
                    it.setTextAlignment(Qt.AlignmentFlag.AlignCenter)
                self.table.setItem(r, col, it)

        self.table.setSortingEnabled(True)
        # re-assert file order: enabling sorting makes Qt apply whatever indicator the
        # header happens to hold, which is not the order the service wrote the edges in
        self.table.sortItems(0, Qt.SortOrder.AscendingOrder)
        total = len(self.events)
        self.count_label.setText("%d edges" % total if len(rows) == total
                                 else "%d of %d edges" % (len(rows), total))

