    def _fit_mode(self):
        """True when his saved PNG is fitted to the pane instead of width-filled."""
        return bool(getattr(self, "fit_btn", None)) and self.fit_btn.isChecked()

    def _diagram_canvas_height(self):
        """
        Canvas height for his saved PNG, or None when that is not what is on screen.

        FIT (default): a FLOOR, not a height. With widgetResizable the canvas then
        stretches to the viewport, and imshow's equal aspect letterboxes his portrait
        figure inside it - so the whole eleven-row diagram is on screen and nothing
        scrolls, at any pane size above the floor. Below the floor the pane scrolls
        rather than showing a smear, which is the same trade WA_ENGINEER_MIN_PX makes.

        FULL WIDTH: the original rule - his PNG at the pane's full width, which is
        taller than the pane and therefore scrolls. It is kept because a raster has no
        axes to read off, so magnifying it is the only way to read a value, and the
        toolbar's zoom starts from whatever is on the canvas.

        The scrollbar is subtracted BEFORE the height is set, not discovered after it.
        Sizing off the current viewport width makes the scrollbar appear, which takes
        that width away again - the canvas then sits ~1% wider than its own viewport
        and the pane gains a horizontal scrollbar it does not need.
        """
        if not self._diagram_from_png():
            return None
        if self._fit_mode():
            return WA_DIAG_FIT_MIN_PX
        ar = self._diagram_aspect()
        if not ar:
            return None
        vp = self.canvas_scroll.viewport()
        vw = vp.width() or self.canvas.width()
        if vw <= 0:
            return None
        bar = self.canvas_scroll.verticalScrollBar()
        if not bar.isVisible() and vw * ar > vp.height():
            vw -= max(bar.sizeHint().width(), 0)
        return int(min(max(vw * ar, WA_DIAG_PNG_MIN_PX), WA_DIAG_PNG_MAX_PX))

    def _redraw_plot(self):
        """Re-run the plot at the CURRENT canvas size (label thinning depends on it)."""
        if not MATPLOTLIB_AVAILABLE or self.fig is None:
            return
        if self._engineer_view():
            if self._diagram_from_png():
                # v1.1: shown by the Qt pane at a readable scale, not by matplotlib
                pane = getattr(self, "png_pane", None)
                if pane is not None and not pane.view.has_image():
                    pane.set_image(self._png_qimage)
                self._eng_warns = []
                self._sync_plot_page()
                return
            else:
                self._eng_warns = wa_draw_engineer_diagram(
                    self.fig, self._csv_path(), self.axle_index)
        else:
            wa_draw_timing(self.fig, self.events, self._signal())
        self.canvas.draw_idle()

    def _sync_view_controls(self):
        """
        The Signal combo filters LANES, and the system diagram has no lanes - its
        eleven rows are fixed by his script. Leaving it live there would be a control
        that silently does nothing, so it is disabled and says why.
        """
        eng = self._engineer_view()
        # v1.1: both filters live on the edge-table card and filter the TABLE only,
        # so they are always live - the diagram above is never filtered by them.
        self.signal_combo.setEnabled(True)
        for _w in (getattr(self, "signal_lbl", None), self.signal_combo,
                   getattr(self, "edge_lbl", None), self.edge_combo):
            if _w is not None:
                _w.setVisible(True)
        self._sync_plot_page()
        # The diagram source is a control for ONE view, and it is only a choice when
        # the scan actually shipped a PNG. Disabled either way rather than hidden, so
        # the reason is on the tooltip instead of the control disappearing.
        self.diag_combo.setEnabled(eng and self.diagram_png is not None)
        n_ax = int(getattr(self.axle_index, "n_axles", 0) or 0)
        if self.diagram_png is None:
            self.diag_combo.setToolTip(
                "This scan carries no %s/%s, so the diagram is drawn here from "
                "triggers_data.csv." % (axle_mod.ENGINEER_OUTPUT_DIR,
                                        axle_mod.ENGINEER_DIAGRAM_NAME))
        elif not eng:
            self.diag_combo.setToolTip(
                "Applies to the System diagram view only.")
        else:
            self.diag_combo.setToolTip(
                "From scan - his own saved figure, at the resolution he wrote it. It "
                "is an image,\nso the toolbar zooms pixels. His grid is fixed at two "
                "axle rows.\n"
                "Generated here - the same rows re-drawn from this scan's "
                "triggers_data.csv, with live\naxes the toolbar can read off"
                + ("; from three axles up it is drawn with ONE ROW PER\nAXLE, which "
                   "is why it is the default on this scan (%d axles)." % n_ax
                   if n_ax >= WA_N_AXLE_MIN else ".")
                + "\n\n%s" % self.diagram_png)
        self._sync_fit_controls()
        self._sync_canvas_height()
        self.signal_combo.setToolTip("Show every signal's edges in the table, or one "
                                     "signal's only.\nThe diagram above is not "
                                     "filtered.")

    def _sync_plot_page(self):
        """PNG page when the scan carries a readable PNG, matplotlib page otherwise."""
        stack = getattr(self, "plot_stack", None)
        on_png = self._diagram_from_png()
        if stack is not None:
            stack.setCurrentIndex(1 if on_png else 0)
        lbl = getattr(self, "source_lbl", None)
        if lbl is not None:
            if on_png:
                w, h = self.png_pane.view.image_size() if stack is not None else (0, 0)
                lbl.setText("%s/%s  ·  %d × %d px  ·  as saved by the classifier"
                            % (axle_mod.ENGINEER_OUTPUT_DIR,
                               axle_mod.ENGINEER_DIAGRAM_NAME, w, h))
                lbl.setToolTip(self.diagram_png)
            elif self._png_bad:
                lbl.setText("⚠ %s could not be read (%s) - generated here from %s "
                            "instead" % (axle_mod.ENGINEER_DIAGRAM_NAME,
                                         self._png_error, WA_CSV_NAME))
                lbl.setToolTip(self._png_bad)
            else:
                lbl.setText("⚠ this scan has no %s/%s - generated here from %s "
                            "instead" % (axle_mod.ENGINEER_OUTPUT_DIR,
                                         axle_mod.ENGINEER_DIAGRAM_NAME, WA_CSV_NAME))
                lbl.setToolTip("")

    def _on_view_changed(self, *_):
        self._sync_view_controls()
        self._redraw_plot()
        self._update_summary()
        self._apply_card_state()

    def _on_filter_changed(self, *_):
        self._redraw_plot()
        self._fill_table()

    # ---------------- load / draw ----------------
    def render(self):
        path = self._csv_path()
        self.path_label.setText(path or "(no wheel_assembler folder loaded)")
        self.events, self.warns = [], []
        if path and os.path.isfile(path):
            try:
                self.events, self.warns = wa_read_triggers(path)
            except Exception as e:
                self.warns = [f"could not read {WA_CSV_NAME}: {e}"]
        elif path:
            self.warns = [f"{WA_CSV_NAME} not found in {self.folder}"]

        names = wa_lane_names(self.events)
        self.signal_combo.blockSignals(True)
        self.signal_combo.clear()
        self.signal_combo.addItem("All signals")
        for _nm in names:                       # label shown, event name stored
            self.signal_combo.addItem(wa_label(_nm), _nm)
        self.signal_combo.blockSignals(False)

        # Neither view needs the gate-pulse split any more, so the state machine is
        # NOT re-run here. The classification the scan was loaded with is still on
        # self.axle_index and still fills the table's Axle column; nothing about it is
        # recomputed because a plot was redrawn.
        self._sync_view_controls()

        if MATPLOTLIB_AVAILABLE and self.fig is not None:
            self._redraw_plot()
            self.canvas.draw()
        self._fill_table()
        self._sync_toggle_text()      # edge count is only known once the file is read
        self._update_summary()        # sets the text AND re-caps the collapsed card

    def _update_summary(self):
        """
        The summary under the plot. The two views answer different questions, so they
        get different summaries - the combined one counts edges and pulse widths, the
        system diagram says what his figure is and what it does not cover. Both keep
        their full statement on the tooltip, so switching view loses nothing, and both
        are kept SHORT: this label shares a column of pixels with the plot.
        """
        if self._engineer_view():
            self.summary_label.setText(self._engineer_summary())
            self.summary_label.setToolTip(self._engineer_detail())
            if self.events_btn.isChecked() and not self.tbl_toggle.isChecked():
                self._toggle_table(False)
            self._sync_events_btn()
            return
        self.summary_label.setText(wa_build_summary(self.events, self.warns))
        # the per-signal detail the one-line summary no longer prints
        self.summary_label.setToolTip(wa_build_summary_detail(self.events, self.warns))
        if self.events_btn.isChecked() and not self.tbl_toggle.isChecked():
            self._toggle_table(False)   # re-cap: the summary height just changed
        self._sync_events_btn()         # count and ⚠ follow the summary

    def _engineer_summary(self):
        """
        What his diagram is, what it covers, and anything it reported.

        Says the axle ceiling out loud: his grid is fixed at two axle rows, so on a
        3+ axle vehicle the figure is not the whole vehicle and must not be read as
        it. The banner at the top of the window carries the real axle count.
        """
        # Kept SHORT on purpose. This label sits directly under the plot in the same
        # column of pixels, and every line it grows is a line the eleven rows lose -
        # which is what put a scrollbar back on this view. The full statement is on
        # the tooltip, and nothing is dropped from it.
        if self._diagram_from_png():
            lines = ["His own saved figure, read from <b>%s/%s</b> &middot; it is the "
                     "diagram his classifier drew on the run that produced this scan, "
                     "not a redraw. <i>His axle rows model the firmware, not a "
                     "measurement, and are not an acceptance criterion.</i>"
                     % (axle_mod.ENGINEER_OUTPUT_DIR,
                        axle_mod.ENGINEER_DIAGRAM_NAME),
                     "<span style='color:%s'>Fitted to the pane's width so every row "
                     "is legible &mdash; scroll through the rows, Ctrl+wheel to zoom, "
                     "<b>Open full size</b> (or double-click) for a full-screen copy. "
                     "Save Plot PNG writes a byte-exact copy of his file.</span>"
                     % C_TEXT_DIM]
        else:
            script, func, n_ax = wa_engineer_choice(self.axle_index)
            if script == ENGINEER_PLOT_SCRIPT_N:
                lines = ["Drawn by <b>%s</b> &rarr; <b>%s()</b> &middot; rows: "
                         "vehicle entry, gates 1-3, vehicle exit, the four driven "
                         "outputs, then <b>one sliced row per axle (%d)</b>. Same "
                         "events, order, colours and 2.5 s tread window as his "
                         "figure; only the fixed 11-row grid is generalised. <i>The "
                         "axle rows model the firmware, not a measurement, and are "
                         "not an acceptance criterion.</i>"
                         % (ENGINEER_PLOT_SCRIPT_N, ENGINEER_PLOT_FUNC_N, n_ax)]
            else:
                lines = ["Drawn by <b>%s</b> &rarr; <b>%s()</b>, run exactly as "
                         "written &middot; rows: vehicle entry, gates 1-3, vehicle "
                         "exit, the four driven outputs, then one sliced row per "
                         "axle (2 maximum). <i>His axle rows model the firmware, not "
                         "a measurement, and are not an acceptance criterion.</i>"
                         % (ENGINEER_PLOT_SCRIPT, ENGINEER_PLOT_FUNC)]
            lines.insert(0, "<span style='color:%s'><b>&#9888; Generated here</b> "
                            "&mdash; %s</span>"
                         % (C_RED,
                            "his %s could not be read (%s)" % (
                                axle_mod.ENGINEER_DIAGRAM_NAME, self._png_error)
                            if self._png_bad else
                            "this scan carries no %s/%s"
                            % (axle_mod.ENGINEER_OUTPUT_DIR,
                               axle_mod.ENGINEER_DIAGRAM_NAME)))
        n = getattr(self.axle_index, "n_axles", 0) or 0
        if n and self._diagram_from_png():
            # the PNG's axle rows come from HIS run; the split the viewer reads may
            # resolve a different count, and the two are stated side by side
            lines.append("<span style='color:%s'>The loaded split resolves <b>%d</b> "
                         "axle%s &mdash; compare with the axle rows drawn in his "
                         "figure.</span>" % (C_TEXT_DIM, n, "" if n == 1 else "s"))
        for w in (getattr(self, "_eng_warns", None) or []):
            lines.append("<span style='color:%s'>&#9888; %s</span>" % (C_RED, w))
        pipe = wa_pipeline_line(self.axle_index)
        if pipe:
            lines.append(pipe)
        return "<br>".join(lines)

