    def _export(self):
        if not self.events:
            QMessageBox.warning(self, "Export", "No trigger events to export.")
            return
        path, _f = QFileDialog.getSaveFileName(self, "Export trigger events",
                                               "wheel_assembler_events.csv", "CSV (*.csv)")
        if not path:
            return
        if not path.lower().endswith(".csv"):
            path += ".csv"
        widths = wa_pulse_widths(self.events)
        t0 = self.events[0]["ts"]
        h0 = next((e["host_ms"] for e in self.events
                   if e.get("host_ms") is not None), None)
        try:
            with open(path, "w", newline="", encoding="utf-8") as fh:
                w = csv.writer(fh)
                w.writerow(list(WA_COLS) + ["io_type", "t_rel_s", "delta_device_s",
                                            "delta_host_ms", "skew_ms", "pulse_width_s",
                                            "short_pulse_flag"])
                for k, e in enumerate(self.events):
                    prev = self.events[k - 1] if k > 0 else None
                    t_rel = (e["ts"] - t0).total_seconds()
                    d_dev = "" if prev is None else "%.6f" % (e["ts"] - prev["ts"]).total_seconds()
                    d_host = ("" if (prev is None or e.get("host_ms") is None
                                     or prev.get("host_ms") is None)
                              else "%.3f" % (e["host_ms"] - prev["host_ms"]))
                    skew = ("" if (h0 is None or e.get("host_ms") is None)
                            else "%.3f" % (t_rel * 1000.0 - (e["host_ms"] - h0)))
                    pw = widths.get(e["i"])
                    w.writerow([e["ts"].strftime("%Y-%m-%dT%H:%M:%S.%f"), e["event"],
                                "" if e["host"] is None else e["host"], e["orig"],
                                e["edge_raw"], wa_kind(e["event"]),
                                "%.6f" % t_rel, d_dev, d_host, skew,
                                "" if pw is None else "%.6f" % pw,
                                "yes" if (pw is not None and pw * 1000.0 < WA_SHORT_PULSE_MS)
                                else ""])
            QMessageBox.information(self, "Export", f"Saved:\n{path}")
        except Exception as e:
            QMessageBox.warning(self, "Export failed", str(e))

    def _save(self):
        if self._diagram_from_png():
            # his PNG is the evidence: saved as a byte-exact COPY of the file, not a
            # re-render of whatever the pane happens to show
            path, _f = QFileDialog.getSaveFileName(
                self, "Save system pulse diagram", axle_mod.ENGINEER_DIAGRAM_NAME,
                "PNG (*.png)")
            if not path:
                return
            if not path.lower().endswith(".png"):
                path += ".png"
            try:
                if os.path.normcase(os.path.abspath(path)) == \
                        os.path.normcase(os.path.abspath(self.diagram_png)):
                    QMessageBox.information(self, "Save", "That is the scan's own "
                                            "file - nothing was written.")
                    return
                import shutil as _sh
                _sh.copyfile(lp(self.diagram_png), lp(path))
                QMessageBox.information(self, "Save", f"Saved:\n{path}")
            except Exception as e:
                QMessageBox.warning(self, "Save failed", str(e))
            return
        if not MATPLOTLIB_AVAILABLE or self.fig is None:
            QMessageBox.warning(self, "matplotlib missing", "pip install matplotlib")
            return
        # the two views are different evidence, so they must not default to the same
        # filename - a system-diagram PNG silently overwriting the combined one is a
        # lost piece of evidence, not a UI detail
        default = ("wheel_assembler_system_diagram.png" if self._engineer_view()
                   else "wheel_assembler_timing.png")
        path, _f = QFileDialog.getSaveFileName(self, "Save trigger timing plot",
                                               default, "PNG (*.png)")
        if not path:
            return
        if not path.lower().endswith(".png"):
            path += ".png"
        try:
            # THE GENERATED DIAGRAM IS EXPORTED AT PRINT SIZE, 2026-09-08, not at the
            # size it happens to have in the pane. The on-screen figure has been
            # re-fitted for a ~500 px pane (small fonts, labels pulled against the
            # axis), and saving that gives a PNG that is small and hard to read -
            # which is the whole reason this export exists on a test day. A fresh
            # figure is drawn instead, at his authored 15 in width and a height that
            # follows the row count, with the pane re-fit SKIPPED so his own
            # typography is what lands in the file.
            if self._engineer_view() and not self._diagram_from_png():
                rows = wa_engineer_rows(self.axle_index)
                # 15 in wide and 300 dpi are HIS numbers - figsize=(15, 17) and
                # savefig(dpi=300) in his own script - so an exported N-axle figure
                # is the same size and resolution as the system_pulse_diagram.png a
                # 2-axle scan ships, and the two can be put side by side in a report.
                big = Figure(figsize=(15.0, max(11.0, 1.45 * rows)), dpi=300)
                wa_draw_engineer_diagram(big, self._csv_path(), self.axle_index,
                                         refit=False)
                big.savefig(path, dpi=300, bbox_inches="tight", facecolor="white")
            else:
                self.fig.savefig(path, dpi=150, bbox_inches="tight",
                                 facecolor="white")
            QMessageBox.information(self, "Save", f"Saved:\n{path}")
        except Exception as e:
            QMessageBox.warning(self, "Save failed", str(e))
