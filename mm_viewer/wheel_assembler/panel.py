    def _open_full_size(self, *_):
        """
        The current plot in its own resizable window, fitted to that window.

        This is the honest answer to "fit it AND make it readable": his figure is
        portrait (aspect ~1.13) and this pane is wide and short, so a contain-fit in
        the tab is always height-limited - around 500 px wide at the app's default
        window. The same fit in a window opened at 90% of the screen lands near
        monitor height, where eleven rows are legible.

        The window owns its own Figure. Re-parenting the tab's canvas would leave the
        tab blank behind it and would have to put it back on close - two states to get
        wrong for no gain. A previous window is closed first, so the button cannot
        stack copies of the same diagram.
        """
        if self._diagram_from_png() and self._png_qimage is not None:
            old = getattr(self, "_full_win", None)
            if old is not None:
                try:
                    old.close()
                    old.deleteLater()       # parented, so it would otherwise linger
                except RuntimeError:
                    pass
            self._full_win = PulseDiagramWindow(
                self._png_qimage, "System diagram — %s" % self.diagram_png, self)
            scr = QApplication.primaryScreen()
            if scr is not None:
                g = scr.availableGeometry()
                self._full_win.resize(int(g.width() * 0.9), int(g.height() * 0.9))
                self._full_win.move(g.center() - self._full_win.rect().center())
            self._full_win.show()
            self._full_win.raise_()
            return
        if not MATPLOTLIB_AVAILABLE or self.fig is None:
            return
        rows = None                     # only a generated diagram knows its row count
        if self._engineer_view():
            if self._diagram_from_png():
                png = self.diagram_png
                draw = lambda f, _p=png: wa_draw_diagram_png(f, _p)
                title = "System diagram — %s" % os.path.basename(png)
            else:
                csv_path, ai = self._csv_path(), self.axle_index
                draw = lambda f, _c=csv_path, _a=ai: wa_draw_engineer_diagram(f, _c, _a)
                title = "System diagram — generated from %s" % WA_CSV_NAME
                rows = wa_engineer_rows(self.axle_index)
        else:
            events, sig = self.events, self._signal()
            draw = lambda f, _e=events, _s=sig: wa_draw_timing(f, _e, _s)
            title = "Wheel assembler — combined timing"
        old = getattr(self, "_full_win", None)
        if old is not None:
            try:
                old.close()
            except RuntimeError:
                pass                        # its C++ side is already gone
        self._full_win = WaDiagramWindow(draw, title, self, rows=rows)
        scr = QApplication.primaryScreen()
        if scr is not None:
            g = scr.availableGeometry()
            self._full_win.resize(int(g.width() * 0.9), int(g.height() * 0.9))
            self._full_win.move(g.center() - self._full_win.rect().center())
        self._full_win.show()
        self._full_win.raise_()

    def _on_canvas_click(self, ev):
        """Double-click anywhere on the plot opens the full-size window."""
        try:
            if getattr(ev, "dblclick", False):
                self._open_full_size()
        except Exception:
            traceback.print_exc()       # never let a callback out of a Qt slot

    def _sync_canvas_height(self):
        """
        Floor for the canvas in each view. BOTH views fill the viewport now - his
        diagram is re-fitted to pane height instead of being given 1150 px of
        scrollable canvas (see _wa_refit_engineer_axes), so neither view scrolls at
        any normal window size.

        His view keeps a higher floor than the combined one because eleven rows below
        it are illegible whatever the fonts do. At that point the pane scrolls, which
        is honest, rather than showing a smear.
        """
        if getattr(self, "canvas_scroll", None) is None or self.canvas is None:
            return
        if self._diagram_from_png():
            return                      # the PNG pane sizes itself (v1.1)
        h = self._diagram_canvas_height()
        # The floor scales with the ROW COUNT now: a 3-axle scan draws 12 rows and a
        # 4-axle one 13, and eleven rows' worth of floor would quietly squeeze them.
        eng_floor = wa_engineer_min_px(wa_engineer_rows(self.axle_index))
        self.canvas.setMinimumHeight(
            h if h is not None
            else (eng_floor if self._engineer_view() else 200))
