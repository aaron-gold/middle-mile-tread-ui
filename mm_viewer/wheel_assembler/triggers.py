# ============================================================
# WHEEL ASSEMBLER  (trigger gates + entry/exit sensors)
# ------------------------------------------------------------
# wheel_assembler/triggers_data.csv, written by the wheel-assembler service:
#   Device_timestamp,Event,Host,Originator,Rising_Edge
#   2026-08-25T15:28:14.281304,scan_entry,94718238,artemis_uvc,1
# One row per EDGE. Rising_Edge 1 = rise, 0 = fall. Host is the host-side
# monotonic counter in MILLISECONDS. Nothing here is filtered or edited - the
# panel only pairs rises with falls and derives deltas.
# ============================================================
WA_CSV_NAME  = "triggers_data.csv"
WA_ENTRY_EVT = "scan_entry"
WA_EXIT_EVT  = "scan_exit"
WA_COLS      = ("Device_timestamp", "Event", "Host", "Originator", "Rising_Edge")
# The controller writes the host counter under one of two names, and they are not
# the same unit: "Host" is MILLISECONDS, "Host_Timestamp_usec" is microseconds.
# Reading only the first left every edge of a microsecond log with no timestamp at
# all, which takes the Host column out of the edge table, the deltas, the skew and
# every axle attribution built on it. Newest spelling first, same order the
# engineer's scripts use.
WA_HOST_COLS = ("Host_Timestamp_usec", "Host")
WA_HOST_PER_MS = {"Host_Timestamp_usec": 1000.0, "Host": 1.0}

# Display-only flag for a suspiciously narrow pulse. EXPLORATION value - it traces
# to no requirement, no SRS and no ATP, and must never be quoted as an acceptance
# criterion. It flags a row; it never filters, edits or hides an edge.
WA_SHORT_PULSE_MS = 10.0

WA_C_RISE = "#2e9e5b"
WA_C_FALL = C_RED

# ---- SCAN BOUNDARY MARKERS ------------------------------------------------
# scan_entry / scan_exit are SCAN-LIFECYCLE MARKERS, not level signals. Every
# artemis_uvc triggers_data.csv seen so far (2026-08-26 and 2026-08-27) carries exactly
# ONE row for each, so a lane for them is always a flat line at low - it draws a level
# that was never measured. They are therefore plotted ONLY as the full-height green
# lines at each of their edges, which is what they actually mark: the instant the
# controller opened and closed the scan.
# This is a PLOT-ONLY omission. Both events keep every row in the edge table, the
# summary counts and the CSV export - nothing is dropped from the data.
# The physical beams that DO carry a level are VEHICLE_ENTER / VEHICLE_EXIT; they hold
# the entry / exit lanes (see WA_SIGNALS) and are labelled "entry sensor" / "exit
# sensor" on the plot.
WA_MARKER_EVENTS = (WA_ENTRY_EVT, WA_EXIT_EVT)
WA_C_MARKER = "#2e9e5b"

# ---- NAMED CONTROLLER I/O -------------------------------------------------
# The trigger log names the physical lines instead of numbering them, so the panel
# can group them by DIRECTION instead of listing them alphabetically:
#     IN  - a line the controller READS   (entry/exit beams, wheel gates)
#     OUT - a line the controller DRIVES  (camera + flash triggers, laser enable)
#
# This registry is DISPLAY METADATA ONLY: it sets lane order, lane colour and the
# table's Type column. It never renames an event, never merges two events and never
# hides one. An event that is not listed still gets a lane - it is classified "?" and
# sorted into WA_RANK_UNKNOWN - so a firmware release that adds a signal shows it
# immediately instead of dropping it.
WA_KIND_IN   = "IN"
WA_KIND_OUT  = "OUT"
WA_KIND_UNK  = "?"
WA_RANK_UNKNOWN = 60

WA_SIGNALS = OrderedDict((
    # event name                  (kind,         lane rank)
    ("scan_entry",                (WA_KIND_IN,   10)),
    ("VEHICLE_ENTER",             (WA_KIND_IN,   11)),
    ("gate1",                     (WA_KIND_IN,   20)),
    ("gate2",                     (WA_KIND_IN,   21)),
    ("gate3",                     (WA_KIND_IN,   22)),
    ("gate4",                     (WA_KIND_IN,   23)),
    # pre-2026-08-26 controller names, kept so an older trigger log still classifies
    ("OCR_CAMERA",                (WA_KIND_OUT,  40)),
    ("OCR_FLASH",                 (WA_KIND_OUT,  41)),
    ("TREAD_CAMERA_AND_FLASH",    (WA_KIND_OUT,  42)),
    ("LASER_GROOVE",              (WA_KIND_OUT,  43)),
    # current firmware output names. Until these were listed the four output lanes
    # rendered as "? - not in WA_SIGNALS" in the unknown colour, so the plot showed
    # no OUTPUT lane at all on any scan from this firmware.
    ("OUTPUT_OCR_AND_FLASH_LEFT_TRIGGER",  (WA_KIND_OUT, 44)),
    ("OUTPUT_OCR_AND_FLASH_RIGHT_TRIGGER", (WA_KIND_OUT, 45)),
    ("TREAD_OUTPUT_FLASH_CAMERA_PWM",      (WA_KIND_OUT, 46)),
    ("TREAD_OUTPUT_LASER_MASTER_ENABLE",   (WA_KIND_OUT, 47)),
    ("VEHICLE_EXIT",              (WA_KIND_IN,   89)),
    ("scan_exit",                 (WA_KIND_IN,   90)),
))

# Lane LABEL override - DISPLAY ONLY. The controller names the physical beams
# VEHICLE_ENTER / VEHICLE_EXIT; on the plot they read as what they are. The event name
# itself is never rewritten: the edge table, the summary and every export still say
# VEHICLE_ENTER, so a label here can never be mistaken for a data change.
WA_DISPLAY_NAME = {
    "VEHICLE_ENTER": "entry sensor",
    "VEHICLE_EXIT":  "exit sensor",
}

# Lane colours by direction. Inputs read as the machine's view of the vehicle, outputs
# as what the controller fired - keeping them visually apart is the whole point of the
# registry, so an unnamed signal gets a third, deliberately dim colour.
WA_KIND_COLOR = {
    WA_KIND_IN:  C_ORANGE,
    WA_KIND_OUT: C_BLUE,
    WA_KIND_UNK: C_TEXT_DIM,
}


def wa_kind(name):
    """Direction of one event name. Unlisted names are '?', never guessed."""
    ent = WA_SIGNALS.get((name or "").strip())
    return ent[0] if ent else WA_KIND_UNK


def wa_rank(name):
    """Lane rank of one event name; unlisted names sort into the unknown band."""
    ent = WA_SIGNALS.get((name or "").strip())
    return ent[1] if ent else WA_RANK_UNKNOWN


def wa_label(name):
    """Lane label for one event name. Display only - never used to match or store."""
    return WA_DISPLAY_NAME.get((name or "").strip(), name)

# Horizontal footprint of an "HH:MM:SS.mmm" tick label at 8.5 pt rotated 45 deg
# (measured: 64.6 px) plus a little breathing room, and the pixels the y-axis signal
# names + figure margins take off the canvas width. Used to decide how many timestamps
# a given canvas can print without overprinting; the gridline is always kept, only the
# text is thinned. Both are FIXED pixel costs, so they are subtracted, not scaled.
WA_LABEL_PX = 70.0
WA_YAXIS_PX = 130.0

# ---- lane geometry --------------------------------------------------------
# Lane pitch is the distance between two signal baselines, step height is how far a
# lane rises when the signal goes high. The GAP between lanes is PITCH - HEIGHT, so
# raising the pitch alone is what pulls the traces apart; raising both together just
# rescales the plot and changes nothing on screen.
# The RATIO is what shows on screen, not the absolute numbers: scaling both together
# just rescales the axes and looks identical. Pitch sets the gap (PITCH - HEIGHT = 1.70
# here), height sets how tall a rise/fall step is - raising it is what makes a short
# pulse readable rather than a hairline tick.
WA_LANE_PITCH  = 3.00
WA_LANE_HEIGHT = 1.30

# Vertical pixel budget for ONE legend row, and the fixed chrome (suptitle + rotated
# timestamp labels + margins) that never belongs to the lane area. Used to size the
# reserved legend band in DATA units from the CURRENT canvas height, the same way
# WA_LABEL_PX sizes the x-tick thinning from the canvas width.
WA_LEGEND_PX = 34.0
WA_CHROME_PX = 150.0


def wa_host_column(fieldnames):
    """Which host-counter column this log carries, or None. Newest spelling wins."""
    for c in WA_HOST_COLS:
        if c in (fieldnames or []):
            return c
    return None


def wa_parse_ts(s):
    """Parse a Device_timestamp. Returns datetime or None (a trailing Z is tolerated)."""
    s = (s or "").strip().replace("Z", "")
    for fmt in ("%Y-%m-%dT%H:%M:%S.%f", "%Y-%m-%dT%H:%M:%S"):
        try:
            return datetime.strptime(s, fmt)
        except ValueError:
            pass
    return None


def wa_read_triggers(path):
    """
    Read triggers_data.csv -> (events, warnings).
    events are dicts sorted by Device_timestamp; rows with an unparsable timestamp
    are reported in `warnings` and dropped from the plot, never silently.
    """
    events, warns, bad = [], [], 0
    with lp_open(path, "r", encoding="utf-8", errors="replace",
                 newline="") as fh:
        rd = csv.DictReader(fh)
        host_col = wa_host_column(rd.fieldnames)
        per_ms = WA_HOST_PER_MS.get(host_col, 1.0)
        missing = [c for c in WA_COLS if c not in (rd.fieldnames or [])]
        if host_col:
            # "Host" is not missing when the log carries the usec spelling instead
            missing = [c for c in missing if c != "Host"]
        if missing:
            warns.append("missing column(s): " + ", ".join(missing))
        if host_col is None:
            warns.append("no host counter column (%s) - without one the edge "
                         "table has no Host, no delta and no axle"
                         % " / ".join(WA_HOST_COLS))
        for i, row in enumerate(rd):
            ts = wa_parse_ts(row.get("Device_timestamp", ""))
            if ts is None:
                bad += 1
                continue
            try:
                host = int(str(row.get(host_col, "")).strip())
            except Exception:
                host = None
            edge_raw = str(row.get("Rising_Edge", "")).strip()
            # host  = the counter as written, the unit the engineer's windows use
            # host_ms = the same instant in milliseconds, for every column and check
            #           that is LABELLED ms. Keeping both is what stops a microsecond
            #           log from reporting skew and deltas 1000x too large.
            events.append({"i": i + 1, "ts": ts,
                           "event": (row.get("Event") or "").strip(),
                           "host": host,
                           "host_ms": (None if host is None else host / per_ms),
                           "host_col": host_col,
                           "orig": (row.get("Originator") or "").strip(),
                           "rise": (edge_raw == "1"), "edge_raw": edge_raw})
    if bad:
        warns.append(f"{bad} row(s) had an unreadable Device_timestamp and are not plotted")
    events.sort(key=lambda e: e["ts"])
    return events, warns


def wa_signal_order(events):
    """
    Lane order, driven by WA_SIGNALS: scan_entry, then the wheel gates, then the
    driven outputs in firing order, then anything unnamed, then scan_exit. Names that
    share a rank (i.e. unlisted ones) fall back to alphabetical, so the order is
    stable across scans and two runs of the same scan never differ.
    """
    names, seen = [], set()
    for e in events:
        if e["event"] not in seen:
            seen.add(e["event"])
            names.append(e["event"])
    return sorted(names, key=lambda n: (wa_rank(n), n))


def wa_lane_names(events):
    """
    The signals that get a HORIZONTAL LANE, i.e. every signal except the scan-lifecycle
    markers. scan_entry / scan_exit carry one edge each and no measured level, so they
    are drawn as the green vertical lines only - see WA_MARKER_EVENTS. They keep every
    row in the table, the summary and the export; only the empty lane is dropped.
    """
    return [n for n in wa_signal_order(events) if n not in WA_MARKER_EVENTS]


def wa_build_pulses(events, name):
    """
    Pair rise -> fall for ONE signal, in time order.
    Returns (pulses, orphan_rises, orphan_falls). A second rise with no fall in
    between closes nothing and is reported as an orphan - edges are never invented.
    """
    ev = [e for e in events if e["event"] == name]
    pulses, orphan_r, orphan_f, open_r = [], [], [], None
    for e in ev:
        if e["rise"]:
            if open_r is not None:
                orphan_r.append(open_r)
            open_r = e
        else:
            if open_r is None:
                orphan_f.append(e)
            else:
                pulses.append((open_r, e))
                open_r = None
    if open_r is not None:
        orphan_r.append(open_r)
    return pulses, orphan_r, orphan_f


def wa_pulse_widths(events):
    """{falling-edge row index -> pulse width in seconds} for every paired pulse."""
    out = {}
    for name in wa_signal_order(events):
        for r, f in wa_build_pulses(events, name)[0]:
            out[f["i"]] = (f["ts"] - r["ts"]).total_seconds()
    return out


def wa_draw_timing(fig, events, signal=None):
    """
    Simple logic-analyser view: one high/low lane per signal, the event
    timestamps as the x ticks. No derived annotation - the numbers live in the
    summary and the table so the plot stays readable on long scans.
    `signal` = None/"" plots every lane, otherwise just that one.
    """
    fig.clear()
    ax = fig.add_subplot(111)
    if not events:
        ax.text(0.5, 0.5, "no trigger events", ha="center", va="center",
                transform=ax.transAxes, color="gray")
        return

    names = wa_lane_names(events)
    if signal:
        names = [n for n in names if n == signal] or names
    if not names:
        ax.text(0.5, 0.5, "no signal lanes to plot", ha="center", va="center",
                transform=ax.transAxes, color="gray")
        return
    t0 = events[0]["ts"]
    rel = lambda e: (e["ts"] - t0).total_seconds()
    span = max(rel(events[-1]), 0.001)
    pad = span * 0.04
    x0, x1 = -pad, span + pad
    PITCH = WA_LANE_PITCH                           # lane-to-lane spacing
    H = WA_LANE_HEIGHT                              # low -> high step height
    n = len(names)
    lane_y = [float((n - 1 - k) * PITCH) for k in range(n)]      # lane 0 at the top

    for k, name in enumerate(names):
        y = lane_y[k]
        # lane colour = I/O direction, so a driven output is never mistaken for a
        # sensor the controller only watched
        col = WA_KIND_COLOR.get(wa_kind(name), C_ORANGE)
        ev = [e for e in events if e["event"] == name]
        xs, ys, lvl = [x0], [y], 0
        for e in ev:
            xs.append(rel(e)); ys.append(y + (H if lvl else 0.0))
            lvl = 1 if e["rise"] else 0
            xs.append(rel(e)); ys.append(y + (H if lvl else 0.0))
        last_t = rel(ev[-1]) if ev else x0
        xs.append(last_t); ys.append(y + (H if lvl else 0.0))
        ax.plot(xs, ys, color=col, lw=2.2, solid_joinstyle="miter", zorder=3)
        # the tail is the LAST KNOWN state, not a measured one: dashed when the
        # signal never came back low, so a latched signal cannot read as data
        ax.plot([last_t, x1], [y + (H if lvl else 0.0)] * 2, color=col, lw=2.2,
                ls=((0, (4, 3)) if lvl else "-"), zorder=3)

    # x ticks = the event timestamps. Every edge keeps a gridline, but a label is
    # only printed when it clears the previous one - the minimum gap is derived from
    # the CURRENT canvas width, so a 66-edge scan in a wide pane thins out instead of
    # overprinting. WA_LABEL_PX is the horizontal footprint of "HH:MM:SS.mmm" at
    # 8.5 pt rotated 45 deg.
    axes_w_px = max(fig.get_size_inches()[0] * fig.dpi - WA_YAXIS_PX, 200.0)
    min_gap = (x1 - x0) * (WA_LABEL_PX / axes_w_px)
    ticks, labels, last_lab = [], [], None
    for e in events:
        t = rel(e)
        if ticks and abs(t - ticks[-1]) < 1e-9:
            continue
        ticks.append(t)
        if last_lab is not None and (t - last_lab) < min_gap:
            labels.append("")
        else:
            labels.append(e["ts"].strftime("%H:%M:%S.%f")[:-3])
            last_lab = t
    ax.set_xticks(ticks)
    ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=8.5, color=C_NAVY)

    # ---- legend contents, decided BEFORE the y limits ----
    # The lanes fill the axes edge to edge, so a legend placed over them always hides a
    # trace. Instead an empty band is RESERVED above the top lane and the legend is put
    # there as a single row - no lane ever occupies that band, so nothing can be covered.
    # The list only names what is actually on screen: a scan with no unnamed signal must
    # not advertise a "?" category, and a one-lane filtered view must not claim both
    # directions.
    kinds_present = []
    for name in names:
        kd = wa_kind(name)
        if kd not in kinds_present:
            kinds_present.append(kd)
    markers = [e for e in events if e["event"] in WA_MARKER_EVENTS]
    label_for = {WA_KIND_IN:  "INPUT",
                 WA_KIND_OUT: "OUTPUT",
                 WA_KIND_UNK: "? · not in WA_SIGNALS"}
    handles = [Line2D([0], [0], color=WA_KIND_COLOR[kd], lw=2.6,
                      label=label_for.get(kd, kd)) for kd in kinds_present] \
        if MATPLOTLIB_AVAILABLE else []
    if handles and markers:
        handles.append(Line2D([0], [0], color=WA_C_MARKER, lw=2.0,
                              label="scan entry / exit"))
    show_legend = len(handles) > 1
    # Size the reserved band so it is EXACTLY one legend row tall, whatever the lane
    # count or the canvas height. Solving head/(span + head) = legend_px/axes_px for
    # head keeps the band from swallowing the plot on a one-lane view and from being
    # too short to clear the top lane on an eight-lane one.
    head_room = 0.0
    if show_legend:
        span = (lane_y[0] + H + 0.45) - (-0.45)
        axes_h_px = max(fig.get_size_inches()[1] * fig.dpi - WA_CHROME_PX, 120.0)
        r = min(WA_LEGEND_PX / axes_h_px, 0.30)
        head_room = r * span / (1.0 - r)

    ax.set_xlim(x0, x1)
    ax.set_ylim(-0.45, lane_y[0] + H + 0.45 + head_room)
    ax.set_yticks([y + H / 2 for y in lane_y])
    ax.set_yticklabels([wa_label(nm) for nm in names], fontsize=10.5,
                       fontweight="bold", color=C_NAVY)
    # tint each lane label to match its trace, so the name and the waveform read as
    # one signal even when the plot is filtered down to a single lane
    for lab, name in zip(ax.get_yticklabels(), names):
        lab.set_color(WA_KIND_COLOR.get(wa_kind(name), C_NAVY))
    ax.tick_params(axis="y", length=0, pad=8)
    ax.grid(True, axis="x", linestyle=":", alpha=0.55)
    ax.set_axisbelow(True)
    for sp in ("top", "right", "left"):
        ax.spines[sp].set_visible(False)

    # ---- scan boundary markers ----
    # Drawn IN ADDITION to the scan_entry / scan_exit lanes, never instead of them: both
    # are ordinary I/O lines that go high and low, and the 2026-08-26 sample scan only
    # looks flat because that file happens to carry one edge each. The lanes stay the
    # source of truth for level; the green lines just carry the scan window across every
    # other lane. They are drawn on every view, filtered or not - a one-lane view is
    # exactly when knowing where the scan opened and closed matters most.
    # get_xaxis_transform() = x in data coords, y in axes coords, so a line spans the
    # plot however many lanes the current filter shows. zorder 2 puts them above the
    # gridlines but behind the waveforms, so a marker can never hide an edge.
    #
    # EVERY marker edge gets a line, but only the FIRST edge of each event gets a label:
    # an entry that pulses high then low sits two edges apart, and two labels that close
    # together overprint into an unreadable smear. A label is also skipped when it would
    # land within min_gap of one already drawn - the same thinning rule the x-tick labels
    # use, derived from the current canvas width.
    labelled = []
    for e in markers:
        t = rel(e)
        ax.axvline(t, color=WA_C_MARKER, lw=2.0, zorder=2, alpha=0.95)
        if e["event"] in [nm for nm, _ in labelled]:
            continue
        if any(abs(t - lt) < min_gap for _, lt in labelled):
            continue
        labelled.append((e["event"], t))
        frac = (t - x0) / (x1 - x0) if x1 > x0 else 0.5
        ha = "left" if frac < 0.06 else ("right" if frac > 0.94 else "center")
        ax.text(t, 1.006, e["event"], transform=ax.get_xaxis_transform(),
                ha=ha, va="bottom", fontsize=8.5, fontweight="bold",
                color=WA_C_MARKER, clip_on=False, zorder=6)

    # Legend sits in the TOP RIGHT corner, inside the band reserved above the top lane -
    # laid out as ONE ROW so it stays within that band however many entries it carries.
    # The band holds no lane by construction, so the legend cannot cover a trace.
    if show_legend:
        ax.legend(handles=handles, ncol=len(handles), loc="upper right",
                  bbox_to_anchor=(1.0, 1.0), fontsize=8.5, frameon=True,
                  framealpha=0.95, borderpad=0.4, handlelength=1.8,
                  columnspacing=1.6, borderaxespad=0.3)

    fig.suptitle("Wheel Assembler · Trigger & Sensor Timing", fontsize=13,
                 fontweight="bold", y=0.985)
    # Re-run the layout on EVERY draw instead of once at the initial figsize. Qt
    # stretches the canvas to fill the pane after the first draw, and subplotpars are
    # FRACTIONS: a bottom margin computed for a 600 px figure becomes far fewer pixels
    # in a 340 px pane, which cropped the rotated timestamp labels off the figure.
    try:
        fig.set_layout_engine("tight", rect=(0.005, 0.02, 0.995, 0.94))
    except Exception:                       # matplotlib < 3.6 has no layout engine API
        fig.tight_layout(rect=(0.005, 0.02, 0.995, 0.94))


def wa_build_summary(events, warns):
    """
    ONE-LINE summary. The block form used to run to six wrapped lines and pushed the
    plot down the page; this keeps the headline numbers on a single row and hands the
    full breakdown to wa_build_summary_detail() for the tooltip, so nothing is lost -
    every per-signal pulse width and pairing result is still one hover away.
    """
    if not events:
        return "No trigger events parsed from " + WA_CSV_NAME + "."

    t0 = events[0]["ts"]
    rel = lambda e: (e["ts"] - t0).total_seconds()
    names = wa_signal_order(events)
    origs = sorted({e["orig"] for e in events if e["orig"]})

    n_in = sum(1 for n in names if wa_kind(n) == WA_KIND_IN)
    n_out = sum(1 for n in names if wa_kind(n) == WA_KIND_OUT)
    n_unk = sum(1 for n in names if wa_kind(n) == WA_KIND_UNK)
    mix = "%d IN / %d OUT" % (n_in, n_out) + (" / %d ?" % n_unk if n_unk else "")

    n_pulse = 0; n_short = 0; n_unpaired = 0
    for nm in names:
        pulses, orph_r, orph_f = wa_build_pulses(events, nm)
        n_pulse += len(pulses)
        n_unpaired += len(orph_r) + len(orph_f)
        for r, f in pulses:
            if (f["ts"] - r["ts"]).total_seconds() * 1000.0 < WA_SHORT_PULSE_MS:
                n_short += 1

    bits = ["<b>%d edges</b> over <b>%d signals</b> (%s)" % (len(events), len(names), mix),
            "originator: %s" % (", ".join(origs) or "—"),
            "span %.2f s from %s" % (rel(events[-1]),
                                     t0.strftime("%H:%M:%S.%f")[:-3])]

    entry = next((e for e in events if e["event"] == WA_ENTRY_EVT and e["rise"]), None)
    exit_ = next((e for e in events if e["event"] == WA_EXIT_EVT and e["rise"]), None)
    if entry is not None and exit_ is not None:
        bits.append("scan window <b>%.3f s</b>" % (rel(exit_) - rel(entry)))

    pulse_txt = "<b>%d pulses</b>" % n_pulse
    if n_short:
        pulse_txt += (" <span style='color:%s'><b>(%d &lt; %.0f ms ⚠)</b></span>"
                      % (C_RED, n_short, WA_SHORT_PULSE_MS))
    bits.append(pulse_txt)

    if n_unpaired:
        bits.append("<span style='color:%s'><b>%d unpaired edge%s</b></span>"
                    % (C_RED, n_unpaired, "" if n_unpaired == 1 else "s"))
    else:
        bits.append("every rise matched")

    hs = [e for e in events if e.get("host_ms") is not None]
    if len(hs) >= 2:
        h0, d0 = hs[0]["host_ms"], hs[0]["ts"]
        skews = [((e["ts"] - d0).total_seconds() * 1000.0) - (e["host_ms"] - h0)
                 for e in hs]
        bits.append("timebase max |Δ| <b>%.1f ms</b>" % max(abs(s) for s in skews))

    if warns:
        bits.append("<span style='color:%s'><b>⚠ %s</b></span>" % (C_RED, "; ".join(warns)))

    return " &nbsp;·&nbsp; ".join(bits) + (
        "  <span style='color:%s'><i>(hover for the full breakdown)</i></span>" % C_TEXT_DIM)


def wa_build_summary_detail(events, warns):
    """
    The full breakdown, shown as the summary label's tooltip: per-signal pulse widths,
    per-signal edge pairing and the timebase note. Everything here is derived from the
    file as written - no edge is filtered, edited or hidden.
    """
    if not events:
        return "No trigger events parsed from " + WA_CSV_NAME + "."
    t0 = events[0]["ts"]
    rel = lambda e: (e["ts"] - t0).total_seconds()
    names = wa_signal_order(events)
    origs = sorted({e["orig"] for e in events if e["orig"]})

    entry = next((e for e in events if e["event"] == WA_ENTRY_EVT and e["rise"]), None)
    exit_ = next((e for e in events if e["event"] == WA_EXIT_EVT and e["rise"]), None)

    lines = []
    lines.append("<b>%d edges</b> over <b>%d signals</b> &nbsp;·&nbsp; originator: %s"
                 " &nbsp;·&nbsp; first edge %s"
                 % (len(events), len(names), ", ".join(origs) or "—",
                    t0.strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]))

    # Signals listed BY I/O DIRECTION, each name coloured like its lane. An unnamed
    # signal is called out rather than folded in with the known ones - it means the
    # controller emitted something WA_SIGNALS has not been taught yet.
    kind_label = {WA_KIND_IN:  "IN (controller reads)",
                  WA_KIND_OUT: "OUT (controller drives)",
                  WA_KIND_UNK: "unnamed / not in WA_SIGNALS"}
    for kd in (WA_KIND_IN, WA_KIND_OUT, WA_KIND_UNK):
        grp = [n for n in names if wa_kind(n) == kd]
        if not grp:
            continue
        col = WA_KIND_COLOR.get(kd, C_TEXT)
        lines.append("&nbsp;&nbsp;<b>%s</b> &nbsp;<span style='color:%s'>%s</span>"
                     % (kind_label[kd], col, ", ".join(grp)))
    if entry is not None and exit_ is not None:
        lines.append("<b>Scan window</b> (scan_entry ↑ → scan_exit ↑): <b>%.3f s</b>"
                     % (rel(exit_) - rel(entry)))

    widths, unpaired = [], []
    for nm in names:
        pulses, orph_r, orph_f = wa_build_pulses(events, nm)
        for r, f in pulses:
            w = (f["ts"] - r["ts"]).total_seconds()
            txt = ("%s %.1f ms" % (nm, w * 1000.0)) if w < 1 else ("%s %.3f s" % (nm, w))
            if w * 1000.0 < WA_SHORT_PULSE_MS:
                txt = "<span style='color:%s'><b>%s ⚠</b></span>" % (C_RED, txt)
            widths.append(txt)
        if orph_r:
            unpaired.append("%s: %d rise with no fall" % (nm, len(orph_r)))
        if orph_f:
            unpaired.append("%s: %d fall with no rise" % (nm, len(orph_f)))
    if widths:
        lines.append("<b>Pulse widths</b> (rise→fall): " + " &nbsp;·&nbsp; ".join(widths))
    lines.append("<b>Edge pairing</b>: "
                 + ("; ".join(unpaired) if unpaired else "every rise matched by a fall"))

    hs = [e for e in events if e.get("host_ms") is not None]
    if len(hs) >= 2:
        h0, d0 = hs[0]["host_ms"], hs[0]["ts"]
        skews = [((e["ts"] - d0).total_seconds() * 1000.0) - (e["host_ms"] - h0)
                 for e in hs]
        lines.append("<b>Timebase cross-check</b> (Device_timestamp vs Host counter, both "
                     "re-zeroed on the first edge): max |Δ| <b>%.1f ms</b> over %.2f s — "
                     "observation only, no acceptance criterion is defined."
                     % (max(abs(s) for s in skews), rel(events[-1])))
    if warns:
        lines.append("<span style='color:%s'><b>⚠ %s</b></span>" % (C_RED, "; ".join(warns)))
    lines.append("<i>⚠ marks a display flag only (pulse &lt; %.0f ms). It traces to no "
                 "requirement or SRS and must not be quoted as an acceptance criterion. "
                 "No edge is filtered, edited or hidden.</i>" % WA_SHORT_PULSE_MS)
    return "<br>".join(lines)


