import traceback
from PyQt6.QtWidgets import QHBoxLayout, QLabel, QStackedWidget, QVBoxLayout, QWidget


from mm_viewer.common import axle_mod
from mm_viewer.widgets.controls import ArrowComboBox
from mm_viewer.widgets.layout import allow_shrink, field_label
from mm_viewer.vehicle_map.wheel_card import UNASSIGNED_LABEL
from mm_viewer.grooves.depth_panel import GrooveDepthPanel
from mm_viewer.groove_map.stats import GROOVE_VIEWS
from mm_viewer.groove_map.panel import GrooveMapPanel
from mm_viewer.frame_yield.panel import FrameYieldPanel


class GrooveDepthTab(QWidget):
    """
    The Laser Grooves (LMI) tab: a "View" dropdown over the vehicle map (default)
    and the v1.3 plot panel, which is used exactly as it was (self.plot).

    A scan the wheel assembler could not split gets no map - a guessed vehicle is
    worse than none - so the dropdown opens on Plot and says why.
    """

    def __init__(self, folder=None, axle_index=None, diag_folder=None, parent=None):
        super().__init__(parent)
        self.folder = folder
        self.axle_index = axle_index
        self.diag_folder = diag_folder

        self.view_combo = ArrowComboBox()
        self.view_combo.addItems(list(GROOVE_VIEWS))
        self.view_combo.setMinimumWidth(180)
        self.view_combo.setToolTip(
            "Vehicle map - the groove depths of each wheel, per groove.\n"
            "Plot - the laser profiles, frame browser and depth table (as before).\n"
            "Frame yield - frames assigned vs frames with a groove, per wheel/axle.")
        self.view_note = QLabel("")
        self.view_note.setObjectName("hintText")
        allow_shrink(self.view_note, 120)

        top = QHBoxLayout()
        top.setContentsMargins(20, 10, 20, 0)
        top.setSpacing(10)
        top.addWidget(field_label("View"))
        top.addWidget(self.view_combo)
        top.addWidget(self.view_note, 1)

        self.stack = QStackedWidget()
        ok, why = self.map_available(folder, axle_index)
        if ok:
            self.map = GrooveMapPanel(folder, axle_index)
            self.map.openInPlot.connect(self.open_in_plot)
            self.stack.addWidget(self.map)
        else:
            self.map = None
            self.stack.addWidget(MainWindow._info_page(
                "The vehicle map is not available for this scan", why))
        self.plot = GrooveDepthPanel(folder, axle_index=axle_index)
        self.stack.addWidget(self.plot)
        # v1.13: frame yield - per LMI unit (whole scan) by default; per axle x wheel
        # when a diagnostics tree is present.
        self.yield_panel = FrameYieldPanel(groove_folder=folder,
                                           diag_folder=diag_folder,
                                           axle_index=axle_index,
                                           default_group="unit")
        self.stack.addWidget(self.yield_panel)

        root = QVBoxLayout(self)
        root.setContentsMargins(0, 0, 0, 0)
        root.setSpacing(0)
        root.addLayout(top)
        root.addWidget(self.stack, 1)

        self.map_reason = why
        if not ok:
            item = self.view_combo.model().item(0)
            if item is not None:
                item.setEnabled(False)
                item.setToolTip(why)
        self.view_combo.currentIndexChanged.connect(self._on_view)
        self.view_combo.setCurrentIndex(0 if ok else 1)
        self._on_view(self.view_combo.currentIndex())

    @staticmethod
    def map_available(folder, index):
        if not folder:
            return False, "the scan has no tire_laser_groove_data folder."
        if index is None or not int(getattr(index, "n_axles", 0) or 0):
            return False, ("the wheel assembler could not split this scan into axles, "
                           "so there is no vehicle to draw. The Plot view shows the "
                           "whole scan.")
        return True, ""

    def _on_view(self, i):
        self.stack.setCurrentIndex(i)
        if i == 2:
            self.view_note.setText("Frames assigned vs with a groove, per wheel/axle")
        elif i == 0:
            self.view_note.setText("Per wheel, per groove  ·  click a wheel")
        elif self.map is None:
            self.view_note.setText("Vehicle map unavailable: " + self.map_reason)
        else:
            self.view_note.setText("Laser profiles, as before")

    def open_in_plot(self, bucket):
        """Show the Plot view with the axle the map was showing selected."""
        try:
            buckets = list(getattr(self.plot, "_axle_buckets", [None]))
            want = axle_mod.TRASH if bucket == UNASSIGNED_LABEL else bucket
            if want in buckets and self.plot.axle_combo.isEnabled():
                self.plot.axle_combo.setCurrentIndex(buckets.index(want))
        except Exception:
            traceback.print_exc()
        self.view_combo.setCurrentIndex(1)

    def shutdown(self):
        for p in (self.map, self.plot, getattr(self, "yield_panel", None)):
            if p is not None:
                try:
                    p.shutdown()
                except RuntimeError:
                    pass


