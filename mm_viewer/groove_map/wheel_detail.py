# v1.5: GrooveWheelCard (the v1.4 per-wheel card) removed - the wheels are drawn
# by GrooveVehicleView, with their grooves inside them.


class GrooveWheelDetail(QFrame):
    """
    One wheel's groove depths, sized to FIT - the panel never scrolls (v1.6).

        title  ·  ⓘ (source + colour rule, on hover)  ·  Open in Plot
        MIN · MEDIAN · MEAN · MAX · FRAMES · VALUES      one compact strip
        LMI unit(s) that read the wheel                  one line
        one table per TYRE (single, or the two of a dual) - a row per groove slot
        with a reading: status dot, G#, min, median, mean, max, RMSE, N

    Every slot's numbers are pooled over the LMI units that read it - the same
    numbers the vehicle colours are computed from; the per-unit split is on the
    row's tooltip. After every build the content is measured against the panel's
    own height and rebuilt at a smaller type scale until it fits (floor 0.5), so
    nothing below the fold is ever hidden behind a scroll bar.
    """
    openInPlot = pyqtSignal(str)            # bucket

    SCALE_FLOOR = 0.5
    SCALE_STEP = 0.9

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setObjectName("gdDetail")
        self._v = QVBoxLayout(self)
        self._v.setContentsMargins(18, 14, 18, 14)
        self._v.setSpacing(0)
        # the panel never grows to its content - the content shrinks to the panel
        self._v.setSizeConstraint(QLayout.SizeConstraint.SetNoConstraint)
        self.setMinimumSize(DETAIL_MIN_W, 160)
        self.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Ignored)
        self._body = None
        self.bucket = None
        self._rows = {}                      # slot -> [row background frames]
        self._hot = None
        self.limit = GROOVE_RMSE_DEFAULT
        self.scale = 1.0
        self._args = None                    # what show_wheel was last called with
        self._fit_timer = QTimer(self)
        self._fit_timer.setSingleShot(True)
        self._fit_timer.setInterval(0)
        self._fit_timer.timeout.connect(self._refit)
        self.show_message("Click a wheel to see the depth of each of its grooves.")

    # ---- plumbing ----------------------------------------------------
    def _new_body(self, spacing=8):
        if self._body is not None:
            self._body.setParent(None)
            self._body.deleteLater()
        self._body = QWidget()
        self._body.setObjectName("gdBody")     # transparent over the white frame
        v = QVBoxLayout(self._body)
        v.setContentsMargins(0, 0, 0, 0)
        v.setSpacing(spacing)
        self._v.addWidget(self._body)
        return v

    def _px(self, n):
        return max(9, int(round(n * self.scale)))

    def _lbl(self, text, name, align=None, flag=None, px=None, color=None):
        l = QLabel(text)
        l.setObjectName(name)
        if flag is not None:
            l.setProperty("flag", flag)
        if align is not None:
            l.setAlignment(align)
        css = []
        if px:
            css.append("font-size:%dpx;" % self._px(px))
        if color:
            css.append("color:%s;" % color)
        if css:
            l.setStyleSheet(" ".join(css))
        return l

    def show_message(self, text):
        self.bucket = None
        self._args = None
        self._rows = {}
        self._hot = None
        v = self._new_body()
        lbl = QLabel(text)
        lbl.setObjectName("placeholder")
        lbl.setWordWrap(True)
        lbl.setAlignment(Qt.AlignmentFlag.AlignCenter)
        v.addStretch(1)
        v.addWidget(lbl)
        v.addStretch(1)

    # ---- fit ---------------------------------------------------------
    def content_height(self):
        """Height the current content needs, margins included."""
        if self._body is None:
            return 0
        m = self._v.contentsMargins()
        self._body.adjustSize()
        return self._body.sizeHint().height() + m.top() + m.bottom()

    def avail_height(self):
        """
        The height the panel is GIVEN: the scroll area's viewport when it sits in
        one (the last-resort fallback below), else its own height.
        """
        par = self.parentWidget()
        sa = par.parentWidget() if par is not None else None
        if isinstance(sa, QScrollArea) and sa.viewport() is par:
            return par.height()
        return self.height()

    def content_width(self):
        """Width the current content needs without clipping, margins included."""
        if self._body is None:
            return 0
        m = self._v.contentsMargins()
        return self._body.minimumSizeHint().width() + m.left() + m.right()

    def avail_width(self):
        par = self.parentWidget()
        sa = par.parentWidget() if par is not None else None
        if isinstance(sa, QScrollArea) and sa.viewport() is par:
            return par.width()
        return self.width()

    def fits(self):
        # BOTH ways: at the 540 px minimum width a full-size table clipped its
        # numbers (found by the v1.6 suite on 06-28-19 and 08-26-01)
        return (self.content_height() <= self.avail_height() + 1
                and self.content_width() <= self.avail_width() + 1)

    def overflows(self):
        """True only when even the floor scale does not fit (scroll bar shown)."""
        return self.minimumHeight() > self.avail_height() + 1

    def resizeEvent(self, ev):
        super().resizeEvent(ev)
        if self._args is not None:
            self._fit_timer.start()

    def _refit(self):
        try:
            if self._args is None or self.avail_height() < 50:
                return
            # grow back first (the panel may have got taller), then shrink to fit
            self.scale = 1.0
            self._build(*self._args)
            while not self.fits() and self.scale > self.SCALE_FLOOR + 1e-6:
                self.scale = max(self.SCALE_FLOOR, self.scale * self.SCALE_STEP)
                self._build(*self._args)
            # LAST RESORT, only on a window too short for the floor scale (the
            # 1300x820 minimum with a dual wheel): claim the height the content
            # needs so the enclosing scroll area shows a bar - never clip numbers
            # out of sight. At any size where it fits, the bar never appears.
            need = self.content_height()
            want = 160 if need <= self.avail_height() + 1 else need
            if self.minimumHeight() != want:
                self.setMinimumHeight(want)
            self.highlight_groove(self._hot)
        except Exception:
            traceback.print_exc()

    # ---- content -----------------------------------------------------
    def show_wheel(self, wheel, title, bucket, limit=None):
        self.limit = float(limit if limit is not None else _GROOVE_UI["rmse_limit"])
        self._args = (wheel, title, bucket)
        self._hot = None
        self._refit() if self.avail_height() >= 50 else self._build(*self._args)

    def _build(self, wheel, title, bucket):
        self.bucket = bucket
        self._rows = {}
        s = self.scale
        compact = s < 0.85                   # tiles -> one line, provenance -> tooltip
        m = int(round(16 * max(s, 0.5)))
        self._v.setContentsMargins(m + 2, m - 2, m + 2, m - 2)
        v = self._new_body(spacing=self._px(8))
        R = Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter
        L = Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter
        C = Qt.AlignmentFlag.AlignCenter
        st = wheel["all"]
        units = "  +  ".join("%s %d fr" % (lmi_short(u, d["pos"]), d["profiles"])
                             for u, d in wheel["units"].items())
        bits = [units or "no LMI unit"]
        if wheel.get("unmatched"):
            bits.append("%d without a grooves_full match" % wheel["unmatched"])
        if wheel.get("from_frame"):
            bits.append("%d from per-frame CSV (grooves_full empty)"
                        % wheel["from_frame"])
        if wheel.get("shared"):
            bits.append("%d shared with another axle" % wheel["shared"])
        prov_text = "   ·   ".join(bits)
        if (wheel.get("unplaced") or {}).get("n"):
            bits.append("%d depth(s) with no position" % wheel["unplaced"]["n"])
        prov_text = "   ·   ".join(bits)
        unit_tip = "\n".join(
            "%s: %d frames · %d with a depth · %d values · %s"
            % (u, d["profiles"], d["with_depth"], d["all"]["n"],
               ("tilt %.1f° (measured)" % d["tilt_deg"]) if d.get("tilt_measured")
               else "tilt not measurable - raw X used")
            for u, d in wheel["units"].items())

        # ---- title row: title · info · Open in Plot ----
        top = QHBoxLayout()
        top.setSpacing(10)
        ttl = self._lbl(title, "gdWheelTitle", px=24)
        ttl.setToolTip(prov_text + ("\n\n" + unit_tip if unit_tip else ""))
        top.addWidget(ttl)
        info = self._lbl("ⓘ", "gdInfo", C, px=17, color=C_TEXT_DIM)
        info.setToolTip(
            GROOVE_SOURCE_NOTE + "\n\nStatus dot / colour = RMSE of the groove's "
            "readings about their median against %.2f mm: Pass ≤ %.2f · Borderline "
            "≤ %.2f · Fail above, or median outside %g–%g mm · grey = fewer than %d "
            "readings.\nG1, G2 … = physical grooves, numbered left to right as drawn "
            "and placed by the LMI's own X/Z - not by its output slot. X = mm from "
            "the left-most groove of the wheel. X1, X2 … = seen outside the tyre "
            "(listed, not drawn).\nHover a row for the LMI slots and unit behind it."
            % (self.limit, self.limit,
                                     self.limit * GROOVE_BORDER_FACTOR,
                                     PLAUSIBLE_MIN, PLAUSIBLE_MAX, GROOVE_MIN_N))
        info.setCursor(Qt.CursorShape.WhatsThisCursor)
        top.addWidget(info)
        top.addStretch(1)
        btn = QPushButton("Open in Plot  ›")
        btn.setObjectName("primaryBtn")
        btn.setCursor(Qt.CursorShape.PointingHandCursor)
        btn.setStyleSheet("font-size:%dpx; padding:%dpx %dpx; min-height:0px;"
                          % (self._px(14), self._px(4), self._px(12)))
        btn.setToolTip("Switch to the Plot view with %s selected - the profiles "
                       "behind these numbers." % (
                           bucket if bucket != UNASSIGNED_LABEL
                           else "the unassigned profiles"))
        btn.clicked.connect(lambda _c=False, b=bucket: self.openInPlot.emit(b))
        top.addWidget(btn)
        v.addLayout(top)

        # ---- whole-wheel numbers: tiles, or one line when space is short ----
        if not compact:
            def tile(val, name, flag="", tip=""):
                t = QFrame()
                t.setObjectName("gdKpi")
                tv = QVBoxLayout(t)
                tv.setContentsMargins(self._px(10), self._px(4), self._px(10),
                                      self._px(4))
                tv.setSpacing(0)
                tv.addWidget(self._lbl(val, "gdKpiVal", flag=flag, px=24))
                tv.addWidget(self._lbl(name, "gdKpiLbl", px=11))
                if tip:
                    t.setToolTip(tip)
                return t

            kpis = QHBoxLayout()
            kpis.setSpacing(self._px(8))
            for key, name in GROOVE_STAT_KEYS:
                kpis.addWidget(tile(_mm(st[key]), name + " · mm",
                                    _depth_flag(st[key])), 1)
            kpis.addWidget(tile(str(wheel["profiles"]), "FRAMES · %d depth"
                                % wheel["with_depth"],
                                tip="Laser frames (profile files) the axle split put "
                                    "on this wheel; %d of them report a depth."
                                % wheel["with_depth"]), 1)
            kpis.addWidget(tile(str(st["n"]), "VALUES",
                                tip="One value per groove per frame - the min / "
                                    "median / mean / max are taken over these."), 1)
            v.addLayout(kpis)
            prov = self._lbl(prov_text, "hintText", px=FS_SMALL)
            prov.setToolTip(unit_tip)
            allow_shrink(prov, 80)
            v.addWidget(prov)
        else:
            line = self._lbl(
                "min %s  ·  <b>median %s</b>  ·  mean %s  ·  max %s mm   ·   %d frames "
                "(%d depth)  ·  %d values" % (
                    _mm(st["min"]), _mm(st["median"]), _mm(st["mean"]), _mm(st["max"]),
                    wheel["profiles"], wheel["with_depth"], st["n"]),
                "gdKpiLine", px=17, color=C_NAVY)
            line.setTextFormat(Qt.TextFormat.RichText)
            line.setToolTip(prov_text + ("\n\n" + unit_tip if unit_tip else ""))
            allow_shrink(line, 80)
            v.addWidget(line)

        # ---- ONE table, a sub-header per tyre ----
        g = QGridLayout()
        g.setHorizontalSpacing(self._px(16))
        g.setVerticalSpacing(self._px(2))
        # v1.8: + X = the groove's lateral position, mm from the wheel's left-most
        # groove (as drawn)
        heads = ["", "GROOVE", "X"] + [n for _k, n in GROOVE_STAT_KEYS] + ["RMSE", "N"]
        ncol = len(heads)
        for c, h in enumerate(heads):
            hl_ = self._lbl(h, "gdColHead", L if c <= 1 else R, px=12)
            if h == "X":
                hl_.setToolTip("Lateral position of the groove, mm from the left-most "
                               "groove on this wheel as drawn - from the LMI's own X/Z "
                               "(rotated into the tread plane), median over frames.")
            g.addWidget(hl_, 0, c)
        r = 1
        for tyre in wheel_tyres(wheel, bucket):
            r = self._tyre_rows(g, r, ncol, wheel, tyre, L, R, C)
        if wheel.get("off"):
            r = self._tyre_rows(g, r, ncol, wheel,
                                {"role": "off", "slots": list(wheel["off"]),
                                 "all": depth_stats([])}, L, R, C)
        up = wheel.get("unplaced") or {}
        if up.get("n"):
            r = self._unplaced_row(g, r, ncol, up, L, R, C)
        g.setColumnStretch(ncol, 1)
        v.addLayout(g)
        v.addStretch(1)

    def _tyre_rows(self, g, r, ncol, wheel, tyre, L, R, C):
        """
        A tyre's sub-header row, then a row per groove with a reading. Returns the
        next row. v1.8: tyre["slots"] are indices into wheel["grooves"] (physical
        grooves, left to right), not LMI output slots.
        """
        slots = tyre["slots"]
        grooves = wheel.get("grooves") or []
        off = tyre["role"] == "off"
        tst = depth_stats([]) if off else tyre["all"]
        name = ("Outside the tyre" if off
                else TYRE_NAME.get(tyre["role"], tyre["role"])).upper()
        empty = [grooves[s_]["label"] for s_ in slots if not grooves[s_]["n"]]
        head = QWidget()
        head.setObjectName("gdBody")
        hl = QHBoxLayout(head)
        hl.setContentsMargins(0, self._px(6), 0, self._px(1))
        hl.setSpacing(self._px(10))
        span = ("%s–%s" % (grooves[slots[0]]["label"], grooves[slots[-1]]["label"])
                if len(slots) > 1 else (grooves[slots[0]]["label"] if slots
                                        else "no groove seen"))
        hl.addWidget(self._lbl("%s  ·  %s%s" % (name, span,
                                                "  (tyre assumed)" if tyre.get("assumed")
                                                else ""),
                               "gdUnitHead", px=15))
        if off:
            hl.addWidget(self._lbl("listed, not drawn", "gdEmpty", L, px=13))
            head.setToolTip("Grooves the LMI reported beyond the gap that ends this "
                            "wheel's tyre(s) - their positions do not fit the tyre, "
                            "so they are not drawn on it. Their depths still count in "
                            "the wheel totals.")
        elif tst["n"]:
            state = tyre_status(wheel, slots, self.limit)
            hl.addWidget(self._lbl("●", "gdDot", C, px=15, color=GS_COLOR[state]))
            hl.addWidget(self._lbl("median %s mm" % _mm(tst["median"]), "gdTyreMed",
                                   L, px=15, color=C_NAVY))
        else:
            hl.addWidget(self._lbl("no depth on this tyre", "gdEmpty", L, px=14))
        if tyre.get("assumed"):
            head.setToolTip("The LMI saw one tyre of this dual only and its tilt could "
                            "not tell which - drawn on the inner tyre as an assumption.")
        hl.addStretch(1)
        if empty and (tst["n"] or off):
            nr = self._lbl("seen, no depth: " + ", ".join(empty), "hintText", L, px=12)
            nr.setToolTip("Grooves the LMI located (X/Z) on every frame shown but "
                          "reported no depth for: " + ", ".join(empty))
            hl.insertWidget(hl.count() - 1, nr)
        g.addWidget(head, r, 0, 1, ncol)
        r += 1
        for slot in slots:
            gs = grooves[slot]
            if not gs["n"]:
                continue
            state, why = groove_status(gs, self.limit)
            bgf = QFrame()
            bgf.setObjectName("gdRowBg")
            bgf.setToolTip(
                "%s - %s: %s\n\nX %s mm from the left-most groove  ·  %s  ·  LMI slot%s "
                "%s  ·  %d frame%s\n\n" % (
                    gs["label"], GS_NAME[state], why, "%.0f" % gs.get("x_mm", math.nan),
                    gs.get("unit", "?"), "" if len(gs.get("slots", [])) == 1 else "s",
                    ", ".join("Depth_%d" % s for s in gs.get("slots", [])),
                    gs.get("n_frames", 0), "" if gs.get("n_frames", 0) == 1 else "s")
                + "\n".join(
                    "%s: N %d · median %s · RMSE %s mm"
                    % (u, d["grooves"][slot]["n"], _mm(d["grooves"][slot]["median"]),
                       _mm(d["grooves"][slot]["rmse"]))
                    for u, d in wheel["units"].items() if d["grooves"][slot]["n"]))
            g.addWidget(bgf, r, 0, 1, ncol)
            self._rows.setdefault(slot, []).append(bgf)
            dot = self._lbl("●", "gdDot", C, px=16, color=GS_COLOR[state])
            dot.setProperty("state", state)
            dot.setToolTip("%s - %s" % (GS_NAME[state], why))
            g.addWidget(dot, r, 0)
            g.addWidget(self._lbl(gs["label"], "gdGroove", L, px=20), r, 1)
            g.addWidget(self._lbl("%.0f" % gs.get("x_mm", math.nan), "gdCount", R,
                                  px=FS_BASE), r, 2)
            for c, (key, _n) in enumerate(GROOVE_STAT_KEYS, start=3):
                g.addWidget(self._lbl(_mm(gs[key]),
                                      "gdValKey" if key == "median" else "gdVal",
                                      R, _depth_flag(gs[key]),
                                      px=21 if key == "median" else 19), r, c)
            col = (QColor(GS_COLOR[state]).darker(115).name()
                   if state in (GS_BORDER, GS_FAIL) else None)
            rm = self._lbl(_mm(gs.get("rmse", math.nan)), "gdVal", R, "", px=19,
                           color=col)
            rm.setProperty("rmse", True)
            g.addWidget(rm, r, ncol - 2)
            g.addWidget(self._lbl(str(gs["n"]), "gdCount", R, px=FS_BASE), r, ncol - 1)
            r += 1
        return r

    def _unplaced_row(self, g, r, ncol, st, L, R, C):
        """
        v1.8: depths whose own row has no X/Z - real readings, no position. ONE row
        (no sub-header): a busy dual must still fit the no-scroll panel at 1600x900.
        """
        tip = ("No position reported: the LMI wrote these depths on rows whose X and Z "
               "are the -1.797e308 no-data value, so the groove they belong to cannot "
               "be told. Not drawn; kept here and in the wheel totals.")
        bgf = QFrame()
        bgf.setObjectName("gdRowBg")
        bgf.setToolTip(tip)
        g.addWidget(bgf, r, 0, 1, ncol)
        self._rows.setdefault(GROOVE_NO_POS, []).append(bgf)
        g.addWidget(self._lbl("○", "gdDot", C, px=16, color=GS_COLOR[GS_FEW]), r, 0)
        nl = self._lbl("NO POSITION", "gdUnitHead", L, px=13)
        nl.setToolTip(tip)
        g.addWidget(nl, r, 1, 1, 2)
        for c, (key, _n) in enumerate(GROOVE_STAT_KEYS, start=3):
            g.addWidget(self._lbl(_mm(st[key]), "gdVal", R, _depth_flag(st[key]),
                                  px=19), r, c)
        g.addWidget(self._lbl(_mm(st.get("rmse", math.nan)), "gdVal", R, "", px=19),
                    r, ncol - 2)
        g.addWidget(self._lbl(str(st["n"]), "gdCount", R, px=FS_BASE), r, ncol - 1)
        return r + 1

    # ---- row highlight ---------------------------------------------------
    def highlight_groove(self, slot):
        """Tint the table row of one groove slot (None = no tint)."""
        self._hot = slot
        for s_, frames in self._rows.items():
            for f in frames:
                try:
                    f.setProperty("hot", s_ == slot)
                    f.setStyleSheet("QFrame#gdRowBg{background:%s;border-radius:6px;}"
                                    % ("#ffe9d4" if s_ == slot else "transparent"))
                except RuntimeError:
                    pass

    def hot_slot(self):
        """The highlighted slot, or None (tests)."""
        for s_, frames in self._rows.items():
            if any(f.property("hot") for f in frames):
                return s_
        return None

    def row_widget(self, slot):
        frames = self._rows.get(slot) or []
        return frames[0] if frames else None


