# ============================================================
# v1.8  GROOVE POSITION - from the LMI's own X/Z, not the slot number
# ============================================================
# Itay, 2026-10-14: "G1 -> G10 left to right" (v1.6) is not accurate - a groove
# belongs where its X says it is. MEASURED on the 13 scans of 30 Sep (Desktop
# "30092026 - Qual day#5\Scans", 2696 frame files):
#   * slot k is an OUTPUT INDEX, not a lateral position. In one frame the slots run
#     e.g. X(s2) < X(s3) < X(s4) < X(s1) < X(s0); 388 of 744 frames with a depth
#     are not in slot order.
#   * a row's X/Z IS a groove bottom: it sits exactly on the minimum of that
#     frame's laser profile (frame_N_profile.csv).
#   * raw X is NOT a stable tyre coordinate: the sensor is tilted (the tread line
#     in a profile slopes 15-28 deg on LMI_0, -21..-24 deg on LMI_1), so when the
#     tyre comes closer to the sensor (Z jumps ~300 mm between frame "bands") the
#     same groove moves 50-115 mm in X. Rotating (X, Z) by the tread tilt removes
#     most of it; the rest (<= ~25 mm) is taken out per band below.
#   Result: the steer tyre reads as 4 grooves at a 55 mm pitch on every one of the
#   13 scans, and a dual as one fully seen tyre + 1-2 grooves of the far tyre
#   ~150-190 mm away - instead of 4-7 smeared slot groups.
#
# Method, per LMI unit on one scan:
#   1. tilt = median over frames of the line through that frame's groove bottoms
#      (>= 3 grooves spanning >= 40 mm; >= 3 such frames; IQR <= 6 deg). Otherwise
#      tilt 0 = raw X, flagged on the page. The rear units rarely see 3 grooves.
#   2. u = X cos(tilt) + Z sin(tilt) - position along the tread, mm.
#   3. a frame's rows within 12 mm of each other are ONE groove reported twice
#      (seen: slot 0 and slot 5, same X, same depth) - counted once; a second depth
#      on it is set aside and counted (wheel "dup_depths"), never silently lost.
#   4. frames grouped into Z bands (> 60 mm apart); each band shifted onto the
#      richest one by < 0.45 pitch - never a whole groove, so it cannot alias.
#   5. readings within 0.4 pitch = one groove; a cluster holding two rows of one
#      frame is split. Gaps > max(90 mm, 1.7 pitch) separate tyres.
#   6. axle 1: the group with most readings is the tyre, any other group is
#      "outside the tyre" (listed, not drawn). Axle 2+: the main group + the
#      adjacent group within 300 mm are the two tyres of the dual. With one group
#      only, it is the tyre NEAR the sensor: the tread rises toward the sensor, so
#      the near tyre is at high u when the tilt is positive.
# ASSUMPTION (not measurable from the data): +u is drawn to the RIGHT for every
# unit, the same "low -> high = left -> right" convention as v1.6. Flip one unit
# in LMI_SCREEN_SIGN if its mounting says otherwise.
# A depth row whose X/Z is the no-data value cannot be placed: it is counted and
# listed ("no position"), never drawn.
GP_TILT_MIN_GROOVES = 3
GP_TILT_MIN_SPAN_MM = 40.0
GP_TILT_MIN_FRAMES = 3
GP_TILT_MAX_IQR_DEG = 6.0
GP_SIGN_MIN_SPAN_MM = 20.0         # 2-groove frames: enough to tell the tilt's sign
GP_SIGN_MIN_AGREE = 0.75
GP_SIGN_MIN_DEG = 1.0              # |tilt| below this votes for neither direction
GP_PITCH_DEFAULT_MM = 52.0
GP_PITCH_RANGE_MM = (30.0, 80.0)
GP_BAND_DZ_MM = 60.0
GP_BAND_SHIFT_FRAC = 0.45
GP_BAND_COST_CAP_MM = 12.0
GP_CLUSTER_FRAC = 0.40
# two rows of ONE frame closer than this are one groove reported twice. Real grooves
# are >= ~40 mm apart; of 1621 in-frame gaps on 30 Sep, 18 were < 15 mm (seen:
# slot 0 + slot 5 at the same X; a no-depth row 2-11 mm beside a depth row)
GP_DUP_MM = 12.0
GP_TYRE_GAP_MM = 90.0
GP_DUAL_MAX_GAP_MM = 300.0
GP_TYRE_MM = 300.0                 # drawn tread width
GP_DUAL_HALF_GAP_MM = 20.0
LMI_SCREEN_SIGN = {}               # unit name -> -1 to mirror it; default +1
GROOVE_NO_POS = -2                 # detail-table key of the "no position" row


def gp_quantile(v, q):
    v = sorted(v)
    if not v:
        return math.nan
    k = (len(v) - 1) * q
    lo, hi = int(math.floor(k)), int(math.ceil(k))
    return v[lo] + (v[hi] - v[lo]) * (k - lo)


def gp_median(v):
    return gp_quantile(v, 0.5)


def gp_line_tilt(pts, min_n=GP_TILT_MIN_GROOVES, min_span=GP_TILT_MIN_SPAN_MM):
    """Tilt (rad) of the line through one frame's groove bottoms [(x, z)], or None."""
    if len(pts) < min_n:
        return None
    xs = [p[0] for p in pts]
    zs = [p[1] for p in pts]
    if max(xs) - min(xs) < min_span:
        return None
    mx, mz = sum(xs) / len(xs), sum(zs) / len(zs)
    sxx = sum((x - mx) ** 2 for x in xs)
    if sxx <= 0:
        return None
    return math.atan(sum((x - mx) * (z - mz) for x, z in zip(xs, zs)) / sxx)


def gp_unit_tilt(frames_pts):
    """
    One LMI unit, every frame it wrote: frames_pts = [[(x, z), ...], ...].
    Returns {"tilt", "measured", "n", "iqr_deg", "sign"}; tilt 0 when not measured.
    `sign` (+1 / -1 / 0) is the tilt's direction, also from 2-groove frames - it
    only decides which tyre of a dual is the near one.
    """
    t = [a for a in (gp_line_tilt(p) for p in frames_pts) if a is not None]
    out = {"tilt": 0.0, "measured": False, "n": len(t), "iqr_deg": math.nan, "sign": 0}
    if len(t) >= GP_TILT_MIN_FRAMES:
        iqr = math.degrees(gp_quantile(t, 0.75) - gp_quantile(t, 0.25))
        out["iqr_deg"] = iqr
        if iqr <= GP_TILT_MAX_IQR_DEG:
            out["tilt"] = gp_median(t)
            out["measured"] = True
            out["sign"] = 1 if out["tilt"] > 0 else (-1 if out["tilt"] < 0 else 0)
            return out
    t2 = [a for a in (gp_line_tilt(p, 2, GP_SIGN_MIN_SPAN_MM) for p in frames_pts)
          if a is not None]
    if len(t2) >= GP_TILT_MIN_FRAMES:
        # a ~flat frame says nothing about the direction: it votes for neither
        eps = math.radians(GP_SIGN_MIN_DEG)
        pos = sum(1 for a in t2 if a > eps) / float(len(t2))
        neg = sum(1 for a in t2 if a < -eps) / float(len(t2))
        if pos >= GP_SIGN_MIN_AGREE:
            out["sign"] = 1
        elif neg >= GP_SIGN_MIN_AGREE:
            out["sign"] = -1
    return out


def gp_lateral(x, z, tilt):
    """Position along the tread line, mm (X itself when the tilt is 0)."""
    return x * math.cos(tilt) + z * math.sin(tilt)


def gp_pitch(frames_u):
    gaps = []
    for us in frames_u:
        s = sorted(us)
        gaps += [b - a for a, b in zip(s, s[1:])
                 if GP_PITCH_RANGE_MM[0] <= b - a <= GP_PITCH_RANGE_MM[1]]
    return gp_median(gaps) if len(gaps) >= 3 else GP_PITCH_DEFAULT_MM


def gp_bands(frames):
    """frames [(fid, z_med, [u...])] -> bands (lists of frames), split on Z jumps."""
    bands = []
    for f in sorted(frames, key=lambda f: f[1]):
        if bands and f[1] - bands[-1][-1][1] <= GP_BAND_DZ_MM:
            bands[-1].append(f)
        else:
            bands.append([f])
    return bands


def gp_band_shift(ref_u, band_u, pitch):
    """Shift (mm, |s| <= GP_BAND_SHIFT_FRAC pitch) that best lays band_u on ref_u."""
    if not ref_u or not band_u:
        return 0.0
    ref = sorted(ref_u)
    n = len(ref)
    lim = GP_BAND_SHIFT_FRAC * pitch
    steps = int(lim / 0.5)
    best_key, best_s = None, 0.0
    for i in range(-steps, steps + 1):
        s = i * 0.5
        cost = 0.0
        for u in band_u:
            v = u + s
            lo, hi = 0, n
            while lo < hi:
                mid = (lo + hi) // 2
                if ref[mid] < v:
                    lo = mid + 1
                else:
                    hi = mid
            d = min(abs(v - ref[j]) for j in (lo - 1, lo) if 0 <= j < n)
            cost += min(d, GP_BAND_COST_CAP_MM)
        key = (round(cost, 6), abs(s))
        if best_key is None or key < best_key:
            best_key, best_s = key, s
    return best_s


def gp_cluster(points, pitch):
    """
    points [(u, fid, row)] -> clusters, left to right. Single linkage at
    GP_CLUSTER_FRAC pitch; a cluster holding two points of ONE frame is split at
    its widest gap - one frame cannot see one groove twice.
    """
    gap = GP_CLUSTER_FRAC * pitch
    cl = []
    for p in sorted(points, key=lambda p: p[0]):
        if cl and p[0] - cl[-1][-1][0] <= gap:
            cl[-1].append(p)
        else:
            cl.append([p])
    out, todo = [], cl
    while todo:
        c = todo.pop(0)
        fids = [p[1] for p in c]
        if len(c) < 2 or len(set(fids)) == len(fids):
            out.append(c)
            continue
        _g, i = max((c[k + 1][0] - c[k][0], k) for k in range(len(c) - 1))
        todo[:0] = [c[:i + 1], c[i + 1:]]
    return sorted(out, key=lambda c: c[0][0])


def gp_groups(centres, pitch):
    """Cluster indices split into groups at gaps wider than a tyre gap."""
    if not centres:
        return []
    lim = max(GP_TYRE_GAP_MM, 1.7 * pitch)
    groups = [[0]]
    for i in range(1, len(centres)):
        if centres[i] - centres[i - 1] > lim:
            groups.append([i])
        else:
            groups[-1].append(i)
    return groups


def gp_place(frames, tilt_info, mode, screen_sign=1):
    """
    One LMI unit on one wheel.

      frames = [(fid, [(x, z, depth_or_nan, slot), ...]), ...]  rows WITH an X/Z
      mode   = "single" (axle 1) | "dual" (axle 2+) | "all" (no tyre claimed)

    Returns {"grooves": [{"u", "points": [(u, fid, row)], "tag"}], "pitch",
    "bands", "shifts", "n_dup"}. u is in SCREEN mm (screen_sign applied), tag is the
    drawn tyre: "S" single/all, "L"/"R" the left/right tyre of a dual, "?" a dual
    tyre that could not be told, "off" outside the tyre.
    """
    tilt = tilt_info.get("tilt", 0.0)
    fr, n_dup, dup_vals = [], 0, []
    for fid, rows in frames:
        if not rows:
            continue
        rows = sorted(rows, key=lambda r: gp_lateral(r[0], r[1], tilt))
        kept = []
        for r in rows:
            if kept and abs(gp_lateral(r[0], r[1], tilt)
                            - gp_lateral(kept[-1][0], kept[-1][1], tilt)) <= GP_DUP_MM:
                n_dup += 1
                # keep the row WITH a depth; a second depth on the same groove of
                # the same frame is set aside (counted, never silently lost)
                if math.isnan(kept[-1][2]):
                    kept[-1] = r
                elif not math.isnan(r[2]):
                    dup_vals.append(r[2])
                continue
            kept.append(r)
        us = [gp_lateral(r[0], r[1], tilt) for r in kept]
        fr.append((fid, gp_median([r[1] for r in kept]), us, kept))
    res = {"grooves": [], "pitch": GP_PITCH_DEFAULT_MM, "bands": 0, "shifts": [],
           "n_dup": n_dup, "dup_vals": dup_vals}
    if not fr:
        return res
    pitch = gp_pitch([f[2] for f in fr])
    bands = gp_bands([(f[0], f[1], f[2]) for f in fr])
    ref_i = max(range(len(bands)), key=lambda i: sum(len(f[2]) for f in bands[i]))
    ref_u = [u for f in bands[ref_i] for u in f[2]]
    shift_of, shifts = {}, []
    for i, b in enumerate(bands):
        s = 0.0 if i == ref_i else gp_band_shift(ref_u, [u for f in b for u in f[2]],
                                                   pitch)
        shifts.append(s)
        for f in b:
            shift_of[f[0]] = s
    pts = [((u + shift_of.get(fid, 0.0)) * screen_sign, fid, row)
           for fid, _z, us, rows in fr for u, row in zip(us, rows)]
    cl = gp_cluster(pts, pitch)
    centres = [gp_median([p[0] for p in c]) for c in cl]
    groups = gp_groups(centres, pitch)

    def weight(g):
        return (sum(1 for i in g for p in cl[i] if not math.isnan(p[2][2])),
                sum(len(cl[i]) for i in g))

    tags = {}
    if groups and mode == "all":
        tags = {gi: "S" for gi in range(len(groups))}
    elif groups:
        main = max(range(len(groups)), key=lambda gi: weight(groups[gi]))
        if mode == "single":
            tags[main] = "S"
        else:
            cand = []
            for gi in (main - 1, main + 1):
                if 0 <= gi < len(groups):
                    a, b = sorted((gi, main))
                    gap_mm = centres[groups[b][0]] - centres[groups[a][-1]]
                    if gap_mm <= GP_DUAL_MAX_GAP_MM:
                        cand.append((weight(groups[gi]), -gap_mm, gi))
            if cand:
                lo, hi = sorted((main, max(cand)[2]))
                tags[lo], tags[hi] = "L", "R"
            elif tilt_info.get("sign"):
                # the near tyre is at high u when the tilt is positive; on screen
                # high u is right for screen_sign +1
                tags[main] = "R" if (tilt_info["sign"] > 0) == (screen_sign > 0) else "L"
            else:
                tags[main] = "?"
    for gi, g in enumerate(groups):
        for i in g:
            res["grooves"].append({"u": centres[i], "points": cl[i],
                                   "tag": tags.get(gi, "off")})
    res.update(pitch=pitch, bands=len(bands), shifts=shifts)
    return res


def gp_fracs(us, mode, gap_mid=None):
    """
    Where each groove sits inside its drawn tyre, 0..1 left to right. The true
    spacing is kept at GP_TYRE_MM per tyre width (compressed only if it would not
    fit). "centre": the group centred in its tyre. "L"/"R" with gap_mid: a dual
    seen on both tyres, laid out from the gap between them.
    """
    if not us:
        return []
    span = max(us) - min(us)
    k = 1.0 if span <= 0.88 * GP_TYRE_MM else 0.88 * GP_TYRE_MM / span
    if mode == "L" and gap_mid is not None:
        fr = [1.0 - ((gap_mid - u) - GP_DUAL_HALF_GAP_MM) * k / GP_TYRE_MM for u in us]
    elif mode == "R" and gap_mid is not None:
        fr = [((u - gap_mid) - GP_DUAL_HALF_GAP_MM) * k / GP_TYRE_MM for u in us]
    else:
        c = (max(us) + min(us)) / 2.0
        fr = [0.5 + (u - c) * k / GP_TYRE_MM for u in us]
    return [min(0.96, max(0.04, f)) for f in fr]


def tyre_roles(axle_no, side):
    """Drawn tyres of a wheel, left to right: roles only (v1.8)."""
    if not axle_no or side not in MAP_SIDES:
        return ["all"]
    if axle_no == 1:
        return ["single"]
    return ["outer", "inner"] if side == "Left" else ["inner", "outer"]
