# ============================================================
# v1.5  LASER GROOVES - GROOVES DRAWN INSIDE EACH WHEEL
# ============================================================
# Every wheel is drawn as a tyre with its grooves inside it, one stripe per depth
# slot that reports anywhere on the vehicle, so all tyres share one layout and a
# missing reading shows as an unlit channel rather than as a narrower tyre.
#
# COLOUR = how consistent the system's readings of that groove are, frame to frame:
#
#     RMSE = sqrt( mean( (reading - median)^2 ) )   over the groove's readings on
#                                                   that wheel (every LMI unit)
#
#     Pass        RMSE <= limit
#     Borderline  limit < RMSE <= 2 x limit
#     Fail        RMSE >  2 x limit,  OR the median is outside 0-30 mm
#     Few         fewer than 3 readings - an RMSE of 1-2 values says nothing
#     (unlit)     no reading in that slot
#
# Default limit 0.40 mm = the candidate groove-depth tolerance (qual plan A2, still
# open against 0.25 mm). The user can change it, from 0.05 to 5.00 mm; the value
# is kept for the session. It is a DISPLAY check of repeatability, not accuracy
# against a gauge and not an acceptance criterion. G# is the system's output slot
# (Depth_0..9), which is not a fixed physical groove - a slot that changes groove
# between frames shows up here as a high RMSE, and that is a real finding.
GROOVE_RMSE_DEFAULT = 0.40
GROOVE_RMSE_MIN = 0.05
GROOVE_RMSE_MAX = 5.00
GROOVE_RMSE_STEP = 0.05
GROOVE_BORDER_FACTOR = 2.0
GROOVE_MIN_N = 3
# session-wide: a reloaded scan opens with the limit the user last chose
_GROOVE_UI = {"rmse_limit": GROOVE_RMSE_DEFAULT}

GS_PASS, GS_BORDER, GS_FAIL, GS_FEW, GS_NONE = "pass", "border", "fail", "few", "none"
GS_COLOR = {GS_PASS: "#2f9e5d", GS_BORDER: "#e3a20f", GS_FAIL: "#d64545",
            GS_FEW: "#8193ab", GS_NONE: "#11161c"}
GS_NAME = {GS_PASS: "Pass", GS_BORDER: "Borderline", GS_FAIL: "Fail",
           GS_FEW: "Few readings", GS_NONE: "No reading"}
GS_RANK = {GS_NONE: 0, GS_PASS: 1, GS_FEW: 2, GS_BORDER: 3, GS_FAIL: 4}


def groove_rmse(values, center):
    """RMSE of the finite values about `center` (mm); NaN when there is none."""
    v = [d for d in values if d is not None and not math.isnan(d)]
    if not v or center is None or math.isnan(center):
        return math.nan
    return math.sqrt(sum((d - center) ** 2 for d in v) / len(v))


def groove_status(st, limit):
    """(state, reason) for one groove's stats against an RMSE limit in mm."""
    if not st or not st.get("n"):
        return GS_NONE, "no reading in this slot"
    med = st["median"]
    if med < PLAUSIBLE_MIN or med > PLAUSIBLE_MAX:
        return GS_FAIL, ("median %.2f mm is outside the %g–%g mm range"
                         % (med, PLAUSIBLE_MIN, PLAUSIBLE_MAX))
    if st["n"] < GROOVE_MIN_N:
        return GS_FEW, ("only %d reading%s - RMSE needs at least %d"
                        % (st["n"], "" if st["n"] == 1 else "s", GROOVE_MIN_N))
    r = st.get("rmse", math.nan)
    if math.isnan(r):
        return GS_FEW, "RMSE could not be computed"
    if r <= limit + 1e-9:
        return GS_PASS, "RMSE %.2f mm ≤ %.2f mm limit" % (r, limit)
    if r <= limit * GROOVE_BORDER_FACTOR + 1e-9:
        return GS_BORDER, ("RMSE %.2f mm - above the %.2f limit, within %.2f (×%g)"
                           % (r, limit, limit * GROOVE_BORDER_FACTOR,
                              GROOVE_BORDER_FACTOR))
    return GS_FAIL, ("RMSE %.2f mm > %.2f mm (×%g limit)"
                     % (r, limit * GROOVE_BORDER_FACTOR, GROOVE_BORDER_FACTOR))


def wheel_status(wheel, limit):
    """The worst groove state on a wheel (GS_NONE when nothing reads)."""
    worst = GS_NONE
    for gs in (wheel or {}).get("grooves", []):
        s, _r = groove_status(gs, limit)
        if GS_RANK[s] > GS_RANK[worst]:
            worst = s
    return worst


def groove_slots(summary):
    """Slots (0-based) that read on ANY axle wheel - the shared tyre layout."""
    used = set()
    for (b, _s), w in ((summary or {}).get("wheels") or {}).items():
        if b == UNASSIGNED_LABEL:
            continue
        for k, gs in enumerate(w.get("grooves", [])):
            if gs.get("n"):
                used.add(k)
    return sorted(used)


def _qc(hex_, alpha=255):
    c = QColor(hex_)
    c.setAlpha(max(0, min(255, int(alpha))))
    return c


# ---- v1.6: which slot is on which tyre ---------------------------------------
# Itay, 2026-10-06: the system's depth slots run G1 -> G10 across the tread, LEFT to
# RIGHT as the vehicle is drawn here (front up). Axle 1 is always a single tyre and
# carries all ten. Every other axle is a dual and BOTH tyres are measured: G1-G5 are
# the tyre drawn on the left, G6-G10 the one on the right - so on the RIGHT side of
# the vehicle G1 is the INNER tyre, and on the LEFT side G1 is the OUTER tyre.
TYRE_NAME = {"single": "Tyre", "outer": "Outer tyre", "inner": "Inner tyre",
             "all": "All grooves", "off": "Outside the tyre"}


def tyre_layout(axle_no, side):
    """
    [(role, [slot, ...]), ...] in screen order, left to right. Slots are 0-based.
    No axle (Unassigned) or no side -> one 'all' group, nothing claimed about tyres.
    """
    full = list(range(N_GROOVES))
    if not axle_no or side not in MAP_SIDES:
        return [("all", full)]
    if axle_no == 1:
        return [("single", full)]
    half = N_GROOVES // 2
    a, b = full[:half], full[half:]
    return [("outer", a), ("inner", b)] if side == "Left" else [("inner", a), ("outer", b)]


def wheel_tyres(wheel, bucket=None):
    """
    The wheel's tyres with their pooled stats (computed by groove_wheel_summary).
    v1.8: "slots" = indices into wheel["grooves"]; a wheel with no data -> the
    drawn tyres with no groove.
    """
    if wheel and wheel.get("tyres"):
        return wheel["tyres"]
    return [{"role": role, "slots": [], "all": depth_stats([]), "assumed": False}
            for role in tyre_roles(axle_number(bucket or (wheel or {}).get("bucket")),
                                   (wheel or {}).get("side"))]


def wheel_groove(wheel, i):
    """v1.8: groove i of a wheel, or None - never an IndexError in a paint path."""
    gl = (wheel or {}).get("grooves") or []
    return gl[i] if i is not None and 0 <= i < len(gl) else None


def slot_ranges(slots):
    """[0, 4, 5, 6, 9] -> 'G1, G5–G7, G10' (0-based in, 1-based out)."""
    out, run = [], []
    for s_ in sorted(slots):
        if run and s_ == run[-1] + 1:
            run.append(s_)
            continue
        if run:
            out.append(run)
        run = [s_]
    if run:
        out.append(run)
    return ", ".join("G%d" % (r[0] + 1) if len(r) == 1 else
                     "G%d–G%d" % (r[0] + 1, r[-1] + 1) for r in out)


def tyre_status(wheel, slots, limit):
    """Worst groove state over a tyre's slots."""
    worst = GS_NONE
    for s in slots:
        st_, _r = groove_status(wheel_groove(wheel, s), limit)
        if GS_RANK[st_] > GS_RANK[worst]:
            worst = st_
    return worst
