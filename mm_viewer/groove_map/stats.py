def depth_stats(values):
    """n / min / median / mean / max / n_out over the finite values (mm)."""
    v = sorted(d for d in values if d is not None and not math.isnan(d))
    n = len(v)
    if not n:
        return {"n": 0, "min": math.nan, "median": math.nan, "mean": math.nan,
                "max": math.nan, "n_out": 0, "rmse": math.nan}
    med = v[n // 2] if n % 2 else (v[n // 2 - 1] + v[n // 2]) / 2.0
    return {"n": n, "min": v[0],
            # same median as annotate_drops(), so the two views can never disagree
            "median": med,
            "mean": sum(v) / n, "max": v[-1],
            "n_out": sum(1 for d in v if d < PLAUSIBLE_MIN or d > PLAUSIBLE_MAX),
            # v1.5: spread about the median, for the groove colours
            "rmse": math.sqrt(sum((d - med) ** 2 for d in v) / n)}


def lmi_unit_name(path, pos):
    """
    The LMI unit a profile came from, as the scan names it: the per-unit folder
    (LMI_0_FRONT_LEFT) under the new layout, the token in the filename under the old
    flat one, and the wheel position only when neither carries it.
    """
    parent = os.path.basename(os.path.dirname(os.path.abspath(path)))
    if "LMI" in parent.upper():
        return parent
    m = re.search(r"LMI_\d+_(?:FRONT|REAR)_(?:LEFT|RIGHT)",
                  os.path.basename(path).upper())
    return m.group(0) if m else pos


def lmi_short(unit, pos):
    """'LMI 0 · FL' for a card, where the full folder name does not fit."""
    m = re.search(r"LMI_(\d+)", unit or "", re.IGNORECASE)
    abbr = "".join(w[0] for w in (pos or "").split())
    if m:
        return "LMI %s · %s" % (m.group(1), abbr) if abbr else "LMI " + m.group(1)
    return unit or pos or "-"


def _groove_side(pos, meta_side):
    if meta_side in MAP_SIDES:
        return meta_side
    if "LEFT" in (pos or ""):
        return "Left"
    if "RIGHT" in (pos or ""):
        return "Right"
    return None
