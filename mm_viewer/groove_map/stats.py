# ============================================================
# v1.4  LASER GROOVES - VEHICLE MAP
# ============================================================
# The Laser Grooves tab opens on the vehicle, like Tread and Tire Wall: one card per
# wheel carrying that wheel's median groove depth, and a click shows the wheel's
# depths per groove slot - one table per LMI unit that measured it.
#
# What the numbers are (printed on the panel too, so nobody has to ask):
#   * system-reported depths from *_grooves_full.csv (Depth_0..9), joined to each
#     profile exactly as the Plot view joins them (build_depth_rows). UNFILTERED -
#     the Plot view's profile filter does not change them. No value is edited.
#   * a wheel = the profiles the axle split put on (axle, side). The side is the
#     split's own; a profile it gives no side falls back to its LMI unit's side.
#   * G1..G10 are the system's depth SLOTS. Whether slot k is the same physical
#     groove on every frame is the firmware's ordering, not something checked here.
#   * N = frames that reported that slot (one value each). The median sits beside
#     the mean because single readings of 200-330 mm (MEASURED, 2026-09-28T06-13-17)
#     drag the mean far off the bulk. Red = outside PLAUSIBLE_MIN..PLAUSIBLE_MAX, a
#     display check, not an acceptance criterion - the value still counts.
#   * profiles the split put in Trash are not a wheel: they are counted in the
#     header and open from their own "Unassigned" buttons, never drawn on the vehicle.
