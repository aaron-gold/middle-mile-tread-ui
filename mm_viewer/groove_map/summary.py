def frame_groove_geometry(path):
    """
    v1.8: {slot: (x, z)} for the rows of one frame_<N>_grooves.csv that carry a
    position (X and Z both real). {} if the file is missing or unreadable.
    """
    out = {}
    for r in read_frame_grooves(path):
        if not (math.isnan(r["x"]) or math.isnan(r["z"])):
            out[r["slot"]] = (r["x"], r["z"])
    return out


def groove_wheel_summary(folder, index):
    """
    v1.8: per-wheel, per-PHYSICAL-groove depth statistics for the vehicle map.

    Depths are exactly v1.7's (build_depth_rows: grooves_full, or the per-frame
    file for an empty table). Each depth is placed by the X/Z on its own row of
    the frame's frame_<N>_grooves.csv - see the block comment above.

    wheels[(bucket, side)] = {
        "bucket", "side", "shared", "profiles", "with_depth", "unmatched",
        "from_frame", "n_dup",
        "grooves": [groove],        tyre 0 left->right, tyre 1 ..., then off-tyre
        "tyres":   [{"role", "slots": [groove index], "all": stats, "assumed"}],
        "off":     [groove index]   seen outside the tyre - listed, not drawn,
        "unplaced": stats           depths whose row has no X/Z,
        "all":     stats            every depth on the wheel,
        "units":   OrderedDict(unit -> {"pos", "profiles", "with_depth",
                   "unmatched", "from_frame", "tilt_deg", "tilt_measured",
                   "pitch", "grooves": [stats per wheel groove], "all"})}
    groove = depth_stats(...) + {"label", "unit", "tyre", "frac", "x_mm",
             "slots", "n_rows", "n_frames"}
    Pure - no Qt - so it runs on a worker and in tests.
    """
    rows_by_pos, full_counts = build_depth_rows(folder)
    labels = {}
    if index is not None:
        for p, b in _index_pairs(index):
            labels.setdefault(p, []).append(b)
    meta = index.meta if index is not None else {}
    norm = {os.path.normcase(os.path.abspath(p)): v for p, v in labels.items()}

    # ---- every frame's groove geometry, once; the tilt per LMI unit ----
    geo = {}                               # profile path -> {slot: (x, z)}
    tilts = {}                             # unit -> gp_unit_tilt()
    for pos in POS_ORDER:
        per_unit = {}
        for r in rows_by_pos.get(pos, []):
            p = r.get("path") or ""
            sib = (p[:-len("_profile.csv")] + "_grooves.csv"
                   if p.lower().endswith("_profile.csv") else None)
            g = frame_groove_geometry(sib) if sib and lp_isfile(sib) else {}
            geo[p] = g
            per_unit.setdefault(lmi_unit_name(p, pos), []).append(list(g.values()))
        for unit, fp in per_unit.items():
            tilts[unit] = gp_unit_tilt(fp)

    wheels = {}
    n_rows = n_vals = n_shared = 0
    for pos in POS_ORDER:
        for r in rows_by_pos.get(pos, []):
            p = r.get("path") or ""
            got = labels.get(p)
            if got is None:
                got = norm.get(os.path.normcase(os.path.abspath(p)))
            axles = [b for b in (got or []) if axle_number(b or "") is not None]
            buckets = axles or [UNASSIGNED_LABEL]
            n_rows += 1
            n_vals += sum(1 for d in r["depths"][:N_GROOVES] if not math.isnan(d))
            n_shared += 1 if len(axles) > 1 else 0
            side = _groove_side(pos, (meta.get(p, {}) or {}).get("side"))
            unit = lmi_unit_name(p, pos)
            g = geo.get(p) or {}
            placed, unplaced = [], []
            for slot, (x, z) in g.items():
                d = r["depths"][slot] if slot < N_GROOVES else math.nan
                placed.append((x, z, d, slot))
            for slot, d in enumerate(r["depths"][:N_GROOVES]):
                if not math.isnan(d) and slot not in g:
                    unplaced.append(d)
            for bucket in buckets:
                w = wheels.setdefault((bucket, side), {"bucket": bucket, "side": side,
                                                       "units": OrderedDict(),
                                                       "shared": 0})
                w["shared"] += 1 if len(axles) > 1 else 0
                u = w["units"].setdefault(unit, {
                    "pos": pos, "profiles": 0, "with_depth": 0, "unmatched": 0,
                    "from_frame": 0, "frames": [], "unplaced": []})
                u["profiles"] += 1
                u["with_depth"] += 1 if r["n_valid"] else 0
                src = r.get("source", DEPTH_SRC_NONE)
                u["unmatched"] += 1 if src == DEPTH_SRC_NONE else 0
                u["from_frame"] += 1 if src == DEPTH_SRC_FRAME else 0
                if placed:
                    u["frames"].append((p, placed))
                u["unplaced"].extend(unplaced)

    for (bucket, side), w in wheels.items():
        axle = axle_number(bucket)
        roles = tyre_roles(axle, side)
        mode = "all" if len(roles) == 1 and roles[0] == "all" else (
            "single" if len(roles) == 1 else "dual")
        # front unit before rear, the order the vehicle meets them
        w["units"] = OrderedDict(sorted(
            w["units"].items(),
            key=lambda kv: (POS_ORDER.index(kv[1]["pos"])
                            if kv[1]["pos"] in POS_ORDER else 99, kv[0])))
        grooves, unplaced_all, n_dup, assumed, dup_vals = [], [], 0, set(), []
        for unit, ud in w["units"].items():
            ti = tilts.get(unit) or gp_unit_tilt([])
            sign = -1 if LMI_SCREEN_SIGN.get(unit, 1) < 0 else 1
            res = gp_place(ud.pop("frames"), ti, mode, sign)
            n_dup += res["n_dup"]
            dup_vals.extend(res["dup_vals"])
            ud["tilt_deg"] = math.degrees(ti["tilt"])
            ud["tilt_measured"] = ti["measured"]
            ud["pitch"] = res["pitch"]
            ud["bands"] = res["bands"]
            unplaced_all.extend(ud["unplaced"])
            ud["unplaced_stats"] = depth_stats(ud.pop("unplaced"))
            gs = res["grooves"]
            # drawn tyre index of each tag
            if mode == "dual":
                tyre_of = {"L": 0, "R": 1, "?": roles.index("inner")}
            else:
                tyre_of = {"S": 0}
            on = [g_ for g_ in gs if g_["tag"] in tyre_of]
            ref = min((g_["u"] for g_ in on), default=0.0)
            lu = [g_["u"] for g_ in on if g_["tag"] == "L"]
            ru = [g_["u"] for g_ in on if g_["tag"] == "R"]
            gap_mid = (max(lu) + min(ru)) / 2.0 if lu and ru else None
            for tag in ("S", "L", "R", "?"):
                mine = [g_ for g_ in on if g_["tag"] == tag]
                fr = gp_fracs([g_["u"] for g_ in mine],
                              tag if tag in ("L", "R") and gap_mid is not None
                              else "centre", gap_mid)
                for g_, f in zip(mine, fr):
                    g_["frac"] = f
                if mine and tag == "?":
                    assumed.add(tyre_of["?"])
            for g_ in gs:
                vals = [p_[2][2] for p_ in g_["points"] if not math.isnan(p_[2][2])]
                st = depth_stats(vals)
                st.update({
                    "unit": unit, "u": g_["u"],
                    "tyre": tyre_of.get(g_["tag"]),
                    "frac": g_.get("frac", math.nan),
                    "x_mm": g_["u"] - ref,
                    "slots": sorted({p_[2][3] for p_ in g_["points"]}),
                    "n_rows": len(g_["points"]),
                    "n_frames": len({p_[1] for p_ in g_["points"]}),
                    # (profile path, LMI slot) of every row on this groove
                    "members": [(p_[1], p_[2][3]) for p_ in g_["points"]],
                    "_vals": vals})
                grooves.append(st)
        # tyre 0 left->right, tyre 1 ..., then off-tyre (left->right)
        grooves.sort(key=lambda g_: (g_["tyre"] is None,
                                     g_["tyre"] if g_["tyre"] is not None else 0,
                                     g_["frac"] if g_["tyre"] is not None else g_["x_mm"]))
        on_n = 0
        for g_ in grooves:
            if g_["tyre"] is not None:
                on_n += 1
                g_["label"] = "G%d" % on_n
        k_off = 0
        for g_ in grooves:
            if g_["tyre"] is None:
                k_off += 1
                g_["label"] = "X%d" % k_off
        w["grooves"] = grooves
        w["off"] = [i for i, g_ in enumerate(grooves) if g_["tyre"] is None]
        w["tyres"] = []
        for ti_, role in enumerate(roles):
            idx = [i for i, g_ in enumerate(grooves) if g_["tyre"] == ti_]
            w["tyres"].append({"role": role, "slots": idx,
                               "all": depth_stats([d for i in idx
                                                   for d in grooves[i]["_vals"]]),
                               "assumed": ti_ in assumed})
        for ud_name, ud in w["units"].items():
            ud["grooves"] = [depth_stats(g_["_vals"]) if g_["unit"] == ud_name
                             else depth_stats([]) for g_ in grooves]
            ud["all"] = depth_stats(
                [d for g_ in grooves if g_["unit"] == ud_name for d in g_["_vals"]])
        w["unplaced"] = depth_stats(unplaced_all)
        w["n_dup"] = n_dup
        # depths set aside because their groove already had one on that frame
        w["dup_depths"] = list(dup_vals)
        w["all"] = depth_stats([d for g_ in grooves for d in g_["_vals"]] + unplaced_all)
        for g_ in grooves:
            g_.pop("_vals", None)
        for k in ("profiles", "with_depth", "unmatched", "from_frame"):
            w[k] = sum(u[k] for u in w["units"].values())

    return {
        "n_axles": int(getattr(index, "n_axles", 0) or 0),
        "wheels": wheels,
        "n_profiles": n_rows,
        "n_values": n_vals,
        "n_shared": n_shared,
        "fallback_units": [p_ for p_ in POS_ORDER
                           if (full_counts.get(p_) or {}).get("fallback")],
        "n_from_frame": sum(1 for p_ in POS_ORDER for r in rows_by_pos.get(p_, [])
                            if r.get("source") == DEPTH_SRC_FRAME),
        "n_unassigned": sum(w["profiles"] for (b, _s), w in wheels.items()
                            if b == UNASSIGNED_LABEL),
        # v1.8
        "tilts": {u: {"deg": math.degrees(t["tilt"]), "measured": t["measured"],
                      "frames": t["n"], "sign": t["sign"]} for u, t in tilts.items()},
        "n_unplaced": sum(w["unplaced"]["n"] for (b, _s), w in wheels.items()
                          if b != UNASSIGNED_LABEL),
        "n_dup": sum(w["n_dup"] for (b, _s), w in wheels.items()
                     if b != UNASSIGNED_LABEL),
    }


def groove_wheel_summary_v17(folder, index):
    """
    v1.7's per-slot summary, kept unchanged for comparison and tests.
    Per-wheel, per-groove depth statistics for the Laser Grooves vehicle map.

    Returns {"n_axles", "wheels", "n_profiles", "n_values", "n_unassigned"} with
    wheels = {(bucket, side): wheel}; bucket is "Axle N" or UNASSIGNED_LABEL, and
    wheel = {"bucket", "side", "profiles", "with_depth", "unmatched",
             "grooves": [stats] * N_GROOVES   (every unit pooled),
             "all": stats                     (every groove, every unit),
             "units": OrderedDict(unit name -> {"pos", "profiles", "with_depth",
                                  "unmatched", "grooves", "all"})}
    stats = depth_stats(). Pure - no Qt - so it runs on a worker and in tests.
    """
    rows_by_pos, full_counts = build_depth_rows(folder)
    # v1.5: every bucket a profile is on - a frame his classifier SHARED between two
    # axles feeds both wheels. labels[path] = [primary, further...]
    labels = {}
    if index is not None:
        for p, b in _index_pairs(index):
            labels.setdefault(p, []).append(b)
    meta = index.meta if index is not None else {}
    norm = {os.path.normcase(os.path.abspath(p)): v for p, v in labels.items()}
    wheels = {}
    n_rows = n_vals = n_shared = 0
    for pos in POS_ORDER:
        for r in rows_by_pos.get(pos, []):
            p = r.get("path") or ""
            got = labels.get(p)
            if got is None:
                got = norm.get(os.path.normcase(os.path.abspath(p)))
            axles = [b for b in (got or []) if axle_number(b or "") is not None]
            buckets = axles or [UNASSIGNED_LABEL]
            n_rows += 1
            n_vals += sum(1 for d in r["depths"][:N_GROOVES] if not math.isnan(d))
            n_shared += 1 if len(axles) > 1 else 0
            side = _groove_side(pos, (meta.get(p, {}) or {}).get("side"))
            unit = lmi_unit_name(p, pos)
            for bucket in buckets:
                w = wheels.setdefault((bucket, side), {"bucket": bucket, "side": side,
                                                       "units": OrderedDict(),
                                                       "shared": 0})
                w["shared"] += 1 if len(axles) > 1 else 0
                u = w["units"].setdefault(unit, {
                    "pos": pos, "profiles": 0, "with_depth": 0, "unmatched": 0,
                    "from_frame": 0,
                    "vals": [[] for _g in range(N_GROOVES)]})
                u["profiles"] += 1
                u["with_depth"] += 1 if r["n_valid"] else 0
                # v1.7: unmatched = no depth source; per-frame rows counted apart
                src = r.get("source", DEPTH_SRC_NONE)
                u["unmatched"] += 1 if src == DEPTH_SRC_NONE else 0
                u["from_frame"] += 1 if src == DEPTH_SRC_FRAME else 0
                for g, d in enumerate(r["depths"][:N_GROOVES]):
                    if not math.isnan(d):
                        u["vals"][g].append(d)

    for w in wheels.values():
        pooled = [[] for _g in range(N_GROOVES)]
        for u in w["units"].values():
            vals = u.pop("vals")
            u["grooves"] = [depth_stats(vs) for vs in vals]
            u["all"] = depth_stats([d for vs in vals for d in vs])
            for g, vs in enumerate(vals):
                pooled[g].extend(vs)
        # front unit before rear, the order the vehicle meets them
        w["units"] = OrderedDict(sorted(
            w["units"].items(),
            key=lambda kv: (POS_ORDER.index(kv[1]["pos"])
                            if kv[1]["pos"] in POS_ORDER else 99, kv[0])))
        for k in ("profiles", "with_depth", "unmatched", "from_frame"):
            w[k] = sum(u[k] for u in w["units"].values())
        w["grooves"] = [depth_stats(vs) for vs in pooled]
        w["all"] = depth_stats([d for vs in pooled for d in vs])
        # v1.6: the wheel's tyres (single, or the two of a dual), screen order
        w["tyres"] = [{"role": role, "slots": slots,
                       "all": depth_stats([d for s_ in slots for d in pooled[s_]])}
                      for role, slots in tyre_layout(axle_number(w["bucket"]),
                                                     w["side"])]

    # v1.5: totals count each profile ONCE (a shared frame is on two wheels but is
    # one file); per-wheel numbers count it on every wheel it is on.
    return {
        "n_axles": int(getattr(index, "n_axles", 0) or 0),
        "wheels": wheels,
        "n_profiles": n_rows,
        "n_values": n_vals,
        "n_shared": n_shared,
        # v1.7: units whose grooves_full table was empty -> per-frame depths
        "fallback_units": [p_ for p_ in POS_ORDER
                           if (full_counts.get(p_) or {}).get("fallback")],
        "n_from_frame": sum(1 for p_ in POS_ORDER for r in rows_by_pos.get(p_, [])
                            if r.get("source") == DEPTH_SRC_FRAME),
        "n_unassigned": sum(w["profiles"] for (b, _s), w in wheels.items()
                            if b == UNASSIGNED_LABEL),
    }


def _mm(v):
    """A depth for the screen: two decimals, or an em dash for no reading."""
    return "—" if v is None or math.isnan(v) else "%.2f" % v


def _depth_flag(v):
    if v is None or math.isnan(v):
        return "none"
    return "out" if (v < PLAUSIBLE_MIN or v > PLAUSIBLE_MAX) else ""


class GrooveMapWorker(QThread):
    """groove_wheel_summary() off the GUI thread. Touches no widget."""
    done = pyqtSignal(object)
    failed = pyqtSignal(str)

    def __init__(self, folder, index):
        super().__init__(None)               # unparented: outlives a closing tab
        self.folder = folder or ""
        self.index = index

    def run(self):
        try:
            res = groove_wheel_summary(self.folder, self.index)
        except Exception:
            self.failed.emit(traceback.format_exc(limit=6))
            return
        if not self.isInterruptionRequested():
            self.done.emit(res)


