class GrooveMapPanel(QWidget):
    """
    The Laser Grooves vehicle map: summary strip, the RMSE limit + legend, the
    vehicle with every wheel's grooves drawn inside it (GrooveVehicleView), and the
    selected wheel's per-groove table on the right. The depths are read once, on a
    GrooveMapWorker, behind the usual spinner; changing the limit only repaints.

    v1.5: replaces the v1.4 card grid. Hover a groove for its numbers; click a wheel
    (or a groove) for the table - a clicked groove's row stays highlighted.
    """
    openInPlot = pyqtSignal(str)            # bucket

    def __init__(self, folder, index, parent=None):
        super().__init__(parent)
        self.folder = folder
        self.index = index
        self.n_axles = max(1, int(getattr(index, "n_axles", 1) or 1))
        self.summary = None
        self._keys = {}                      # wheel key -> (bucket, side)
        self._selected = None
        self._pinned_slot = None             # groove row kept highlighted
        self._worker = None
        self._closing = False
        self.setFocusPolicy(Qt.FocusPolicy.StrongFocus)

        head_card, head_v = card()
        self.title = QLabel("Laser Grooves   ·   vehicle map")
        self.title.setObjectName("mapTitle")
        # v1.6: shares a row with the RMSE controls - it keeps its width (a shrunk
        # title was painted UNDER the "RMSE limit" label)
        self.title.setSizePolicy(QSizePolicy.Policy.Fixed, QSizePolicy.Policy.Preferred)
        self.summary_label = QLabel("Reading groove depths…")
        self.summary_label.setObjectName("mapSummary")
        # v1.6: never wraps - exactly two lines (counts, one note), clipped on a
        # narrow window with the full text on hover. Wrapped, it took 4-6 lines at
        # 1300 px and left the wheel panel ~110 px.
        self.summary_label.setWordWrap(False)
        allow_shrink(self.summary_label, 200)
        self.unassigned_host = QWidget()
        self.unassigned_host.setObjectName("gdBody")
        # v1.5: stacked, short labels. Side by side with the full counts in the text
        # they were 1,378 px wide and set the window minimum to ~1,640 px on any scan
        # with Trash laser frames on both sides (latent in v1.4 - its window check
        # ran without an axle split, so the map was never built there).
        # v1.6: side by side again (short labels now) - stacked they cost a row of
        # height, which the no-scroll wheel panel below needs more
        self.unassigned_row = QHBoxLayout(self.unassigned_host)
        self.unassigned_row.setContentsMargins(0, 0, 0, 0)
        self.unassigned_row.setSpacing(6)
        row2 = QHBoxLayout()
        row2.setSpacing(14)
        row2.addWidget(self.summary_label, 1)
        row2.addWidget(self.unassigned_host, 0, Qt.AlignmentFlag.AlignTop)

        # ---- RMSE limit + legend ----
        self.rmse_spin = QDoubleSpinBox()
        self.rmse_spin.setObjectName("gdRmseSpin")
        self.rmse_spin.setDecimals(2)
        self.rmse_spin.setRange(GROOVE_RMSE_MIN, GROOVE_RMSE_MAX)
        self.rmse_spin.setSingleStep(GROOVE_RMSE_STEP)
        self.rmse_spin.setSuffix(" mm")
        self.rmse_spin.setValue(_GROOVE_UI["rmse_limit"])
        self.rmse_spin.setKeyboardTracking(False)
        self.rmse_spin.setMinimumWidth(104)
        self.rmse_spin.setToolTip(
            "RMSE limit for the groove colours.\n\n"
            "RMSE = √ mean((reading − median)²) over one groove's readings on one "
            "wheel:\nhow consistently the system reports that groove, frame to "
            "frame.\n\nPass ≤ limit · Borderline ≤ %g× limit · Fail above that, or a "
            "median outside %g–%g mm.\nDefault %.2f mm = the candidate groove "
            "tolerance (A2, open vs 0.25 mm).\nA display check - not accuracy vs "
            "a gauge, not an acceptance criterion."
            % (GROOVE_BORDER_FACTOR, PLAUSIBLE_MIN, PLAUSIBLE_MAX, GROOVE_RMSE_DEFAULT))
        self.rmse_reset = QPushButton("Default")
        self.rmse_reset.setObjectName("ghostBtn")
        self.rmse_reset.setCursor(Qt.CursorShape.PointingHandCursor)
        self.rmse_reset.setToolTip("Back to %.2f mm" % GROOVE_RMSE_DEFAULT)
        self.rmse_reset.clicked.connect(
            lambda _c=False: self.rmse_spin.setValue(GROOVE_RMSE_DEFAULT))
        self.legend = QLabel("")
        self.legend.setObjectName("gdLegend")
        self.legend.setTextFormat(Qt.TextFormat.RichText)
        allow_shrink(self.legend, 120)
        ctl = QHBoxLayout()
        ctl.setSpacing(8)
        ctl.addWidget(self.title)
        ctl.addSpacing(18)
        ctl.addWidget(field_label("RMSE limit"))
        ctl.addWidget(self.rmse_spin)
        ctl.addWidget(self.rmse_reset)
        ctl.addSpacing(10)
        ctl.addWidget(self.legend, 1)
        head_v.addLayout(ctl)
        head_v.addLayout(row2)

        self.view = GrooveVehicleView()
        self.view.wheelClicked.connect(self._on_view_wheel)
        self.view.grooveClicked.connect(self._on_view_groove)
        self.view.grooveHovered.connect(self._on_view_hover)
        self.view.set_data(None, self.n_axles)

        map_scroll = QScrollArea()
        map_scroll.setWidget(self.view)
        map_scroll.setWidgetResizable(True)
        map_scroll.setFrameShape(QFrame.Shape.NoFrame)
        map_scroll.viewport().setAutoFillBackground(False)
        map_scroll.setStyleSheet("QScrollArea{background:transparent;border:0;}")
        map_scroll.setMinimumWidth(GrooveVehicleView.MIN_W + 20)
        self.map_scroll = map_scroll

        # v1.6: the detail FITS its content to the height it is given (type scales
        # down to 50%). The scroll area is only the last resort for a window too
        # short even for that - its bar never shows when the content fits.
        self.detail = GrooveWheelDetail()
        self.detail.openInPlot.connect(self.openInPlot)
        det_scroll = QScrollArea()
        det_scroll.setWidget(self.detail)
        det_scroll.setWidgetResizable(True)
        det_scroll.setFrameShape(QFrame.Shape.NoFrame)
        det_scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        det_scroll.viewport().setAutoFillBackground(False)
        det_scroll.setStyleSheet("QScrollArea{background:transparent;border:0;}")
        det_scroll.setMinimumWidth(DETAIL_MIN_W)
        det_scroll.setMaximumWidth(DETAIL_MAX_W)
        self.detail_scroll = det_scroll

        split = QSplitter(Qt.Orientation.Horizontal)
        split.setChildrenCollapsible(False)
        split.setHandleWidth(8)
        split.addWidget(map_scroll)
        split.addWidget(det_scroll)
        split.setStretchFactor(0, 1)
        split.setStretchFactor(1, 0)
        self.split = split
        self._sized = False

        hint = QLabel("Hover a groove for its depth and RMSE  ·  click a wheel or a "
                      "groove for the per-groove table  ·  ← → ↑ ↓ move between "
                      "wheels  ·  each groove is drawn where the LMI's own X/Z puts "
                      "it on the tread (not by its output slot); G1, G2 … count left "
                      "to right as drawn.")
        hint.setObjectName("hintText")
        hint.setWordWrap(True)
        allow_shrink(hint, 160)

        root = QVBoxLayout(self)
        root.setContentsMargins(10, 10, 10, 10)
        root.setSpacing(10)
        root.addWidget(head_card)
        root.addWidget(split, 1)
        root.addWidget(hint)

        self.rmse_spin.valueChanged.connect(self._on_limit)
        self._update_legend()

        self.busy = BusyOverlay(self, subtitle="Groove depths — please wait")
        self._build()
        self._start()

    # ---------- load ----------
    def _start(self):
        if not self.folder:
            self.summary_label.setText("No tire_laser_groove_data folder in this scan.")
            return
        w = GrooveMapWorker(self.folder, self.index)
        self._worker = w
        _GROOVE_WORKERS.add(w)
        w.done.connect(self._on_done)
        w.failed.connect(self._on_failed)
        w.finished.connect(self._on_finished)
        w.finished.connect(lambda t=w: _GROOVE_WORKERS.discard(t))
        self.busy.setGeometry(self.rect())
        self.busy.start("Reading groove depths…")
        w.start()

    def _on_done(self, res):
        # an exception escaping a Qt slot is qFatal() - never let one out
        try:
            if self._closing:
                return
            self.summary = res
            self._build()
            self._update_summary()
            self._select_first()
        except Exception:
            traceback.print_exc()
            self.summary_label.setText("⚠  The groove depths could not be shown - "
                                       "see the console. The Plot view is unaffected.")

    def _on_failed(self, tb):
        try:
            print(tb, file=sys.stderr)
            if not self._closing:
                self.summary_label.setText("⚠  Reading the groove depths failed: "
                                           + (tb.strip().splitlines() or ["?"])[-1])
        except Exception:
            traceback.print_exc()

    def _on_finished(self):
        try:
            self._worker = None
            self.busy.stop()
        except Exception:
            traceback.print_exc()

    def shutdown(self):
        """Same rule as GrooveDepthPanel.shutdown: disconnect, then stop."""
        self._closing = True
        w, self._worker = self._worker, None
        if w is None:
            return
        for sig, slot in ((w.done, self._on_done), (w.failed, self._on_failed),
                          (w.finished, self._on_finished)):
            try:
                sig.disconnect(slot)
            except (TypeError, RuntimeError):
                pass
        try:
            w.requestInterruption()
            if w.isRunning():
                w.wait(10000)
        except RuntimeError:
            pass

    def closeEvent(self, ev):
        self.shutdown()
        super().closeEvent(ev)

    def resizeEvent(self, ev):
        super().resizeEvent(ev)
        b = getattr(self, "busy", None)
        if b is not None and not b.isHidden():
            b.setGeometry(self.rect())
        # first real width: the detail opens at its cap, the vehicle takes the rest.
        # Once only - after that the splitter is the user's.
        if not self._sized and self.split.width() > 200:
            self._sized = True
            total = self.split.width() - self.split.handleWidth()
            det = max(DETAIL_MIN_W, min(DETAIL_MAX_W, total // 2))
            self.split.setSizes([max(1, total - det), det])

    # ---------- build ----------
    def wheel(self, bucket, side):
        if not self.summary:
            return None
        return self.summary["wheels"].get((bucket, side))

    def limit(self):
        return float(self.rmse_spin.value())

    def _build(self):
        VehicleMapPanel._clear_layout(self.unassigned_row)
        self._keys.clear()
        for i in range(self.n_axles):
            bucket = "Axle %d" % (i + 1)
            for side in MAP_SIDES:
                wh = self.wheel(bucket, side)
                if wh and wh["profiles"]:
                    self._keys["%s|%s" % (bucket, side)] = (bucket, side)
        self.view.set_data(self.summary, self.n_axles)
        self.view.set_limit(self.limit())

        un = [(s, w) for (b, s), w in sorted(
            (self.summary or {}).get("wheels", {}).items(), key=lambda kv: str(kv[0]))
              if b == UNASSIGNED_LABEL]
        for side, w in un:
            key = "%s|%s" % (UNASSIGNED_LABEL, side)
            self._keys[key] = (UNASSIGNED_LABEL, side)
            b = QPushButton("Unassigned · %s  ·  %d fr  →" % (side or "—", w["profiles"]))
            b.setObjectName("ghostBtn")
            b.setCursor(Qt.CursorShape.PointingHandCursor)
            b.setToolTip("Unassigned · %s:  %d laser frames · %d depth values\n\n"
                         "Laser frames the axle split put on no axle (Trash).\n"
                         "They are not a wheel, so they are not on the vehicle - "
                         "open their groove depths here."
                         % (side or "—", w["profiles"], w["all"]["n"]))
            b.clicked.connect(lambda _c=False, k=key: self._select(k))
            self.unassigned_row.addWidget(b)
        self.unassigned_host.setVisible(bool(un))

    def _update_legend(self):
        lim = self.limit()
        dot = ("<span style='color:%s; font-size:16px;'>●</span>&nbsp;%s")
        parts = [dot % (GS_COLOR[GS_PASS], "Pass ≤ %.2f" % lim),
                 dot % (GS_COLOR[GS_BORDER], "Borderline ≤ %.2f"
                        % (lim * GROOVE_BORDER_FACTOR)),
                 dot % (GS_COLOR[GS_FAIL], "Fail > %.2f or outside %g–%g mm"
                        % (lim * GROOVE_BORDER_FACTOR, PLAUSIBLE_MIN, PLAUSIBLE_MAX)),
                 dot % (GS_COLOR[GS_FEW], "&lt; %d readings" % GROOVE_MIN_N),
                 "<span style='color:%s; font-size:16px;'>▮</span>&nbsp;no reading"
                 % "#3a4350"]
        self.legend.setText("<span style='color:%s'>%s</span>"
                            % (C_TEXT_DIM, "&nbsp;&nbsp;&nbsp;".join(parts)))

    def _update_summary(self):
        s = self.summary or {}
        wheels = s.get("wheels", {})
        un_vals = sum(w["all"]["n"] for (b, _s), w in wheels.items()
                      if b == UNASSIGNED_LABEL)
        on_prof = s.get("n_profiles", 0) - s.get("n_unassigned", 0)
        on_vals = s.get("n_values", 0) - un_vals
        bits = ["<b>%d</b> axle%s from the wheel assembler"
                % (self.n_axles, "" if self.n_axles == 1 else "s"),
                "<b>%d</b> laser frames on a wheel  ·  <b>%d</b> depth values"
                % (on_prof, on_vals)]
        if s.get("n_shared"):
            bits.append("<b>%d</b> shared by two axles (counted on each wheel)"
                        % s["n_shared"])
        if s.get("n_unassigned"):
            bits.append("<b>%d</b> frames on no axle (Trash)" % s["n_unassigned"])
        txt = "   ·   ".join(bits)
        # v1.6: ONE note line on the page (the most serious), the rest on hover -
        # every line here is a line the no-scroll wheel panel loses
        gaps = ["Axle %d %s" % (a, sd) for a in range(1, self.n_axles + 1)
                for sd in MAP_SIDES
                if not (self.wheel("Axle %d" % a, sd) or {}).get("profiles")]
        warnings_ = list(getattr(self.index, "warnings", []) or [])
        shown, hidden = rank_map_warnings(warnings_, "Laser grooves")
        notes = (["no laser frame for: " + ", ".join(gaps)] if gaps else []) + shown
        # v1.7: an empty grooves_full table is the most serious note - without the
        # fallback every wheel on it would be drawn with no groove
        fb = s.get("fallback_units") or []
        if fb:
            notes.insert(0, "scan_grooves_full.csv empty for %s - %d frame(s) read "
                            "from their own frame_N_grooves.csv"
                         % (", ".join("".join(w_[0] for w_ in p_.split()) for p_ in fb),
                            s.get("n_from_frame", 0)))
        # v1.8: how the groove positions were obtained - on hover, after the rest
        tl = s.get("tilts") or {}
        if tl:
            def _nm(u):
                return lmi_short(u, _pos_from_token(u.upper()) or "")
            meas = ["%s %.1f°" % (_nm(u), t["deg"]) for u, t in sorted(tl.items())
                    if t["measured"]]
            raw = [_nm(u) for u, t in sorted(tl.items()) if not t["measured"]]
            hidden = list(hidden) + [
                "groove positions = LMI X/Z rotated by the tread tilt"
                + ((": " + ", ".join(meas)) if meas else "")
                + (("  ·  raw X (tilt not measurable - fewer than %d frames with %d+ "
                    "grooves): %s" % (GP_TILT_MIN_FRAMES, GP_TILT_MIN_GROOVES,
                                      ", ".join(raw))) if raw else "")]
        if s.get("n_unplaced"):
            hidden = list(hidden) + [
                "%d depth value(s) on a wheel have no X/Z on their row - listed per "
                "wheel as 'no position', not drawn" % s["n_unplaced"]]
        if s.get("n_dup"):
            hidden = list(hidden) + [
                "%d row(s) repeated a groove already on the same frame (same X/Z) - "
                "counted once" % s["n_dup"]]
        n_more = len(notes) - 1 + len(hidden)
        if notes:
            txt += ("<br><span style='color:#8a5310'>⚠  %s</span>" % notes[0])
            if n_more > 0:
                txt += ("<span style='color:%s'>   (+%d more note%s — hover)</span>"
                        % (C_TEXT_DIM, n_more, "" if n_more == 1 else "s"))
        self.summary_label.setText(txt)
        self.summary_label.setToolTip(
            "Values: system-reported grooves_full.csv depths, unfiltered - the Plot "
            "view's profile filter does not change them. A unit whose "
            "grooves_full.csv is empty uses each frame's own *_grooves.csv (the same "
            "numbers where both exist).\n\n"
            + "\n\n".join("%d. %s" % (i, w) for i, w in
                           enumerate(notes[:1] + notes[1:] + hidden, 1)))

    # ---------- controls ----------
    def _on_limit(self, v):
        try:
            _GROOVE_UI["rmse_limit"] = float(v)
            self.view.set_limit(v)
            self._update_legend()
            if self._selected:
                self._select(self._selected, keep_slot=True)
        except Exception:
            traceback.print_exc()

    # ---------- selection ----------
    def _select_first(self):
        order = [("Axle %d" % a, sd) for a in range(1, self.n_axles + 1)
                 for sd in MAP_SIDES]
        for want_depth in (True, False):
            for bucket, sd in order:
                wh = self.wheel(bucket, sd)
                if wh and wh["profiles"] and (wh["all"]["n"] or not want_depth):
                    self._select("%s|%s" % (bucket, sd))
                    return
        self.detail.show_message("No laser frame is on any wheel of this scan."
                                 + ("  Use the Unassigned buttons above for the "
                                    "frames the split put in Trash."
                                    if (self.summary or {}).get("n_unassigned")
                                    else ""))

    def _select(self, key, keep_slot=False):
        bs = self._keys.get(key)
        if not bs:
            return
        bucket, side = bs
        wh = self.wheel(bucket, side)
        if not wh:
            return
        if not keep_slot or key != self._selected:
            self._pinned_slot = None
        self._selected = key
        self.view.set_selected(key if bucket != UNASSIGNED_LABEL else None)
        if bucket == UNASSIGNED_LABEL:
            title = "Unassigned  ·  %s   (on no axle)" % (side or "—")
        else:
            title = "%s  ·  %s" % (bucket, side)
        self.detail.show_wheel(wh, title, bucket, self.limit())
        self.detail.highlight_groove(self._pinned_slot)

    def selected_key(self):
        return self._selected

    def _on_view_wheel(self, key):
        try:
            self._select(key)
        except Exception:
            traceback.print_exc()

    def _on_view_groove(self, key, slot):
        try:
            self._select(key)
            self._pinned_slot = slot
            self.detail.highlight_groove(slot)
        except Exception:
            traceback.print_exc()

    def _on_view_hover(self, key, slot):
        try:
            if key and key == self._selected and slot >= 0:
                self.detail.highlight_groove(slot)
            else:
                self.detail.highlight_groove(self._pinned_slot)
        except Exception:
            traceback.print_exc()


