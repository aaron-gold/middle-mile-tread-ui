# SEGMENTED CONTROL  (replaces radio buttons - arrow marker + visible box)
# ============================================================
class SegmentedControl(QWidget):
    """
    A boxed row of mutually exclusive options. The active option is filled UVeye
    orange and marked with a solid arrow; inactive options show a hollow arrow.
    Far more legible at a glance than a radio circle.
    """
    changed = pyqtSignal(str)   # emits the key of the newly selected option

    def __init__(self, options, parent=None):
        """options: list of (key, label) tuples."""
        super().__init__(parent)
        self._buttons = OrderedDict()
        self._current = None

        box = QFrame(self)
        box.setObjectName("segbox")
        row = QHBoxLayout(box)
        row.setContentsMargins(3, 3, 3, 3)
        row.setSpacing(3)

        for key, label in options:
            b = QPushButton(f"▷ {label}")
            b.setObjectName("segbtn")
            b.setCheckable(True)
            b.setCursor(Qt.CursorShape.PointingHandCursor)
            b.setMinimumHeight(30)
            b.setAccessibleName(label)
            b.clicked.connect(lambda _c, k=key: self.set_current(k, emit=True))
            self._buttons[key] = (b, label)
            row.addWidget(b)

        outer = QHBoxLayout(self)
        outer.setContentsMargins(0, 0, 0, 0)
        outer.addWidget(box)
        self.setSizePolicy(QSizePolicy.Policy.Maximum, QSizePolicy.Policy.Fixed)

    def keys(self):
        return list(self._buttons.keys())

    def current(self):
        return self._current

    def set_enabled_key(self, key, enabled):
        if key in self._buttons:
            self._buttons[key][0].setEnabled(enabled)

    def is_enabled_key(self, key):
        return key in self._buttons and self._buttons[key][0].isEnabled()

    def set_current(self, key, emit=False):
        if key not in self._buttons:
            return
        if not self._buttons[key][0].isEnabled():
            # bounce back to whatever is actually selected
            self._repaint_states()
            return
        changed = (key != self._current)
        self._current = key
        self._repaint_states()
        if emit and changed:
            self.changed.emit(key)

    def _repaint_states(self):
        for key, (b, label) in self._buttons.items():
            on = (key == self._current)
            b.setChecked(on)
            b.setText(f"{'▶' if on else '▷'} {label}")


class SegToggle(QWidget):
    """
    v1.2: one on/off option drawn exactly like a SegmentedControl (same box, same
    button height, same arrow), so it lines up with the segmented rows beside it.
    `button` is a plain checkable QPushButton - toggled / setChecked work as usual.
    """

    def __init__(self, label, parent=None):
        super().__init__(parent)
        self._label = label
        box = QFrame(self)
        box.setObjectName("segbox")
        row = QHBoxLayout(box)
        row.setContentsMargins(3, 3, 3, 3)
        row.setSpacing(3)
        self.button = QPushButton()
        self.button.setObjectName("segbtn")
        self.button.setCheckable(True)
        self.button.setCursor(Qt.CursorShape.PointingHandCursor)
        self.button.setMinimumHeight(30)
        self.button.setAccessibleName(label)
        self.button.toggled.connect(self._repaint)
        row.addWidget(self.button)
        outer = QHBoxLayout(self)
        outer.setContentsMargins(0, 0, 0, 0)
        outer.addWidget(box)
        self.setSizePolicy(QSizePolicy.Policy.Maximum, QSizePolicy.Policy.Fixed)
        self._repaint(False)

    def _repaint(self, on):
        self.button.setText(f"{'▶' if on else '▷'} {self._label}")


