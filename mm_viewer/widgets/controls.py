# DROPDOWN  (combo box with an explicit chevron)
# ============================================================
class ArrowComboBox(QComboBox):
    """
    A QComboBox that always shows a down chevron, so it is obvious at a glance
    that the control is a dropdown and not a plain text box.

    Styling `QComboBox::drop-down` in the stylesheet suppresses the native arrow,
    so the chevron is painted here instead: no image asset, no SVG plugin
    dependency, and it stays crisp at any DPI scaling.
    """
    ARROW_ZONE = 26          # px reserved on the right by QComboBox::drop-down

    def paintEvent(self, event):
        super().paintEvent(event)                      # QSS box + current text
        p = QPainter(self)
        p.setRenderHint(QPainter.RenderHint.Antialiasing, True)
        if not self.isEnabled():
            col = QColor("#b3bdcc")
        elif self.underMouse() or (self.view() is not None and self.view().isVisible()):
            col = QColor(C_ORANGE)                     # hover / popup open
        else:
            col = QColor(C_TEXT_DIM)
        pen = QPen(col)
        pen.setWidthF(2.0)
        pen.setCapStyle(Qt.PenCapStyle.RoundCap)
        pen.setJoinStyle(Qt.PenJoinStyle.RoundJoin)
        p.setPen(pen)
        cx = self.width() - self.ARROW_ZONE / 2.0 - 1.0
        cy = self.height() / 2.0
        dx, dy = 4.5, 2.6
        p.drawLine(QPointF(cx - dx, cy - dy), QPointF(cx, cy + dy))
        p.drawLine(QPointF(cx, cy + dy), QPointF(cx + dx, cy - dy))
        p.end()
