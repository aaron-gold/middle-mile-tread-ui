"""Zoom view.

Part of the mm_viewer package - moved verbatim from MiddleMile_GUI v1.8,
lines 926-1253. Imports generated by the split (2026-10-18)."""


import numpy as np
from PyQt6.QtCore import pyqtSignal, QLineF, QRectF, Qt
from PyQt6.QtGui import QBrush, QColor, QImage, QPen, QPixmap
from PyQt6.QtWidgets import (
    QGraphicsLineItem, QGraphicsPixmapItem, QGraphicsRectItem, QGraphicsScene,
    QGraphicsView
)


from mm_viewer.theme import C_BLUE, C_BORDER, C_VIEW_BG, ROI_COLOR_FROZEN, ROI_COLOR_LIVE


# ============================================================
# ZOOM / PAN / ROI / LINE VIEW
# ============================================================
class ZoomPanView(QGraphicsView):
    pixelMoved = pyqtSignal(int, int, object)      # x, y, value (int or (r,g,b) or None)
    roiChanged = pyqtSignal(int, int, int, int)    # x, y, w, h
    roiCleared = pyqtSignal()
    roiFrozenChanged = pyqtSignal(bool)
    lineSelected = pyqtSignal(int, int, int, int)  # x0, y0, x1, y1
    lineCancelled = pyqtSignal()

    MODE_PAN = "pan"
    MODE_ROI = "roi"
    MODE_LINE = "line"

    MIN_SCALE = 0.005
    MAX_SCALE = 400.0
    CLICK_SLOP = 4        # px of movement below which a drag counts as a click

    def __init__(self):
        super().__init__()
        self.setScene(QGraphicsScene(self))
        self.pix_item = None
        self.raw = None
        self._disp_buf = None
        self._zoom_active = False
        self.mode = self.MODE_PAN

        self._panning = False
        self._pan_start = None
        self._press_view_pos = None
        self._drag_start_scene = None
        self._rubber_line = None

        # persistent ROI (survives frame / camera changes)
        self.roi = None            # (x, y, w, h) in image pixels
        self.roi_frozen = False
        self._roi_item = None
        self._roi_drawing = False   # a real drag is in progress
        self._roi_pending = False   # mouse is down in ROI mode, drag not started yet
        self._roi_before = None     # ROI as it was before this drag started

        self.setMouseTracking(True)
        self.setTransformationAnchor(QGraphicsView.ViewportAnchor.NoAnchor)
        self.setResizeAnchor(QGraphicsView.ViewportAnchor.NoAnchor)
        self.setFocusPolicy(Qt.FocusPolicy.StrongFocus)
        self.setStyleSheet(f"background-color:{C_VIEW_BG}; border:1px solid {C_BORDER};"
                           " border-radius:8px;")

    # ---------- mode ----------
    def set_mode(self, mode):
        self.mode = mode
        self._clear_line_overlay()
        if mode == self.MODE_LINE:
            self.viewport().setCursor(Qt.CursorShape.CrossCursor)
        elif mode == self.MODE_ROI:
            self.viewport().setCursor(Qt.CursorShape.CrossCursor)
        else:
            self.viewport().setCursor(Qt.CursorShape.ArrowCursor)

    # ---------- overlays ----------
    def _clear_line_overlay(self):
        if self._rubber_line is not None and self._rubber_line.scene() is not None:
            self.scene().removeItem(self._rubber_line)
        self._rubber_line = None

    def _roi_pen(self):
        pen = QPen(QColor(ROI_COLOR_FROZEN if self.roi_frozen else ROI_COLOR_LIVE))
        pen.setCosmetic(True)
        pen.setWidth(3 if self.roi_frozen else 2)
        if not self.roi_frozen and self._roi_drawing:
            pen.setStyle(Qt.PenStyle.DashLine)
        return pen

    def _ensure_roi_item(self):
        if self._roi_item is None or self._roi_item.scene() is None:
            self._roi_item = QGraphicsRectItem()
            self._roi_item.setBrush(QBrush(Qt.BrushStyle.NoBrush))   # OUTLINE ONLY
            self._roi_item.setZValue(10)
            self.scene().addItem(self._roi_item)
        self._roi_item.setPen(self._roi_pen())
        return self._roi_item

    def _redraw_roi(self):
        if self.roi is None:
            if self._roi_item is not None and self._roi_item.scene() is not None:
                self.scene().removeItem(self._roi_item)
            self._roi_item = None
            return
        x, y, w, h = self.roi
        it = self._ensure_roi_item()
        it.setRect(QRectF(x, y, w, h))

    def clear_roi(self):
        had = self.roi is not None
        self.roi = None
        self.roi_frozen = False
        self._roi_drawing = False
        self._roi_pending = False
        self._roi_before = None
        self._redraw_roi()
        if had:
            self.roiCleared.emit()
            self.roiFrozenChanged.emit(False)

    def toggle_roi_freeze(self):
        if self.roi is None:
            return
        self.roi_frozen = not self.roi_frozen
        self._redraw_roi()
        self.roiFrozenChanged.emit(self.roi_frozen)

    # ---------- image ----------
    def fit_image(self):
        if self.pix_item:
            self.fitInView(self.pix_item, Qt.AspectRatioMode.KeepAspectRatio)
            self._zoom_active = False

    def reset_view(self):
        self.fit_image()

    def set_image(self, display_rgb, raw):
        self.raw = raw
        self._disp_buf = np.ascontiguousarray(display_rgb)  # keep ref alive for QImage
        if self._disp_buf.ndim == 2:
            # v1.1 fast path: an 8-bit grayscale frame shown as-is (identical pixels
            # to the stacked-RGB route, a third of the bytes, no 3-channel copy)
            h, w = self._disp_buf.shape
            qimg = QImage(self._disp_buf.data, w, h, w, QImage.Format.Format_Grayscale8)
        else:
            h, w, ch = self._disp_buf.shape
            qimg = QImage(self._disp_buf.data, w, h, ch * w, QImage.Format.Format_RGB888)
        pix = QPixmap.fromImage(qimg)

        keep_transform = self._zoom_active
        tr = self.transform()

        self.scene().clear()          # drops every item, including the ROI item
        self._roi_item = None
        self._rubber_line = None
        self.pix_item = QGraphicsPixmapItem(pix)
        self.scene().addItem(self.pix_item)
        self.setSceneRect(self.pix_item.boundingRect())

        if keep_transform:
            self.setTransform(tr)     # stay where the user zoomed while stepping frames
        else:
            self.fit_image()

        # ROI persists across frames, but must stay inside the new image
        if self.roi is not None:
            x, y, w, h = self.roi
            r = QRectF(x, y, w, h).intersected(self.pix_item.boundingRect())
            if r.width() < 2 or r.height() < 2:
                self.clear_roi()
            else:
                self.roi = (int(r.x()), int(r.y()), int(r.width()), int(r.height()))
        self._redraw_roi()

    def reset_zoom_state(self):
        """Forget the user's zoom/pan so the next image is fitted to the view."""
        self._zoom_active = False
        self.resetTransform()

    def clear_image(self):
        self.scene().clear()
        self.pix_item = None
        self.raw = None
        self._roi_item = None
        self._rubber_line = None

    def resizeEvent(self, event):
        super().resizeEvent(event)
        if not self._zoom_active:
            self.fit_image()

    def wheelEvent(self, event):
        if not self.pix_item:
            return
        f_in = 1.15
        factor = f_in if event.angleDelta().y() > 0 else 1.0 / f_in
        cur = self.transform().m11()
        target = cur * factor
        if target < self.MIN_SCALE or target > self.MAX_SCALE:
            return                                   # clamp - no runaway zoom
        self._zoom_active = True
        old = self.mapToScene(event.position().toPoint())
        self.scale(factor, factor)
        new = self.mapToScene(event.position().toPoint())
        d = new - old
        self.translate(d.x(), d.y())

    def _pixel_at(self, scene_pt):
        if self.raw is None:
            return None
        x = int(scene_pt.x())
        y = int(scene_pt.y())
        H, W = self.raw.shape[:2]
        if x < 0 or y < 0 or x >= W or y >= H:
            return None
        v = self.raw[y, x]
        if self.raw.ndim == 2:
            return (x, y, int(v))
        return (x, y, tuple(int(c) for c in np.atleast_1d(v)[:3]))

    # ---------- mouse ----------
    def mousePressEvent(self, event):
        if event.button() == Qt.MouseButton.LeftButton and self.pix_item is not None:
            self._drag_start_scene = self.mapToScene(event.position().toPoint())
            self._press_view_pos = event.position()

            if self.mode == self.MODE_LINE:
                self._clear_line_overlay()
                pen = QPen(QColor(C_BLUE)); pen.setCosmetic(True); pen.setWidth(2)
                self._rubber_line = QGraphicsLineItem(
                    QLineF(self._drag_start_scene, self._drag_start_scene))
                self._rubber_line.setPen(pen)
                self._rubber_line.setZValue(11)
                self.scene().addItem(self._rubber_line)
            elif self.mode == self.MODE_ROI and not self.roi_frozen:
                # do NOT touch the existing ROI yet - a plain click must not destroy it
                self._roi_pending = True
                self._roi_drawing = False
                self._roi_before = self.roi
            else:
                # Pan mode, or ROI mode with a frozen ROI -> still allow panning
                self._panning = True
                self._pan_start = event.position()
                self.viewport().setCursor(Qt.CursorShape.ClosedHandCursor)
        super().mousePressEvent(event)

    def mouseMoveEvent(self, event):
        pt = self.mapToScene(event.position().toPoint())
        info = self._pixel_at(pt)
        if info is None:
            self.pixelMoved.emit(-1, -1, None)
        else:
            self.pixelMoved.emit(info[0], info[1], info[2])

        if self._panning and self._pan_start is not None:
            d = event.position() - self._pan_start
            self._pan_start = event.position()
            self._zoom_active = True          # user positioned the view deliberately
            self.translate(-d.x(), -d.y())
        elif (self._roi_pending or self._roi_drawing) and self._drag_start_scene is not None:
            if not self._roi_drawing:
                d = event.position() - (self._press_view_pos or event.position())
                if abs(d.x()) <= self.CLICK_SLOP and abs(d.y()) <= self.CLICK_SLOP:
                    super().mouseMoveEvent(event)
                    return                      # still just a click, leave the ROI alone
                self._roi_drawing = True
            r = QRectF(self._drag_start_scene, pt).normalized()
            if self.pix_item is not None:                     # keep the ROI inside the image
                r = r.intersected(self.pix_item.boundingRect())
            self.roi = (int(r.x()), int(r.y()), int(r.width()), int(r.height()))
            self._redraw_roi()
        elif self.mode == self.MODE_LINE and self._rubber_line is not None \
                and self._drag_start_scene is not None:
            self._rubber_line.setLine(QLineF(self._drag_start_scene, pt))
        super().mouseMoveEvent(event)

    def _was_click(self, event):
        if self._press_view_pos is None:
            return False
        d = event.position() - self._press_view_pos
        return abs(d.x()) <= self.CLICK_SLOP and abs(d.y()) <= self.CLICK_SLOP

    def mouseReleaseEvent(self, event):
        if event.button() == Qt.MouseButton.LeftButton:
            click = self._was_click(event)

            if self._panning:
                self._panning = False
                self._pan_start = None
                self.viewport().setCursor(
                    Qt.CursorShape.CrossCursor if self.mode in (self.MODE_ROI, self.MODE_LINE)
                    else Qt.CursorShape.ArrowCursor)
                # click (no drag) inside ROI mode toggles the freeze
                if click and self.mode == self.MODE_ROI:
                    self.toggle_roi_freeze()

            elif self._roi_drawing or self._roi_pending:
                drawing = self._roi_drawing
                self._roi_drawing = False
                self._roi_pending = False
                if not drawing:
                    # plain click in ROI mode -> lock / unlock the existing ROI
                    self.roi = self._roi_before
                    self._redraw_roi()
                    if self.roi is not None:
                        self.toggle_roi_freeze()
                elif self.roi is None or self.roi[2] < 2 or self.roi[3] < 2:
                    self.roi = self._roi_before      # too small to be a ROI - keep the old one
                    self._redraw_roi()
                    if self.roi is None:
                        self.roiCleared.emit()
                else:
                    self._redraw_roi()
                    self.roiChanged.emit(*self.roi)

            elif self.mode == self.MODE_LINE and self._rubber_line is not None \
                    and self._drag_start_scene is not None:
                p1 = self._drag_start_scene
                p2 = self.mapToScene(event.position().toPoint())
                if click:
                    self._clear_line_overlay()
                    self.lineCancelled.emit()
                else:
                    self.lineSelected.emit(int(p1.x()), int(p1.y()), int(p2.x()), int(p2.y()))

            self._press_view_pos = None
        super().mouseReleaseEvent(event)

    def keyPressEvent(self, event):
        k = event.key()
        if k in (Qt.Key.Key_Backspace, Qt.Key.Key_Delete):
            self.clear_roi()
            event.accept()
            return
        if k == Qt.Key.Key_Escape:
            if self.mode == self.MODE_LINE:
                self._clear_line_overlay()
                self.lineCancelled.emit()
                event.accept()
                return
        super().keyPressEvent(event)
