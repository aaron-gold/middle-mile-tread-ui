def allow_shrink(widget, floor=80):
    """
    Let a long single-line label be narrower than its text.

    A QLabel reports its full text width as its MINIMUM width, so one long status or
    header line silently sets the whole window's minimum width. These labels are
    informational and may clip; clipping (unlike eliding) leaves the stored text
    complete, so a clipped scan ID is still selectable and copyable in full.
    """
    widget.setSizePolicy(QSizePolicy.Policy.Ignored, widget.sizePolicy().verticalPolicy())
    widget.setMinimumWidth(floor)
    return widget


class ElidedLabel(QLabel):
    """
    A path label that never forces its window wider than the screen.

    A plain QLabel reports its FULL text width as its minimum width, and the scan
    paths shown in the toolbars are long absolute paths. That pushed the whole
    window's minimum width to ~2460 px - wider than a 1920 px screen - so the app
    could not be shrunk or maximised to fit and opened with its right-hand controls
    off the edge.

    This label elides the middle of the path (keeping the drive and the file name,
    which are the parts that identify it) and always keeps the full text in the
    tooltip and in text().
    """

    def __init__(self, text="", parent=None):
        super().__init__(parent)
        self._full = text or ""
        # Ignored: the layout may shrink this below its natural width
        self.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
        self.setMinimumWidth(80)
        self.setText(self._full)

    def setText(self, text):
        self._full = text or ""
        self.setToolTip(self._full)
        self._relayout()

    def text(self):
        """The full path, not the elided rendering - callers expect the real value."""
        return self._full

    def resizeEvent(self, ev):
        super().resizeEvent(ev)
        self._relayout()

    def _relayout(self):
        fm = QFontMetrics(self.font())
        super().setText(fm.elidedText(self._full, Qt.TextElideMode.ElideMiddle,
                                      max(0, self.width() - 4)))


class SortCell(QTableWidgetItem):
    """
    Table cell that sorts by a real value instead of by its display string.

    Without this, clicking a depth-column header sorts "10.500" before "9.200"
    because QTableWidgetItem compares text. `seq` is the row's natural (unit, time)
    position and breaks ties, so enabling sorting never scrambles the default order,
    and NaN always sinks to the bottom whichever direction is chosen.
    """
    __slots__ = ("_key", "_seq")

    def __init__(self, text, key=None, seq=0):
        super().__init__(text)
        self._key = key
        self._seq = seq

    def __lt__(self, other):
        if not isinstance(other, SortCell):
            return super().__lt__(other)
        a, b = self._key, other._key
        a_bad = a is None or (isinstance(a, float) and math.isnan(a))
        b_bad = b is None or (isinstance(b, float) and math.isnan(b))
        if a_bad and b_bad:
            return self._seq < other._seq
        if a_bad:
            return False
        if b_bad:
            return True
        if a == b:
            return self._seq < other._seq
        return a < b


