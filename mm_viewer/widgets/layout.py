def card(title=None):
    """A white panel with an optional small uppercase caption. Returns (frame, vbox)."""
    f = QFrame()
    f.setObjectName("card")
    v = QVBoxLayout(f)
    v.setContentsMargins(12, 10, 12, 10)
    v.setSpacing(8)
    if title:
        cap = QLabel(title.upper())
        cap.setObjectName("caption")
        v.addWidget(cap)
    return f, v


