class FlowLayout(QLayout):
    """
    A horizontal row that WRAPS instead of forcing its window wider.

    Why this exists: a QHBoxLayout reports the SUM of its children as its minimum
    width, so the dense control rows (brightness + gamma, the tool row, the groove
    and wheel-assembler toolbars) pushed MainWindow.minimumSizeHint() to 1827 x 946.
    On any display narrower than that - 1366x768 and 1600x900 laptops, and a 1920px
    screen once Windows scaling is on - the window could not be sized into the work
    area, so maximising left the right-hand controls off the edge.

    Wrapping makes the minimum width the width of the WIDEST SINGLE control instead
    of the whole row: when the window is narrow the toolbar grows one line taller
    rather than pushing the window wider, and every control stays reachable.

    Standard Qt flow-layout contract: hasHeightForWidth() is True and
    heightForWidth() re-runs the placement in measure-only mode.
    """

    def __init__(self, parent=None, margin=0, hspacing=8, vspacing=6):
        super().__init__(parent)
        self._items = []
        self._hspace = hspacing
        self._vspace = vspacing
        self.setContentsMargins(margin, margin, margin, margin)

    # ---- QLayout plumbing ----
    def __del__(self):
        while self.count():
            self.takeAt(0)

    def addItem(self, item):
        self._items.append(item)

    def count(self):
        return len(self._items)

    def itemAt(self, index):
        if 0 <= index < len(self._items):
            return self._items[index]
        return None

    def takeAt(self, index):
        if 0 <= index < len(self._items):
            return self._items.pop(index)
        return None

    def expandingDirections(self):
        return Qt.Orientation(0)

    def hasHeightForWidth(self):
        return True

    def heightForWidth(self, width):
        return self._do_layout(QRect(0, 0, width, 0), test_only=True)

    def setGeometry(self, rect):
        super().setGeometry(rect)
        self._do_layout(rect, test_only=False)

    def sizeHint(self):
        w = 0
        h = 0
        for i, it in enumerate(self._items):
            s = it.sizeHint()
            w += s.width() + (self._hspace if i else 0)
            h = max(h, s.height())
        m = self.contentsMargins()
        return QSize(w + m.left() + m.right(), h + m.top() + m.bottom())

    def minimumSize(self):
        """
        The widest single child, NOT the sum - that is the whole point of this class.
        The height floor is one row; the real height comes from heightForWidth.
        """
        w = h = 0
        for it in self._items:
            s = it.minimumSize()
            w = max(w, s.width())
            h = max(h, s.height())
        m = self.contentsMargins()
        return QSize(w + m.left() + m.right(), h + m.top() + m.bottom())

    # ---- placement ----
    def _do_layout(self, rect, test_only):
        m = self.contentsMargins()
        eff = rect.adjusted(m.left(), m.top(), -m.right(), -m.bottom())
        x, y = eff.x(), eff.y()
        line_h = 0
        line = []                                   # (item, x, size) on this line

        def place(items, top, h):
            # v1.2: centred on the line, not top-aligned - a 30 px label beside a
            # 38 px segmented box used to sit visibly higher than it
            for it_, x_, s_ in items:
                it_.setGeometry(QRect(QPoint(x_, top + (h - s_.height()) // 2), s_))

        for it in self._items:
            s = it.sizeHint()
            # An ElidedLabel reports its FULL path as its sizeHint. Clamp to the row
            # so it elides instead of running off the right edge.
            if s.width() > eff.width():
                s = QSize(eff.width(), s.height())
            nx = x + s.width()
            if nx > eff.right() + 1 and line_h > 0:      # does not fit - wrap
                if not test_only:
                    place(line, y, line_h)
                line = []
                x = eff.x()
                y = y + line_h + self._vspace
                nx = x + s.width()
                line_h = 0
            line.append((it, x, s))
            x = nx + self._hspace
            line_h = max(line_h, s.height())
        if not test_only:
            place(line, y, line_h)
        return y + line_h - rect.y() + m.bottom()


class AutoHeightScroll(QScrollArea):
    """
    Holds a stack of control cards that must never dictate how tall the window can be.

    The image canvas has a floor and the toolbars have a natural height; together
    they made the window's MINIMUM height 962 px, so on a 1366x768 laptop - or a
    1920x1080 screen at 150% Windows scaling, where the work area is only 693 px -
    the window could not be sized into the screen and its bottom ran off the display.

    Wrapping the control stack here makes its minimum ~120 px: on a normal screen it
    asks for its full natural height and nothing scrolls, and on a short one it
    scrolls instead of pushing the window off the bottom of the display.
    """

    MIN_H = 120

    def __init__(self, body, parent=None):
        super().__init__(parent)
        self.setWidget(body)
        self.setWidgetResizable(True)
        self.setFrameShape(QFrame.Shape.NoFrame)
        self.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        self.viewport().setAutoFillBackground(False)
        self.setStyleSheet("QScrollArea{background:transparent;border:0;}")
        # Maximum, not Preferred: the scroller takes its sizeHint AT MOST, so the
        # extra height of a big window goes to the image canvas (stretch 1) instead
        # of inflating the control cards.
        self.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Maximum)

    def sizeHint(self):
        w = self.widget()
        return QSize(w.sizeHint().width(), w.sizeHint().height()) if w             else super().sizeHint()

    def minimumSizeHint(self):
        return QSize(0, self.MIN_H)


def flow_row(widgets, hspacing=8, vspacing=6):
    """Build a FlowLayout from a list of widgets (None entries are skipped)."""
    fl = FlowLayout(hspacing=hspacing, vspacing=vspacing)
    for w in widgets:
        if w is not None:
            fl.addWidget(w)
    return fl
