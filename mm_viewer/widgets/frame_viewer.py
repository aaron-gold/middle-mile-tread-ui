    # ---------- helpers ----------
    @staticmethod
    def _fmt(v):
        return f"{v:.3f}".rstrip("0").rstrip(".")

    def _get_gamma(self):
        try:
            return float(self.gamma_store.get(self.group_key, 1.0))
        except Exception:
            return 1.0

    def _set_gamma(self, g):
        self.gamma_store[self.group_key] = float(g)

    def _cams(self):
        return self.collection.get(self.current_variant, OrderedDict())

    def _current_cam_id(self):
        i = self.cam_combo.currentIndex()
        return self._cam_ids[i] if 0 <= i < len(self._cam_ids) else ""

    # ---------- population ----------
    def _populate_cameras(self):
        self.cam_combo.blockSignals(True)
        self.cam_combo.clear()
        cams = self._cams()
        self._cam_ids = list(cams.keys())
        for cid in self._cam_ids:
            n = len(cams[cid]["files"])
            self.cam_combo.addItem(f"{cid}   ({n} frame{'s' if n != 1 else ''})")
        self.cam_combo.blockSignals(False)
        if self._cam_ids:
            self.cam_combo.setCurrentIndex(0)
            self._on_camera_changed(0)
        else:
            self.files = []
            self._show_empty()

    def _on_variant_changed(self, key):
        if key == self.current_variant:
            return
        keep = self._current_cam_id()     # stay on the same axle / camera
        self.current_variant = key
        self._clear_roi()                 # a ROI from another variant is not comparable
        self._populate_cameras()
        if keep and keep in self._cam_ids:
            i = self._cam_ids.index(keep)
            if self.cam_combo.currentIndex() != i:
                self.cam_combo.setCurrentIndex(i)

    def _on_camera_changed(self, idx):
        if not self._cam_ids:
            self.files = []
            self._show_empty()
            return
        idx = max(0, min(idx, len(self._cam_ids) - 1))
        entry = self._cams()[self._cam_ids[idx]]
        self.files = entry["files"]
        self.view.reset_zoom_state()      # a new camera may have a different frame size
        n = len(self.files)
        self.frame_slider.blockSignals(True)
        self.frame_slider.setMinimum(0)
        self.frame_slider.setMaximum(max(0, n - 1))
        self.frame_slider.setValue(0)
        self.frame_slider.blockSignals(False)
        if n:
            self._load_frame(0)
        else:
            self._show_empty()
        self._update_nav_buttons()

    # ---------- vehicle-map integration ----------
    def select_source(self, variant, key):
        """
        Open one specific dropdown entry - what a click on the vehicle map does.

        Nothing is guessed: an unknown key leaves the viewer exactly where it was
        and returns False, so a stale map can never silently show a different
        wheel's frames than the one that was clicked.
        """
        if (variant in ("raw", "compressed") and variant != self.current_variant
                and self.collection.get(variant)
                and self.variant_seg.is_enabled_key(variant)):
            self.variant_seg.set_current(variant, emit=True)
        try:
            i = self._cam_ids.index(key)
        except ValueError:
            return False
        if self.cam_combo.currentIndex() == i:
            self._on_camera_changed(i)          # already selected - still refresh
        else:
            self.cam_combo.setCurrentIndex(i)   # fires _on_camera_changed
        return True

    def keyPressEvent(self, ev):
        """
        Esc returns to the vehicle map - but NOT while a cross-section line is being
        drawn, where Esc already means 'cancel the line'. A QShortcut would have
        swallowed that; handling the key here lets the view keep first refusal.
        """
        if (ev.key() == Qt.Key.Key_Escape and self.on_back is not None
                and self.view.mode != ZoomPanView.MODE_LINE):
            self.on_back()
            ev.accept()
            return
        super().keyPressEvent(ev)

    def _show_empty(self):
        self.raw = None
        self._current_path = None
        self.view.clear_image()
        self._info_base = f"{self.label}  ·  no frames"
        self._info_flag = ""
        self._update_info()
        self.frame_label.setText("Frame 0 / 0")
        self.meta.setPlainText("")
        self._update_nav_buttons()

    # ---------- frame loading ----------
    def _on_slider(self, idx):
        self._pending_idx = idx
        self._update_nav_buttons()
        self._slider_timer.start()

    def _load_pending_frame(self):
        if self._pending_idx is not None:
            idx, self._pending_idx = self._pending_idx, None
            self._load_frame(idx)

    def _load_frame(self, idx):
        if not self.files:
            self._show_empty()
            return
        idx = max(0, min(idx, len(self.files) - 1))
        path = self.files[idx]
        try:
            raw = load_frame_cached(path)
        except Exception as e:
            raw = None
            self._info_base = f"{os.path.basename(path)}  ·  READ ERROR: {e}"
        if raw is None:
            self.raw = None
            self.view.clear_image()
            if "READ ERROR" not in self._info_base:
                self._info_base = f"{os.path.basename(path)}  ·  FAILED TO DECODE"
            self._info_flag = ""
            self._update_info()
            self.frame_label.setText(f"Frame {idx} / {max(0, len(self.files) - 1)}")
            self.meta.setPlainText("")
            self._update_nav_buttons()
            return

        self.raw = raw
        self._current_path = path
        cam = self._current_cam_id()
        H, W = raw.shape[:2]
        ch = 1 if raw.ndim == 2 else raw.shape[2]
        # An axle group merges the front and rear cameras of one side, so the frame's
        # own folder is the only thing left that says which camera produced it. It is
        # shown for every frame - losing camera identity is exactly the defect the
        # in-memory classification exists to avoid.
        src_cam = os.path.basename(os.path.dirname(path))
        self._info_base = (f"{cam} [{self.current_variant}]  ·  {src_cam}"
                           f"  ·  {os.path.basename(path)}"
                           f"  ·  {W}x{H}  {raw.dtype} {ch}ch")
        self._refresh_display()
        self.frame_label.setText(f"Frame {idx} / {len(self.files) - 1}")
        self._load_sidecar(path)
        self._update_nav_buttons()

    def _refresh_display(self):
        if self.raw is None:
            return
        b = self.bright_slider.value()
        self.bright_val.setText(str(b))
        g = self._get_gamma()
        if (self.raw.ndim == 2 and self.raw.dtype == np.uint8 and b == 0
                and abs(g - 1.0) <= 1e-9):
            # untouched 8-bit grayscale: the data itself is the display image
            rgb, scaled = self.raw, False
        else:
            rgb, scaled = to_display_rgb(self.raw, gamma=g, brightness=b)
        self.view.set_image(rgb, self.raw)
        # rebuilt from state every time - never appended (that used to grow forever)
        self._info_flag = "  ·  [display-scaled >8bit]" if scaled else ""
        self._update_info()

    def _update_info(self):
        roi_txt = ""
        if self.roi is not None:
            x, y, w, h = self.roi
            lock = " \U0001F512" if self.view.roi_frozen else ""
            roi_txt = f"  ·  ROI x={x} y={y} w={w} h={h}{lock}"
        self.info_label.setText(f"{self._info_base}{self._info_flag}{roi_txt}")

    def _update_nav_buttons(self):
        n = len(self.files)
        v = self.frame_slider.value()
        self.prev_btn.setEnabled(n > 0 and v > 0)
        self.next_btn.setEnabled(n > 0 and v < self.frame_slider.maximum())

    def _load_sidecar(self, path):
        c = sidecar_path(path)
        if c is None:
            self.meta.setPlainText("(no JSON sidecar)")
            return
        try:
            with lp_open(c, "r", encoding="utf-8", errors="replace") as fh:
                d = json.load(fh)
        except Exception as e:
            self.meta.setPlainText(f"(could not parse {os.path.basename(c)}: {e})")
            return
        self.meta.setPlainText(self._summarize_meta(d))

    @staticmethod
    def _summarize_meta(d):
        keys = ["ScanTimestampUtc", "MessageTimestampUtc", "Timestamp_usec", "CameraTemp_degC",
                "Result", "Error", "ScanId", "FrameUUID", "sourceId", "shotId"]
        lines = []
        for k in keys:
            if isinstance(d, dict) and k in d:
                lines.append(f"{k}: {d[k]}")
        # acquisition params if present
        try:
            src = d.get("sourceInfo", [{}])[0]
            ap = src.get("AcquisitionParameters", {})
            if ap:
                lines.append(f"Exposure_msec: {ap.get('Exposure_msec')}  Gain: {ap.get('Gain')}")
                dims = ap.get("Dimensions_pix", {})
                if dims:
                    lines.append(f"Dimensions_pix: {dims.get('Width')}x{dims.get('Height')}")
            lines.append(f"Camera: {src.get('vendor')} {src.get('model')}  SN {src.get('serialNo')}")
        except Exception:
            pass
        if lines:
            return "\n".join(lines)
        try:
            return json.dumps(d, indent=2)[:2000]
        except Exception:
            return str(d)[:2000]

    # ---------- navigation ----------
    def next_frame(self):
        if not self.files:
            return
        v = self.frame_slider.value()
        if v < self.frame_slider.maximum():
            self.frame_slider.setValue(v + 1)

    def prev_frame(self):
        if not self.files:
            return
        v = self.frame_slider.value()
        if v > 0:
            self.frame_slider.setValue(v - 1)

    # ---------- view adjust ----------
    def _apply_gamma(self):
        try:
            g = float(self.gamma_input.text())
            if not np.isfinite(g) or g <= 0:
                raise ValueError
        except Exception:
            QMessageBox.warning(self, "Invalid gamma", "Enter a positive number (e.g. 0.8, 1.0, 1.4).")
            self.gamma_input.setText(self._fmt(self._get_gamma()))
            return
        self._set_gamma(g)
        self._refresh_display()

    def _reset_gamma(self):
        self._set_gamma(1.0)
        self.gamma_input.setText("1")
        self._refresh_display()

    # ---------- mode / ROI ----------
    def _on_mode_changed(self, key):
        self._cancel_line_mode(silent=True)
        self.view.set_mode(ZoomPanView.MODE_ROI if key == "roi" else ZoomPanView.MODE_PAN)
        self._update_roi_state()

    def _on_pixel(self, x, y, val):
        if val is None:
            self.pixel_label.setText("x=-, y=-, I=-")
        elif isinstance(val, tuple):
            self.pixel_label.setText(f"x={x}, y={y}, RGB={val}")
        else:
            self.pixel_label.setText(f"x={x}, y={y}, I={val}")

    def _on_roi(self, x, y, w, h):
        self.roi = (x, y, w, h)
        self._update_info()
        self._update_roi_state()

    def _on_roi_cleared(self):
        self.roi = None
        self._update_info()
        self._update_roi_state()

    def _on_roi_frozen(self, frozen):
        self._update_info()
        self._update_roi_state()

    def _clear_roi_key(self):
        """
        Backspace/Delete deletes the ROI - but never while the caret is in a field
        (otherwise editing the gamma value would silently wipe the ROI).
        focusWidget() is scoped to THIS viewer, so it is correct regardless of which
        window is currently active.
        """
        fw = self.focusWidget()
        if isinstance(fw, (QLineEdit, QTextEdit, QComboBox)):
            return
        self._clear_roi()

    def _clear_roi(self):
        self.view.clear_roi()
        self.roi = None
        self._update_info()
        self._update_roi_state()

    def _update_roi_state(self):
        if self.mode_seg.current() != "roi":
            self.roi_state_label.setText("")
            self.roi_state_label.setProperty("locked", False)
        elif self.roi is None:
            self.roi_state_label.setText("drag a box on the image")
            self.roi_state_label.setProperty("locked", False)
        elif self.view.roi_frozen:
            self.roi_state_label.setText("\U0001F512 ROI locked · click = unlock · Backspace = delete")
            self.roi_state_label.setProperty("locked", True)
        else:
            self.roi_state_label.setText("click = lock ROI · Backspace = delete")
            self.roi_state_label.setProperty("locked", False)
        self.roi_state_label.style().unpolish(self.roi_state_label)
        self.roi_state_label.style().polish(self.roi_state_label)

    # ---------- cross-section (armed from the Tool list, not a mode) ----------
    def _arm_line_mode(self):
        if self.raw is None:
            QMessageBox.information(self, "No image", "Load a frame first.")
            return
        if not MATPLOTLIB_AVAILABLE:
            QMessageBox.warning(self, "matplotlib missing", "pip install matplotlib")
            return
        self.view.set_mode(ZoomPanView.MODE_LINE)
        self.hint_chip.setText("▶ Drag ONE line on the image   ·   Esc cancels")
        self.hint_chip.setVisible(True)
        self.view.setFocus()

    def _cancel_line_mode(self, silent=False):
        if self.view.mode == ZoomPanView.MODE_LINE:
            self.view.set_mode(ZoomPanView.MODE_ROI
                               if self.mode_seg.current() == "roi" else ZoomPanView.MODE_PAN)
        self.hint_chip.setVisible(False)

    def _on_line(self, x0, y0, x1, y1):
        self._cancel_line_mode()          # one-shot: always returns to the selected mode
        if self.raw is None:
            return
        gray = raw_to_gray_f32(self.raw)
        win = self._new_plot_win("Cross-section")
        if win is None:
            return
        win.plot_cross_section(gray, x0, y0, x1, y1, self._title())
        win.show(); win.raise_(); win.activateWindow()

    # ---------- tools ----------
    def _title(self):
        return f"{self._current_cam_id()} [{self.current_variant}] · frame {self.frame_slider.value()}"

    def _prune_windows(self):
        """
        Drop analytics windows the user has closed.

        Plot windows are WA_DeleteOnClose, so after a close the Python wrapper
        refers to a destroyed C++ object and ANY call on it (even isVisible())
        raises RuntimeError. Raised inside a Qt slot, PyQt6 answers that with
        qFatal() - the whole app dies with no traceback. Hence the guard.
        """
        alive = []
        for w in self.analytics_windows:
            try:
                if w.isVisible():
                    alive.append(w)
            except RuntimeError:
                pass                      # already destroyed - just forget it
        self.analytics_windows = alive

    def _forget_window(self, win):
        """Called when a plot window is destroyed; compares by identity only."""
        self.analytics_windows = [w for w in self.analytics_windows if w is not win]

    def _new_plot_win(self, title):
        """A FRESH window per tool run - windows are never recycled between tools."""
        if not MATPLOTLIB_AVAILABLE:
            QMessageBox.warning(self, "matplotlib missing", "pip install matplotlib")
            return None
        win = AnalyticsWindow(self, title=f"{title} — {self._title()}")
        self._prune_windows()
        self.analytics_windows.append(win)
        # remove it from the list the moment Qt destroys it (identity compare only,
        # so the dead wrapper is never touched)
        win.destroyed.connect(lambda _obj=None, w=win: self._forget_window(w))
        return win

    def _roi_gray(self):
        gray = raw_to_gray_f32(self.raw)
        if self.roi is not None and self.roi[2] >= 2 and self.roi[3] >= 2:
            x, y, x2, y2 = safe_roi(gray.shape, *self.roi)
            sub = gray[y:y2, x:x2]
            if sub.size:
                return sub, f"{self._title()} · ROI"
        return gray, self._title()

    def run_tool(self):
        if self.raw is None:
            QMessageBox.information(self, "No image", "Load a frame first.")
            return
        tool = self.tool_combo.currentText()

        if tool == self.TOOL_LINE:
            self._arm_line_mode()
            return

        if tool == self.TOOL_HIST:
            gray, title = self._roi_gray()
            win = self._new_plot_win("Histogram")
            if win is None:
                return
            win.plot_histogram(gray, title, is_uint8=(self.raw.dtype == np.uint8))
            win.show(); win.raise_(); win.activateWindow()

        elif tool == self.TOOL_HEAT:
            gray, title = self._roi_gray()
            win = self._new_plot_win("Heat map")
            if win is None:
                return
            win.plot_heatmap(gray, title)
            win.show(); win.raise_(); win.activateWindow()

        elif tool == self.TOOL_ROI:
            gray, title = self._roi_gray()
            s = basic_stats(gray)
            scope = "ROI" if (self.roi is not None) else "Full frame"
            lock = " (locked)" if self.view.roi_frozen else ""
            QMessageBox.information(
                self, "ROI / region stats",
                f"{title}\n\nScope: {scope}{lock}\n"
                f"size: {gray.shape[1]} x {gray.shape[0]} px\n"
                f"min : {s['min']:.2f}\nmax : {s['max']:.2f}\n"
                f"mean: {s['mean']:.2f}\nstd : {s['std']:.2f}")

    # ---------- save ----------
    def save_view(self):
        if self.raw is None:
            QMessageBox.information(self, "No image", "Load a frame first.")
            return
        rgb, _ = to_display_rgb(self.raw, gamma=self._get_gamma(),
                                brightness=self.bright_slider.value())
        default = f"{self._current_cam_id()}_{self.current_variant}_f{self.frame_slider.value()}_view.png"
        path, _f = QFileDialog.getSaveFileName(self, "Save current view", default, "PNG (*.png)")
        if not path:
            return
        if not path.lower().endswith(".png"):
            path += ".png"
        ok = imwrite_unicode(path, rgb)
        if ok:
            QMessageBox.information(self, "Save", f"Saved:\n{path}")
        else:
            QMessageBox.warning(self, "Save failed", f"Could not write:\n{path}")
