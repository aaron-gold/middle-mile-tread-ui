from PyQt6.QtCore import Qt
from PyQt6.QtGui import QFont
from PyQt6.QtWidgets import (
    QComboBox, QDialog, QHBoxLayout, QLabel, QListWidget, QListWidgetItem, QPushButton,
    QVBoxLayout
)


# ============================================================
# FRAME SELECTOR DIALOG  (for accumulation & legend display)
# ============================================================
class FrameSelectorDialog(QDialog):
    """
    Dialog to select which frames to accumulate and display in legend.
    Supports both rising-order accumulation and custom frame selection.
    """
    def __init__(self, available_frames, selected_frames=None, parent=None):
        super().__init__(parent)
        self.available_frames = available_frames or []
        self.selected_frames = selected_frames or []
        self.setWindowTitle("Select Frames for Accumulation & Legend")
        self.setGeometry(100, 100, 600, 450)
        self._init_ui()

    def _init_ui(self):
        layout = QVBoxLayout()
        layout.setContentsMargins(12, 12, 12, 12)
        layout.setSpacing(12)

        # Title
        title = QLabel("Choose frames to display:")
        title_font = QFont()
        title_font.setPointSize(11)
        title_font.setBold(True)
        title.setFont(title_font)
        layout.addWidget(title)

        # Accumulation mode selection
        mode_row = QHBoxLayout()
        mode_row.setSpacing(8)
        mode_row.addWidget(QLabel("Accumulation order:"))
        self.mode_combo = QComboBox()
        self.mode_combo.addItems(["Rising order (frame 1→N)", "Any order (custom)"])
        self.mode_combo.setMinimumWidth(220)
        self.mode_combo.setToolTip(
            "Rising order: frames accumulated in index order (frame_0, frame_1, ...)\n"
            "Any order: accumulate selected frames in any order you choose")
        mode_row.addWidget(self.mode_combo)
        mode_row.addStretch()
        layout.addLayout(mode_row)

        # Frame list with checkboxes
        layout.addWidget(QLabel(f"Available frames ({len(self.available_frames)} total):"))
        self.frame_list = QListWidget()
        self.frame_list.setObjectName("frameList")
        self.frame_list.setSelectionMode(QListWidget.SelectionMode.MultiSelection)
        self.frame_list.setMinimumHeight(250)

        # Sort frames numerically if they're numbered
        sorted_frames = self._sort_frames(self.available_frames)
        for frame in sorted_frames:
            item = QListWidgetItem(frame)
            item.setFlags(item.flags() | Qt.ItemFlag.ItemIsUserCheckable)
            is_selected = frame in self.selected_frames
            state = Qt.CheckState.Checked if is_selected else Qt.CheckState.Unchecked
            item.setCheckState(state)
            self.frame_list.addItem(item)

        layout.addWidget(self.frame_list)

        # Action buttons row 1 - select/deselect
        action_row1 = QHBoxLayout()
        action_row1.setSpacing(8)

        select_all_btn = QPushButton("Select All")
        select_all_btn.setMinimumWidth(100)
        select_all_btn.clicked.connect(self._select_all)
        action_row1.addWidget(select_all_btn)

        deselect_all_btn = QPushButton("Deselect All")
        deselect_all_btn.setMinimumWidth(100)
        deselect_all_btn.clicked.connect(self._deselect_all)
        action_row1.addWidget(deselect_all_btn)

        invert_btn = QPushButton("Invert Selection")
        invert_btn.setMinimumWidth(100)
        invert_btn.clicked.connect(self._invert_selection)
        action_row1.addWidget(invert_btn)

        action_row1.addStretch()
        layout.addLayout(action_row1)

        # Action buttons row 2 - apply/cancel
        button_row = QHBoxLayout()
        button_row.setSpacing(8)
        button_row.addStretch()

        ok_btn = QPushButton("Apply")
        ok_btn.setObjectName("primaryBtn")
        ok_btn.setMinimumWidth(100)
        ok_btn.clicked.connect(self.accept)
        button_row.addWidget(ok_btn)

        cancel_btn = QPushButton("Cancel")
        cancel_btn.setMinimumWidth(100)
        cancel_btn.clicked.connect(self.reject)
        button_row.addWidget(cancel_btn)

        layout.addLayout(button_row)
        self.setLayout(layout)

    @staticmethod
    def _sort_frames(frames):
        """Sort frame names, handling numeric suffixes intelligently."""
        def extract_num(s):
            # Extract the number from "frame_123" or similar
            import re
            match = re.search(r'(\d+)', s)
            return int(match.group(1)) if match else 0
        try:
            return sorted(frames, key=extract_num)
        except Exception:
            return sorted(frames)

    def _select_all(self):
        for i in range(self.frame_list.count()):
            item = self.frame_list.item(i)
            item.setCheckState(Qt.CheckState.Checked)

    def _deselect_all(self):
        for i in range(self.frame_list.count()):
            item = self.frame_list.item(i)
            item.setCheckState(Qt.CheckState.Unchecked)

    def _invert_selection(self):
        for i in range(self.frame_list.count()):
            item = self.frame_list.item(i)
            current = item.checkState()
            new_state = (Qt.CheckState.Unchecked if current == Qt.CheckState.Checked
                        else Qt.CheckState.Checked)
            item.setCheckState(new_state)

    def get_selected_frames(self):
        """Return list of selected frame names."""
        frames = []
        for i in range(self.frame_list.count()):
            item = self.frame_list.item(i)
            if item.checkState() == Qt.CheckState.Checked:
                frames.append(item.text())
        return frames

    def get_accumulation_mode(self):
        """Return 'rising_order' or 'any_order'."""
        mode_text = self.mode_combo.currentText()
        return "rising_order" if "Rising" in mode_text else "any_order"
