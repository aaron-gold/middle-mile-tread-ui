import numpy as np
from PyQt6.QtCore import Qt
from PyQt6.QtWidgets import QDialog, QLabel, QVBoxLayout


from mm_viewer.common import Figure, FigureCanvas, MATPLOTLIB_AVAILABLE, NavigationToolbar
from mm_viewer.theme import C_BLUE, C_ORANGE


# ============================================================
# ANALYTICS  (all computed on RAW gray)
# ============================================================
def basic_stats(gray_f32):
    return {
        "min": float(gray_f32.min()),
        "max": float(gray_f32.max()),
        "mean": float(gray_f32.mean()),
        "std": float(gray_f32.std()),
    }


def safe_roi(shape_hw, x, y, w, h):
    H, W = shape_hw
    x = max(0, min(int(x), W - 1))
    y = max(0, min(int(y), H - 1))
    w = max(1, int(w))
    h = max(1, int(h))
    x2 = min(x + w, W)
    y2 = min(y + h, H)
    return x, y, x2, y2


class AnalyticsWindow(QDialog):
    """Reusable matplotlib window with a save/zoom toolbar."""
    def __init__(self, parent=None, title="Analytics"):
        super().__init__(parent)
        self.setWindowTitle(title)
        self.setModal(False)
        self.setAttribute(Qt.WidgetAttribute.WA_DeleteOnClose, True)
        self.resize(950, 620)
        layout = QVBoxLayout()
        self.ok = MATPLOTLIB_AVAILABLE
        if not MATPLOTLIB_AVAILABLE:
            layout.addWidget(QLabel("matplotlib is not installed.\nRun: pip install matplotlib"))
            self.setLayout(layout)
            return
        self.fig = Figure(figsize=(7, 4), dpi=100)
        self.canvas = FigureCanvas(self.fig)
        self.toolbar = NavigationToolbar(self.canvas, self)
        layout.addWidget(self.toolbar)
        layout.addWidget(self.canvas)
        self.setLayout(layout)

    def plot_histogram(self, gray_f32, title, is_uint8=True):
        if not self.ok:
            return
        self.fig.clear()
        ax = self.fig.add_subplot(111)
        vmax = 255 if is_uint8 else float(max(1.0, gray_f32.max()))
        bins = 256
        h, edges = np.histogram(gray_f32, bins=bins, range=(0, vmax))
        ax.plot(edges[:-1], h, linewidth=1.5, color=C_ORANGE)
        ax.fill_between(edges[:-1], h, alpha=0.25, color=C_ORANGE)
        ax.set_title(f"Histogram (raw intensity) | {title}")
        ax.set_xlabel(f"Intensity (0-{int(vmax)})")
        ax.set_ylabel("Pixel count")
        ax.grid(True, alpha=0.3)
        self.canvas.draw()

    def plot_cross_section(self, gray_f32, x0, y0, x1, y1, title):
        if not self.ok:
            return
        self.fig.clear()
        ax = self.fig.add_subplot(111)
        n = max(2, int(np.hypot(x1 - x0, y1 - y0)))
        xs = np.clip(np.round(np.linspace(x0, x1, n)).astype(int), 0, gray_f32.shape[1] - 1)
        ys = np.clip(np.round(np.linspace(y0, y1, n)).astype(int), 0, gray_f32.shape[0] - 1)
        vals = gray_f32[ys, xs]
        ax.plot(np.arange(n), vals, linewidth=1.6, color=C_BLUE)
        ax.set_title(f"Cross-section intensity | {title}\n({x0},{y0}) -> ({x1},{y1})")
        ax.set_xlabel("Distance along line (px)")
        ax.set_ylabel("Raw intensity")
        ax.grid(True, alpha=0.3)
        self.canvas.draw()

    def plot_heatmap(self, gray_f32, title):
        if not self.ok:
            return
        self.fig.clear()
        ax = self.fig.add_subplot(111)
        im = ax.imshow(gray_f32, cmap="jet", aspect="auto")
        self.fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04, label="Raw intensity")
        ax.set_title(f"Intensity heat map (raw) | {title}")
        ax.set_xlabel("X (px)")
        ax.set_ylabel("Y (px)")
        self.canvas.draw()
