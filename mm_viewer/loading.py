class BusyOverlay(QWidget):
    """
    Full-window scrim with an animated arc spinner and a phase caption.
    Loading a scan takes a few seconds (tab construction, first-frame decode,
    groove plot); without this the window just sits there and looks hung.
    Painted entirely in paintEvent - no image assets, no stylesheet background.
    """

    def __init__(self, parent, subtitle="Loading scan — please wait"):
        super().__init__(parent)
        self.setObjectName("busyOverlay")
        self.setCursor(Qt.CursorShape.BusyCursor)
        self._angle = 0
        self._phase = ""
        self._subtitle = subtitle
        self._timer = QTimer(self)
        self._timer.setInterval(16)                     # ~60 fps
        self._timer.timeout.connect(self._tick)
        # optional Cancel, only for work that can actually be stopped (archive
        # extraction). Hidden otherwise, so a scan load still looks as it always did.
        self._cancel_cb = None
        self.cancel_btn = QPushButton("Cancel", self)
        self.cancel_btn.setCursor(Qt.CursorShape.PointingHandCursor)
        self.cancel_btn.clicked.connect(self._on_cancel)
        self.cancel_btn.hide()
        self.hide()

    def set_cancel(self, callback):
        """Show a Cancel button that calls `callback`; None hides it."""
        self._cancel_cb = callback
        self.cancel_btn.setEnabled(True)
        self.cancel_btn.setVisible(callback is not None)
        self._place_cancel()

    def _on_cancel(self):
        cb = self._cancel_cb
        self.cancel_btn.setEnabled(False)
        if cb is not None:
            try:
                cb()
            except Exception:
                traceback.print_exc()

    def _place_cancel(self):
        b = self.cancel_btn
        b.adjustSize()
        bw = max(b.sizeHint().width(), 120)
        b.setGeometry(int(self.width() / 2 - bw / 2), int(self.height() / 2 + 84 + 12),
                      bw, b.sizeHint().height())

    def resizeEvent(self, ev):
        super().resizeEvent(ev)
        self._place_cancel()

    def _tick(self):
        self._angle = (self._angle + 6) % 360
        self.update()

    def start(self, phase=""):
        self._phase = phase or ""
        p = self.parentWidget()
        if p is not None:
            self.setGeometry(p.rect())
        self.raise_()
        self.show()
        if not self._timer.isActive():
            self._timer.start()
        self.repaint()

    def set_phase(self, text, force=True):
        """force=True repaints synchronously - needed when the caller then BLOCKS the
        GUI thread (tab building). A caption fed from a worker thread should pass
        force=False so Qt coalesces the repaints instead of doing one per message."""
        self._phase = text or ""
        if force:
            self.repaint()
        else:
            self.update()

    def stop(self):
        self._timer.stop()
        self.set_cancel(None)
        self.hide()

    def paintEvent(self, _ev):
        p = QPainter(self)
        p.setRenderHint(QPainter.RenderHint.Antialiasing, True)
        p.fillRect(self.rect(), QColor(217, 230, 245, 215))          # C_BG, translucent

        w, h = 460.0, 168.0
        cx, cy = self.width() / 2.0, self.height() / 2.0
        card_r = QRectF(cx - w / 2, cy - h / 2, w, h)
        p.setPen(QPen(QColor(C_BORDER), 1))
        p.setBrush(QBrush(QColor(C_SURFACE)))
        p.drawRoundedRect(card_r, 12, 12)

        d = 46.0
        spin_r = QRectF(cx - d / 2, card_r.top() + 28, d, d)
        p.setBrush(Qt.BrushStyle.NoBrush)
        p.setPen(QPen(QColor(C_BORDER), 4))
        p.drawArc(spin_r, 0, 360 * 16)                               # track
        arc_pen = QPen(QColor(C_ORANGE), 4)
        arc_pen.setCapStyle(Qt.PenCapStyle.RoundCap)
        p.setPen(arc_pen)
        p.drawArc(spin_r, int(-self._angle * 16), int(-105 * 16))    # sweep

        f = p.font()
        f.setPixelSize(FS_HEAD)
        f.setBold(True)
        p.setFont(f)
        p.setPen(QColor(C_NAVY))
        p.drawText(QRectF(card_r.left(), spin_r.bottom() + 16, w, 26),
                   int(Qt.AlignmentFlag.AlignHCenter | Qt.AlignmentFlag.AlignTop),
                   self._phase or "Loading…")

        f.setPixelSize(FS_SMALL)
        f.setBold(False)
        p.setFont(f)
        p.setPen(QColor(C_TEXT_DIM))
        p.drawText(QRectF(card_r.left(), spin_r.bottom() + 44, w, 24),
                   int(Qt.AlignmentFlag.AlignHCenter | Qt.AlignmentFlag.AlignTop),
                   self._subtitle)
        p.end()


class ScanPrescanWorker(QThread):
    """
    Filesystem-only pass, off the GUI thread so the spinner keeps animating:
    walks the scan folder, verifies the scan ID, and decodes each camera's first
    frame. Touches no Qt widgets and no shared state - the model and the decoded
    frames are handed back and applied on the GUI thread.
    """
    phase = pyqtSignal(str)
    scanned = pyqtSignal(object, object, object)        # model, conflicts, {path: array}
    failed = pyqtSignal(str)

    def __init__(self, folder, parent=None):
        super().__init__(parent)
        self.folder = folder

    def run(self):
        try:
            self.phase.emit("Reading camera folders…")
            model = InputModel()
            model.load_scan(self.folder)

            self.phase.emit("Verifying scan ID…")
            conflicts = model.scan_id_conflicts()

            # Axle classification, on this thread so the spinner keeps moving. A scan
            # that cannot be classified is NOT a load failure: the error is carried
            # back, shown as a banner, and the viewer falls back to per-camera tabs.
            # An input that carries nothing to split by is not run through the
            # classifier at all - see InputModel._resolve_split_availability. The
            # reason travels on the model and the banner states it; what would
            # otherwise happen here is a guaranteed ClassificationError and a red
            # banner over a folder the user deliberately opened on its own.
            if not conflicts and AXLE_AVAILABLE and not model.no_split_reason:
                # A scan that ARRIVED classified is read, not re-classified. Running
                # the state machine over it would be pointless (its trigger log is
                # usually not in the tree at all) and worse than pointless if it
                # disagreed with the folders the user is looking at: the split on disk
                # is the record.
                pre = model.classified_root
                man = model.manifest_path
                self.phase.emit(
                    "Reading the existing axle split…" if pre
                    else "Reading the scan's classification manifest…" if man
                    else "Classifying frames per axle…")
                try:
                    if pre:
                        model.axle_index = axle_mod.index_from_tree(
                            pre, model.scan_folder)
                    elif man:
                        # HIS answer, from the run that produced the scan. A manifest
                        # that cannot be read is not a dead end: the scan still has
                        # its trigger log, so the state machine is run instead and
                        # the reason is carried on the index as a warning. Falling
                        # straight to an error banner here would refuse to show a
                        # scan the viewer can perfectly well classify.
                        try:
                            model.axle_index = axle_mod.index_from_manifest(
                                man, model.scan_folder)
                        except axle_mod.ClassificationError as m_exc:
                            self.phase.emit("Classifying frames per axle…")
                            model.axle_index = axle_mod.classify_scan(
                                model.scan_folder)
                            model.axle_index.warnings.insert(
                                0, "%s could not be used (%s) - this split was "
                                   "computed here from the trigger log instead."
                                   % (axle_mod.MANIFEST_NAME, m_exc.message))
                    else:
                        model.axle_index = axle_mod.classify_scan(model.scan_folder)
                except axle_mod.ClassificationError as exc:
                    model.axle_error = exc
                except Exception as exc:
                    traceback.print_exc()
                    model.axle_error = axle_mod.ClassificationError(
                        "Axle classification failed unexpectedly.",
                        detail=f"{type(exc).__name__}: {exc}",
                        hint="See the console for the full traceback.")

            decoded = {}
            if not conflicts and getattr(model, "diagram_png", None):
                self.phase.emit("Reading the pulse diagram…")
                try:
                    preload_diagram_qimage(model.diagram_png)     # v1.2, see note
                except Exception:
                    traceback.print_exc()        # the GUI thread just loads it itself
            if not conflicts:
                self.phase.emit("Decoding first frames…")
                for col in (COL_ATLAS, COL_HELIOS, COL_TREAD, COL_OCR):
                    for variant in ("raw", "compressed"):
                        for _cam, entry in model.collections[col][variant].items():
                            files = entry["files"]
                            if not files:
                                continue
                            arr = load_image_raw(files[0])
                            if arr is not None:
                                decoded[files[0]] = arr
            self.scanned.emit(model, conflicts, decoded)
        except Exception:
            self.failed.emit(traceback.format_exc())
