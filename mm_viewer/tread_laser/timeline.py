# ============================================================
# INPUT MODEL  (scan folders -> classified collections)
# ============================================================
# ============================================================
# TREAD + LASER  (v1.1 - tread frames played with the nearest-in-time laser frame)
# ============================================================
#
# WHAT "SAME TIME" MEANS HERE. The tread camera JSON (Timestamp_usec), the LMI
# grooves CSV (Host_Timestamp_usec) and the trigger log run on THREE different
# clocks - on 2026-09-16T12-09-18 they read 83.5e9, 97.0e9 and 7.06e9 us for the
# same second. Comparing them raw would pair frames tens of seconds apart. The one
# clock both media share is the classifier's calculated_host_timestamp_usec: every
# tread frame and every laser profile carries one in scan_classification_manifest.csv
# (AxleIndex.host_ts), mapped into the controller host clock. That is the ONLY
# timestamp used for pairing, and the delta shown is  laser - tread  on that clock.
# A frame without one is shown, never paired, and says why.
#
# THE PAIRING WINDOW is display-only and traces to no requirement. Its default is
# data-derived: half the median interval between this wheel's tread frames, i.e. a
# laser frame is "concurrent" with the tread frame whose exposure slot it falls in.
# It is editable, and a step outside it still shows the nearest laser frame - just
# flagged, with the delta, so nothing is hidden.
TL_STEP_TREAD = "tread"
TL_STEP_LASER = "laser"
TL_STEP_BOTH = "both"
TL_STEP_MODES = ((TL_STEP_TREAD, "Tread frames"), (TL_STEP_LASER, "Laser frames"),
                 (TL_STEP_BOTH, "Both · time order"))
TL_SPEEDS = (("2 fps", 500), ("5 fps", 200), ("10 fps", 100), ("20 fps", 50),
             ("Real time ×0.25", -0.25), ("Real time ×1", -1.0))
TL_SPEED_DEFAULT = 1                      # 5 fps
TL_WINDOW_FALLBACK_MS = 10.0              # only when no tread interval can be measured
TL_C_OK = "#126b45"
TL_C_OUT = "#8a5310"
TL_C_NONE = "#9b2c2c"
_TREAD_DIR_RE = re.compile(r"^tr_(front|rear)_(l|r)(?:_|$)", re.IGNORECASE)


def tread_pos(path):
    """'…/tr_front_l_01/frame_0003.tif' -> 'FRONT LEFT' (the LMI unit it pairs with)."""
    name = os.path.basename(os.path.dirname(os.path.abspath(path))).lower()
    if name.startswith("compressed_"):
        name = name[len("compressed_"):]
    m = _TREAD_DIR_RE.match(name)
    if not m:
        return None
    return "%s %s" % (m.group(1).upper(), "LEFT" if m.group(2) == "l" else "RIGHT")


def _index_pairs(index):
    """
    v1.5: every (path, bucket) membership of an axle index - a frame shared by two
    axles appears twice. Falls back to assign.items() for an index without pairs()
    (an older classifier module, or a test double), which is the v1.4 behaviour.
    """
    fn = getattr(index, "pairs", None)
    return fn() if callable(fn) else index.assign.items()


def _buckets_of(index, path):
    """v1.5: every bucket a file is on, primary first; [] when it is on none."""
    fn = getattr(index, "buckets_of", None)
    if callable(fn) and path in index.assign:
        return fn(path)
    b = index.assign.get(path)
    return [b] if b is not None else []


def laser_frames_by_pos(index):
    """
    {pos: [(ts_us, name, abs_path, bucket, side), ...] sorted by time} for every
    *_profile.csv the index carries a host timestamp for. Whole scan, every bucket:
    the nearest laser frame to a tread frame is the nearest one, whichever axle
    window the classifier put it in (its bucket is shown beside it).
    """
    out = {p: [] for p in POS_ORDER}
    if index is None:
        return out
    for p, ts in index.host_ts.items():
        if not p.lower().endswith("_profile.csv") or ts is None:
            continue
        pos = wheel_pos(p)
        if pos not in out:
            continue
        meta = index.meta.get(p, {}) or {}
        # v1.5: one row per axle the frame is on, so each wheel's timeline (which
        # filters on the bucket) still finds a frame shared with the next axle
        for b in (_buckets_of(index, p) or [None]):
            out[pos].append((int(ts), os.path.basename(p), p, b, meta.get("side")))
    for pos in out:
        out[pos].sort(key=lambda r: (r[0], r[1]))
    return out


def _nearest(ts_sorted, t):
    """Index into ts_sorted (ascending ints) nearest to t, or None when empty."""
    n = len(ts_sorted)
    if not n or t is None:
        return None
    import bisect
    i = bisect.bisect_left(ts_sorted, t)
    if i <= 0:
        return 0
    if i >= n:
        return n - 1
    return i if (ts_sorted[i] - t) < (t - ts_sorted[i - 1]) else i - 1


def median_interval_us(ts_groups):
    """Median positive step inside each group of timestamps, pooled; None if none."""
    steps = []
    for g in ts_groups:
        s = sorted(t for t in g if t is not None)
        steps.extend(b - a for a, b in zip(s, s[1:]) if b > a)
    if not steps:
        return None
    steps.sort()
    n = len(steps)
    return float(steps[n // 2] if n % 2 else (steps[n // 2 - 1] + steps[n // 2]) / 2.0)


def default_pair_window_ms(tread_files, host_ts):
    """Half the median tread-frame interval of these frames, in ms (see block note)."""
    groups = {}
    for f in tread_files:
        groups.setdefault(tread_pos(f), []).append(host_ts.get(os.path.abspath(f)))
    med = median_interval_us(groups.values())
    if med is None:
        return TL_WINDOW_FALLBACK_MS, False
    return med / 2000.0, True


def build_timeline(tread_files, host_ts, laser_by_pos, mode, bucket=None, side=None):
    """
    The steps the combined viewer walks. Each step is a dict:
        kind       "tread" / "laser"  - which module's frame drives this step
        t_i        index into tread_files, or None
        t_ts       tread host time (us) or None
        laser      (ts, name, path, bucket, side, pos) or None
        l_ts       laser host time (us) or None
        dt_us      l_ts - t_ts, or None when either side has no time
        pos        the LMI unit / tread camera position of the pair
        why        reason text when there is no partner
    Pure data - no Qt - so the smoke suite can pin it.
    """
    lts = {pos: [r[0] for r in rows] for pos, rows in laser_by_pos.items()}
    steps = []

    tread = []                                   # (i, path, ts, pos)
    for i, f in enumerate(tread_files):
        tread.append((i, f, host_ts.get(os.path.abspath(f)), tread_pos(f)))

    def laser_row(pos, k):
        r = laser_by_pos[pos][k]
        return (r[0], r[1], r[2], r[3], r[4], pos)

    if mode in (TL_STEP_TREAD, TL_STEP_BOTH):
        for i, f, ts, pos in tread:
            st = {"kind": "tread", "t_i": i, "t_ts": ts, "laser": None, "l_ts": None,
                  "dt_us": None, "pos": pos, "why": ""}
            if ts is None:
                st["why"] = "this tread frame has no host timestamp in the manifest"
            elif pos is None or not lts.get(pos):
                st["why"] = ("no laser frame with a host timestamp for %s"
                             % (pos or "this camera"))
            else:
                k = _nearest(lts[pos], ts)
                st["laser"] = laser_row(pos, k)
                st["l_ts"] = st["laser"][0]
                st["dt_us"] = st["l_ts"] - ts
            steps.append(st)

    if mode in (TL_STEP_LASER, TL_STEP_BOTH):
        by_pos = {}
        for i, f, ts, pos in tread:
            if ts is not None:
                by_pos.setdefault(pos, []).append((ts, i))
        for v in by_pos.values():
            v.sort()
        for pos in POS_ORDER:
            for k, r in enumerate(laser_by_pos.get(pos, [])):
                if bucket is not None and r[3] != bucket:
                    continue
                if side is not None and r[4] != side:
                    continue
                # SAME position only: a rear laser frame is never "paired" with a
                # front tread frame, however close in time they happen to be
                cand = by_pos.get(pos)
                st = {"kind": "laser", "t_i": None, "t_ts": None,
                      "laser": laser_row(pos, k), "l_ts": r[0], "dt_us": None,
                      "pos": pos, "why": ""}
                if cand:
                    j = _nearest([c[0] for c in cand], r[0])
                    st["t_ts"], st["t_i"] = cand[j]
                    st["dt_us"] = r[0] - st["t_ts"]
                else:
                    st["why"] = ("no %s tread frame of this wheel has a host "
                                 "timestamp" % pos.lower())
                steps.append(st)

    if mode == TL_STEP_BOTH:
        def _own(s):
            t = s["t_ts"] if s["kind"] == "tread" else s["l_ts"]
            return (t is None, t if t is not None else 0, 0 if s["kind"] == "tread"
                    else 1)
        steps.sort(key=_own)
    elif mode == TL_STEP_LASER:
        steps.sort(key=lambda s: (s["l_ts"],))
    return steps


# v1.3: the combined tab walks ONE timeline - every tread and laser frame of the
# opened wheel in host-time order - with a fixed default tolerance the user edits.
TL_WINDOW_DEFAULT_MS = 10.0
TL_PAIRED_LABEL = "Show only frames paired within tolerance"


def wheel_laser_by_pos(laser_by_pos, bucket, side):
    """
    v1.3: only the laser frames the classifier put on THIS wheel (same axle bucket,
    same side). Trash is never a wheel, so it never reaches the combined timeline -
    neither as a step nor as the "nearest partner" of a tread frame.
    """
    out = {}
    for pos, rows in (laser_by_pos or {}).items():
        out[pos] = [r for r in rows
                    if r[3] == bucket and (side is None or r[4] == side)]
    return out


def wheel_timeline(tread_files, host_ts, laser_by_pos, bucket, side):
    """
    v1.3: the combined tab's steps. This wheel's tread frames + this wheel's laser
    frames, in host-time order; each step carries its nearest partner from the SAME
    wheel and position. A tread frame and a laser frame that are each other's nearest
    partner would otherwise be two identical screens in a row - that pair is kept
    ONCE (as the laser-driven step). No frame disappears: the tread frame is still on
    screen, as that step's partner.
    """
    if bucket is None or bucket == axle_mod.TRASH:
        return []
    lb = wheel_laser_by_pos(laser_by_pos, bucket, side)
    steps = build_timeline(tread_files, host_ts, lb, TL_STEP_BOTH,
                           bucket=bucket, side=side)
    laser_pairs = {(s["t_i"], s["laser"][2]) for s in steps
                   if s["kind"] == "laser" and s["t_i"] is not None}
    out = []
    for s in steps:
        if (s["kind"] == "tread" and s["laser"] is not None
                and (s["t_i"], s["laser"][2]) in laser_pairs):
            continue
        if s["kind"] == "tread" and s["laser"] is None and s["t_ts"] is not None:
            s["why"] = ("the %s laser unit has no frame on this wheel (%s)"
                        % ((s["pos"] or "matching").lower(), bucket))
        elif s["kind"] == "laser" and s["t_i"] is None:
            s["why"] = ("this wheel has no %s tread frame with a host time"
                        % (s["pos"] or "").lower())
        out.append(s)
    return out


def is_paired(step, window_ms):
    return step["dt_us"] is not None and abs(step["dt_us"]) <= window_ms * 1000.0


def fmt_dt_ms(dt_us):
    return "—" if dt_us is None else "%+.3f ms" % (dt_us / 1000.0)
