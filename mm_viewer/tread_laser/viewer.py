    def _fold_tread_controls(self):
        """Put every tread control behind a collapsed toggle; the image gets the pane."""
        t = self.tread
        self._tread_cards = {"info": t.head_card, "adjust": t.frame_card,
                             "tools": t.tool_card, "meta": t.meta_card}
        # the info card is taken out of the header slot and put with the others, so
        # every section opens in the same band under the image
        lay = t.layout()
        lay.removeWidget(t.head_card)
        body_v = t.ctrl_scroll.widget().layout()
        body_v.insertWidget(0, t.head_card)
        self._tread_btns = {}
        row = []
        for key, label, tip in self.TL_TREAD_SECTIONS:
            b = GrooveDepthPanel._collapse_btn("▸  " + label, tip)
            b.toggled.connect(lambda on, k=key: self._toggle_tread_section(k, on))
            self._tread_btns[key] = b
            row.append(b)
        bar = QWidget()
        bl = QHBoxLayout(bar)
        bl.setContentsMargins(0, 0, 0, 0)
        bl.setSpacing(4)
        for b in row:
            bl.addWidget(b)
        bl.addStretch(1)
        # the live pixel readout stays on screen - it is what the cursor is reading.
        # A mirror of the viewer's own label (which stays in the folded info card),
        # updated right after the viewer writes it.
        self.tread_px = QLabel(t.pixel_label.text())
        self.tread_px.setObjectName("pixelLabel")
        t.view.pixelMoved.connect(
            lambda *_: self.tread_px.setText(self.tread.pixel_label.text()))
        bl.addWidget(self.tread_px)
        self.tread_bar = bar
        lay.insertWidget(0, bar)
        for c in self._tread_cards.values():
            c.setVisible(False)
        t.ctrl_scroll.setVisible(False)
        t.ctrl_scroll.setMaximumHeight(260)

    def _toggle_tread_section(self, key, on):
        _k, label, _tip = next(s for s in self.TL_TREAD_SECTIONS if s[0] == key)
        self._tread_btns[key].setText(("▾  " if on else "▸  ") + label)
        self._tread_cards[key].setVisible(on)
        self.tread.ctrl_scroll.setVisible(
            any(b.isChecked() for b in self._tread_btns.values()))
        self.tread.ctrl_scroll.updateGeometry()

