# ============================================================
# SCAN ARCHIVES  (.tar -> scan folder, extracted NEXT TO the archive)
# ============================================================
#
# A scan pulled off the FG as one archive (e.g. 2026-09-16T12-09-18.000Z_<uuid>.tar,
# ~8 GB, one top-level folder named for the scan) is extracted into the folder the
# .tar sits in and then loaded exactly like a scan folder picked by hand.
#
# How it is written, and why:
#   * STREAMED, one pass ('r|*'): an 8 GB archive is never listed first, and the
#     progress is the byte position in the archive file itself, so it is right for
#     .tar and for .tar.gz alike.
#   * Into a HIDDEN SIBLING first (.<name>.extracting-<pid>), renamed into place only
#     after the last byte. A cancelled / failed / crashed run can therefore never
#     leave a half-written folder under the real scan name that a later load would
#     take for a complete scan. The temporary folder is this run's own output and is
#     removed on cancel or failure - nothing that existed before is ever touched.
#   * NEVER OVERWRITES. If the scan folder already exists the user chooses: open the
#     existing folder, extract to a new "<name>_extracted_N" folder, or cancel.
#   * SAFE MEMBERS ONLY: absolute paths, drive letters and '..' are refused (a tar is
#     data - a crafted one must not write outside the destination); links, devices
#     and FIFOs are skipped and counted; characters Windows forbids in a file name
#     are replaced by '_' and counted. Long paths go through lp() like every read.
SCAN_ARCHIVE_EXTS = (".tar", ".tar.gz", ".tgz", ".tar.bz2", ".tbz2", ".tar.xz", ".txz")
ARCHIVE_CHUNK = 4 * 1024 * 1024
_WIN_BAD_CHARS = re.compile(r'[<>:"|?*\x00-\x1f]')


class ArchiveError(Exception):
    """A scan archive that cannot be extracted - message is user-readable."""


class _KeepTemp(Exception):
    """Internal: the extraction is complete but could not be renamed - keep it."""


# names Windows reserves whatever the extension (CON, NUL, COM1.txt, ...)
_WIN_RESERVED = ({"con", "prn", "aux", "nul"} | {"com%d" % i for i in range(1, 10)}
                 | {"lpt%d" % i for i in range(1, 10)})


def is_scan_archive(path):
    low = (path or "").lower()
    return any(low.endswith(e) for e in SCAN_ARCHIVE_EXTS) and lp_isfile(path)


def archive_stem(path):
    """'…/2026-09-16T12-09-18.000Z_<uuid>.tar' -> '2026-09-16T12-09-18.000Z_<uuid>'."""
    name = os.path.basename(path)
    low = name.lower()
    for e in sorted(SCAN_ARCHIVE_EXTS, key=len, reverse=True):
        if low.endswith(e):
            return name[:-len(e)]
    return os.path.splitext(name)[0]


def archives_in(folder):
    """Scan archives sitting directly in `folder` (for the 'folder holds only .tar' hint)."""
    try:
        return sorted(os.path.join(folder, n) for n in lp_listdir(folder)
                      if is_scan_archive(os.path.join(folder, n)))
    except Exception:
        return []


def _safe_member_parts(name):
    """
    Tar member name -> (list of path components, renamed_flag), or (None, False) when
    the member must not be written at all (absolute, drive-qualified, '..' escape).
    """
    n = (name or "").replace("\\", "/")
    if n.startswith("/") or re.match(r"^[A-Za-z]:", n):
        return None, False
    parts = [p for p in n.split("/") if p not in ("", ".")]
    if not parts or any(p == ".." for p in parts):
        return None, False
    renamed = False
    clean = []
    for p in parts:
        q = _WIN_BAD_CHARS.sub("_", p).rstrip(" .") or "_"
        if q.split(".", 1)[0].lower() in _WIN_RESERVED:
            q = "_" + q
        renamed = renamed or (q != p)
        clean.append(q)
    return clean, renamed


def peek_archive_root(path, max_members=64):
    """
    The single top-level folder the archive's FIRST members sit in, or None.

    Only the first few headers are read (streaming, no listing of an 8 GB file). It
    is a prediction used to check for an existing folder BEFORE extracting; the real
    layout is re-checked after extraction, so a wrong guess cannot misplace data.
    """
    import tarfile
    tops = set()
    # a plain .tar is opened SEEKABLE, so reading the first headers skips over the
    # data instead of streaming through hundreds of MB of it on the GUI thread
    mode = "r:" if path.lower().endswith(".tar") else "r|*"
    try:
        with lp_open(path, "rb") as fh:
            with tarfile.open(fileobj=fh, mode=mode) as tf:
                for i, m in enumerate(tf):
                    parts, _r = _safe_member_parts(m.name)
                    if parts:
                        tops.add(parts[0] if (len(parts) > 1 or m.isdir()) else None)
                    if i + 1 >= max_members:
                        break
    except Exception as exc:
        raise ArchiveError("The archive could not be read (%s: %s)."
                           % (type(exc).__name__, exc))
    if len(tops) == 1:
        (t,) = tops
        return t
    return None


def free_extract_name(parent, name):
    """`name`, or the first '<name>_extracted_N' that does not exist in `parent`."""
    cand = os.path.join(parent, name)
    if not lp_exists(cand):
        return cand
    for k in range(2, 1000):
        cand = os.path.join(parent, "%s_extracted_%d" % (name, k))
        if not lp_exists(cand):
            return cand
    raise ArchiveError("No free folder name next to %s." % name)


def extract_scan_archive(path, final_dir, progress=None, cancelled=None):
    """
    Extract `path` so that its scan folder ends up at `final_dir` (which must NOT
    exist). Returns (final_dir, stats). Raises ArchiveError; on any failure or cancel
    the temporary folder is removed and `final_dir` is not created.

    Layout rule: an archive whose members all sit under ONE top folder (the normal
    FG export) has that folder's CONTENT placed at final_dir; an archive with loose
    top-level members is placed at final_dir as-is.
    """
    import tarfile
    import shutil
    import time
    parent = os.path.dirname(os.path.abspath(final_dir))
    if lp_exists(final_dir):
        raise ArchiveError("%s already exists - it is never overwritten." % final_dir)
    total = max(1, lp_stat(path).st_size)
    tmp = os.path.join(parent, ".%s.extracting-%d"
                       % (os.path.basename(final_dir), os.getpid()))
    if lp_exists(tmp):
        shutil.rmtree(lp(tmp), ignore_errors=True)   # this process's own leftover
    stats = {"files": 0, "dirs": 0, "bytes": 0, "skipped": 0, "unsafe": 0,
             "renamed": 0}
    last = [0.0]

    def _tick(fh, name, force=False):
        now = time.monotonic()
        if progress is not None and (force or now - last[0] > 0.15):
            last[0] = now
            try:
                pos = fh.tell()
            except Exception:
                pos = 0
            progress(min(pos, total), total, stats["files"], name)

    def _cancel_check():
        if cancelled is not None and cancelled():
            raise ArchiveError("Extraction cancelled.")

    try:
        os.makedirs(lp(tmp), exist_ok=False)
        with lp_open(path, "rb") as fh:
            try:
                tf = tarfile.open(fileobj=fh, mode="r|*")
            except Exception as exc:
                raise ArchiveError("Not a readable tar archive (%s: %s)."
                                   % (type(exc).__name__, exc))
            with tf:
                for m in tf:
                    _cancel_check()
                    parts, renamed = _safe_member_parts(m.name)
                    if parts is None:
                        stats["unsafe"] += 1
                        continue
                    stats["renamed"] += int(renamed)
                    dest = os.path.join(tmp, *parts)
                    if m.isdir():
                        os.makedirs(lp(dest), exist_ok=True)
                        stats["dirs"] += 1
                        continue
                    if not m.isreg():
                        stats["skipped"] += 1      # link / device / fifo: not scan data
                        continue
                    os.makedirs(lp(os.path.dirname(dest)), exist_ok=True)
                    src = tf.extractfile(m)
                    if src is None:
                        stats["skipped"] += 1
                        continue
                    with src, open(lp(dest), "wb") as out:
                        while True:
                            buf = src.read(ARCHIVE_CHUNK)
                            if not buf:
                                break
                            out.write(buf)
                            stats["bytes"] += len(buf)
                            _cancel_check()
                            _tick(fh, m.name)
                    try:
                        os.utime(lp(dest), (m.mtime, m.mtime))
                    except Exception:
                        pass
                    stats["files"] += 1
                    _tick(fh, m.name)
            _tick(fh, "", force=True)
        if stats["files"] == 0:
            raise ArchiveError("The archive holds no regular file.")
        # where the scan folder really is, now that every member has been seen
        entries = lp_listdir(tmp)
        src_root = tmp
        if len(entries) == 1 and lp_isdir(os.path.join(tmp, entries[0])):
            src_root = os.path.join(tmp, entries[0])
        else:
            # more than one top-level entry: placed as-is. Said out loud, because a
            # scan folder may then sit one level down.
            stats["layout_note"] = ("the archive has %d top-level entries, so they "
                                    "were placed as-is inside %s"
                                    % (len(entries), os.path.basename(final_dir)))
        if lp_exists(final_dir):                 # appeared while we were extracting
            raise ArchiveError("%s appeared during extraction - not overwritten."
                               % final_dir)
        # Antivirus / the search indexer routinely hold handles on files written a
        # moment ago, and a directory rename then fails with WinError 5. Retried with
        # a back-off; if it still fails the COMPLETE extraction is kept (never
        # deleted) and its location is reported.
        for attempt in range(12):
            try:
                os.rename(lp(src_root), lp(final_dir))
                break
            except PermissionError:
                if attempt == 11:
                    raise _KeepTemp(src_root)
                time.sleep(0.5)
        if src_root != tmp:
            shutil.rmtree(lp(tmp), ignore_errors=True)
        return final_dir, stats
    except _KeepTemp as kt:
        raise ArchiveError("The scan was extracted completely but the folder could "
                           "not be renamed into place (a file is held open, usually "
                           "by antivirus). Nothing was deleted - the complete "
                           "extraction is in:\n%s\nRename it to %s, or try again."
                           % (kt.args[0], os.path.basename(final_dir)))
    except ArchiveError:
        shutil.rmtree(lp(tmp), ignore_errors=True)
        raise
    except OSError as exc:
        shutil.rmtree(lp(tmp), ignore_errors=True)
        hint = (" The disk is full." if getattr(exc, "errno", None) == 28 else "")
        raise ArchiveError("Writing the extracted scan failed (%s: %s).%s"
                           % (type(exc).__name__, exc, hint))
    except Exception as exc:
        shutil.rmtree(lp(tmp), ignore_errors=True)
        raise ArchiveError("Extraction failed (%s: %s)." % (type(exc).__name__, exc))


