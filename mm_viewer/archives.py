class ScanArchiveWorker(QThread):
    """Runs extract_scan_archive off the GUI thread. Touches no widgets."""
    progress = pyqtSignal(object, object, int, str)    # pos, total, files, member
    done = pyqtSignal(str, object)                      # final folder, stats
    failed = pyqtSignal(str)

    def __init__(self, archive, final_dir, parent=None):
        super().__init__(parent)
        self.archive = archive
        self.final_dir = final_dir
        self._cancel = False

    def cancel(self):
        self._cancel = True

    def run(self):
        try:
            final, stats = extract_scan_archive(
                self.archive, self.final_dir,
                progress=lambda p, t, n, nm: self.progress.emit(p, t, n, nm),
                cancelled=lambda: self._cancel)
            self.done.emit(final, stats)
        except ArchiveError as exc:
            self.failed.emit(str(exc))
        except Exception:
            self.failed.emit(traceback.format_exc())
