"""Input model.

Part of the mm_viewer package - moved verbatim from MiddleMile_GUI v1.8,
lines 12808-13114, 13115-13192. Imports generated by the split (2026-10-18)."""


import json
import os
import traceback
from collections import OrderedDict


from mm_viewer.common import (
    AXLE_AVAILABLE, axle_mod, lp_isdir, lp_isfile, lp_listdir, lp_open, lp_walk
)
from mm_viewer.config import (
    classify_folder, COL_ATLAS, COL_DIAG, COL_HELIOS, COL_OCR, COL_TREAD, COL_WA
)
from mm_viewer.scan_files import list_images, order_key, parse_scan_id, sidecar_path
from mm_viewer.wheel_assembler.triggers import WA_CSV_NAME
from mm_viewer.tread_laser.timeline import _index_pairs
from mm_viewer.diagnostics.loader import diagnostics_present, find_stitched_images


class InputModel:
    def __init__(self):
        self.clear()

    def clear(self):
        # collection_id -> { variant -> OrderedDict{ camera_id -> {'folder':.., 'files':[..]} } }
        self.collections = {
            COL_ATLAS: {"raw": OrderedDict(), "compressed": OrderedDict()},
            COL_HELIOS: {"raw": OrderedDict(), "compressed": OrderedDict()},
            COL_TREAD: {"raw": OrderedDict(), "compressed": OrderedDict()},
            COL_OCR: {"raw": OrderedDict(), "compressed": OrderedDict()},
        }
        self.groove_folder = None
        self.wa_folder = None
        # Laser-groove ALGO diagnostics tree (v1.11). The folder that holds
        # diagnostics/laser_tread (a scan root, the diagnostics folder, or the
        # laser_tread folder itself), or None when the scan carries none.
        self.diag_folder = None
        # Stitched side image(s) found in the scan root / a stitched sub-folder, shown
        # in the Stitched tab. [] when none; the viewer never generates one.
        self.stitched_images = []
        self.seen_folders = set()
        self.scan_folder = None
        self.scan_id = None
        self.scan_uuid = None
        # The Axle_N root when this scan arrived ALREADY classified, else None. Set by
        # load_scan and read by the pre-scan worker, which skips the state machine
        # entirely when it is set - see _add_classified_tree.
        self.classified_root = None
        # His own classifier output, when a complete scan shipped it. Both are located
        # on THIS thread (two isfile checks) and used by the pre-scan worker and the
        # wheel-assembler tab respectively. None for either is not an error - it is a
        # scan processed before his writer existed, and the viewer says so.
        self.manifest_path = None       # Scan_Output_Classified/…_manifest.csv
        self.diagram_png = None         # Scan_Output_Classified/system_pulse_diagram.png
        # SINGLE-FOLDER LOAD. Set when the folder the user picked IS one data folder -
        # a camera folder, wheel_assembler/ or the LMI groove folder - rather than a
        # scan root holding them. Carries the human name of what was loaded; None for
        # a normal scan. See load_scan.
        self.single_folder = None
        # WHY no axle split was attempted, or None when one was. A scan with no
        # trigger log and no classifier output cannot be split by anything, so the
        # state machine is not run over it at all - and "nothing to split from" is a
        # statement about the input, not a failure of the viewer. Read by the pre-scan
        # worker (to skip the classifier) and by the banner (to say so calmly).
        self.no_split_reason = None
        # axle classification - populated by the pre-scan worker, never on this thread
        self.axle_index = None          # AxleIndex, or None when it could not run
        self.axle_error = None          # ClassificationError, surfaced as a banner

    def load_scan(self, scan_folder):
        """
        Primary entry: input is ONE scan folder whose name carries the scan ID.

        Two shapes are accepted, and which one arrived is decided from the folders on
        disk, never from a setting:

          a raw scan          camera folders at the top level. Walked as it always
                              was. Its axle split comes from his manifest CSV when
                              the scan carries one, and from the engineer's state
                              machine in the pre-scan worker when it does not.
          a classified tree   Axle_1 / Axle_2 / Trash / Unclassified. The split is
                              ALREADY on disk, so nothing is re-derived: the tree is
                              walked in full and read as the classification.

        A complete scan also carries Scan_Output_Classified/ - his manifest CSV and
        his saved system-pulse PNG. Both are only LOCATED here; what is done with
        them is decided by the pre-scan worker and the wheel-assembler tab.
        """
        self.clear()
        self.scan_folder = scan_folder
        name = os.path.basename(scan_folder.rstrip("\\/"))
        self.scan_id, self.scan_uuid = parse_scan_id(name)
        if AXLE_AVAILABLE:
            try:
                self.classified_root = axle_mod.detect_classified_tree(scan_folder)
            except Exception:
                traceback.print_exc()
                self.classified_root = None     # a detection failure is not a load
                                                # failure - fall back to a raw scan
            try:
                self.manifest_path = \
                    axle_mod.find_classification_manifest(scan_folder)
                self.diagram_png = axle_mod.find_system_diagram(scan_folder)
            except Exception:
                traceback.print_exc()
                self.manifest_path = self.diagram_png = None
        if self.classified_root:
            self._add_classified_tree(self.classified_root)
        else:
            self.add_paths([scan_folder])
        # a stitched side image is a scan-root artefact, not a camera folder - looked
        # for once, here, over the scan root only (never trawls the frame folders)
        try:
            self.stitched_images = find_stitched_images(scan_folder)
        except Exception:
            traceback.print_exc()
            self.stitched_images = []
        self._resolve_split_availability(name)

    # What a single-folder load is called on screen, per collection. The key is what
    # classify_folder() returns for the folder's own name.
    SINGLE_FOLDER_NAMES = {
        COL_WA: "wheel_assembler folder",
        COL_DIAG: "diagnostics (laser-groove algo) folder",
        "ArtemisGroove": "laser-groove (LMI) folder",
        COL_ATLAS: "Atlas camera folder",
        COL_HELIOS: "Helios camera folder",
        COL_TREAD: "Artemis tread camera folder",
        COL_OCR: "Artemis tire-wall (OCR) camera folder",
    }

    def _resolve_split_availability(self, name):
        """
        Decide, from what the walk actually found, whether an axle split is even
        possible here - and whether one data folder was loaded rather than a scan.

        TWO INPUTS ARE NOT SCANS, and neither of them is a broken scan:

          a single data folder   the user pointed at wheel_assembler/, one camera
                                 folder or the LMI groove folder. It classifies under
                                 its own name, so the walk already registered it and
                                 it already lands in its own tab; what it does NOT
                                 have is a vehicle to split into axles.
          a scan with no split   a scan-ID folder downloaded without wheel_assembler/
                                 and without Scan_Output_Classified/. There is no
                                 trigger log to run the state machine over and no
                                 manifest to read one out of.

        In both cases the classifier is skipped entirely rather than run and allowed
        to fail. Running it would produce a red "Axle split failed" banner over an
        input that was never going to split, which reads as "your scan is broken" when
        the truth is "this input carries nothing to split by".

        A single folder also gets its SCAN ID cleared: a folder name is not a scan ID,
        and parse_scan_id would otherwise put "wheel_assembler" in the scan-ID field.
        """
        col, _grp, _cam, _var = classify_folder(name)
        loaded_something = (bool(self.wa_folder) or bool(self.groove_folder)
                            or bool(self.diag_folder)
                            or any(self.has(c) for c in (COL_ATLAS, COL_HELIOS,
                                                         COL_TREAD, COL_OCR)))
        if col is not None and loaded_something:
            self.single_folder = self.SINGLE_FOLDER_NAMES.get(col, "data folder")
            self.scan_id = self.scan_uuid = None
            self.no_split_reason = (
                "a single %s was loaded, not a scan folder, so there is no vehicle "
                "to split into axles" % self.single_folder)
            return
        if not self.classified_root and not self.manifest_path and not self.wa_folder:
            self.no_split_reason = (
                "this scan carries no wheel_assembler/%s and no %s folder, so there "
                "is nothing to derive an axle split from"
                % (WA_CSV_NAME, axle_mod.ENGINEER_OUTPUT_DIR if AXLE_AVAILABLE
                   else "Scan_Output_Classified"))

    def scan_id_conflicts(self):
        """
        Guard against images from a different scan sneaking in. For every camera folder,
        read the first frame's sidecar JSON `ScanId` and compare to the folder's scan uuid.
        Returns a list of (folder, found_scanid) that DO NOT match (empty = ok / unverifiable).
        Folders without a sidecar can't be verified and are not treated as conflicts.
        """
        conflicts = []
        if not self.scan_uuid:
            return conflicts
        target = self.scan_uuid.lower()
        for col in (COL_ATLAS, COL_HELIOS, COL_TREAD, COL_OCR):
            for variant in ("raw", "compressed"):
                for _cam, entry in self.collections[col][variant].items():
                    files = entry["files"]
                    if not files:
                        continue
                    cand = sidecar_path(files[0])
                    if cand is None:
                        continue
                    try:
                        with lp_open(cand, "r", encoding="utf-8",
                                     errors="replace") as fh:
                            sid = str(json.load(fh).get("ScanId", "")).lower()
                    except Exception:
                        continue
                    if sid and target not in sid and sid not in target:
                        conflicts.append((entry["folder"], sid))
        return conflicts

    def add_paths(self, paths):
        """Each path may be a leaf camera folder OR a container/session root."""
        for p in paths:
            if not lp_isdir(p):
                continue
            self._consider(p)                       # the folder itself
            try:
                for sub in sorted(lp_listdir(p)):
                    full = os.path.join(p, sub)
                    if lp_isdir(full):
                        self._consider(full)        # its immediate children
            except Exception:
                pass

    # How deep a classified tree is walked for camera folders. The deepest layout in
    # use is Axle_1/Left/Tread/<camera folder> (4), and Unclassified/ reproduces the
    # source scan's own depth beneath it; 6 covers both. The cap is what stops a
    # mis-detected root from walking an entire drive.
    #
    # It is also the one place this walk and the INDEX can disagree: index_from_tree
    # walks the tree in full, so a camera folder buried deeper than this is in the
    # index but not in the frame viewer's collections. No writer nests that deep, and
    # the alternative - no cap at all - means a wrong detection walks a drive. The
    # smoke suite pins both halves of that trade.
    TREE_WALK_DEPTH = 6

    def _add_classified_tree(self, root):
        """
        Walk a classified tree and register every camera folder in it, at any depth.

        Two things differ from the flat walk, and both matter:

          * DEPTH. Camera folders sit three or four levels down, so the one-level walk
            add_paths() does would find nothing at all and the scan would come up with
            no tabs.
          * UNIQUE KEYS. The same camera folder name appears under several buckets -
            tr_rear_l_01 exists under Axle_1 AND under Trash - and the collections are
            keyed by camera id. Keyed by bare name, the Trash copy would REPLACE the
            axle one and those frames would vanish from the axle tab. The key is
            therefore the path relative to the tree root, which is unique by
            construction; the axle grouping the viewer shows is unaffected, since it
            comes from the index, not from these keys.
        """
        root = os.path.abspath(root)
        for cur, dirs, _files in lp_walk(root):
            try:
                rel = os.path.relpath(cur, root)
            except ValueError:                  # a different drive: not our tree
                dirs[:] = []
                continue
            depth = 0 if rel in (".", "") else len(rel.split(os.sep))
            if depth >= self.TREE_WALK_DEPTH:
                dirs[:] = []                    # stop descending, keep this level
            if depth == 0:
                continue
            key = rel.replace(os.sep, " / ")
            self._consider(cur, cam_id=key)
            if cur not in self.seen_folders:
                self._consider_tree_media(cur, rel.split(os.sep), key)

    def _consider_tree_media(self, folder, parts, cam_id):
        """
        Register a frame folder that the NAME-based walk cannot recognise.

        His classifier writes Axle_1/Left/Tread/<frames> - the frames sit straight in
        the media folder and the camera folder is gone, so classify_folder() sees
        "Tread", which matches no camera prefix, and the tab would come up empty. The
        viewer's own export keeps the camera folder and never reaches this path.

        The media type is taken from the tree POSITION, which is the same rule the
        index itself is built with (axle_mod.tree_entry), so a frame cannot be filed
        under one media here and another one there. Anything under Unclassified/ is
        left to the name-based walk: that subtree reproduces the source scan and its
        folder names are the real ones.
        """
        if not parts or not AXLE_AVAILABLE:
            return
        if parts[0].lower() == axle_mod.UNCLASSIFIED.lower():
            return
        _side, media, _f = axle_mod.tree_entry(parts[1:])
        col = {axle_mod.MEDIA_TREAD: COL_TREAD, axle_mod.MEDIA_OCR: COL_OCR}.get(media)
        if col is None:
            return                          # Laser is CSV profiles, not frames
        files = list_images(folder)
        if not files:
            return
        # "raw": his layout drops the compressed_ prefix with the camera folder, so
        # there is nothing left on disk that could say otherwise. The viewer's export
        # keeps the folder and never lands here.
        self.collections[col]["raw"][cam_id] = {"folder": folder, "files": files}
        self.seen_folders.add(folder)

    def _consider(self, folder, cam_id=None):
        if folder in self.seen_folders:
            return
        name = os.path.basename(folder.rstrip("\\/"))
        col, group, cam, variant = classify_folder(name)
        if col is None:
            return
        if col == COL_DIAG:
            # claim it only when the laser_tread/LMI_* tree is actually there, so an
            # unrelated folder called "diagnostics" never produces an empty tab
            if diagnostics_present(folder):
                self.diag_folder = folder
            self.seen_folders.add(folder)
            return
        if col == "ArtemisGroove":
            self.groove_folder = folder
            self.seen_folders.add(folder)
            return
        if col == COL_WA:
            # only claim it if the trigger file is actually there - an empty
            # wheel_assembler folder must not produce a tab that says nothing
            if lp_isfile(os.path.join(folder, WA_CSV_NAME)):
                self.wa_folder = folder
            self.seen_folders.add(folder)
            return
        files = list_images(folder)
        if not files:
            return
        self.collections[col][variant][cam_id or cam] = {"folder": folder,
                                                         "files": files}
        self.seen_folders.add(folder)

    # convenience presence checks
    def has(self, col):
        c = self.collections[col]
        return bool(c["raw"]) or bool(c["compressed"])

    def summary(self):
        def cnt(col):
            c = self.collections[col]
            return len(c["raw"]) + len(c["compressed"])
        parts = [f"Atlas: {cnt(COL_ATLAS)}", f"Helios: {cnt(COL_HELIOS)}",
                 f"Tread: {cnt(COL_TREAD)}", f"OCR: {cnt(COL_OCR)}",
                 f"Groove (LMI): {'yes' if self.groove_folder else 'no'}",
                 f"Diagnostics: {'yes' if self.diag_folder else 'no'}",
                 f"Wheel Assembler: {'yes' if self.wa_folder else 'no'}"]
        if self.classified_root:
            parts.append("pre-classified: yes")
        if self.manifest_path:
            parts.append("Scan_Output_Classified: yes")
        return "   ·   ".join(parts)


def axle_collections(collection, index, media):
    """
    Re-key a camera-keyed collection by axle, for the frame viewer's dropdown.

    In  {variant: {camera_id: {folder, files}}}          - per camera
    Out {variant: {"Axle 1 · Left": {folder, files}}}    - per axle and side

    The viewer reads nothing but this dict, so switching the navigation from camera
    to axle needs no change inside ImageFrameViewer at all. Files keep their real
    paths, so the physical camera is still shown on the frame's path label - the
    axle grouping adds a level, it does not hide where a frame came from.

    Returns None when there is no classification, so the caller can fall back to the
    original per-camera collection.
    """
    if index is None:
        return None

    # v1.2: ONE pass over the classification, grouped by (bucket, side). This used to
    # call index.files_for() - a full scan of every classified file plus a sort -
    # three times per bucket per variant per media: ~1.1 s of frozen window on a
    # 10 000-file scan. Same membership, same final order (every group is sorted by
    # order_key below, exactly as before).
    by_bs = {}                                   # (bucket, side) -> [abs path]
    # v1.5: pairs(), so a frame shared by two axles is listed under both
    for p, b in _index_pairs(index):
        m = index.meta.get(p, {})
        if media is not None and m.get("media") != media:
            continue
        by_bs.setdefault((b, m.get("side")), []).append(os.path.abspath(p))

    out = {}
    for variant, cams in collection.items():
        owned = {}
        for entry in cams.values():
            for f in entry["files"]:
                owned[os.path.abspath(f)] = f

        groups = OrderedDict()
        buckets = index.axle_labels() + [axle_mod.TRASH]
        for bucket in buckets:
            # "Left" / "Right" is what a classification his script produced always
            # carries. A classification READ off a folder tree can also carry no side
            # at all - Trash has no side folder in either layout - and those frames
            # get a group of their own rather than being left out of the dropdown,
            # which would take them off the vehicle entirely.
            sided = set()
            for side in ("Left", "Right"):
                files = [owned[p] for p in by_bs.get((bucket, side), ())
                         if p in owned]
                sided.update(os.path.abspath(f) for f in files)
                if not files:
                    continue
                name = "Unassigned" if bucket == axle_mod.TRASH else bucket
                groups[f"{name}  ·  {side}"] = {
                    "folder": index.scan_dir,
                    "files": sorted(files, key=order_key),
                }
            rest = [owned[p]
                    for (b_, _s), paths in by_bs.items() if b_ == bucket
                    for p in paths
                    if p in owned and p not in sided]
            if rest:
                name = "Unassigned" if bucket == axle_mod.TRASH else bucket
                groups[f"{name}  ·  side unknown"] = {
                    "folder": index.scan_dir,
                    "files": sorted(rest, key=order_key),
                }
        out[variant] = groups

    # An all-empty grouping is still a truthy dict, and handing it to the viewer
    # would show "no frames" for a scan that genuinely has frames. Fall back to the
    # per-camera collection instead.
    if not any(out.values()):
        return None
    return out
