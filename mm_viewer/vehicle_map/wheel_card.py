import os
import re
from PyQt6.QtCore import (
    pyqtProperty, pyqtSignal, QEasingCurve, QPropertyAnimation, QRectF, Qt
)
from PyQt6.QtGui import QBrush, QColor, QFontMetrics, QPainter, QPainterPath, QPen
from PyQt6.QtWidgets import QFrame, QSizePolicy


from mm_viewer.theme import (
    C_BLUE, C_BORDER, C_NAVY, C_ORANGE, C_SURFACE, C_TEXT_DIM, FS_SMALL
)


# ============================================================
# VEHICLE MAP  (per-axle landing view for Tread mapping / Tire Wall)
# ============================================================
#
# The Tread mapping and Tire Wall (OCR) tabs open on a map of the vehicle instead of
# on a bare dropdown: one card per wheel carrying the AXLE NUMBER and the NUMBER OF
# FRAMES attributed to it, an undercarriage illustration drawn for as many axles as
# the wheel assembler resolved, and a click that opens the ordinary frame viewer on
# that axle and side. The frame viewer itself is unchanged - the map is a front door,
# not a replacement.
#
# Unlike UVcamp, tread and tire wall are NOT merged into one wheel view: each tab
# draws its own map over its own media type, so a wheel that has tread frames but no
# OCR frames reads as exactly that instead of hiding behind a combined count.
#
# Everything here is painted, not stylesheet-driven: a QSS rule cannot animate, and
# the hover response is half the point of the control.

AXLE_KEY_SEP = "·"
MAP_SIDES = ("Left", "Right")
UNASSIGNED_LABEL = "Unassigned"


def parse_axle_key(key):
    """'Axle 2  .  Left' -> ('Axle 2', 'Left').   Anything else -> (key, '')."""
    if AXLE_KEY_SEP in key:
        bucket, side = key.split(AXLE_KEY_SEP, 1)
        return bucket.strip(), side.strip()
    return key.strip(), ""


def axle_number(bucket):
    """'Axle 3' -> 3.  'Unassigned' / anything unparseable -> None."""
    b = bucket or ""
    m = re.search(r"(\d+)", b)
    return int(m.group(1)) if m and b.lower().startswith("axle") else None


def _mix(c1, c2, t):
    """Blend two colours, t in 0..1. Used for the hover transition."""
    a, b = QColor(c1), QColor(c2)
    t = max(0.0, min(1.0, float(t)))
    return QColor(int(a.red() + (b.red() - a.red()) * t),
                  int(a.green() + (b.green() - a.green()) * t),
                  int(a.blue() + (b.blue() - a.blue()) * t))


def _sources_of(files):
    """The camera folder names a set of frames came from, de-duplicated and ordered."""
    return sorted({os.path.basename(os.path.dirname(f)) for f in files})


class WheelCard(QFrame):
    """
    One wheel's tile: axle number, side, frame count, a share bar and the camera
    folders behind it. Fully custom-painted so the hover state can animate.

    A wheel with zero frames is NOT hidden - a missing wheel would read as "this
    vehicle has no such wheel" when what actually happened is that the axle window
    matched nothing. It is drawn muted, marked NO FRAMES, and refuses the click.
    """
    clicked = pyqtSignal(str)             # source key to open
    hovered = pyqtSignal(int, str, bool)  # axle number, side, entered

    CARD_H = 126
    CARD_W_MIN = 248
    CARD_W_MAX = 430          # on a 1920 screen a full-column card reads as empty

    def __init__(self, axle_no, side, n_frames, sources, peak, key=None,
                 bucket_label=None, parent=None, extra=""):
        super().__init__(parent)
        self.axle_no = axle_no
        self.side = side
        self.key = key
        # v1.1: a second count beside the frame count (the Tread + Laser map puts
        # the wheel's laser-frame count here). Empty = the card is as it was.
        self.extra = extra or ""
        self.bucket_label = bucket_label or (
            f"Axle {axle_no}" if axle_no else UNASSIGNED_LABEL)
        self.n_frames = int(n_frames)
        self.sources = list(sources or [])
        self.peak = max(1, int(peak))
        self.active = self.n_frames > 0 and bool(key)

        self._t = 0.0
        self._anim = QPropertyAnimation(self, b"glow", self)
        self._anim.setDuration(150)
        self._anim.setEasingCurve(QEasingCurve.Type.OutCubic)

        self.setFixedHeight(self.CARD_H)
        self.setMinimumWidth(self.CARD_W_MIN)
        self.setMaximumWidth(self.CARD_W_MAX)
        self.setSizePolicy(QSizePolicy.Policy.Preferred, QSizePolicy.Policy.Fixed)
        self.setMouseTracking(True)
        self.setFocusPolicy(Qt.FocusPolicy.StrongFocus if self.active
                            else Qt.FocusPolicy.NoFocus)
        self.setCursor(Qt.CursorShape.PointingHandCursor if self.active
                       else Qt.CursorShape.ArrowCursor)
        self.setAccessibleName(f"{self.bucket_label} {side}, {self.n_frames} frames")
        if self.active:
            src = ", ".join(self.sources) or "-"
            self.setToolTip(f"{self.bucket_label}  -  {side}\n"
                            f"{self.n_frames} frames\n"
                            f"Camera folder(s): {src}\n\n"
                            "Click to open these frames in the viewer.")
        else:
            self.setToolTip(f"{self.bucket_label}  -  {side}\n"
                            "No frames were attributed to this wheel, so there is "
                            "nothing to open.\nThe axle window matched no frame of "
                            "this media type.")

    # ---- animated hover property ----
    def _get_glow(self):
        return self._t

    def _set_glow(self, v):
        self._t = float(v)
        self.update()

    glow = pyqtProperty(float, fget=_get_glow, fset=_set_glow)

    def set_hot(self, on, notify=True):
        """Drive the hover state, optionally without echoing the signal back."""
        if not self.active:
            return
        self._anim.stop()
        self._anim.setStartValue(self._t)
        self._anim.setEndValue(1.0 if on else 0.0)
        self._anim.start()
        if notify:
            self.hovered.emit(self.axle_no or 0, self.side, bool(on))

    # ---- events ----
    def enterEvent(self, ev):
        self.set_hot(True)
        super().enterEvent(ev)

    def leaveEvent(self, ev):
        self.set_hot(False)
        super().leaveEvent(ev)

    def mouseReleaseEvent(self, ev):
        if self.active and ev.button() == Qt.MouseButton.LeftButton \
                and self.rect().contains(ev.position().toPoint()):
            self.clicked.emit(self.key)
        super().mouseReleaseEvent(ev)

    def keyPressEvent(self, ev):
        if self.active and ev.key() in (Qt.Key.Key_Return, Qt.Key.Key_Enter,
                                        Qt.Key.Key_Space):
            self.clicked.emit(self.key)
            return
        super().keyPressEvent(ev)

    # ---- painting ----
    def paintEvent(self, _ev):
        p = QPainter(self)
        p.setRenderHint(QPainter.RenderHint.Antialiasing, True)
        t = self._t if self.active else 0.0
        r = QRectF(self.rect()).adjusted(1, 1, -1, -1)

        bg = _mix(C_SURFACE, "#fff6ee", t) if self.active else QColor("#f4f6fa")
        border = _mix(C_BORDER, C_ORANGE, t) if self.active else QColor("#e0e6ee")
        p.setPen(QPen(border, 1.0 + 1.0 * t))
        p.setBrush(QBrush(bg))
        p.drawRoundedRect(r, 10, 10)

        # left accent rail - grows and warms on hover
        rail_w = 4.0 + 4.0 * t
        rail = QRectF(r.left() + 1, r.top() + 1, rail_w, r.height() - 2)
        path = QPainterPath()
        path.addRoundedRect(rail, 3, 3)
        p.fillPath(path, QBrush(QColor(C_ORANGE) if self.active
                                else QColor("#c9d2df")))

        if self.hasFocus():
            p.setPen(QPen(QColor(C_BLUE), 2, Qt.PenStyle.DashLine))
            p.setBrush(Qt.BrushStyle.NoBrush)
            p.drawRoundedRect(r.adjusted(2, 2, -2, -2), 8, 8)

        x0 = r.left() + rail_w + 12
        w = r.right() - 12 - x0
        dim = QColor(C_TEXT_DIM) if self.active else QColor("#9aa5b5")
        ink = QColor(C_NAVY) if self.active else QColor("#8d99aa")

        f = p.font()
        # ---- line 1: axle label + side chip ----
        f.setPixelSize(FS_SMALL - 1)
        f.setBold(True)
        p.setFont(f)
        p.setPen(dim)
        p.drawText(QRectF(x0, r.top() + 10, w, 16),
                   int(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter),
                   self.bucket_label.upper())

        chip_txt = (self.side or "-").upper()
        fm = QFontMetrics(f)
        cw = fm.horizontalAdvance(chip_txt) + 16
        chip = QRectF(r.right() - 12 - cw, r.top() + 8, cw, 20)
        p.setPen(Qt.PenStyle.NoPen)
        p.setBrush(QBrush(_mix("#eef2f8", C_ORANGE, t) if self.active
                          else QColor("#eceff4")))
        p.drawRoundedRect(chip, 9, 9)
        p.setPen(_mix(C_TEXT_DIM, "#ffffff", t) if self.active else dim)
        p.drawText(chip, int(Qt.AlignmentFlag.AlignCenter), chip_txt)

        # ---- line 2: the number that matters ----
        f.setPixelSize(30)
        f.setBold(True)
        p.setFont(f)
        p.setPen(ink)
        num = str(self.n_frames)
        p.drawText(QRectF(x0, r.top() + 30, w, 36),
                   int(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter),
                   num)
        nw = QFontMetrics(f).horizontalAdvance(num)
        f.setPixelSize(FS_SMALL)
        f.setBold(False)
        p.setFont(f)
        p.setPen(dim)
        word = "frames" if self.n_frames != 1 else "frame"
        p.drawText(QRectF(x0 + nw + 8, r.top() + 30, max(0.0, w - nw - 8), 36),
                   int(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter),
                   word)
        if self.extra:
            ww = QFontMetrics(f).horizontalAdvance(word)
            f.setBold(True)
            p.setFont(f)
            p.setPen(QColor(C_BLUE) if self.active else dim)
            ex0 = x0 + nw + 8 + ww + 12
            p.drawText(QRectF(ex0, r.top() + 30, max(0.0, r.right() - 12 - ex0), 36),
                       int(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter),
                       QFontMetrics(f).elidedText("·  " + self.extra,
                                                  Qt.TextElideMode.ElideRight,
                                                  int(max(0.0, r.right() - 12 - ex0))))
            f.setBold(False)
            p.setFont(f)

        # ---- line 3: share bar (this wheel against the busiest wheel on the map) ----
        bar = QRectF(x0, r.top() + 72, max(10.0, w), 5)
        p.setPen(Qt.PenStyle.NoPen)
        p.setBrush(QBrush(QColor("#e6ebf3")))
        p.drawRoundedRect(bar, 2.5, 2.5)
        frac = min(1.0, self.n_frames / float(self.peak))
        if frac > 0:
            fill = QRectF(bar.left(), bar.top(),
                          max(3.0, bar.width() * frac), bar.height())
            p.setBrush(QBrush(_mix("#f0a460", C_ORANGE, t) if self.active
                              else QColor("#c9d2df")))
            p.drawRoundedRect(fill, 2.5, 2.5)

        # ---- line 4: provenance, or the reason there is nothing to open ----
        f.setPixelSize(FS_SMALL - 1)
        p.setFont(f)
        fm2 = QFontMetrics(f)
        if self.active:
            src = ", ".join(self.sources) or "-"
            p.setPen(dim)
            p.drawText(QRectF(x0, r.bottom() - 30, w * 0.62, 16),
                       int(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter),
                       fm2.elidedText(src, Qt.TextElideMode.ElideMiddle,
                                      int(w * 0.62)))
            f.setBold(True)
            p.setFont(f)
            p.setPen(_mix(C_TEXT_DIM, C_ORANGE, t))
            p.drawText(QRectF(x0, r.bottom() - 30, w, 16),
                       int(Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter),
                       "View frames  ›")
        else:
            txt = "NO FRAMES"
            cw2 = fm2.horizontalAdvance(txt) + 16
            warn = QRectF(x0, r.bottom() - 32, cw2, 20)
            p.setPen(Qt.PenStyle.NoPen)
            p.setBrush(QBrush(QColor("#fdf3e3")))
            p.drawRoundedRect(warn, 9, 9)
            f.setBold(True)
            p.setFont(f)
            p.setPen(QColor("#8a5310"))
            p.drawText(warn, int(Qt.AlignmentFlag.AlignCenter), txt)
        p.end()
