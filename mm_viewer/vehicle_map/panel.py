from PyQt6.QtCore import pyqtSignal, Qt
from PyQt6.QtWidgets import (
    QFrame, QGridLayout, QHBoxLayout, QLabel, QPushButton, QScrollArea, QStackedWidget,
    QVBoxLayout, QWidget
)
from collections import OrderedDict


from mm_viewer.theme import C_TEXT_DIM
from mm_viewer.widgets.controls import SegmentedControl
from mm_viewer.widgets.layout import allow_shrink, card, field_label
from mm_viewer.widgets.frame_viewer import ImageFrameViewer
from mm_viewer.vehicle_map.wheel_card import (
    _sources_of, axle_number, MAP_SIDES, parse_axle_key, WheelCard
)
from mm_viewer.vehicle_map.diagram import rank_map_warnings, VehicleDiagram


class VehicleMapPanel(QWidget):
    """
    The landing page of a per-axle tab: a summary strip, the vehicle, and one card
    per wheel. Emits (variant, source_key) when a wheel is chosen.

    The keys it emits are exactly the keys axle_collections() put in the viewer's
    dropdown, so opening a wheel and picking the same entry from the dropdown are
    the same action - the map cannot drift out of step with the viewer.
    """
    opened = pyqtSignal(str, str)          # variant, source key

    def __init__(self, axled, n_axles, media_label, warnings=None, parent=None,
                 extra_counts=None, show_unassigned=True):
        super().__init__(parent)
        self.axled = axled or {}
        # v1.3: False on the Tread + Laser map - frames the classifier put in Trash
        # are not offered there at all (counted in the summary, never opened)
        self.show_unassigned = bool(show_unassigned)
        self.n_axles = max(1, int(n_axles or 1))
        self.media_label = media_label
        self.warnings = list(warnings or [])
        # v1.1: {(axle_no, side): "24 laser"} - a second count per wheel card
        self.extra_counts = dict(extra_counts or {})
        self.cards = {}                    # (axle_no, side) -> WheelCard
        self._variant = "raw" if self.axled.get("raw") else "compressed"
        self._pending_axle = 1
        self.setFocusPolicy(Qt.FocusPolicy.StrongFocus)

        # ---------- header ----------
        head_card, head_v = card()
        self.title = QLabel(f"{media_label}   ·   vehicle map")
        self.title.setObjectName("mapTitle")
        allow_shrink(self.title, 160)

        has_raw = bool(self.axled.get("raw"))
        has_comp = bool(self.axled.get("compressed"))
        self.variant_seg = SegmentedControl([("raw", "Raw"),
                                             ("compressed", "Compressed")])
        self.variant_seg.set_enabled_key("raw", has_raw)
        self.variant_seg.set_enabled_key("compressed", has_comp)
        self.variant_seg.set_current(self._variant)
        self.variant_seg.changed.connect(self._on_variant)
        self.variant_seg.setToolTip("Frame counts, and the frames a wheel opens, "
                                    "are for this image type.")

        row1 = QHBoxLayout()
        row1.setSpacing(10)
        row1.addWidget(self.title, 1)
        row1.addWidget(field_label("Type"))
        row1.addWidget(self.variant_seg)
        head_v.addLayout(row1)

        self.summary = QLabel("")
        self.summary.setObjectName("mapSummary")
        self.summary.setWordWrap(True)
        allow_shrink(self.summary, 200)

        # Frames that matched no axle window are NOT drawn on the vehicle: a card
        # beside the wheels invites the reader to treat them as a wheel's frames.
        # They get a quiet shortcut in the header instead - off the map, still one
        # click away, and never silently dropped.
        self.unassigned_host = QWidget()
        self.unassigned_row = QHBoxLayout(self.unassigned_host)
        self.unassigned_row.setContentsMargins(0, 0, 0, 0)
        self.unassigned_row.setSpacing(8)

        row2 = QHBoxLayout()
        row2.setSpacing(14)
        row2.addWidget(self.summary, 1)
        row2.addWidget(self.unassigned_host, 0, Qt.AlignmentFlag.AlignTop)
        head_v.addLayout(row2)

        # ---------- vehicle + cards ----------
        self.diagram = VehicleDiagram(self.n_axles, {})
        self.diagram.wheelClicked.connect(self._on_wheel_clicked)
        self.diagram.wheelHovered.connect(self._on_wheel_hovered)

        self.grid_host = QWidget()
        self.grid = QGridLayout(self.grid_host)
        self.grid.setContentsMargins(4, 4, 4, 4)
        self.grid.setHorizontalSpacing(18)
        self.grid.setVerticalSpacing(12)

        body = QWidget()
        body_v = QVBoxLayout(body)
        body_v.setContentsMargins(0, 0, 0, 0)
        body_v.setSpacing(10)
        # stretch=1: the axle rows share the whole panel height, so the wheels
        # spread out on a big screen instead of huddling under the header.
        body_v.addWidget(self.grid_host, 1)
        body_v.addStretch(0)

        scroll = QScrollArea()
        scroll.setWidget(body)
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QFrame.Shape.NoFrame)
        scroll.viewport().setAutoFillBackground(False)
        scroll.setStyleSheet("QScrollArea{background:transparent;border:0;}")

        hint = QLabel("Click a wheel or its card to step through that wheel's frames."
                      "     Keys:  1…9 pick axle  ·  L / R open a side  "
                      "·  Esc returns here.")
        hint.setObjectName("hintText")
        allow_shrink(hint, 160)

        root = QVBoxLayout()
        root.setContentsMargins(10, 10, 10, 10)
        root.setSpacing(10)
        root.addWidget(head_card)
        root.addWidget(scroll, 1)
        root.addWidget(hint)
        self.setLayout(root)

        self._rebuild()

    # ---------- data ----------
    def _entries(self):
        return self.axled.get(self._variant, OrderedDict())

    def _counts(self):
        """{(axle_no, side): n} for the current variant, axles only."""
        out = {}
        for key, entry in self._entries().items():
            bucket, side = parse_axle_key(key)
            no = axle_number(bucket)
            if no is not None and side in MAP_SIDES:
                out[(no, side)] = len(entry["files"])
        return out

    def _unassigned(self):
        """[(key, side, files)] for whatever did not match an axle window."""
        out = []
        for key, entry in self._entries().items():
            bucket, side = parse_axle_key(key)
            if axle_number(bucket) is None:
                out.append((key, side, entry["files"]))
        return out

    def _key_for(self, axle_no, side):
        for key in self._entries():
            bucket, s = parse_axle_key(key)
            if axle_number(bucket) == axle_no and s == side:
                return key
        return None

    # ---------- build ----------
    @staticmethod
    def _clear_layout(lay):
        while lay.count():
            it = lay.takeAt(0)
            w = it.widget()
            if w is not None:
                w.setParent(None)
                w.deleteLater()

    def _rebuild(self):
        # the diagram is reused across variants, so pull it out before the clear
        # deletes everything the layout is holding
        self.diagram.hide()
        self.diagram.setParent(None)
        self._clear_layout(self.grid)
        self._clear_layout(self.unassigned_row)
        self.cards.clear()

        counts = self._counts()
        peak = max([1] + list(counts.values()))
        entries = self._entries()

        for i in range(self.n_axles):
            axle_no = i + 1
            for col, side in ((0, "Left"), (2, "Right")):
                key = self._key_for(axle_no, side)
                files = entries[key]["files"] if key else []
                c = WheelCard(axle_no, side, len(files), _sources_of(files), peak,
                              key=key,
                              extra=self.extra_counts.get((axle_no, side), ""))
                c.clicked.connect(self._open_key)
                c.hovered.connect(self._on_card_hovered)
                # each column's cards hug the vehicle in the middle, the way the
                # wheel panels sit beside the axle in UVcamp
                self.grid.addWidget(c, i, col, Qt.AlignmentFlag.AlignVCenter
                                    | (Qt.AlignmentFlag.AlignRight if col == 0
                                       else Qt.AlignmentFlag.AlignLeft))
                self.cards[(axle_no, side)] = c
            self.grid.setRowStretch(i, 1)

        self.diagram.set_counts(counts, self.n_axles)
        self.grid.addWidget(self.diagram, 0, 1, self.n_axles, 1)
        self.diagram.show()
        self.grid.setColumnStretch(0, 1)
        self.grid.setColumnStretch(1, 0)
        self.grid.setColumnStretch(2, 1)
        # rows share the height they are given, but only up to a sane band per axle -
        # a 2-axle van stretched over 1100 px reads as a road train
        self.grid_host.setMaximumHeight(self.n_axles * 200 + 40)

        # Unassigned frames are real frames - "1578 tread frames matched no axle"
        # is a finding, so they keep a route into the viewer. It just is not a card
        # standing next to the wheels.
        unassigned = self._unassigned()
        for key, side, files in (unassigned if self.show_unassigned else []):
            b = QPushButton(f"Unassigned · {side or '—'}   "
                            f"{len(files)} frame{'s' if len(files) != 1 else ''}   →")
            b.setObjectName("ghostBtn")
            b.setCursor(Qt.CursorShape.PointingHandCursor)
            b.setToolTip("Frames that fell outside every axle window.\n"
                         "They are not attributed to a wheel, so they are not on the "
                         "vehicle - open them here to inspect them.")
            b.clicked.connect(lambda _c=False, k=key: self._open_key(k))
            self.unassigned_row.addWidget(b)
        self.unassigned_host.setVisible(bool(unassigned) and self.show_unassigned)

        self._update_summary(counts, unassigned)

    def _update_summary(self, counts, unassigned):
        total = sum(counts.values())
        un = sum(len(f) for _k, _s, f in unassigned)
        gaps = sorted({f"Axle {a} {s}"
                       for a in range(1, self.n_axles + 1) for s in MAP_SIDES
                       if counts.get((a, s), 0) == 0})
        bits = [f"<b>{self.n_axles}</b> axle{'s' if self.n_axles != 1 else ''} "
                "from the wheel assembler",
                f"<b>{total}</b> {self.media_label.lower()} frames attributed"]
        if un:
            bits.append(f"<b>{un}</b> not attributed to any axle"
                        + ("" if self.show_unassigned else
                           " (Trash - not shown in this tab)"))
        txt = "   ·   ".join(bits)
        # The gaps line is the panel's OWN finding about the vehicle it is drawing -
        # which wheel has no frames - so it is always on screen and is not part of the
        # ranked budget below.
        if gaps:
            txt += ("<br><span style='color:#8a5310'>⚠  no frames for: "
                    + ", ".join(gaps) + "</span>")
        shown, hidden = rank_map_warnings(self.warnings, self.media_label)
        for w in shown:
            txt += f"<br><span style='color:#8a5310'>⚠  {w}</span>"
        if hidden:
            txt += ("<br><span style='color:%s'>+%d more classification note%s "
                    "— hover, or see the banner at the top of the window."
                    "</span>" % (C_TEXT_DIM, len(hidden),
                                 "" if len(hidden) == 1 else "s"))
        self.summary.setText(txt)
        # Nothing is lost: every note, numbered, in the order the classifier raised
        # them rather than in the ranked order, so it reads the same as the banner.
        self.summary.setToolTip(
            "\n\n".join("%d. %s" % (i, w)
                          for i, w in enumerate(self.warnings, 1))
            if self.warnings else "")

    # ---------- interaction ----------
    def _on_variant(self, key):
        if key == self._variant:
            return
        self._variant = key
        self._rebuild()

    def _open_key(self, key):
        if key:
            self.opened.emit(self._variant, key)

    def _on_wheel_clicked(self, axle_no, side):
        key = self._key_for(axle_no, side)
        if key:
            self._open_key(key)

    def _on_wheel_hovered(self, axle_no, side, on):
        c = self.cards.get((axle_no, side))
        if c is not None:
            c.set_hot(on, notify=False)         # no echo back to the diagram

    def _on_card_hovered(self, axle_no, side, on):
        self.diagram.set_hot(axle_no, side, on)

    # ---------- keyboard ----------
    def _highlight_axle(self, axle_no):
        for (a, s), c in self.cards.items():
            c.set_hot(a == axle_no, notify=False)
        self.diagram.set_hot(axle_no, "Left", True)

    def keyPressEvent(self, ev):
        k = ev.key()
        if Qt.Key.Key_1 <= k <= Qt.Key.Key_9:
            no = k - Qt.Key.Key_0
            if 1 <= no <= self.n_axles:
                self._pending_axle = no
                self._highlight_axle(no)
            return
        if k in (Qt.Key.Key_L, Qt.Key.Key_R):
            side = "Left" if k == Qt.Key.Key_L else "Right"
            key = self._key_for(self._pending_axle, side)
            if key:
                self._open_key(key)
            return
        super().keyPressEvent(ev)


class AxleFrameTab(QStackedWidget):
    """
    A per-axle tab: the vehicle map in front, the ordinary frame viewer behind it.

    Built ONLY for a scan the wheel assembler could split. A scan it could not split
    gets no map and no card page at all - MainWindow.rebuild() falls back to the
    plain per-camera ImageFrameViewer the app used before the map existed, so the
    unclassified case behaves exactly as it always did.

    The viewer is the SAME ImageFrameViewer the per-camera tabs use - same frame
    slider, ROI, gamma and tools - with one difference: its source dropdown is
    hidden, because the wheel is chosen on the map and two controls for one choice
    is the ambiguity the map exists to remove. The Raw/Compressed toggle stays in
    both places and the two are kept in step.
    """

    mapped = True

    def __init__(self, axled, n_axles, group_key, gamma_store, label,
                 media_label, warnings=None, parent=None):
        super().__init__(parent)
        self._syncing = False
        self.map = VehicleMapPanel(axled, n_axles, media_label, warnings=warnings)
        self.viewer = ImageFrameViewer(axled, group_key, gamma_store, label,
                                       selector_label="Axle",
                                       on_back=self.show_map,
                                       show_selector=False)
        self.addWidget(self.map)
        self.addWidget(self.viewer)
        self.map.opened.connect(self.open_source)
        # Raw/Compressed is offered on both pages, so it has to mean the same thing
        # on both. The guard stops the two controls from echoing each other.
        self.map.variant_seg.changed.connect(self._map_variant_changed)
        self.viewer.variant_seg.changed.connect(self._viewer_variant_changed)
        self.setCurrentIndex(0)

    # ---- variant sync ----
    def _map_variant_changed(self, key):
        if self._syncing:
            return
        self._syncing = True
        try:
            if self.viewer.variant_seg.is_enabled_key(key):
                self.viewer.variant_seg.set_current(key, emit=True)
        finally:
            self._syncing = False

    def _viewer_variant_changed(self, key):
        if self._syncing:
            return
        self._syncing = True
        try:
            if self.map.variant_seg.is_enabled_key(key):
                self.map.variant_seg.set_current(key, emit=True)
        finally:
            self._syncing = False

    # ---- navigation ----
    def open_source(self, variant, key):
        self.viewer.select_source(variant, key)
        self.setCurrentIndex(1)
        self.viewer.setFocus()

    def show_map(self):
        self.setCurrentIndex(0)
        self.map.setFocus()
